#!/usr/bin/env python3
"""Post-hoc LEA all-force corpus evaluation for 2026-06-02."""

from __future__ import annotations

import importlib.util
import json
import math
import pathlib
import sys
from collections import Counter
from typing import Any


ROOT = pathlib.Path(__file__).resolve().parents[2]
RUN_DIR = ROOT / "corpus/results/x86_kvm_corpus_20260602_193030_774646"
OUT_MD = ROOT / "docs" / "tmp" / "kop_lea_all_force_eval_20260602_summary.md"
FIG_OUT = ROOT / "docs" / "figures" / "eval-kop-lea-all-force-corpus-20260602.png"


def load_helpers() -> Any:
    path = ROOT / "docs" / "tmp" / "kop_eval_20260602.py"
    spec = importlib.util.spec_from_file_location("kop_eval_20260602_helpers", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"failed to load {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    module.RUN_DIR = RUN_DIR
    module.FIG_OUT = FIG_OUT
    module.base.RUN_DIR = RUN_DIR
    return module


def fmt_ratio(value: float) -> str:
    return "n/a" if math.isnan(value) else f"{value:.3f}x"


def write_summary(
    helpers: Any,
    workloads: list[Any],
    bpf: list[Any],
    apply: dict[str, dict[str, Counter[str]]],
    applied_names: dict[str, Counter[str]],
    fig: pathlib.Path,
) -> None:
    metadata = json.loads((RUN_DIR / "metadata.json").read_text())
    all_bpf_ratios = [pair.ratio for row in bpf for pair in row.qualified]
    direct_bpf_ratios = [pair.ratio for row in bpf for pair in row.direct_applied]
    workload_ratios = [row.post_over_baseline for row in workloads]

    total = Counter()
    for key, _, _ in helpers.APPS:
        total.update(apply[key].get("lea", Counter()))

    lines: list[str] = []
    lines.append("# LEA All-Force KOperation Corpus Evaluation, 2026-06-02")
    lines.append("")
    lines.append("Generated by `docs/tmp/kop_lea_all_force_eval_20260602.py` from raw artifacts.")
    lines.append("")
    lines.append(f"- Artifact: `{RUN_DIR.relative_to(ROOT)}`")
    lines.append(f"- Figure: `{fig.relative_to(ROOT)}`")
    lines.append(f"- Enabled passes: `{', '.join(metadata['config']['enabled_passes'])}`")
    lines.append(f"- Samples: `{metadata['samples']}`")
    lines.append(f"- Workload seconds: `{metadata['workload_seconds']:.0f}`")
    lines.append("- Policy: LLVM backend defaults to force and `bpfopt` injects `all=force`; no YAML overrides were used.")
    lines.append(f"- Loadtime apply: `{total['sites']}/{total['matched']}` sites applied, `{total['skipped']}` skipped, `{total['errors']}` errors.")
    lines.append(f"- Workload post/baseline geomean: `{helpers.geomean(workload_ratios):.3f}x`")
    lines.append(f"- BPF all-qualified per-program geomean: `{helpers.geomean(all_bpf_ratios):.3f}x`")
    lines.append(f"- BPF direct-self-applied per-program geomean: `{fmt_ratio(helpers.geomean(direct_bpf_ratios))}`")
    lines.append("")
    lines.append("## Workload Throughput")
    lines.append("")
    lines.append("| App | Baseline throughput | post_rejit throughput | post/baseline | reported errors |")
    lines.append("| --- | ---: | ---: | ---: | ---: |")
    for row in workloads:
        lines.append(
            f"| `{row.key}` | {row.baseline:.2f} | {row.post_rejit:.2f} | "
            f"{row.post_over_baseline:.3f}x | {row.reported_errors} |"
        )

    lines.append("")
    lines.append("## BPF Per-Program Counters")
    lines.append("")
    lines.append("| App | all-qualified n | all-qualified geomean | wins/losses/ties | direct applied n | direct applied geomean | direct wins/losses/ties |")
    lines.append("| --- | ---: | ---: | ---: | ---: | ---: | ---: |")
    for row in bpf:
        all_values = [pair.ratio for pair in row.qualified]
        direct_values = [pair.ratio for pair in row.direct_applied]
        all_wlt = helpers.wins_losses(all_values)
        direct_wlt = helpers.wins_losses(direct_values)
        lines.append(
            f"| `{row.key}` | {len(row.qualified)} | {fmt_ratio(helpers.geomean(all_values))} | "
            f"{all_wlt[0]}/{all_wlt[1]}/{all_wlt[2]} | {len(row.direct_applied)} | "
            f"{fmt_ratio(helpers.geomean(direct_values))} | {direct_wlt[0]}/{direct_wlt[1]}/{direct_wlt[2]} |"
        )

    lines.append("")
    lines.append("## Loadtime Apply")
    lines.append("")
    lines.append("| App | reports | applied programs | sites applied | sites matched | skipped | errors |")
    lines.append("| --- | ---: | ---: | ---: | ---: | ---: | ---: |")
    for key, _, _ in helpers.APPS:
        summary = apply[key].get("lea", Counter())
        lines.append(
            f"| `{key}` | {summary.get('reports', 0)} | {summary.get('applied_programs', 0)} | "
            f"{summary.get('sites', 0)} | {summary.get('matched', 0)} | "
            f"{summary.get('skipped', 0)} | {summary.get('errors', 0)} |"
        )
    lines.append(
        f"| `total` | {total['reports']} | {total['applied_programs']} | "
        f"{total['sites']} | {total['matched']} | {total['skipped']} | {total['errors']} |"
    )

    lines.append("")
    lines.append("## Top Applied Programs")
    lines.append("")
    lines.append("| App | Applied programs by site count |")
    lines.append("| --- | --- |")
    for key, _, _ in helpers.APPS:
        rendered = ", ".join(f"`{name}`={count}" for name, count in applied_names[key].most_common(12))
        lines.append(f"| `{key}` | {rendered or 'none'} |")

    caveats = helpers.raw_counter_caveats(bpf)
    if caveats:
        lines.append("")
        lines.append("## Raw Counter Caveats")
        lines.append("")
        lines.append("| App | Program | Type | baseline ns/run | post ns/run | post/baseline | baseline/post runs |")
        lines.append("| --- | --- | --- | ---: | ---: | ---: | ---: |")
        for key, pair in caveats:
            lines.append(
                f"| `{key}` | `{pair.name}` | `{pair.prog_type}` | "
                f"{pair.baseline_ns_per_run:.2f} | {pair.post_ns_per_run:.2f} | "
                f"{pair.ratio:.3f}x | {pair.baseline_runs}/{pair.post_runs} |"
            )

    lines.append("")
    OUT_MD.write_text("\n".join(lines))


def main() -> None:
    helpers = load_helpers()
    metadata = json.loads((RUN_DIR / "metadata.json").read_text())
    if metadata.get("status") != "completed":
        raise RuntimeError(f"unexpected run metadata: {metadata}")
    if metadata.get("config", {}).get("enabled_passes") != ["lea"]:
        raise RuntimeError(f"unexpected enabled passes: {metadata.get('config')}")
    workloads = helpers.workload_rows(int(metadata.get("samples") or 0))
    apply, applied_names = helpers.loadtime_summary()
    bpf = helpers.base.bpf_rows(applied_names)
    fig = helpers.plot_corpus(workloads, bpf, apply)
    write_summary(helpers, workloads, bpf, apply, applied_names, fig)
    print(f"wrote {OUT_MD.relative_to(ROOT)}")
    print(f"wrote {fig.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
