#!/usr/bin/env python3
"""Generate the shared AArch64 MOV provenance-path contract.

The two move opcodes write the destination register through one of two register
writes, and which one is chosen is the ISA decision this contract pins:

  * `ARM64_OP_MOV_IMM` (1) always writes a width-narrowed value, dropping any
    source provenance tag (the source is an immediate, which carries no tag).
  * `ARM64_OP_MOV_REG` (2) copies the *source* register's provenance tag into the
    destination when the access is 64-bit (`ARM64_SIM_L_WRITE_REG_PTR_TAG`), and
    otherwise writes a width-narrowed scalar, dropping the tag.

The generated Lean `GeneratedArm64Mov.ptrTagPath` and the C macro
`KPROG_ARM64_MOV_PTR_TAG_PATH` implement exactly that Boolean selection: the
register-source move at doubleword width is the tag-copy path, every other
(opcode, width) pair is the tag-dropping width-narrow path. The surrounding
register reads, the tag value itself, and the two register writes stay in the
handler; this contract decides only *which* write path runs.

Both opcode numbers are re-checked against native-sim/arm64/arm64_sim.h, so a
drift there fails `--check`.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_mov_spec.json"
SIM_HEADER = ROOT.parent / "arm64/arm64_sim.h"
LEAN = ROOT / "KProgFormal/GeneratedArm64Mov.lean"
CHEADER = ROOT / "generated/arm64_mov.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64Mov",
    "operations": [
        {"name": "movImm", "code": 1, "macro": "ARM64_OP_MOV_IMM"},
        {"name": "movReg", "code": 2, "macro": "ARM64_OP_MOV_REG"},
    ],
}

OPCODE_DEFINE = re.compile(
    r"^#define\s+(ARM64_OP_[A-Z0-9_]+)\s+0x([0-9a-fA-F]+)U\s*$", re.M)


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 mov specification: {data!r}")
    ops = EXPECTED["operations"]
    if [row["name"] for row in ops] != ["movImm", "movReg"]:
        raise SystemExit(f"invalid arm64 mov order: {ops!r}")
    if [row["macro"] for row in ops] != [
            "ARM64_OP_MOV_IMM", "ARM64_OP_MOV_REG"]:
        raise SystemExit(f"invalid arm64 mov macros: {ops!r}")
    opcodes = {name: int(value, 16)
               for name, value in OPCODE_DEFINE.findall(SIM_HEADER.read_text())}
    if not opcodes:
        raise SystemExit(
            f"no ARM64_OP_* opcode definitions found in {SIM_HEADER}")
    for row in ops:
        if opcodes.get(row["macro"]) != row["code"]:
            raise SystemExit(
                "arm64 mov opcodes drift from native-sim/arm64/arm64_sim.h: "
                f"spec={row['macro']}={row['code']:#x} "
                f"sim={opcodes.get(row['macro'])}")
    return ops


def render_lean(ops: list[dict]) -> str:
    ctors = "\n".join(f"  | {row['name']}" for row in ops)
    codes = "\n".join(f"  | .{row['name']} => {row['code']}" for row in ops)
    mnemonics = "\n".join(
        f"  | .{row['name']} => \"{row['name']}\"" for row in ops)
    return f'''-- Generated by generate_arm64_mov_spec.py from arm64_mov_spec.json.
import KProgFormal.GeneratedArm64Width
namespace KProgFormal.GeneratedArm64Mov
open KProgFormal.GeneratedArm64Width (Width)
/-- The two AArch64 move opcodes the handler routes. -/
inductive Mov where
{ctors}
deriving DecidableEq, Repr
/-- The ARM64_OP_* opcode number the move carries in arm64_sim.h. -/
def code : Mov -> Nat
{codes}
/-- The AArch64 mnemonic of the move. -/
def mnemonic : Mov -> String
{mnemonics}
/-- Whether this (move, width) pair takes the tag-copy register-write path
(`ARM64_SIM_L_WRITE_REG_PTR_TAG`, which copies the source register's provenance
tag) rather than the tag-dropping width-narrowed scalar write. Only the
register-source move at doubleword width preserves provenance: MOV_IMM's source
is an immediate and a sub-word register move is a scalar narrowing, so both drop
the tag. -/
def ptrTagPath (op : Mov) (width : Width) : Bool :=
  match op, width with
  | .movReg, .w64 => true
  | _, _ => false
end KProgFormal.GeneratedArm64Mov
'''


def render_c(ops: list[dict]) -> str:
    codes = "\n".join(
        f"_Static_assert({row['macro']} == {row['code']}U, "
        '"arm64 mov code drift");'
        for row in ops)
    handled = " || \\\n\t".join(
        f"((OP) == {row['macro']})" for row in ops)
    coverage = "\n".join(
        f"_Static_assert(KPROG_ARM64_MOV_HANDLED({row['macro']}), "
        '"arm64 mov coverage drift");'
        for row in ops)
    return f'''/* Generated by generate_arm64_mov_spec.py from arm64_mov_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_MOV_H
#define KPROG_FORMAL_GENERATED_ARM64_MOV_H
/*
 * The routing decision shared by the two AArch64 move opcodes: whether the
 * destination is written by the tag-copy register write (which carries the
 * source register's provenance) or by a width-narrowed scalar write (which drops
 * it). Only the register-source move at doubleword width preserves provenance.
 * An opcode outside the family reaches the caller-supplied unsupported arm.
 */
#include "arm64_width.h"
{codes}
#define KPROG_ARM64_MOV_HANDLED(OP)                                         \\
\t({handled})
{coverage}
/*
 * The numeric case labels 1U and 2U track the ARM64_OP_MOV_IMM and
 * ARM64_OP_MOV_REG values defined in native-sim/arm64/arm64_sim.h. OP is the
 * opcode and WIDTH the access width code; OP and WIDTH are each read once. The
 * result is 1 when the destination must be written through
 * ARM64_SIM_L_WRITE_REG_PTR_TAG (copying ARM64_SIM_L_REG_TAG(SRC)) and 0 when it
 * must be written through ARM64_SIM_L_WRITE_REG_WIDTH (dropping the tag).
 */
#define KPROG_ARM64_MOV_PTR_TAG_PATH(OP, WIDTH, UNSUPPORTED)                \\
\t({{ \\
\t\t__u64 __kprog_a64_mov_op = (OP); \\
\t\t__u64 __kprog_a64_mov_width = (WIDTH); \\
\t\t__u64 __kprog_a64_mov_path = 0; \\
\\
\t\tswitch (__kprog_a64_mov_op) {{ \\
\t\tcase 1U: \\
\t\t\tbreak; \\
\t\tcase 2U: \\
\t\t\t__kprog_a64_mov_path = (__kprog_a64_mov_width == ARM64_WIDTH_64); \\
\t\t\tbreak; \\
\t\tdefault: \\
\t\t\tUNSUPPORTED; \\
\t\t\tbreak; \\
\t\t}} \\
\t\t__kprog_a64_mov_path; \\
\t}})
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    ops = load()
    for path, expected in ((LEAN, render_lean(ops)), (CHEADER, render_c(ops))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 mov contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
