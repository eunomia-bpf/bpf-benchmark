#!/usr/bin/env python3
"""Generate the shared x86 register-writeback bits and tag contract."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_reg_write_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86RegWrite.lean"
C_HEADER = ROOT / "generated/x86_reg_write.h"
EXPECTED = {
    "schema_version": 1,
    "operation": "x86RegWrite",
    "tag": "scalar",
    "byte_lanes": [
        {"name": "low", "shift": 0},
        {"name": "high", "shift": 8},
    ],
    "widths": [
        {"name": "w8", "bits": 8, "preserve_upper": True},
        {"name": "w16", "bits": 16, "preserve_upper": True},
        {"name": "w32", "bits": 32, "preserve_upper": False},
        {"name": "w64", "bits": 64, "preserve_upper": False},
    ],
}


def load() -> None:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 register-write specification: {data!r}")


def render_lean() -> str:
    return '''-- Generated by generate_x86_reg_write_spec.py from x86_reg_write_spec.json.
import KProgFormal.GeneratedX86Width
namespace KProgFormal.GeneratedX86RegWrite
structure Result where
  bits : BitVec 64
  scalarizes : Bool
  deriving DecidableEq, Repr
inductive ByteLane
  | low
  | high
  deriving DecidableEq, Repr
def byteShift : ByteLane -> Nat
  | .low => 0
  | .high => 8
def bits (old value : BitVec 64) : GeneratedX86Width.Width -> BitVec 64
  | .w8 => BitVec.or (BitVec.and old 0xffffffffffffff00) (BitVec.and value 0xff)
  | .w16 => BitVec.or (BitVec.and old 0xffffffffffff0000) (BitVec.and value 0xffff)
  | .w32 => BitVec.and value 0xffffffff
  | .w64 => value
def bitsAt (old value : BitVec 64) (width : GeneratedX86Width.Width)
    (lane : ByteLane) : BitVec 64 :=
  match width, lane with
  | .w8, .low => BitVec.or (BitVec.and old 0xffffffffffffff00) (BitVec.and value 0xff)
  | .w8, .high => BitVec.or (BitVec.and old 0xffffffffffff00ff)
      (BitVec.shiftLeft (BitVec.and value 0xff) 8)
  | .w16, _ => BitVec.or (BitVec.and old 0xffffffffffff0000) (BitVec.and value 0xffff)
  | .w32, _ => BitVec.and value 0xffffffff
  | .w64, _ => value
def writeAt (old value : BitVec 64) (width : GeneratedX86Width.Width)
    (lane : ByteLane) : Result :=
  { bits := bitsAt old value width lane, scalarizes := true }
def write (old value : BitVec 64) (width : GeneratedX86Width.Width) : Result :=
  { bits := bits old value width, scalarizes := true }
end KProgFormal.GeneratedX86RegWrite
'''


def render_c() -> str:
    return '''/* Generated by generate_x86_reg_write_spec.py from x86_reg_write_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_REG_WRITE_H
#define KPROG_FORMAL_GENERATED_X86_REG_WRITE_H
#define KPROG_X86_WRITE_REG8(STORAGE, TAG, VALUE, BYTE_SHIFT, SCALAR_TAG)   \\
\tdo {                                                               \\
\t\tif ((BYTE_SHIFT) == 8U)                                   \\
\t\t\t(STORAGE).b[1] = (__u8)(VALUE);                   \\
\t\telse                                                       \\
\t\t\t(STORAGE).b[0] = (__u8)(VALUE);                   \\
\t\t(TAG) = (SCALAR_TAG);                                     \\
\t} while (0)
#define KPROG_X86_WRITE_REG16(STORAGE, TAG, VALUE, SCALAR_TAG)              \\
\tdo {                                                               \\
\t\t(STORAGE).w = (__u16)(VALUE);                            \\
\t\t(TAG) = (SCALAR_TAG);                                     \\
\t} while (0)
#define KPROG_X86_WRITE_REG32(STORAGE, TAG, VALUE, SCALAR_TAG)              \\
\tdo {                                                               \\
\t\t(STORAGE).ptr = (void *)(long)(__u32)(VALUE);              \\
\t\t(TAG) = (SCALAR_TAG);                                     \\
\t} while (0)
#define KPROG_X86_WRITE_REG64(STORAGE, TAG, VALUE, SCALAR_TAG)              \\
\tdo {                                                               \\
\t\t(STORAGE).ptr = (void *)(long)(__u64)(VALUE);              \\
\t\t(TAG) = (SCALAR_TAG);                                     \\
\t} while (0)
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    load()
    for path, expected in ((LEAN, render_lean()), (C_HEADER, render_c())):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated x86 register-write contract is stale: {path}"
                )
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
