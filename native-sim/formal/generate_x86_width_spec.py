#!/usr/bin/env python3
"""Generate the shared x86 width/narrowing contract for Lean and C."""
import argparse, json
from pathlib import Path
ROOT=Path(__file__).resolve().parent
SPEC=ROOT/"x86_width_spec.json"; LEAN=ROOT/"KProgFormal/GeneratedX86Width.lean"; CHEADER=ROOT/"generated/x86_width.h"
EXPECTED=[("w8",1,8,"0xff"),("w16",2,16,"0xffff"),("w32",4,32,"0xffffffff"),("w64",8,64,"0xffffffffffffffff")]
def load():
 data=json.loads(SPEC.read_text())
 if set(data)!={"schema_version","operation","widths"} or data["schema_version"]!=1 or data["operation"]!="x86Width": raise SystemExit(f"invalid x86 width specification: {data!r}")
 if len(data["widths"])!=4: raise SystemExit(f"invalid x86 width list: {data['widths']!r}")
 for w,e in zip(data["widths"],EXPECTED,strict=True):
  if set(w)!={"name","code","bits","mask"} or (w["name"],w["code"],w["bits"],w["mask"])!=e: raise SystemExit(f"non-canonical x86 width: {w!r}")
 return data["widths"]
def render_lean(ws):
 cs="\n".join(f"  | {w['name']}" for w in ws); codes="\n".join(f"  | .{w['name']} => {w['code']}" for w in ws); ms="\n".join(f"  | .{w['name']} => BitVec.ofNat 64 {w['mask']}" for w in ws); bs="\n".join(f"  | .{w['name']} => {w['bits']}" for w in ws)
 return f'''-- Generated by generate_x86_width_spec.py from x86_width_spec.json.
import Std
namespace KProgFormal.GeneratedX86Width
inductive Width
{cs}
  deriving DecidableEq, Repr
def code : Width -> Nat
{codes}
def mask : Width -> BitVec 64
{ms}
def bits : Width -> Nat
{bs}
def narrow (value : BitVec 64) (width : Width) := BitVec.and value (mask width)
def zero (value : BitVec 64) (width : Width) : Bool := narrow value width == 0
def sign (value : BitVec 64) (width : Width) : Bool := (narrow value width).getLsbD (bits width - 1)
end KProgFormal.GeneratedX86Width
'''
def render_c(ws):
 assertions="\n".join(f'_Static_assert(X86_WIDTH_{w["bits"]} == {w["code"]}U, "x86 width code drift");' for w in ws)
 masks=" \\\n".join(f"\t((WIDTH) == X86_WIDTH_{w['bits']} ? {w['mask']}ULL :" for w in ws[:-1]); bits=" \\\n".join(f"\t((WIDTH) == X86_WIDTH_{w['bits']} ? {w['bits']}U :" for w in ws[:-1]); closes=")"*3
 return f'''/* Generated by generate_x86_width_spec.py from x86_width_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_WIDTH_H
#define KPROG_FORMAL_GENERATED_X86_WIDTH_H
{assertions}
#define KPROG_X86_WIDTH_MASK(WIDTH)                                         \\
{masks} \\
\t 0xffffffffffffffffULL{closes}
#define KPROG_X86_WIDTH_BITS(WIDTH)                                         \\
{bits} \\
\t 64U{closes}
#define KPROG_X86_APPLY_WIDTH(VALUE, WIDTH) ((VALUE) & KPROG_X86_WIDTH_MASK(WIDTH))
#endif
'''
def main():
 p=argparse.ArgumentParser(); p.add_argument("--check",action="store_true"); a=p.parse_args(); ws=load()
 for path,want in ((LEAN,render_lean(ws)),(CHEADER,render_c(ws))):
  if a.check:
   if not path.is_file() or path.read_text()!=want: raise SystemExit(f"generated x86 width contract is stale: {path}")
  else: path.parent.mkdir(parents=True,exist_ok=True); path.write_text(want)
if __name__=="__main__": main()
