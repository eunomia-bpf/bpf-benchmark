#!/usr/bin/env python3
"""Generate the x86-64 `BT` / `BT_IMM` / `BT_MEM_IMM` handler-composition
contract.

`BT` (`X86_OP_BT`, `0x37`), `BT_IMM` (`X86_OP_BT_IMM`, `0x42`) and
`BT_MEM_IMM` (`X86_OP_BT_MEM_IMM`, `0x43`) are three `X86_SIM_L_EXEC` arms
sharing one result shape: test one bit and assign it to `CF`. They differ only
in where the tested base and the bit index come from, so this contract carries
per-opcode base-source and index-source tables. It pins the facts the three
bodies share and the ones that separate them:

  * all three resolve one width `FLAGS ? FLAGS : 64` and narrow the base to it
    before the bit test;
  * `BT` reads the base from a register and the index from `SRC`;
  * `BT_IMM` reads the base from a register and the index from the literal
    immediate;
  * `BT_MEM_IMM` reads the base from memory at the resolved width and the index
    from the immediate *widened to 32 bits* (a 32-bit immediate value, not the
    raw 64-bit field);
  * all three write only `CF`: no register is written.

The index-width asymmetry is binding: a `BT_MEM_IMM` that fed the raw 64-bit
immediate to the bit test (as `BT`/`BT_IMM` do) would still produce a plausible
bit but would let high immediate bits select a bit the operand does not have.

Outputs (both regenerated whole, `--check` rejects any stale copy):
  * `KProgFormal/GeneratedX86Bt.lean`
  * `generated/x86_bt.h`
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_bt_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86Bt.lean"
CHEADER = ROOT / "generated/x86_bt.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "x86Bt",
    "selector": "flags_resolved_width_then_per_opcode_base_and_index_source_"
                "then_bit_test",
    "opcodes": [
        {"name": "bt", "define": "X86_OP_BT", "code": "0x37",
         "base": "registerRead", "index": "register"},
        {"name": "btImm", "define": "X86_OP_BT_IMM", "code": "0x42",
         "base": "registerRead", "index": "immediate"},
        {"name": "btMemImm", "define": "X86_OP_BT_MEM_IMM", "code": "0x43",
         "base": "memoryRead", "index": "imm32"},
    ],
    "write_width_default": "b64",
}

OP_ORDER = ("bt", "btImm", "btMemImm")
OP_DEFINES = {"bt": "X86_OP_BT", "btImm": "X86_OP_BT_IMM",
              "btMemImm": "X86_OP_BT_MEM_IMM"}
OP_CODES = {"bt": "0x37", "btImm": "0x42", "btMemImm": "0x43"}
OP_BASES = {"bt": "registerRead", "btImm": "registerRead",
            "btMemImm": "memoryRead"}
OP_INDEXES = {"bt": "register", "btImm": "immediate", "btMemImm": "imm32"}

BASE_ORDER = ("registerRead", "memoryRead")
INDEX_ORDER = ("register", "immediate", "imm32")

WRITE_WIDTH_DEFAULT = "b64"


def load():
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 bt specification: {data!r}")
    ops = data["opcodes"]
    if [row["name"] for row in ops] != list(OP_ORDER):
        raise SystemExit(f"invalid x86 bt opcodes: {ops!r}")
    if [row["define"] for row in ops] != [OP_DEFINES[n] for n in OP_ORDER]:
        raise SystemExit(f"invalid x86 bt opcode defines: {ops!r}")
    if [row["code"] for row in ops] != [OP_CODES[n] for n in OP_ORDER]:
        raise SystemExit(f"invalid x86 bt opcode codes: {ops!r}")
    if [row["base"] for row in ops] != [OP_BASES[n] for n in OP_ORDER]:
        raise SystemExit(f"invalid x86 bt opcode bases: {ops!r}")
    if [row["index"] for row in ops] != [OP_INDEXES[n] for n in OP_ORDER]:
        raise SystemExit(f"invalid x86 bt opcode indexes: {ops!r}")
    if len({row["define"] for row in ops}) != len(ops):
        raise SystemExit(f"duplicate x86 bt opcode: {ops!r}")
    if data["write_width_default"] != WRITE_WIDTH_DEFAULT:
        raise SystemExit(f"invalid x86 bt write width default: {data!r}")
    return data


def render_lean(data, opcode_rows) -> str:
    op_ctors = "\n".join(f"  | {row['name']}" for row in opcode_rows)
    op_base_arms = "\n".join(
        f"  | .{row['name']} => .{row['base']}" for row in opcode_rows)
    op_index_arms = "\n".join(
        f"  | .{row['name']} => .{row['index']}" for row in opcode_rows)
    return f'''-- Generated by generate_x86_bt_spec.py from x86_bt_spec.json.
import Std
import KProgFormal.GeneratedX86Store
namespace KProgFormal.GeneratedX86Bt
open GeneratedX86Store (Code)
/-- The three BT opcodes this contract spans: `BT` reads its base from a
register and its index from a register, `BT_IMM` reads its base from a register
and its index from the literal immediate, `BT_MEM_IMM` reads its base from
memory and its index from the immediate widened to 32 bits. -/
inductive Op where
{op_ctors}
deriving DecidableEq, Repr
/-- Where each opcode reads the tested base. -/
inductive BaseSource where
  | registerRead
  | memoryRead
deriving DecidableEq, Repr
/-- Where each opcode reads the bit index. -/
inductive IndexSource where
  | register
  | immediate
  | imm32
deriving DecidableEq, Repr
/-- The base source each opcode uses. -/
def baseSource : Op -> BaseSource
{op_base_arms}
/-- The index source each opcode uses. -/
def indexSource : Op -> IndexSource
{op_index_arms}
/-- The width a body falls back to when its opcode carries the "absent" FLAGS
code 0. -/
def writeWidthDefault : GeneratedX86Store.Code := .{WRITE_WIDTH_DEFAULT}
/-- The resolved width: the opcode's FLAGS code itself, or 64 bits when it
carries none - the width every BT body narrows the tested base to. -/
def resolveWidth : Code -> Code
  | .absent => .b64
  | .b8 => .b8
  | .b16 => .b16
  | .b32 => .b32
  | .b64 => .b64
end KProgFormal.GeneratedX86Bt
'''


def render_c(data, opcode_rows) -> str:
    op_asserts = "\n".join(
        f'_Static_assert({row["define"]} == {row["code"]}U, '
        f'"x86 bt {row["name"]} opcode drift");'
        for row in opcode_rows)
    op_source_defines = "\n".join(
        f'#define KPROG_X86_BT_OP_{row["define"][len("X86_OP_"):]}_'
        f'BASE_SOURCE KPROG_X86_BT_BASE_'
        f'{"MEMORY" if row["base"] == "memoryRead" else "REGISTER"}\n'
        f'#define KPROG_X86_BT_OP_{row["define"][len("X86_OP_"):]}_'
        f'INDEX_SOURCE KPROG_X86_BT_INDEX_'
        f'{"REGISTER" if row["index"] == "register" else ("IMM32" if row["index"] == "imm32" else "IMMEDIATE")}'
        for row in opcode_rows)
    lines = [
        "/* Generated by generate_x86_bt_spec.py from x86_bt_spec.json. */",
        "#ifndef KPROG_FORMAL_GENERATED_X86_BT_H",
        "#define KPROG_FORMAL_GENERATED_X86_BT_H",
        "/*",
        " * x86-64 `BT` / `BT_IMM` / `BT_MEM_IMM` handler-composition contract.",
        " * All three bodies resolve one width `FLAGS ? FLAGS : 64`, narrow the",
        " * tested base to it, and assign the indexed bit to CF, writing no",
        " * register. `BT` reads the base from a register and the index from",
        " * `SRC`; `BT_IMM` reads the base from a register and the index from the",
        " * literal immediate; `BT_MEM_IMM` reads the base from memory at the",
        " * resolved width and the index from the immediate widened to 32 bits.",
        " * The contract selects the opcodes, the base source, and the index",
        " * source; the reads, the bit test, and the flag assignment stay in the",
        " * C handlers.",
        " */",
        op_asserts,
        "/* The FLAGS width codes, including the 0 \"absent\" code. */",
        "#define X86_WIDTH_8 1U",
        "#define X86_WIDTH_16 2U",
        "#define X86_WIDTH_32 4U",
        "#define X86_WIDTH_64 8U",
        "_Static_assert(X86_WIDTH_64 == 8U, \"x86 width code drift\");",
        "/* The width a body falls back to when its FLAGS code is absent. */",
        "#define KPROG_X86_BT_WRITE_WIDTH_DEFAULT X86_WIDTH_64",
        "/*",
        " * The base source and the index source of each opcode. Both are per-opcode",
        " * table entries: only the memory form reads memory, and the memory form",
        " * takes its index from the immediately-widened 32-bit value.",
        " */",
        "#define KPROG_X86_BT_BASE_REGISTER 0U",
        "#define KPROG_X86_BT_BASE_MEMORY 1U",
        "#define KPROG_X86_BT_INDEX_REGISTER 0U",
        "#define KPROG_X86_BT_INDEX_IMMEDIATE 1U",
        "#define KPROG_X86_BT_INDEX_IMM32 2U",
        op_source_defines,
        "#define KPROG_X86_BT_BASE_SOURCE(OP_IS_MEMORY) \\",
        "\t((OP_IS_MEMORY) ? KPROG_X86_BT_BASE_MEMORY : \\",
        "\t\t  KPROG_X86_BT_BASE_REGISTER)",
        "#define KPROG_X86_BT_INDEX_SOURCE(INDEX_IS_MEMORY, INDEX_IS_REGISTER) \\",
        "\t((INDEX_IS_MEMORY) ? KPROG_X86_BT_INDEX_IMM32 : \\",
        "\t ((INDEX_IS_REGISTER) ? KPROG_X86_BT_INDEX_REGISTER : \\",
        "\t  KPROG_X86_BT_INDEX_IMMEDIATE))",
        "/*",
        " * FLAGS is the opcode's width code, with 0 the \"absent\" code; the resolved",
        " * width is the code itself, or the 64-bit default when it is absent. The",
        " * tested base is narrowed to this one width.",
        " */",
        "#define KPROG_X86_BT_WRITE_WIDTH(FLAGS) \\",
        "\t((FLAGS) ? (FLAGS) : KPROG_X86_BT_WRITE_WIDTH_DEFAULT)",
        "#endif",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = load()
    opcode_rows = [{"name": n, "define": OP_DEFINES[n], "code": OP_CODES[n],
                    "base": OP_BASES[n], "index": OP_INDEXES[n]}
                   for n in OP_ORDER]
    for path, expected in ((LEAN, render_lean(data, opcode_rows)),
                           (CHEADER, render_c(data, opcode_rows))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated x86 bt contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
