#!/usr/bin/env python3
"""Render the shared AArch64 condition-code semantics for Lean and C."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parent
SPEC_PATH = ROOT / "arm64_cond_spec.json"
LEAN_PATH = ROOT / "KProgFormal" / "GeneratedArm64Cond.lean"
C_PATH = ROOT / "generated" / "arm64_cond.h"
FLAGS = {"n", "z", "c", "v"}
NAMES = ["eq", "ne", "cs", "cc", "mi", "pl", "vs", "vc",
         "hi", "ls", "ge", "lt", "gt", "le", "al"]


def validate_expr(expr: Any) -> None:
    if not isinstance(expr, dict) or not isinstance(expr.get("op"), str):
        raise SystemExit(f"invalid condition expression: {expr!r}")
    op = expr["op"]
    if op == "flag":
        if set(expr) != {"op", "name"} or expr["name"] not in FLAGS:
            raise SystemExit(f"invalid flag expression: {expr!r}")
    elif op == "const":
        if set(expr) != {"op", "value"} or not isinstance(expr["value"], bool):
            raise SystemExit(f"invalid constant expression: {expr!r}")
    elif op == "not":
        if set(expr) != {"op", "arg"}:
            raise SystemExit(f"invalid not expression: {expr!r}")
        validate_expr(expr["arg"])
    elif op in {"and", "or"}:
        if set(expr) != {"op", "args"} or not isinstance(expr["args"], list) or len(expr["args"]) != 2:
            raise SystemExit(f"invalid binary expression: {expr!r}")
        for arg in expr["args"]:
            validate_expr(arg)
    elif op in {"eq", "ne"}:
        if set(expr) != {"op", "lhs", "rhs"}:
            raise SystemExit(f"invalid comparison expression: {expr!r}")
        validate_expr(expr["lhs"])
        validate_expr(expr["rhs"])
    else:
        raise SystemExit(f"unsupported condition operation: {expr!r}")


def load_spec() -> list[dict[str, Any]]:
    spec = json.loads(SPEC_PATH.read_text())
    if set(spec) != {"schema_version", "operation", "conditions"} or \
            spec["schema_version"] != 1 or spec["operation"] != "arm64Condition":
        raise SystemExit(f"invalid AArch64 condition specification: {spec!r}")
    conditions = spec["conditions"]
    if not isinstance(conditions, list) or len(conditions) != len(NAMES):
        raise SystemExit(f"invalid AArch64 condition list: {conditions!r}")
    for code, (condition, name) in enumerate(zip(conditions, NAMES, strict=True)):
        if not isinstance(condition, dict) or set(condition) != {"name", "code", "predicate"}:
            raise SystemExit(f"invalid AArch64 condition: {condition!r}")
        if condition["name"] != name or condition["code"] != code:
            raise SystemExit(f"non-canonical AArch64 condition: {condition!r}")
        validate_expr(condition["predicate"])
    return conditions


def render_expr(expr: dict[str, Any], language: str) -> str:
    op = expr["op"]
    if op == "flag":
        return expr["name"] if language == "lean" else expr["name"].upper()
    if op == "const":
        if language == "lean":
            return "true" if expr["value"] else "false"
        return "1" if expr["value"] else "0"
    if op == "not":
        return f"(!{render_expr(expr['arg'], language)})"
    if op in {"and", "or"}:
        lhs, rhs = (render_expr(arg, language) for arg in expr["args"])
        operator = "&&" if op == "and" else "||"
        return f"({lhs} {operator} {rhs})"
    lhs = render_expr(expr["lhs"], language)
    rhs = render_expr(expr["rhs"], language)
    operator = "==" if op == "eq" else "!="
    return f"({lhs} {operator} {rhs})"


def render_lean(conditions: list[dict[str, Any]]) -> str:
    constructors = "\n".join(f"  | {condition['name']}" for condition in conditions)
    cases = "\n".join(
        f"  | .{condition['name']} => {render_expr(condition['predicate'], 'lean')}"
        for condition in conditions)
    return f"""-- Generated by generate_arm64_cond_spec.py from arm64_cond_spec.json.
import Std

namespace KProgFormal.GeneratedArm64Cond

inductive Cond
{constructors}
  deriving DecidableEq, Repr

def eval (n z c v : Bool) : Cond -> Bool
{cases}

end KProgFormal.GeneratedArm64Cond
"""


def render_c(conditions: list[dict[str, Any]]) -> str:
    assertions = "\n".join(
        f'_Static_assert(ARM64_COND_{condition["name"].upper()} == {condition["code"]}U, "AArch64 condition code drift");'
        for condition in conditions)
    case_lines = []
    for index, condition in enumerate(conditions[:-1]):
        prefix = "\t((COND)" if index == 0 else "\t (COND)"
        case_lines.append(
            f"{prefix} == ARM64_COND_{condition['name'].upper()} ? "
            f"{render_expr(condition['predicate'], 'c')} :")
    cases = " \\\n".join(case_lines)
    final = conditions[-1]
    return f"""/* Generated by generate_arm64_cond_spec.py from arm64_cond_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_COND_H
#define KPROG_FORMAL_GENERATED_ARM64_COND_H

{assertions}

#define KPROG_ARM64_EVAL_COND(COND, N, Z, C, V, UNSUPPORTED)                \\
{cases} \\
\t (COND) == ARM64_COND_{final['name'].upper()} ? {render_expr(final['predicate'], 'c')} : \\
\t ({{ UNSUPPORTED; 0; }}))

#endif
"""


def check(path: Path, expected: str) -> None:
    if not path.is_file() or path.read_text() != expected:
        raise SystemExit(f"generated AArch64 condition contract is stale: {path}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    conditions = load_spec()
    outputs = ((LEAN_PATH, render_lean(conditions)), (C_PATH, render_c(conditions)))
    if args.check:
        for path, expected in outputs:
            check(path, expected)
        return
    for path, contents in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents)


if __name__ == "__main__":
    main()
