#!/usr/bin/env python3
"""Generate the shared AArch64 memory access address-offset contract.

The generated Lean definition `GeneratedArm64MemOffset.value` and the C macro
`KPROG_ARM64_MEM_OFFSET` implement the offset the simulator adds to a memory
base register before a load/store:

  - a pre/post-indexed access contributes no immediate (the writeback already
    applied it, or applies it after), while an offset access contributes the
    immediate;
  - an indexed access additionally contributes the (already source-modified)
    index register value.

Both the C and the contract accumulate in the 64-bit two's-complement domain.
The C code adds `__s64` values, but signed two's-complement addition and
wrapping 64-bit addition produce the same bits, so the contract can state the
accumulation as `BitVec 64` addition; `KProgFormal/Arm64MemOffset.lean` records
that equivalence explicitly.

The C macro evaluates the immediate once and the (already read) index once; it
writes no NZCV.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_mem_offset_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64MemOffset.lean"
CHEADER = ROOT / "generated/arm64_mem_offset.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64MemOffset",
    "flags": [
        {"name": "offset", "prepost": False, "has_index_forms": True},
        {"name": "prepost", "prepost": True, "has_index_forms": True},
    ],
}


def load() -> dict:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 memory-offset specification: {data!r}")
    if [row["name"] for row in EXPECTED["flags"]] != ["offset", "prepost"]:
        raise SystemExit(f"invalid arm64 memory-offset order: {EXPECTED!r}")
    return EXPECTED


def render_lean(spec: dict) -> str:
    return '''-- Generated by generate_arm64_mem_offset_spec.py from arm64_mem_offset_spec.json.
import Std
namespace KProgFormal.GeneratedArm64MemOffset
/-- Shared AArch64 load/store address offset. `prepost` is true for a
pre/post-indexed access (which contributes no immediate here), `hasIndex` is true
when the addressing mode carries an index register. -/
def value (prepost hasIndex : Bool) (imm index : BitVec 64) : BitVec 64 :=
  let base := if prepost then 0 else imm
  if hasIndex then base + index else base
/-- The independent case table over the four (prepost, hasIndex) combinations. -/
def valueSpec (prepost hasIndex : Bool) (imm index : BitVec 64) : BitVec 64 :=
  match prepost, hasIndex with
  | true, true => index
  | true, false => 0
  | false, true => imm + index
  | false, false => imm
end KProgFormal.GeneratedArm64MemOffset
'''


def render_c(spec: dict) -> str:
    body = [
        "\t({",
        "\t\t__u64 __kprog_a64_mbo_imm = (IMM);",
        "\t\t__u64 __kprog_a64_mbo_index = (INDEX);",
        "\t\tint __kprog_a64_mbo_prepost = (PREPOST) ? 1 : 0;",
        "\t\tint __kprog_a64_mbo_has_index = (HAS_INDEX) ? 1 : 0;",
        "\t\t__u64 __kprog_a64_mbo_base =",
        "\t\t\t__kprog_a64_mbo_prepost ? 0ULL : __kprog_a64_mbo_imm;",
        "\t\t__u64 __kprog_a64_mbo_result = __kprog_a64_mbo_base;",
        "",
        "\t\tif (__kprog_a64_mbo_has_index)",
        "\t\t\t__kprog_a64_mbo_result = __kprog_a64_mbo_base +",
        "\t\t\t\t__kprog_a64_mbo_index;",
        "\t\t__kprog_a64_mbo_result;",
        "\t})",
    ]
    continued = " \\\n".join(body)
    return f'''/* Generated by generate_arm64_mem_offset_spec.py from arm64_mem_offset_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_MEM_OFFSET_H
#define KPROG_FORMAL_GENERATED_ARM64_MEM_OFFSET_H
/*
 * AArch64 load/store address offset: a pre/post-indexed access contributes no
 * immediate here (its writeback applies it separately), an offset access
 * contributes the immediate, and an indexed access adds the index register.
 * The accumulation is 64-bit two's-complement wrapping, which is the same bit
 * pattern as the C code's signed `__s64` addition.
 */
/*
 * PREPOST and HAS_INDEX are booleans; IMM and INDEX are the 64-bit immediate
 * and (already source-modified) index register value. IMM and INDEX are each
 * evaluated exactly once and no NZCV is written. The result is the raw 64-bit
 * offset; the caller adds it to the base register.
 */
#define KPROG_ARM64_MEM_OFFSET(PREPOST, HAS_INDEX, IMM, INDEX)              \\
{continued}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = load()
    for path, expected in ((LEAN, render_lean(spec)), (CHEADER, render_c(spec))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 memory-offset contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
