#!/usr/bin/env python3
"""Generate the shared AArch64 ORN (complemented logical OR) contract.

The generated Lean definition `GeneratedArm64Orn.value` and the C macro
`KPROG_ARM64_ORN_VALUE` implement the one AArch64 ORN value the simulator
applies to a source register pair: the logical OR of the first source with the
bitwise complement of the (already source-modified) second source.

  - lhs | ~rhs

The result is narrowed to the destination width (ARM64_WIDTH_32 or
ARM64_WIDTH_64), exactly the step `ARM64_SIM_L_WRITE_REG_WIDTH` performs on the
value the C macro produces. The contract therefore carries the
`ARM64_OP_ORN_REG` opcode number, which `load()` re-checks against
native-sim/arm64/arm64_sim.h. The right-hand source modification (the eleven-arm
`KPROG_ARM64_MOD_VALUE` contract) is applied by the caller before this value, so
this contract's independent statement is the De Morgan complement form of the
OR of the first source with the bitwise complement of the second.

The C macro evaluates the two sources exactly once and writes no NZCV; the
result is the width-narrowed 64-bit value the caller stores back into the
destination.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_orn_spec.json"
SIM_HEADER = ROOT.parent / "arm64/arm64_sim.h"
LEAN = ROOT / "KProgFormal/GeneratedArm64Orn.lean"
CHEADER = ROOT / "generated/arm64_orn.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64Orn",
    "operations": [
        {"name": "orn_reg", "code": 53, "macro": "ARM64_OP_ORN_REG"},
    ],
}

OPCODE_DEFINE = re.compile(
    r"^#define\s+(ARM64_OP_[A-Z0-9_]+)\s+0x([0-9a-fA-F]+)U\s*$", re.M)

# The C arm computes the raw 64-bit value; the destination narrowing is applied
# afterwards through KPROG_ARM64_WIDTH_MASK, so the macro result is exactly what
# WRITE_REG_WIDTH would store.
C_BODY = "\t\t\t__kprog_a64_orn_result = " \
         "(__kprog_a64_orn_lhs | ~__kprog_a64_orn_rhs) & " \
         "__kprog_a64_orn_wmask;"


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 orn specification: {data!r}")
    ops = EXPECTED["operations"]
    names = [row["name"] for row in ops]
    if names != ["orn_reg"]:
        raise SystemExit(f"invalid arm64 orn order: {ops!r}")
    if [row["macro"] for row in ops] != [
            "ARM64_OP_" + row["name"].upper() for row in ops]:
        raise SystemExit(f"invalid arm64 orn macros: {ops!r}")
    opcodes = {name: int(value, 16)
               for name, value in OPCODE_DEFINE.findall(SIM_HEADER.read_text())}
    if not opcodes:
        raise SystemExit(
            f"no ARM64_OP_* opcode definitions found in {SIM_HEADER}")
    for row in ops:
        if opcodes.get(row["macro"]) != row["code"]:
            raise SystemExit(
                "arm64 orn opcodes drift from native-sim/arm64/"
                f"arm64_sim.h: spec={row['macro']}={row['code']:#x} "
                f"sim={row['macro']}={opcodes.get(row['macro'])}")
    return ops


def render_lean(ops: list[dict]) -> str:
    ctors = "\n".join(f"  | {row['name']}" for row in ops)
    codes = "\n".join(f"  | .{row['name']} => {row['code']}" for row in ops)
    mnemonics = "\n".join(
        f"  | .{row['name']} => \"ORN\"" for row in ops)
    arms = "\n".join(
        "  | .orn_reg =>\n"
        "    narrow (lhs ||| ~~~rhs) width" for row in ops)
    return f'''-- Generated by generate_arm64_orn_spec.py from arm64_orn_spec.json.
import Init.Data.BitVec
import KProgFormal.GeneratedArm64Width
namespace KProgFormal.GeneratedArm64Orn
open KProgFormal.GeneratedArm64Width (Width narrow)
/-- The AArch64 complemented-logical-OR value the simulator applies to a source
register pair. -/
inductive Orn where
{ctors}
deriving DecidableEq, Repr
/-- The ARM64_OP_* opcode number the value carries in arm64_sim.h. -/
def code : Orn -> Nat
{codes}
/-- The AArch64 mnemonic of the value. -/
def mnemonic : Orn -> String
{mnemonics}
/-- Shared AArch64 ORN value, narrowed to the destination width. `lhs` is the
first source and `rhs` the (already source-modified) second source; the arm is
the OR of `lhs` with the bitwise complement of `rhs`. `narrow` keeps only the
low `bits width` lanes, exactly the C `& __kprog_a64_orn_wmask` step. -/
def value (op : Orn) (lhs rhs : BitVec 64) (width : Width) : BitVec 64 :=
  match op with
{arms}
/-- The ORN handler writes no NZCV, so the flag state threads through
unchanged. -/
def flagsUnchanged (op : Orn) : Bool :=
  match op with
  | .orn_reg => true
end KProgFormal.GeneratedArm64Orn
'''


def render_c(ops: list[dict]) -> str:
    codes = "\n".join(
        f"_Static_assert({row['macro']} == {row['code']}U, "
        '"arm64 orn code drift");'
        for row in ops)
    handled = " || \\\n\t".join(
        f"((OP) == {row['macro']})" for row in ops)
    coverage = "\n".join(
        f"_Static_assert(KPROG_ARM64_ORN_HANDLED({row['macro']}), "
        '"arm64 orn coverage drift");'
        for row in ops)
    body = [
        "\t({",
        "\t\t__u64 __kprog_a64_orn_op = (OP);",
        "\t\t__u64 __kprog_a64_orn_lhs = (LHS);",
        "\t\t__u64 __kprog_a64_orn_rhs = (RHS);",
        "\t\t__u64 __kprog_a64_orn_width = (WIDTH);",
        "\t\t__u64 __kprog_a64_orn_wmask = "
        "KPROG_ARM64_WIDTH_MASK(__kprog_a64_orn_width);",
        "\t\t__u64 __kprog_a64_orn_result = 0;",
        "",
        "\t\tswitch (__kprog_a64_orn_op) {",
    ]
    for row in ops:
        body.append(f"\t\tcase {row['code']}U:                          ")
        body.append(C_BODY)
        body.append("\t\t\tbreak;")
    body += [
        "\t\tdefault:",
        "\t\t\tUNSUPPORTED;",
        "\t\t\tbreak;",
        "\t\t}",
        "\t\t__kprog_a64_orn_result;",
        "\t})",
    ]
    continued = " \\\n".join(body)
    return f'''/* Generated by generate_arm64_orn_spec.py from arm64_orn_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_ORN_H
#define KPROG_FORMAL_GENERATED_ARM64_ORN_H
/*
 * The one arm is the AArch64 complemented logical OR (ORN): the OR of the first
 * source with the bitwise complement of the already source-modified second
 * source. The result is masked to the destination width, exactly the narrowing
 * the caller's register write performs. The complement is inlined, so this
 * header calls no hand-written helper. An opcode outside the family reaches the
 * caller-supplied unsupported arm.
 */
#include "arm64_width.h"
{codes}
#define KPROG_ARM64_ORN_HANDLED(OP)                                         \\
\t({handled})
{coverage}
/*
 * The numeric case label 53U tracks the ARM64_OP_ORN_REG value defined in
 * native-sim/arm64/arm64_sim.h. OP is the opcode, LHS the first source register
 * contents, RHS the second source register contents (the caller has applied any
 * source modifier), and WIDTH the destination width code. LHS and RHS are each
 * evaluated exactly once and no arm writes NZCV. The result is the
 * width-narrowed raw 64-bit value the caller writes back.
 */
#define KPROG_ARM64_ORN_VALUE(OP, LHS, RHS, WIDTH, UNSUPPORTED)             \\
{continued}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    ops = load()
    for path, expected in ((LEAN, render_lean(ops)), (CHEADER, render_c(ops))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 orn contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
