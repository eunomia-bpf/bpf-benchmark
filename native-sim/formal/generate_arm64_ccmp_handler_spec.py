#!/usr/bin/env python3
"""Generate the shared AArch64 CCMP flag-state transition for C and Lean."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_ccmp_handler_spec.json"
COND_SPEC = ROOT / "arm64_cond_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64CcmpHandler.lean"
CHEADER = ROOT / "generated/arm64_ccmp_handler.h"
EXPECTED = {
    "schema_version": 1,
    "operation": "arm64ConditionalCompare",
    "condition_source": "incoming_nzcv",
    "true_path": "sub_flags",
    "false_path": {"n": 3, "z": 2, "c": 1, "v": 0},
    "preserves_registers": True,
}


def load() -> dict[str, int]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 CCMP handler specification: {data!r}")
    cond = json.loads(COND_SPEC.read_text())
    codes = [row.get("code") for row in cond.get("conditions", [])]
    if codes != list(range(15)):
        raise SystemExit(f"arm64 CCMP condition table is not canonical: {codes!r}")
    return data["false_path"]


def render_lean(bits: dict[str, int]) -> str:
    flag_rows = "\n".join(
        f"    {name} := (nzcv &&& {1 << bit:#x}) != 0" +
        ("," if name != "v" else "")
        for name, bit in bits.items())
    return f'''-- Generated by generate_arm64_ccmp_handler_spec.py from arm64_ccmp_handler_spec.json.
import KProgFormal.GeneratedArm64Cond
import KProgFormal.GeneratedArm64Flags

namespace KProgFormal.GeneratedArm64CcmpHandler

structure Step where
  flags : GeneratedArm64Flags.Flags
  deriving DecidableEq, Repr

def fallbackFlags (nzcv : BitVec 8) : GeneratedArm64Flags.Flags :=
  {{
{flag_rows} }}

def apply (incoming : GeneratedArm64Flags.Flags)
    (cond : GeneratedArm64Cond.Cond) (lhs rhs : BitVec 64)
    (width : GeneratedArm64Width.Width) (fallback : BitVec 8) : Step :=
  if GeneratedArm64Cond.eval incoming.n incoming.z incoming.c incoming.v cond then
    {{ flags := GeneratedArm64Flags.applySub lhs rhs width }}
  else
    {{ flags := fallbackFlags fallback }}

end KProgFormal.GeneratedArm64CcmpHandler
'''


def render_c(bits: dict[str, int]) -> str:
    assignments = "\n".join(
        f"\t\t\t(C_{name.upper()}) = (__kprog_a64_ccmp_fallback >> {bit}) & 1U; \\"
        for name, bit in bits.items())
    return f'''/* Generated by generate_arm64_ccmp_handler_spec.py from arm64_ccmp_handler_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_CCMP_HANDLER_H
#define KPROG_FORMAL_GENERATED_ARM64_CCMP_HANDLER_H

#define KPROG_ARM64_EXEC_CCMP(COND, FALLBACK, C_N, C_Z, C_C, C_V, LHS, RHS, WIDTH, UNSUPPORTED) \\
\tdo {{ \\
\t\tif (KPROG_ARM64_EVAL_COND((COND), (C_N), (C_Z), (C_C), (C_V), UNSUPPORTED)) {{ \\
\t\t\tKPROG_ARM64_SET_SUB_FLAGS((C_N), (C_Z), (C_C), (C_V), (LHS), (RHS), (WIDTH)); \\
\t\t}} else {{ \\
\t\t\t__u8 __kprog_a64_ccmp_fallback = (FALLBACK); \\
{assignments}
\t\t}} \\
\t}} while (0)

#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    bits = load()
    for path, expected in ((LEAN, render_lean(bits)),
                           (CHEADER, render_c(bits))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 CCMP handler contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
