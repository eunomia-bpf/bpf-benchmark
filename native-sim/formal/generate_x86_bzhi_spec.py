#!/usr/bin/env python3
"""Generate the x86-64 `BZHI` / `BZHI_MEM` handler-composition contract.

The module pins the two `X86_SIM_L_EXEC_BZHI` / `X86_SIM_L_EXEC_BZHI_MEM`
handler bodies (`x86_sim_local_bpf.h`) at the level this line machine-checks:
the FLAGS-resolved width both share (`FLAGS ? FLAGS : 64`), and the per-opcode
fact that selects each body's two inputs. `BZHI` reads its value from `SRC` and
its bit count from `X86_SIM_L_READ_REG(COUNT) & 0xff`; `BZHI_MEM` reads its
value from memory at the *resolved width* (not a second AUX width, unlike
`ANDN_MEM`) and its count from the register named by
`X86_REG_AUX_GET_SRC_SHIFT(AUX) & 0xff`, with the count byte-masked to 0xff.

Outputs, from `x86_bzhi_spec.json` (schema_version 1):
  * `KProgFormal/GeneratedX86Bzhi.lean` — the opcode/source/value/count tables.
  * `generated/x86_bzhi.h` — the C contract macros.

`--check` rejects a stale generated file instead of rewriting it, so the
`make check` target fails when a generator or its JSON drift.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_bzhi_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86Bzhi.lean"
CHEADER = ROOT / "generated/x86_bzhi.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "x86Bzhi",
    "selector": "flags_resolved_width_then_per_opcode_value_and_count_source_"
                "then_masked_bit_clear",
    "opcodes": [
        {"name": "bzhi", "define": "X86_OP_BZHI", "code": "0x34",
         "value": "registerRead", "count": "register"},
        {"name": "bzhiMem", "define": "X86_OP_BZHI_MEM", "code": "0x35",
         "value": "memoryRead", "count": "auxShift"},
    ],
    "write_width_default": "b64",
    "count_mask": "0xff",
}

OP_ORDER = ("bzhi", "bzhiMem")
OP_DEFINES = {"bzhi": "X86_OP_BZHI", "bzhiMem": "X86_OP_BZHI_MEM"}
OP_CODES = {"bzhi": "0x34", "bzhiMem": "0x35"}
OP_VALUES = {"bzhi": "registerRead", "bzhiMem": "memoryRead"}
OP_COUNTS = {"bzhi": "register", "bzhiMem": "auxShift"}

VALUE_ORDER = ("registerRead", "memoryRead")
COUNT_ORDER = ("register", "auxShift")

WRITE_WIDTH_DEFAULT = "b64"
COUNT_MASK = "0xff"


def load():
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 bzhi specification: {data!r}")
    ops = data["opcodes"]
    if [row["name"] for row in ops] != list(OP_ORDER):
        raise SystemExit(f"invalid x86 bzhi opcodes: {ops!r}")
    if [row["define"] for row in ops] != [OP_DEFINES[n] for n in OP_ORDER]:
        raise SystemExit(f"invalid x86 bzhi opcode defines: {ops!r}")
    if [row["code"] for row in ops] != [OP_CODES[n] for n in OP_ORDER]:
        raise SystemExit(f"invalid x86 bzhi opcode codes: {ops!r}")
    if [row["value"] for row in ops] != [OP_VALUES[n] for n in OP_ORDER]:
        raise SystemExit(f"invalid x86 bzhi opcode values: {ops!r}")
    if [row["count"] for row in ops] != [OP_COUNTS[n] for n in OP_ORDER]:
        raise SystemExit(f"invalid x86 bzhi opcode counts: {ops!r}")
    if len({row["define"] for row in ops}) != len(ops):
        raise SystemExit(f"duplicate x86 bzhi opcode: {ops!r}")
    if data["write_width_default"] != WRITE_WIDTH_DEFAULT:
        raise SystemExit(f"invalid x86 bzhi write width default: {data!r}")
    if data["count_mask"] != COUNT_MASK:
        raise SystemExit(f"invalid x86 bzhi count mask: {data!r}")
    return data


def render_lean(data, opcode_rows) -> str:
    op_ctors = "\n".join(f"  | {row['name']}" for row in opcode_rows)
    op_value_arms = "\n".join(
        f"  | .{row['name']} => .{row['value']}" for row in opcode_rows)
    op_count_arms = "\n".join(
        f"  | .{row['name']} => .{row['count']}" for row in opcode_rows)
    return f'''-- Generated by generate_x86_bzhi_spec.py from x86_bzhi_spec.json.
import Std
import KProgFormal.GeneratedX86Store
namespace KProgFormal.GeneratedX86Bzhi
open GeneratedX86Store (Code)
/-- The two BZHI opcodes this contract spans: `BZHI` reads its value from a
register and its count from a register, `BZHI_MEM` reads its value from memory
and its count from the register the AUX shift byte names. -/
inductive Op where
{op_ctors}
deriving DecidableEq, Repr
/-- Where each opcode reads its value (the bit source). -/
inductive ValueSource where
  | registerRead
  | memoryRead
deriving DecidableEq, Repr
/-- Where each opcode reads its bit count. -/
inductive CountSource where
  | register
  | auxShift
deriving DecidableEq, Repr
/-- The value source each opcode uses. -/
def valueSource : Op -> ValueSource
{op_value_arms}
/-- The count source each opcode uses. -/
def countSource : Op -> CountSource
{op_count_arms}
/-- The width a body falls back to when its opcode carries the "absent" FLAGS
code 0. -/
def writeWidthDefault : GeneratedX86Store.Code := .{WRITE_WIDTH_DEFAULT}
/-- The resolved width: the opcode's FLAGS code itself, or 64 bits when it
carries none - the width both the value read and the destination write of a
BZHI body use. -/
def resolveWidth : Code -> Code
  | .absent => .b64
  | .b8 => .b8
  | .b16 => .b16
  | .b32 => .b32
  | .b64 => .b64
end KProgFormal.GeneratedX86Bzhi
'''


def render_c(data, opcode_rows) -> str:
    op_asserts = "\n".join(
        f'_Static_assert({row["define"]} == {row["code"]}U, '
        f'"x86 bzhi {row["name"]} opcode drift");'
        for row in opcode_rows)
    op_source_defines = "\n".join(
        f'#define KPROG_X86_BZHI_OP_{row["define"][len("X86_OP_"):]}_'
        f'VALUE_SOURCE KPROG_X86_BZHI_VALUE_'
        f'{"MEMORY" if row["value"] == "memoryRead" else "REGISTER"}\n'
        f'#define KPROG_X86_BZHI_OP_{row["define"][len("X86_OP_"):]}_'
        f'COUNT_SOURCE KPROG_X86_BZHI_COUNT_'
        f'{"AUX_SHIFT" if row["count"] == "auxShift" else "REGISTER"}'
        for row in opcode_rows)
    lines = [
        "/* Generated by generate_x86_bzhi_spec.py from x86_bzhi_spec.json. */",
        "#ifndef KPROG_FORMAL_GENERATED_X86_BZHI_H",
        "#define KPROG_FORMAL_GENERATED_X86_BZHI_H",
        "/*",
        " * x86-64 `BZHI` / `BZHI_MEM` handler-composition contract. Both bodies",
        " * resolve one width `FLAGS ? FLAGS : 64` and use it for *both* the value",
        " * read and the destination write, clear the bits at or above the",
        " * byte-masked count, and derive CF from whether the count reached the",
        " * width with SF=0 and ZF the zero test of the cleared value. `BZHI` reads",
        " * the value from `SRC` and the count from `COUNT`; `BZHI_MEM` reads the",
        " * value from memory at the resolved width and the count from the register",
        " * the AUX shift byte names. The contract selects the opcodes, the value",
        " * source, and the count source; the reads, the masked bit-clear, the flag",
        " * production, and the register writeback stay in the C handlers.",
        " */",
        op_asserts,
        "/* The FLAGS width codes, including the 0 \"absent\" code. */",
        "#define X86_WIDTH_8 1U",
        "#define X86_WIDTH_16 2U",
        "#define X86_WIDTH_32 4U",
        "#define X86_WIDTH_64 8U",
        "_Static_assert(X86_WIDTH_64 == 8U, \"x86 width code drift\");",
        "/* The width a body falls back to when its FLAGS code is absent. */",
        "#define KPROG_X86_BZHI_WRITE_WIDTH_DEFAULT X86_WIDTH_64",
        "/*",
        " * The value source and the count source of each opcode. Both are per-opcode",
        " * table entries: only the memory form reads memory, and only the memory",
        " * form takes its count from the AUX shift byte rather than `COUNT`.",
        " */",
        "#define KPROG_X86_BZHI_VALUE_REGISTER 0U",
        "#define KPROG_X86_BZHI_VALUE_MEMORY 1U",
        "#define KPROG_X86_BZHI_COUNT_REGISTER 0U",
        "#define KPROG_X86_BZHI_COUNT_AUX_SHIFT 1U",
        op_source_defines,
        "#define KPROG_X86_BZHI_VALUE_SOURCE(OP_IS_MEMORY) \\",
        "\t((OP_IS_MEMORY) ? KPROG_X86_BZHI_VALUE_MEMORY : \\",
        "\t\t  KPROG_X86_BZHI_VALUE_REGISTER)",
        "#define KPROG_X86_BZHI_COUNT_SOURCE(OP_IS_MEMORY) \\",
        "\t((OP_IS_MEMORY) ? KPROG_X86_BZHI_COUNT_AUX_SHIFT : \\",
        "\t\t  KPROG_X86_BZHI_COUNT_REGISTER)",
        "/*",
        " * FLAGS is the opcode's width code, with 0 the \"absent\" code; the resolved",
        " * width is the code itself, or the 64-bit default when it is absent. Both",
        " * the value read and the destination write use this one width.",
        " */",
        "#define KPROG_X86_BZHI_WRITE_WIDTH(FLAGS) \\",
        "\t((FLAGS) ? (FLAGS) : KPROG_X86_BZHI_WRITE_WIDTH_DEFAULT)",
        "/* The bit count is byte-masked, as both bodies mask it. */",
        "#define KPROG_X86_BZHI_COUNT_MASK 0xffULL",
        "#endif",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = load()
    opcode_rows = [{"name": n, "define": OP_DEFINES[n], "code": OP_CODES[n],
                    "value": OP_VALUES[n], "count": OP_COUNTS[n]}
                   for n in OP_ORDER]
    for path, expected in ((LEAN, render_lean(data, opcode_rows)),
                           (CHEADER, render_c(data, opcode_rows))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated x86 bzhi contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
