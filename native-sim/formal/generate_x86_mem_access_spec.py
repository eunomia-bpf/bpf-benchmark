#!/usr/bin/env python3
"""Generate the shared x86 little-endian memory load/store byte contract."""
import argparse, json
from pathlib import Path
ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_mem_access_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86MemAccess.lean"
C_HEADER = ROOT / "generated/x86_mem_access.h"
EXPECTED = {
    "schema_version": 1,
    "operation": "x86MemAccess",
    "endianness": "little",
    "width_rule": "zero_is_64",
    "load": "assemble_width_bytes_little_endian_then_narrow",
    "store": "mask_value_then_write_width_bytes_little_endian",
    "byte_rule": "byte_i_is_bits_8i_to_8i_plus_8",
    "widths": [
        {"name": "w8", "bits": 8, "bytes": 1, "mask": "0xff"},
        {"name": "w16", "bits": 16, "bytes": 2, "mask": "0xffff"},
        {"name": "w32", "bits": 32, "bytes": 4, "mask": "0xffffffff"},
        {"name": "w64", "bits": 64, "bytes": 8, "mask": "0xffffffffffffffff"},
    ],
}


def load() -> list:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 memory-access specification: {data!r}")
    return data["widths"]


def render_lean(ws) -> str:
    counts = "\n".join(f"  | .{w['name']} => {w['bytes']}" for w in ws)
    # assemble is a left-folded BitVec.or of byte i shifted left by 8*i.
    def assemble_body(w) -> str:
        terms = [
            f"BitVec.shiftLeft (BitVec.setWidth 64 (byte {i})) {8 * i}"
            for i in range(w["bytes"])
        ]
        expr = terms[0]
        for t in terms[1:]:
            expr = f"BitVec.or ({expr}) ({t})"
        return f"    {expr}"
    assemble_cases = "\n".join(
        f"  | .{w['name']} =>\n{assemble_body(w)}" for w in ws
    )
    return f'''-- Generated by generate_x86_mem_access_spec.py from x86_mem_access_spec.json.
import KProgFormal.GeneratedX86Width
namespace KProgFormal.GeneratedX86MemAccess
/-- Number of little-endian bytes an access of the given width touches. -/
def byteCount : GeneratedX86Width.Width -> Nat
{counts}
/-- Assemble the width's little-endian bytes into a 64-bit value. Only
`byteCount width` bytes are read; the value is then narrowed by `load`. -/
def assemble (byte : Nat -> BitVec 8) : GeneratedX86Width.Width -> BitVec 64
{assemble_cases}
/-- Load: assemble the width's little-endian bytes, then narrow to the width
mask so bytes above the access width cannot contribute. -/
def load (byte : Nat -> BitVec 8) (width : GeneratedX86Width.Width) :
    BitVec 64 :=
  BitVec.and (assemble byte width) (GeneratedX86Width.mask width)
/-- The `i`-th little-endian byte of a width-narrowed value. -/
def storeByte (value : BitVec 64) (width : GeneratedX86Width.Width)
    (i : Nat) : BitVec 8 :=
  BitVec.setWidth 8
    (BitVec.ushiftRight (BitVec.and value (GeneratedX86Width.mask width))
      (8 * i))
/-- Store: the byte a width-masked value places at index `i`. -/
def store (value : BitVec 64) (width : GeneratedX86Width.Width)
    (i : Nat) : BitVec 8 :=
  storeByte value width i
end KProgFormal.GeneratedX86MemAccess
'''


def render_c(ws) -> str:
    load_branches = []
    store_branches = []
    for w in ws:
        if w["bytes"] == 1:
            load_branches.append(
                f"\t\tif (__x86_mem_width == X86_WIDTH_{w['bits']})           \\\n"
                f"\t\t\t__x86_mem_value = (__u64)(__x86_mem_addr[0]);      \\")
            store_branches.append(
                f"\t\tif (__x86_mem_width == X86_WIDTH_{w['bits']})           \\\n"
                f"\t\t\t*(__u8 *)__x86_mem_addr = (__u8)__x86_mem_value;  \\")
        elif w["bytes"] == 8:
            load_branches.append(
                f"\t\tif (__x86_mem_width == X86_WIDTH_{w['bits']}) {{         \\")
            load_branches += [
                f"\t\t\t__x86_mem_value |=                                       \\\n"
                f"\t\t\t\t(__u64)(__x86_mem_addr[{i}]) << {8 * i};           \\"
                for i in range(w["bytes"])]
            load_branches.append("\t\t}                                                       \\")
            store_branches.append(
                f"\t\tif (__x86_mem_width == X86_WIDTH_{w['bits']}) {{         \\")
            store_branches += [
                f"\t\t\t__x86_mem_addr[{i}] =                                      \\\n"
                f"\t\t\t\t(__u8)(__x86_mem_value >> {8 * i});                 \\"
                for i in range(w["bytes"])]
            store_branches.append("\t\t}                                                       \\")
        else:
            load_branches.append(
                f"\t\tif (__x86_mem_width == X86_WIDTH_{w['bits']}) {{         \\")
            load_branches += [
                f"\t\t\t__x86_mem_value |= (__u64)(__x86_mem_addr[{i}]) << {8 * i};\t\\"
                for i in range(w["bytes"])]
            load_branches.append("\t\t}                                                       \\")
            store_branches.append(
                f"\t\tif (__x86_mem_width == X86_WIDTH_{w['bits']}) {{         \\")
            store_branches += [
                f"\t\t\t__x86_mem_addr[{i}] = (__u8)(__x86_mem_value >> {8 * i});\t\\"
                for i in range(w["bytes"])]
            store_branches.append("\t\t}                                                       \\")
    load_body = "\n".join(load_branches)
    store_body = "\n".join(store_branches)
    return f'''/* Generated by generate_x86_mem_access_spec.py from x86_mem_access_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_MEM_ACCESS_H
#define KPROG_FORMAL_GENERATED_X86_MEM_ACCESS_H
#define KPROG_X86_MEM_LOAD(ADDR, WIDTH)                                    \\
\t({{                                                                 \\
\t\tvolatile const __u8 *__x86_mem_addr =                            \\
\t\t\t(volatile const __u8 *)(ADDR);                            \\
\t\t__u8 __x86_mem_width = (WIDTH) ? (WIDTH) : X86_WIDTH_64;          \\
\t\t__u64 __x86_mem_value = (__u64)(__x86_mem_addr[0]);               \\
{load_body}
\t\t__x86_mem_value;                                            \\
\t}})
#define KPROG_X86_MEM_STORE(ADDR, WIDTH, VALUE)                            \\
\tdo {{                                                              \\
\t\t__u8 *__x86_mem_addr = (__u8 *)(ADDR);                            \\
\t\t__u8 __x86_mem_width = (WIDTH) ? (WIDTH) : X86_WIDTH_64;          \\
\t\t__u64 __x86_mem_value =                                            \\
\t\t\t(VALUE) & KPROG_X86_WIDTH_MASK(__x86_mem_width);           \\
{store_body}
\t}} while (0)
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    ws = load()
    for path, expected in ((LEAN, render_lean(ws)), (C_HEADER, render_c(ws))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(f"generated x86 memory-access contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
