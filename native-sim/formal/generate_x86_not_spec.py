#!/usr/bin/env python3
"""Generate the shared x86 NOT result and flag-preservation contract."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_not_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86Not.lean"
C_HEADER = ROOT / "generated/x86_not.h"
EXPECTED = {
    "schema_version": 1,
    "operation": "x86Not",
    "result": {"op": "bit_not", "input": "value"},
    "flags": {"op": "preserve", "inputs": ["cf", "zf", "sf", "of"]},
}


def load() -> None:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 NOT specification: {data!r}")


def render_lean() -> str:
    return '''-- Generated by generate_x86_not_spec.py from x86_not_spec.json.
import Std
namespace KProgFormal.GeneratedX86Not
structure Flags where
  cf : Bool
  zf : Bool
  sf : Bool
  of : Bool
  deriving DecidableEq, Repr
def result (value : BitVec 64) : BitVec 64 := BitVec.not value
def flags (cf zf sf of : Bool) : Flags :=
  { cf := cf, zf := zf, sf := sf, of := of }
end KProgFormal.GeneratedX86Not
'''


def render_c() -> str:
    return '''/* Generated by generate_x86_not_spec.py from x86_not_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_NOT_H
#define KPROG_FORMAL_GENERATED_X86_NOT_H
#define KPROG_X86_NOT_RESULT(VALUE) (~(VALUE))
#define KPROG_X86_PRESERVE_FLAGS() do { (void)0; } while (0)
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    load()
    for path, expected in ((LEAN, render_lean()), (C_HEADER, render_c())):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(f"generated x86 NOT contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
