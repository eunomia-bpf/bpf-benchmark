#!/usr/bin/env python3
"""Generate the packed AArch64 AUX word layout for Lean and C.

Every AArch64 simulator opcode carries a 32-bit AUX word whose four bytes are
fixed by this contract:

  bits  0-7  ALU opcode / memory index register / bitfield kind
  bits  8-15 source modifier / bitfield LSB / CCMP NZCV
  bits 16-23 shift amount / bitfield width / MOVK column
  bits 24-31 memory flags (`ARM64_MEM_PRE` / `ARM64_MEM_POST`)

The bytes are packed little-endian, so lane `k` occupies bits `8k`-`8k+7` and
the layout is never wider than the 32-bit word. The generator emits:

  - a Lean `GeneratedArm64Aux` module whose `pack` is the C-shaped masked-or
    expression and whose four lane decoders are byte extractions, plus the
    `regNone` sentinel; and
  - the C `KPROG_ARM64_AUX` packer and the four `KPROG_ARM64_AUX_B0..B3`
    decoders that `arm64/arm64_sim.h` aliases its `ARM64_AUX*` packers to and
    that `arm64/arm64_sim_local_bpf.h` aliases its `ARM64_SIM_L_*` decoders to,
    so the ALU-opcode, source-modifier, shift, memory-index, memory-flag,
    bitfield, and CCMP fields all share one machine-checked layout.

`KProgFormal/Arm64Aux.lean` proves the C-shaped packer equal to an independent
byte-concatenation specification, pins the canonical byte order, proves each
lane's roundtrip, the sentinel roundtrip, that the four lanes are pairwise
non-interfering, and the per-interpretation aliasing facts (lane 1 is the
source modifier, the bitfield LSB and the CCMP NZCV; lane 2 is the ALU
modifier's shift amount, the bitfield width and the MOVK column). The shift
*kind* of `ARM64_OP_SHIFT_*` is a lane-0 byte shared with the ALU opcode.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_aux_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64Aux.lean"
CHEADER = ROOT / "generated/arm64_aux.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64Aux",
    "word_bits": 32,
    "field_bits": 8,
    "lanes": [
        {"name": "b0", "shift": 0},
        {"name": "b1", "shift": 8},
        {"name": "b2", "shift": 16},
        {"name": "b3", "shift": 24},
    ],
    "reg_none": "0xff",
}


def load() -> dict:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 aux specification: {data!r}")
    if [lane["shift"] for lane in EXPECTED["lanes"]] != [0, 8, 16, 24]:
        raise SystemExit("invalid arm64 aux lane shifts")
    return EXPECTED


def render_lean(spec: dict) -> str:
    word = spec["word_bits"]
    width = spec["field_bits"]
    lanes = spec["lanes"]
    args = " ".join(lane["name"] for lane in lanes)
    # C-shaped packer: mask each lane and OR its shifted byte into place.
    expr = f"BitVec.and {lanes[0]['name']} 0xff"
    for lane in lanes[1:]:
        name = lane["name"]
        shift = lane["shift"]
        expr = (f"BitVec.or ({expr})\n"
                f"    (BitVec.shiftLeft (BitVec.and {name} 0xff) {shift})")
    decoders = []
    for lane in lanes:
        name = lane["name"]
        shift = lane["shift"]
        if shift == 0:
            decoders.append(
                f"def {name} (aux : BitVec {word}) : BitVec {word} :=\n"
                f"  BitVec.and aux 0xff")
        else:
            decoders.append(
                f"def {name} (aux : BitVec {word}) : BitVec {word} :=\n"
                f"  BitVec.and (aux >>> {shift}) 0xff")
    decoder_text = "\n".join(decoders)
    return f'''-- Generated by generate_arm64_aux_spec.py from arm64_aux_spec.json.
import Std
namespace KProgFormal.GeneratedArm64Aux
/-- Pack the four {width}-bit AUX lane bytes little-endian: lane 0 (ALU opcode /
memory index / bitfield kind) in bits 0-7, lane 1 (source modifier / bitfield
LSB / CCMP NZCV) in bits 8-15, lane 2 (shift / bitfield width / MOVK column) in
bits 16-23, and the memory-flag byte in bits 24-31. Each argument is masked to
its byte first. -/
def pack ({args} : BitVec {word}) : BitVec {word} :=
  {expr}
{decoder_text}
/-- The memory-index lane value that means "no index register"
(`ARM64_REG_NONE`). -/
def regNone : BitVec {word} := {spec["reg_none"]}
end KProgFormal.GeneratedArm64Aux
'''


def render_c(spec: dict) -> str:
    lanes = spec["lanes"]
    args = ", ".join(lane["name"].upper() for lane in lanes)
    terms = []
    for lane in lanes:
        name = lane["name"].upper()
        shift = lane["shift"]
        term = f"((__u32)({name}) & 0xffU)"
        if shift:
            term = f"({term} << {shift})"
        terms.append(term)
    packer = " | \\\n\t ".join(terms)
    decoders = []
    for lane in lanes:
        name = lane["name"].upper()
        shift = lane["shift"]
        if shift == 0:
            decoders.append(
                f"#define KPROG_ARM64_AUX_{name}(AUX) "
                f"((__u8)((AUX) & 0xffU))")
        else:
            decoders.append(
                f"#define KPROG_ARM64_AUX_{name}(AUX) "
                f"((__u8)(((AUX) >> {shift}) & 0xffU))")
    decoder_text = "\n".join(decoders)
    none = int(spec["reg_none"], 16)
    return f'''/* Generated by generate_arm64_aux_spec.py from arm64_aux_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_AUX_H
#define KPROG_FORMAL_GENERATED_ARM64_AUX_H
/*
 * Packed AArch64 simulator AUX word, four bytes little-endian, one shared
 * layout interpreted per opcode:
 *   bits  0-7  ALU opcode / memory index register ({spec["reg_none"]} == no
 *              index, ARM64_REG_NONE) / bitfield kind
 *   bits  8-15 source modifier / bitfield LSB / CCMP NZCV
 *   bits 16-23 shift amount / bitfield width / MOVK column
 *   bits 24-31 memory flags (ARM64_MEM_PRE / ARM64_MEM_POST)
 * Every argument is masked to its byte, so lane bytes never bleed into one
 * another; the decoders extract the same bytes back.
 */
#define KPROG_ARM64_AUX({args}) \\
\t({packer})
{decoder_text}
#define KPROG_ARM64_AUX_REG_NONE {none:#x}U
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = load()
    for path, expected in ((LEAN, render_lean(spec)), (CHEADER, render_c(spec))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 AUX contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
