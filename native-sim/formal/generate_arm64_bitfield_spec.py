#!/usr/bin/env python3
"""Generate the shared AArch64 bitfield-composition contract.

The generated Lean definition `GeneratedArm64Bitfield.value` and the C macro
`KPROG_ARM64_BITFIELD_VALUE` implement the five bitfield arms applied by the
simulator's `ARM64_SIM_L_EXEC_BITFIELD` handler: unsigned bitfield extract
(UBFX), signed bitfield extract (SBFX), unsigned bitfield insert in zeros
(UBFIZ), bitfield extract and insert at low end (BFXIL) and bitfield insert
(BFI).

The per-arm expressions are the spec's `lean` and `c` strings.  The five
operations and their numeric codes must match the bitfield table of
arm64_decode_spec.json exactly, so the numeric case labels in the C macro track
the ARM64_BITFIELD_* constants of the generated arm64_decode.h without
including it.

The arm formulas are stated over the same shared locals in both languages:
`mask` is the bitfield mask of the field width, `srcR`/`srcL` are the source
shifted right/left by the field position, `field` is the field mask placed at
the field position and `signExtend` is the mask-complement-and-subtract sign
extension.  C keeps `mask`/`signExtend` inline so the header stays include-free
and independent of arm64_sim.h.

The C macro is expression-shaped and has one arm per bitfield code; an
out-of-range code reaches the caller-supplied unsupported arm.  KPROG_ARM64_
BITFIELD_HANDLED names exactly the five handled codes, which the generator
asserts per code and which Lean restates as a code-range theorem.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_bitfield_spec.json"
DECODE_SPEC = ROOT / "arm64_decode_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64Bitfield.lean"
CHEADER = ROOT / "generated/arm64_bitfield.h"

# The arms share the `mask`, `srcR`, `srcL`, `field` and `signExtend` locals
# computed once above the switch, so the C and Lean arm texts are the same
# shape and the operand reads happen exactly once.
EXPECTED = {
    "schema_version": 1,
    "operation": "arm64Bitfield",
    "operations": [
        {"name": "ubfx", "code": 0,
         "lean": "srcR &&& m",
         "c": "__kprog_a64_bf_src_r & __kprog_a64_bf_mask"},
        {"name": "sbfx", "code": 1,
         "lean": "signExtend (srcR &&& m) bits",
         "c": "__kprog_a64_bf_bits == 0 ? 0 : "
              "((__kprog_a64_bf_src_r & __kprog_a64_bf_mask) ^ "
              "__kprog_a64_bf_sign) - __kprog_a64_bf_sign"},
        {"name": "ubfiz", "code": 2,
         "lean": "srcL &&& field",
         "c": "__kprog_a64_bf_src_l & __kprog_a64_bf_field"},
        {"name": "bfxil", "code": 3,
         "lean": "(dst &&& ~~~m) ||| (srcR &&& m)",
         "c": "(__kprog_a64_bf_dst & ~__kprog_a64_bf_mask) | "
              "(__kprog_a64_bf_src_r & __kprog_a64_bf_mask)"},
        {"name": "bfi", "code": 4,
         "lean": "(dst &&& ~~~field) ||| (srcL &&& field)",
         "c": "(__kprog_a64_bf_dst & ~__kprog_a64_bf_field) | "
              "(__kprog_a64_bf_src_l & __kprog_a64_bf_field)"},
    ],
}


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 bitfield specification: {data!r}")
    ops = EXPECTED["operations"]
    names = [row["name"] for row in ops]
    if names != ["ubfx", "sbfx", "ubfiz", "bfxil", "bfi"]:
        raise SystemExit(f"invalid arm64 bitfield order: {ops!r}")
    if [row["code"] for row in ops] != list(range(5)):
        raise SystemExit(f"invalid arm64 bitfield codes: {ops!r}")
    decode = json.loads(DECODE_SPEC.read_text())
    if (set(decode) != {"schema_version", "operation", "tables"}
            or decode["schema_version"] != 1
            or decode["operation"] != "arm64Decode"):
        raise SystemExit(f"invalid arm64 decode specification: {decode!r}")
    bitfield_table = decode["tables"]["bitfield"]
    if [tuple(row[key] for key in ("mnemonic", "macro", "code"))
            for row in bitfield_table] != [
            (row["name"], "ARM64_BITFIELD_" + row["name"].upper(), row["code"])
            for row in ops]:
        raise SystemExit(
            "arm64 bitfield codes drift from the arm64 decode bitfield table: "
            f"spec={[(row['name'], row['code']) for row in ops]} "
            f"decode={[(row['mnemonic'], row['code']) for row in bitfield_table]}")
    return ops


def render_lean(ops: list[dict]) -> str:
    arms = "\n".join(f"  | .{row['name']} => {row['lean']}" for row in ops)
    return f'''-- Generated by generate_arm64_bitfield_spec.py from arm64_bitfield_spec.json.
import KProgFormal.GeneratedArm64Decode
namespace KProgFormal.GeneratedArm64Bitfield
open GeneratedArm64BitfieldDecode (Bitfield)
/-- Shared AArch64 bitfield mask. Zero width and widths at or above 64 are the
C `arm64_bits_mask` guards; the wider the field the more ones the mask holds. -/
def mask (bits : BitVec 8) : BitVec 64 :=
  if bits = 0 then 0
  else if (64 : BitVec 8) ≤ bits then 0xffffffffffffffff
  else ((1 : BitVec 64) <<< (bits.setWidth 64)) - 1
/-- Shared AArch64 bitfield sign extension, mirroring C `arm64_sign_extend`:
mask the value to the field width, then complement-and-subtract its sign bit. -/
def signExtend (value : BitVec 64) (bits : BitVec 8) : BitVec 64 :=
  let sign := if bits = 0 then 0
    else (1 : BitVec 64) <<< (if (64 : BitVec 8) ≤ bits then 63
                              else (bits.setWidth 64) - 1)
  if bits = 0 then 0 else ((value &&& mask bits) ^^^ sign) - sign
/-- Shared AArch64 bitfield-composition value. The match arms follow the
generated Arm64Decode Bitfield codes; `mask`, `srcR`, `srcL` and `field` are
computed once exactly like the C macro, and the two insertion arms read `dst`
for the complement half of the destination. -/
def value (kind : Bitfield) (src dst : BitVec 64) (lsb bits : BitVec 8) :
    BitVec 64 :=
  let m := mask bits
  let srcR := if (64 : BitVec 8) ≤ lsb then 0 else src >>> (lsb.setWidth 64)
  let srcL := if (64 : BitVec 8) ≤ lsb then 0 else src <<< (lsb.setWidth 64)
  let field := if (64 : BitVec 8) ≤ lsb then 0 else m <<< (lsb.setWidth 64)
  match kind with
{arms}
end KProgFormal.GeneratedArm64Bitfield
'''


def render_c(ops: list[dict]) -> str:
    codes = "\n".join(
        f"_Static_assert(ARM64_BITFIELD_{row['name'].upper()} == {row['code']}U, "
        '"arm64 bitfield code drift");'
        for row in ops)
    handled = " || \\\n\t".join(
        f"((KIND) == ARM64_BITFIELD_{row['name'].upper()})" for row in ops)
    coverage = "\n".join(
        f"_Static_assert(KPROG_ARM64_BITFIELD_HANDLED("
        f"ARM64_BITFIELD_{row['name'].upper()}), "
        '"arm64 bitfield coverage drift");'
        for row in ops)
    body = [
        "\t({",
        "\t\t__u64 __kprog_a64_bf_src = (SRC);",
        "\t\t__u64 __kprog_a64_bf_dst = (DST);",
        "\t\t__u8 __kprog_a64_bf_kind = (KIND);",
        "\t\t__u8 __kprog_a64_bf_lsb = (LSB);",
        "\t\t__u8 __kprog_a64_bf_bits = (BITS);",
        "\t\t__u64 __kprog_a64_bf_mask =",
        "\t\t\t__kprog_a64_bf_bits == 0 ? 0",
        "\t\t\t: (__kprog_a64_bf_bits >= 64 ? 0xffffffffffffffffULL",
        "\t\t\t   : (1ULL << __kprog_a64_bf_bits) - 1ULL);",
        "\t\t__u64 __kprog_a64_bf_src_r =",
        "\t\t\t__kprog_a64_bf_lsb >= 64 ? 0",
        "\t\t\t: __kprog_a64_bf_src >> __kprog_a64_bf_lsb;",
        "\t\t__u64 __kprog_a64_bf_src_l =",
        "\t\t\t__kprog_a64_bf_lsb >= 64 ? 0",
        "\t\t\t: __kprog_a64_bf_src << __kprog_a64_bf_lsb;",
        "\t\t__u64 __kprog_a64_bf_field =",
        "\t\t\t__kprog_a64_bf_lsb >= 64 ? 0",
        "\t\t\t: __kprog_a64_bf_mask << __kprog_a64_bf_lsb;",
        "\t\t__u64 __kprog_a64_bf_sign =",
        "\t\t\t__kprog_a64_bf_bits == 0 ? 0",
        "\t\t\t: 1ULL << (__kprog_a64_bf_bits >= 64 ? 63U",
        "\t\t\t\t     : __kprog_a64_bf_bits - 1U);",
        "\t\t__u64 __kprog_a64_bf_result = 0;",
        "",
        "\t\tswitch (__kprog_a64_bf_kind) {",
    ]
    for row in ops:
        body.append(f"\t\tcase {row['code']}U:                          ")
        body.append(f"\t\t\t__kprog_a64_bf_result = {row['c']};")
        body.append("\t\t\tbreak;")
    body += [
        "\t\tdefault:",
        "\t\t\tUNSUPPORTED;",
        "\t\t\tbreak;",
        "\t\t}",
        "\t\t__kprog_a64_bf_result;",
        "\t})",
    ]
    continued = " \\\n".join(body)
    return f'''/* Generated by generate_arm64_bitfield_spec.py from arm64_bitfield_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_BITFIELD_H
#define KPROG_FORMAL_GENERATED_ARM64_BITFIELD_H
/*
 * The five bitfield arms are UBFX (extract), SBFX (signed extract), UBFIZ
 * (insert in zeros), BFXIL (extract and insert at low end) and BFI (insert).
 * Every bitfield code of the AArch64 bitfield table has exactly one arm; a code
 * outside the table reaches the caller-supplied unsupported arm.
 */
{codes}
#define KPROG_ARM64_BITFIELD_HANDLED(KIND)                                  \\
\t({handled})
{coverage}
/*
 * The numeric case labels 0U..4U track the ARM64_BITFIELD_* values defined in
 * generated/arm64_decode.h. This header intentionally does not include
 * arm64_decode.h, so it stays usable standalone; load() re-checks the codes
 * against arm64_decode_spec.json and exits 1 if they drift. SRC and DST are
 * each evaluated exactly once. The result is the raw 64-bit field value; the
 * caller applies the operand width afterwards.
 */
#define KPROG_ARM64_BITFIELD_VALUE(KIND, SRC, DST, LSB, BITS, UNSUPPORTED)  \\
{continued}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    ops = load()
    for path, expected in ((LEAN, render_lean(ops)), (CHEADER, render_c(ops))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 bitfield contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
