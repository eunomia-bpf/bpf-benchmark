#!/usr/bin/env python3
"""Generate the shared AArch64 branch-test predicate contract.

The generated Lean definition `GeneratedArm64Branch.value` and the C macro
`KPROG_ARM64_BRANCH_TEST` implement the four compare-and-branch predicates the
simulator applies for the AArch64 `CBZ`/`CBNZ`/`TBZ`/`TBNZ` control transfers:

  * `CBZ`  is taken when the whole register value is zero;
  * `CBNZ` is taken when it is not zero;
  * `TBZ`  is taken when bit `BIT` of the register is zero;
  * `TBNZ` is taken when bit `BIT` is one.

This is the predicate half of the condition-to-next-PC relation: the existing
condition contract (`KPROG_ARM64_EVAL_COND`) already states the flag-based
predicate, and this contract states the value/bit-test predicate the separate
compare-and-branch instructions use. The numeric kinds are a small contiguous
predicate enum, not an opcode table, so the case labels are `0U..3U`; the C
macro evaluates each operand exactly once, takes no unsupported arm (the kind set
is closed), and writes no state.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_branch_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64Branch.lean"
CHEADER = ROOT / "generated/arm64_branch.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64Branch",
    "kinds": [
        {"name": "cbz", "code": 0, "lean": "decide (value = 0)"},
        {"name": "cbnz", "code": 1, "lean": "decide (value ≠ 0)"},
        {"name": "tbz", "code": 2,
         "lean": "decide (((value >>> (bit &&& 63).toNat) &&& 1) = 0)"},
        {"name": "tbnz", "code": 3,
         "lean": "decide (((value >>> (bit &&& 63).toNat) &&& 1) = 1)"},
    ],
}


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 branch specification: {data!r}")
    kinds = EXPECTED["kinds"]
    names = [row["name"] for row in kinds]
    if names != ["cbz", "cbnz", "tbz", "tbnz"]:
        raise SystemExit(f"invalid arm64 branch kinds: {kinds!r}")
    if [row["code"] for row in kinds] != list(range(len(kinds))):
        raise SystemExit(f"invalid arm64 branch codes: {kinds!r}")
    return kinds


def render_lean(kinds: list[dict]) -> str:
    ctors = "\n".join(f"  | {row['name']}" for row in kinds)
    codes = "\n".join(f"  | .{row['name']} => {row['code']}" for row in kinds)
    mnemonics = "\n".join(
        f"  | .{row['name']} => \"{row['name'].upper()}\"" for row in kinds)
    arms = "\n".join(f"  | .{row['name']} => {row['lean']}" for row in kinds)
    return f'''-- Generated by generate_arm64_branch_spec.py from arm64_branch_spec.json.
namespace KProgFormal.GeneratedArm64Branch
/-- The four AArch64 compare-and-branch predicates applied by the simulator's
branch handlers. -/
inductive Branch where
{ctors}
deriving DecidableEq, Repr
/-- The contiguous predicate kind the C macro switches on. -/
def code : Branch -> Nat
{codes}
/-- The ARM instruction mnemonic of the predicate. -/
def mnemonic : Branch -> String
{mnemonics}
/-- Shared AArch64 compare-and-branch predicate. `value` is the tested register
value, `bit` is the tested bit index (used by TBZ/TBNZ and masked to the 64-bit
register domain exactly like the C macro). -/
def value (kind : Branch) (value bit : BitVec 64) : Bool :=
  match kind with
{arms}
end KProgFormal.GeneratedArm64Branch
'''


def render_c(kinds: list[dict]) -> str:
    codes = "\n".join(
        f"_Static_assert(KPROG_ARM64_BRANCH_{row['name'].upper()} == "
        f"{row['code']}U, \"arm64 branch code drift\");"
        for row in kinds)
    handled = " || \\\n\t".join(
        f"((KIND) == KPROG_ARM64_BRANCH_{row['name'].upper()})"
        for row in kinds)
    coverage = "\n".join(
        f"_Static_assert(KPROG_ARM64_BRANCH_HANDLED("
        f"KPROG_ARM64_BRANCH_{row['name'].upper()}), "
        '"arm64 branch coverage drift");'
        for row in kinds)
    body = [
        "\t({",
        "\t\t__u64 __kprog_a64_br_kind = (KIND);",
        "\t\t__u64 __kprog_a64_br_value = (VALUE);",
        "\t\t__u64 __kprog_a64_br_bit = (BIT) & 63ULL;",
        "\t\tint __kprog_a64_br_taken = 0;",
        "",
        "\t\tswitch (__kprog_a64_br_kind) {",
    ]
    for row in kinds:
        body.append(f"\t\tcase {row['code']}U:                          ")
        if row["name"] == "cbz":
            body.append("\t\t\t__kprog_a64_br_taken = "
                        "(__kprog_a64_br_value == 0);")
        elif row["name"] == "cbnz":
            body.append("\t\t\t__kprog_a64_br_taken = "
                        "(__kprog_a64_br_value != 0);")
        elif row["name"] == "tbz":
            body.append("\t\t\t__kprog_a64_br_taken = "
                        "(((__kprog_a64_br_value >> __kprog_a64_br_bit)"
                        " & 1ULL) == 0);")
        else:
            body.append("\t\t\t__kprog_a64_br_taken = "
                        "(((__kprog_a64_br_value >> __kprog_a64_br_bit)"
                        " & 1ULL) != 0);")
        body.append("\t\t\tbreak;")
    body += [
        "\t\t}",
        "\t\t__kprog_a64_br_taken;",
        "\t})",
    ]
    continued = " \\\n".join(body)
    return f'''/* Generated by generate_arm64_branch_spec.py from arm64_branch_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_BRANCH_H
#define KPROG_FORMAL_GENERATED_ARM64_BRANCH_H
/*
 * The four arms are the AArch64 compare-and-branch predicates CBZ/CBNZ (whole
 * value against zero) and TBZ/TBNZ (one bit against zero/one). The kind set is
 * closed, so the macro is total and takes no unsupported arm.
 */
#define KPROG_ARM64_BRANCH_CBZ {EXPECTED["kinds"][0]["code"]}U
#define KPROG_ARM64_BRANCH_CBNZ {EXPECTED["kinds"][1]["code"]}U
#define KPROG_ARM64_BRANCH_TBZ {EXPECTED["kinds"][2]["code"]}U
#define KPROG_ARM64_BRANCH_TBNZ {EXPECTED["kinds"][3]["code"]}U
{codes}
#define KPROG_ARM64_BRANCH_HANDLED(KIND)                                    \\
\t({handled})
{coverage}
/*
 * The numeric case labels 0U..3U are the contiguous predicate kinds above. This
 * header intentionally does not include arm64_sim.h, so it stays usable
 * standalone. KIND, VALUE and BIT are each evaluated exactly once. BIT is masked
 * to the 64-bit register domain, matching the architecture. The result is a C
 * int (1 = branch taken).
 */
#define KPROG_ARM64_BRANCH_TEST(KIND, VALUE, BIT)                           \\
{continued}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    kinds = load()
    for path, expected in ((LEAN, render_lean(kinds)), (CHEADER, render_c(kinds))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 branch contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
