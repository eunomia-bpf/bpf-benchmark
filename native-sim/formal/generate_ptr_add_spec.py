#!/usr/bin/env python3
"""Render the shared pointer-add transition for Lean and the C simulators."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SPEC_PATH = ROOT / "ptr_add_spec.json"
LEAN_PATH = ROOT / "KProgFormal" / "GeneratedPtrAdd.lean"
C_PATH = ROOT / "generated" / "ptr_add.h"


def load_spec() -> dict[str, object]:
    spec = json.loads(SPEC_PATH.read_text())
    if set(spec) != {"schema_version", "operation", "bits", "tag"}:
        raise SystemExit(f"invalid pointer-add specification fields: {spec!r}")
    if spec["schema_version"] != 1 or spec["operation"] != "ptrAdd64":
        raise SystemExit(f"unsupported pointer-add specification: {spec!r}")
    bits = spec["bits"]
    tag = spec["tag"]
    if not isinstance(bits, dict) or bits.get("op") != "add" or \
            set(bits) != {"op", "lhs", "rhs"} or \
            bits.get("lhs") not in {"src", "rhs"} or \
            bits.get("rhs") not in {"src", "rhs"}:
        raise SystemExit(f"unsupported pointer-add bits expression: {bits!r}")
    if not isinstance(tag, dict) or tag.get("op") != "copy" or \
            set(tag) != {"op", "source"} or tag.get("source") != "src":
        raise SystemExit(f"unsupported pointer-add specification: {spec!r}")
    return spec


def render_lean(spec: dict[str, object]) -> str:
    bits = spec["bits"]
    assert isinstance(bits, dict)
    return f"""-- Generated by generate_ptr_add_spec.py from ptr_add_spec.json.
import Std

namespace KProgFormal.GeneratedPtrAdd

def bits {{α : Type}} [Add α] (src rhs : α) : α := {bits['lhs']} + {bits['rhs']}

def tag {{α : Type}} (src : α) : α := src

end KProgFormal.GeneratedPtrAdd
"""


def render_c(spec: dict[str, object]) -> str:
    bits = spec["bits"]
    assert isinstance(bits, dict)
    operands = {"src": "(__u8 *)(SRC_PTR)", "rhs": "(RHS)"}
    return f"""/* Generated by generate_ptr_add_spec.py from ptr_add_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_PTR_ADD_H
#define KPROG_FORMAL_GENERATED_PTR_ADD_H

#define KPROG_PTR_ADD64_BITS(SRC_PTR, RHS) ({operands[bits['lhs']]} + {operands[bits['rhs']]})
#define KPROG_PTR_ADD64_TAG(SRC_TAG) (SRC_TAG)

#endif
"""


def check(path: Path, expected: str) -> None:
    if not path.is_file() or path.read_text() != expected:
        raise SystemExit(f"generated pointer-add contract is stale: {path}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = load_spec()
    outputs = ((LEAN_PATH, render_lean(spec)), (C_PATH, render_c(spec)))
    if args.check:
        for path, expected in outputs:
            check(path, expected)
        return
    for path, contents in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents)


if __name__ == "__main__":
    main()
