#!/usr/bin/env python3
"""Generate the shared AArch64 move-wide (MOVK) contract.

The generated Lean definition `GeneratedArm64Movk.value` and the C macro
`KPROG_ARM64_MOVK_INSERT` implement the AArch64 `MOVK` insertion the simulator
applies: keep the destination's other bits and replace the 16-bit field at one
of the four architectural columns (0, 16, 32, 48) with the low 16 bits of the
immediate.

The column is an architectural `hw` field, encoded in the simulator's AUX as
`ARM64_AUX_MOVK(S)` = `(S & 0xff) << 16` and read back by `ARM64_SIM_L_SHIFT`.
The emitted micro kernels use columns 16, 32 and 48, and the contract covers all
four columns so a column outside {0,16,32,48} is the only unsupported case.

The shift is a finite architectural column rather than an arbitrary shift: the
16-bit mask/insert pair only forms a valid architectural MOVK at a 16-aligned
column below 64, which the four-element enum makes explicit and which the
`--check` drift test pins against the AUX encoding.

The C macro evaluates each operand exactly once and writes no NZCV; the result is
the raw 64-bit value and the caller applies the destination width.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_movk_spec.json"
SIM_HEADER = ROOT.parent / "arm64/arm64_sim.h"
LEAN = ROOT / "KProgFormal/GeneratedArm64Movk.lean"
CHEADER = ROOT / "generated/arm64_movk.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64Movk",
    "columns": [
        {"name": "col0", "column": 0, "lean": "0"},
        {"name": "col16", "column": 16, "lean": "16"},
        {"name": "col32", "column": 32, "lean": "32"},
        {"name": "col48", "column": 48, "lean": "48"},
    ],
}

AUX_MOVK = re.compile(
    r"^#define\s+ARM64_AUX_MOVK\(S\)\s+\(\(\(__u32\)\(S\) & 0xffU\) << 16\)\s*$",
    re.M)


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 movk specification: {data!r}")
    cols = EXPECTED["columns"]
    names = [row["name"] for row in cols]
    if names != ["col0", "col16", "col32", "col48"]:
        raise SystemExit(f"invalid arm64 movk columns: {cols!r}")
    if [row["column"] for row in cols] != [0, 16, 32, 48]:
        raise SystemExit(f"invalid arm64 movk column values: {cols!r}")
    # The AUX encoding must stay `(S & 0xff) << 16` so the shim shift field is
    # the architectural column itself.
    if not AUX_MOVK.search(SIM_HEADER.read_text()):
        raise SystemExit(
            "ARM64_AUX_MOVK is not the expected `(((__u32)(S) & 0xffU) << 16)` "
            f"form in {SIM_HEADER}")
    return cols


def render_lean(cols: list[dict]) -> str:
    ctors = "  | " + " | ".join(row["name"] for row in cols)
    values = "\n".join(
        f"  | .{row['name']} => {row['column']}" for row in cols)
    arms = "\n".join(
        f"  | .{row['name']} => col {row['name']}" for row in cols)
    return f'''-- Generated by generate_arm64_movk_spec.py from arm64_movk_spec.json.
namespace KProgFormal.GeneratedArm64Movk
/-- The four architectural MOVK insertion columns (0, 16, 32, 48). -/
inductive MovkShift where
{ctors}
deriving DecidableEq, Repr
/-- The bit column the 16-bit immediate is inserted at. -/
def column : MovkShift -> Nat
{values}
/-- Shared AArch64 MOVK value: the destination with the 16-bit field at the
column replaced by the low 16 bits of the immediate, keeping every other bit. -/
def value (shift : MovkShift) (dst imm : BitVec 64) : BitVec 64 :=
  let s := column shift
  let m : BitVec 64 := (0xffff : BitVec 64) <<< s
  (dst &&& ~~~m) ||| ((imm <<< s) &&& m)
end KProgFormal.GeneratedArm64Movk
'''


def render_c(cols: list[dict]) -> str:
    handled = " || \\\n\t".join(
        f"((SHIFT) == {row['column']}U)" for row in cols)
    coverage = "\n".join(
        f"_Static_assert(KPROG_ARM64_MOVK_HANDLED({row['column']}U), "
        '"arm64 movk column coverage drift");'
        for row in cols)
    body = [
        "\t({",
        "\t\t__u64 __kprog_a64_movk_dst = (DST);",
        "\t\t__u64 __kprog_a64_movk_imm = (IMM);",
        "\t\t__u64 __kprog_a64_movk_shift = (SHIFT);",
        "\t\t__u64 __kprog_a64_movk_mask;",
        "\t\t__u64 __kprog_a64_movk_result;",
        "",
        "\t\tswitch (__kprog_a64_movk_shift) {",
    ]
    for row in cols:
        body.append(f"\t\tcase {row['column']}U:                          ")
        body.append(f"\t\t\t__kprog_a64_movk_mask = "
                    f"0xffffULL << {row['column']}U;")
        body.append("\t\t\tbreak;")
    body += [
        "\t\tdefault:",
        "\t\t\tUNSUPPORTED;",
        "\t\t\t__kprog_a64_movk_mask = 0;",
        "\t\t\tbreak;",
        "\t\t}",
        "\t\t__kprog_a64_movk_result =",
        "\t\t\t(__kprog_a64_movk_dst & ~__kprog_a64_movk_mask) |",
        "\t\t\t(((__kprog_a64_movk_imm << __kprog_a64_movk_shift)",
        "\t\t\t  & __kprog_a64_movk_mask));",
        "\t\t__kprog_a64_movk_result;",
        "\t})",
    ]
    continued = " \\\n".join(body)
    return f'''/* Generated by generate_arm64_movk_spec.py from arm64_movk_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_MOVK_H
#define KPROG_FORMAL_GENERATED_ARM64_MOVK_H
/*
 * AArch64 MOVK inserts the low 16 bits of an immediate at one of the four
 * architectural columns 0, 16, 32 and 48, keeping every other destination bit.
 * The column set is closed, so the macro is total over SHIFT and an out-of-set
 * column reaches the caller-supplied unsupported arm.
 */
#define KPROG_ARM64_MOVK_HANDLED(SHIFT)                                     \\
\t({handled})
{coverage}
/*
 * SHIFT is the architectural bit column (0, 16, 32 or 48), which is exactly the
 * value `ARM64_SIM_L_SHIFT(AUX)` returns for `ARM64_AUX_MOVK(S)`. DST and IMM
 * are each evaluated exactly once, and no arm writes NZCV. The result is the
 * raw 64-bit value; the caller applies the destination width.
 */
#define KPROG_ARM64_MOVK_INSERT(DST, IMM, SHIFT, UNSUPPORTED)               \\
{continued}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    cols = load()
    for path, expected in ((LEAN, render_lean(cols)), (CHEADER, render_c(cols))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 movk contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
