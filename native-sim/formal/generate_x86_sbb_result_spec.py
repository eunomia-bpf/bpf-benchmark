#!/usr/bin/env python3
"""Generate the shared x86 SBB result expression for Lean and C."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parent;SPEC=ROOT/"x86_sbb_result_spec.json";LEAN=ROOT/"KProgFormal/GeneratedX86SbbResult.lean";CHEADER=ROOT/"generated/x86_sbb_result.h"
def validate(e):
 if not isinstance(e,dict) or "op" not in e: raise SystemExit(f"invalid SBB result expression: {e!r}")
 if e["op"]=="input":
  if set(e)!={"op","name"} or e["name"] not in {"a","b","mask"}: raise SystemExit(f"invalid SBB input: {e!r}")
 elif e["op"]=="borrow":
  if set(e)!={"op"}: raise SystemExit(f"invalid borrow expression: {e!r}")
 elif e["op"] in {"sub","add","and"}:
  if set(e)!={"op","lhs","rhs"}: raise SystemExit(f"invalid subtraction expression: {e!r}")
  validate(e["lhs"]);validate(e["rhs"])
 else:raise SystemExit(f"unsupported SBB expression: {e!r}")
def load():
 d=json.loads(SPEC.read_text())
 if set(d)!={"schema_version","operation","expressions"} or d["schema_version"]!=1 or d["operation"]!="x86SbbResult" or list(d["expressions"])!=["result","subtrahend"]:raise SystemExit(f"invalid SBB specification: {d!r}")
 for e in d["expressions"].values():validate(e)
 return d["expressions"]
def render(e,lean):
 if e["op"]=="input":return e["name"] if lean else e["name"].upper()
 if e["op"]=="borrow":return "(if borrow then 1 else 0)" if lean else "(!!(BORROW))"
 if lean and e["op"]=="and":return f"(BitVec.and {render(e['lhs'],lean)} {render(e['rhs'],lean)})"
 op={"sub":"-","add":"+","and":"&"}[e["op"]]
 return f"({render(e['lhs'],lean)} {op} {render(e['rhs'],lean)})"
def lean_out(es):return f'''-- Generated by generate_x86_sbb_result_spec.py from x86_sbb_result_spec.json.
import Std
namespace KProgFormal.GeneratedX86SbbResult
def result (a b : BitVec 64) (borrow : Bool) : BitVec 64 := {render(es['result'],True)}
def subtrahend (b mask : BitVec 64) (borrow : Bool) : BitVec 64 := {render(es['subtrahend'],True)}
end KProgFormal.GeneratedX86SbbResult
'''
def c_out(es):return f'''/* Generated by generate_x86_sbb_result_spec.py from x86_sbb_result_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_SBB_RESULT_H
#define KPROG_FORMAL_GENERATED_X86_SBB_RESULT_H
#define KPROG_X86_SBB_RESULT(A,B,BORROW) {render(es['result'],False)}
#define KPROG_X86_SBB_SUBTRAHEND(B,MASK,BORROW) {render(es['subtrahend'],False)}
#endif
'''
def main():
 p=argparse.ArgumentParser();p.add_argument("--check",action="store_true");a=p.parse_args();es=load()
 for path,want in ((LEAN,lean_out(es)),(CHEADER,c_out(es))):
  if a.check:
   if not path.is_file() or path.read_text()!=want:raise SystemExit(f"generated x86 SBB result contract is stale: {path}")
  else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(want)
if __name__=="__main__":main()
