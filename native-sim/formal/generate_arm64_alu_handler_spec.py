#!/usr/bin/env python3
"""Generate the AArch64 ALU handler's pointer/scalar path predicate.

The C simulator and Lean handler model share only this path predicate.  The
independent Lean refinement statement separately enumerates the condition and
the two resulting state transitions.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_alu_handler_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64AluHandler.lean"
CHEADER = ROOT / "generated/arm64_alu_handler.h"
EXPECTED = {
    "schema_version": 1,
    "operation": "arm64AluHandlerPath",
    "pointer_path": {
        "width": "w64",
        "alu": "add",
        "destination": "not_sp",
        "source_tag": "non_scalar",
    },
}


def load() -> None:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 ALU handler specification: {data!r}")


def render_lean() -> str:
    return '''-- Generated by generate_arm64_alu_handler_spec.py from arm64_alu_handler_spec.json.
import KProgFormal.GeneratedArm64Decode
import KProgFormal.GeneratedArm64Width

namespace KProgFormal.GeneratedArm64AluHandler

open GeneratedArm64AluDecode (Alu)
open GeneratedArm64Width (Width)

/-- The C handler preserves pointer provenance only for a 64-bit ADD whose
destination is not SP and whose source provenance is non-scalar. -/
def usePointer (width : Width) (op : Alu)
    (dstIsSp srcIsScalar : Bool) : Bool :=
  width == .w64 && op == .add && !dstIsSp && !srcIsScalar

end KProgFormal.GeneratedArm64AluHandler
'''


def render_c() -> str:
    return '''/* Generated by generate_arm64_alu_handler_spec.py from arm64_alu_handler_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_ALU_HANDLER_H
#define KPROG_FORMAL_GENERATED_ARM64_ALU_HANDLER_H

#define KPROG_ARM64_ALU_USE_POINTER(WIDTH, OP, DST_IS_SP, SRC_IS_SCALAR) \\
\t((WIDTH) == ARM64_WIDTH_64 && (OP) == ARM64_ALU_ADD &&             \\
\t !(DST_IS_SP) && !(SRC_IS_SCALAR))

#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    load()
    for path, expected in ((LEAN, render_lean()), (CHEADER, render_c())):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 ALU handler contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
