#!/usr/bin/env python3
"""Generate the shared AArch64 `LDP` / `STP` pair-move contract.

The generated Lean step `GeneratedArm64PairMem` and the C constants
`KPROG_ARM64_PAIR_MEM_*` describe the two bodies that move a register pair to
or from two adjacent 64-bit memory slots:

  * `LDP` loads two 64-bit slots into a register *pair*: the low slot into
    `DST`, the high slot one 64-bit slot stride higher into `SRC`;
  * `STP` stores a register *pair* to the same two slots, low from `SRC` and
    high from `SRC2`.

Both the address offset (`MEM_BASE_OFF`) and the pre/post-indexed base
adjustment (`MEM_PRE` / `MEM_POST`) stay in the C macros that already have
their own proved contracts; the LDP tag-pair probe is likewise a separate
`ARM64_SIM_L_MEM_READ_TAG` composition. This contract fixes only *which* two
slots each opcode transfers and in which order, so the C bodies and Lean share
one pair plan: two 64-bit slots at `MEM_BASE_OFF(AUX, INDEX, IMM) + 0` and
`+8`, each a full 64-bit access.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_pair_mem_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64PairMem.lean"
CHEADER = ROOT / "generated/arm64_pair_mem.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64PairMem",
    "selector": "per_opcode_access_direction_then_pair_slot_offset_plan",
    "opcodes": [
        {"name": "ldp", "define": "ARM64_OP_LDP", "code": "0x21",
         "codeIndex": 0, "access": "load"},
        {"name": "stp", "define": "ARM64_OP_STP", "code": "0x22",
         "codeIndex": 1, "access": "store"},
    ],
    "slot_stride": "ARM64_WIDTH_64",
    "slot_count": 2,
    "high_slot_stride": 8,
}

OP_ORDER = ("ldp", "stp")
OP_DEFINES = {"ldp": "ARM64_OP_LDP", "stp": "ARM64_OP_STP"}
OP_CODES = {"ldp": "0x21", "stp": "0x22"}
OP_CODE_INDEX = {"ldp": 0, "stp": 1}
OP_ACCESS = {"ldp": "load", "stp": "store"}

SLOT_STRIDE = "ARM64_WIDTH_64"
SLOT_COUNT = 2
HIGH_SLOT_STRIDE = 8


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 LDP/STP specification: {data!r}")
    ops = data["opcodes"]
    for key, table in (("name", OP_ORDER), ("define", OP_DEFINES),
                       ("code", OP_CODES), ("codeIndex", OP_CODE_INDEX),
                       ("access", OP_ACCESS)):
        expected_col = [table[n] if isinstance(table, dict) else n
                        for n in OP_ORDER]
        if [row[key] for row in ops] != expected_col:
            raise SystemExit(f"invalid arm64 LDP/STP {key} column: {ops!r}")
    if len({row["define"] for row in ops}) != len(ops):
        raise SystemExit(f"duplicate arm64 LDP/STP opcode: {ops!r}")
    if data["slot_stride"] != SLOT_STRIDE:
        raise SystemExit(f"invalid arm64 LDP/STP slot stride: {data!r}")
    if data["slot_count"] != SLOT_COUNT:
        raise SystemExit(f"invalid arm64 LDP/STP slot count: {data!r}")
    if data["high_slot_stride"] != HIGH_SLOT_STRIDE:
        raise SystemExit(f"invalid arm64 LDP/STP high-slot stride: {data!r}")
    return ops


def render_lean(opcode_rows: list[dict]) -> str:
    op_ctors = "\n".join(f"  | {row['name']}" for row in opcode_rows)
    access_arms = "\n".join(
        f"  | .{row['name']} => .{row['access']}" for row in opcode_rows)
    index_arms = "\n".join(
        f"  | .{row['name']} => {row['codeIndex']}" for row in opcode_rows)
    return f'''-- Generated by generate_arm64_pair_mem_spec.py from arm64_pair_mem_spec.json.
import Std
namespace KProgFormal.GeneratedArm64PairMem
/-- The two pair-move opcodes this contract spans. -/
inductive Op where
{op_ctors}
deriving DecidableEq, Repr
/-- Whether the opcode loads a register pair from memory or stores it to
memory. -/
inductive Access where
  | load
  | store
deriving DecidableEq, Repr
/-- The access direction of each opcode. -/
def access : Op -> Access
{access_arms}
/-- The arm index of the opcode in the two-way dispatch chain, decoded from the
opcode code, so the chain order is a checked fact. -/
def armIndex : Op -> Nat
{index_arms}
/-- The number of 64-bit slots a pair move transfers: always two. -/
def slotCount (_ : Op) : Nat :=
  {SLOT_COUNT}
/-- The byte offset of the `n`-th transferred slot: the slot index scaled by the
64-bit slot stride, so `n = 0` is offset 0 and `n = 1` is offset 8. -/
def slotOffset (_ : Op) (n : Nat) : Nat :=
  n * 8
end KProgFormal.GeneratedArm64PairMem
'''


def render_c(opcode_rows: list[dict]) -> str:
    op_asserts = "\n".join(
        f'_Static_assert({row["define"]} == {row["code"]}U, '
        f'"arm64 LDP/STP {row["name"]} opcode drift");'
        for row in opcode_rows)
    def cont(text: str) -> str:
        return "\t" + text.ljust(63) + "\\"
    index_branches = "".join(
        "\n" + cont("else if ((OP) == %s)" % row["define"]) +
        "\n" + cont("\t__kprog_a64_pair_idx = %dU;" % row["codeIndex"])
        for row in opcode_rows[1:-1])
    return f'''/* Generated by generate_arm64_pair_mem_spec.py from arm64_pair_mem_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_PAIR_MEM_H
#define KPROG_FORMAL_GENERATED_ARM64_PAIR_MEM_H
/*
 * AArch64 `LDP` / `STP` pair-move contract. `LDP` moves two 64-bit slots into a
 * register pair (low slot into DST, high slot into SRC); `STP` moves a register
 * pair out to the same two slots (low from SRC, high from SRC2). The address
 * offset (MEM_BASE_OFF) and the pre/post base adjustment (MEM_PRE / MEM_POST)
 * stay in the macros with their own proved contracts, and the LDP tag-pair
 * probe is a separate MEM_READ_TAG composition; this contract fixes which two
 * slots each opcode transfers and in which order. Every slot is a full 64-bit
 * access.
 */
{op_asserts}
/*
 * The slot stride: every transferred slot is a 64-bit access, and the high slot
 * of a pair move follows the low slot by one slot stride.
 */
#define KPROG_ARM64_PAIR_MEM_SLOT_STRIDE {SLOT_STRIDE}
#define KPROG_ARM64_PAIR_MEM_HIGH_SLOT_STRIDE {HIGH_SLOT_STRIDE}
_Static_assert(KPROG_ARM64_PAIR_MEM_SLOT_STRIDE == 8U,
\t       "arm64 LDP/STP slot stride drift");
/*
 * The number of slots a pair move transfers: exactly two, the low slot then the
 * high slot.
 */
#define KPROG_ARM64_PAIR_MEM_SLOT_COUNT {SLOT_COUNT}U
/*
 * Access direction of each opcode: 0 loads a register pair from memory, 1
 * stores a register pair to memory.
 */
#define KPROG_ARM64_PAIR_MEM_ACCESS_LOAD 0U
#define KPROG_ARM64_PAIR_MEM_ACCESS_STORE 1U
#define KPROG_ARM64_PAIR_MEM_OP_LDP_ACCESS KPROG_ARM64_PAIR_MEM_ACCESS_LOAD
#define KPROG_ARM64_PAIR_MEM_OP_STP_ACCESS KPROG_ARM64_PAIR_MEM_ACCESS_STORE
/*
 * The arm index of each opcode in the two-way `OP == LDP / STP` chain, decoded
 * from the opcode code so the chain order is a checked fact.
 */
#define KPROG_ARM64_PAIR_MEM_OP_LDP_INDEX 0U
#define KPROG_ARM64_PAIR_MEM_OP_STP_INDEX 1U
#define KPROG_ARM64_PAIR_MEM_INDEX(OP)                                \\
\t({{                                                              \\
{cont("__u32 __kprog_a64_pair_idx;")}
{cont("if ((OP) == %s)" % opcode_rows[0]["define"])}
{cont("\t__kprog_a64_pair_idx = %dU;" % opcode_rows[0]["codeIndex"])}{index_branches}
{cont("else")}
{cont("\t__kprog_a64_pair_idx = %dU;" % opcode_rows[-1]["codeIndex"])}
{cont("__kprog_a64_pair_idx;")}
\t}})                                                              \\
\t/* the compound expression yields the arm index */
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rows = load()
    for path, expected in ((LEAN, render_lean(rows)),
                           (CHEADER, render_c(rows))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 LDP/STP contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
