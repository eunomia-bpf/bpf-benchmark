#!/usr/bin/env python3
"""Generate the shared AArch64 vector `.D0` / `.Q0` memory-transfer contract.

The generated Lean step `GeneratedArm64DqMem` and the C constants
`KPROG_ARM64_DQ_MEM_*` describe the four bodies that move a SIMD register's low
64-bit lane (`.D0`) or both 64-bit lanes (`.Q0`) to or from memory:

  * `.D0` moves one 64-bit lane at `MEM_BASE_OFF(AUX, INDEX, IMM) + 0`;
  * `.Q0` moves two 64-bit lanes at `MEM_BASE_OFF(AUX, INDEX, IMM) + 0` and `+8`.

Both the address offset (`MEM_BASE_OFF`) and the pre/post-indexed base adjustment
(`MEM_PRE` / `MEM_POST`) stay in the C macros that already have their own proved
contracts; this contract fixes only *which* lanes each opcode transfers and in
which order, so the C bodies and Lean share one lane plan. Each lane is a full
64-bit scalar access with the scalar tag, and its byte offset is the lane index
scaled by the 64-bit lane stride.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_dq_mem_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64DqMem.lean"
CHEADER = ROOT / "generated/arm64_dq_mem.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64DqMem",
    "selector": "per_opcode_access_direction_and_vector_lane_count_then_lane_offset_plan",
    "opcodes": [
        {"name": "loadD0", "define": "ARM64_OP_LOAD_D0", "code": "0x28",
         "codeIndex": 0, "access": "load", "lanes": "one"},
        {"name": "loadQ0", "define": "ARM64_OP_LOAD_Q0", "code": "0x2a",
         "codeIndex": 1, "access": "load", "lanes": "two"},
        {"name": "storeD0", "define": "ARM64_OP_STORE_D0", "code": "0x29",
         "codeIndex": 2, "access": "store", "lanes": "one"},
        {"name": "storeQ0", "define": "ARM64_OP_STORE_Q0", "code": "0x2b",
         "codeIndex": 3, "access": "store", "lanes": "two"},
    ],
    "lane_stride": "ARM64_WIDTH_64",
    "high_lane_stride": 8,
}

OP_ORDER = ("loadD0", "loadQ0", "storeD0", "storeQ0")
OP_DEFINES = {"loadD0": "ARM64_OP_LOAD_D0", "loadQ0": "ARM64_OP_LOAD_Q0",
              "storeD0": "ARM64_OP_STORE_D0", "storeQ0": "ARM64_OP_STORE_Q0"}
OP_CODES = {"loadD0": "0x28", "loadQ0": "0x2a", "storeD0": "0x29",
            "storeQ0": "0x2b"}
OP_CODE_INDEX = {"loadD0": 0, "loadQ0": 1, "storeD0": 2, "storeQ0": 3}
OP_ACCESS = {"loadD0": "load", "loadQ0": "load", "storeD0": "store",
             "storeQ0": "store"}
OP_LANES = {"loadD0": "one", "loadQ0": "two", "storeD0": "one",
            "storeQ0": "two"}

LANE_STRIDE = "ARM64_WIDTH_64"
HIGH_LANE_STRIDE = 8


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 D0/Q0 specification: {data!r}")
    ops = data["opcodes"]
    for key, table in (("name", OP_ORDER), ("define", OP_DEFINES),
                       ("code", OP_CODES), ("codeIndex", OP_CODE_INDEX),
                       ("access", OP_ACCESS), ("lanes", OP_LANES)):
        expected_col = [table[n] if isinstance(table, dict) else n
                        for n in OP_ORDER]
        if [row[key] for row in ops] != expected_col:
            raise SystemExit(f"invalid arm64 D0/Q0 {key} column: {ops!r}")
    if len({row["define"] for row in ops}) != len(ops):
        raise SystemExit(f"duplicate arm64 D0/Q0 opcode: {ops!r}")
    if data["lane_stride"] != LANE_STRIDE:
        raise SystemExit(f"invalid arm64 D0/Q0 lane stride: {data!r}")
    if data["high_lane_stride"] != HIGH_LANE_STRIDE:
        raise SystemExit(f"invalid arm64 D0/Q0 high-lane stride: {data!r}")
    return ops


def render_lean(opcode_rows: list[dict]) -> str:
    op_ctors = "\n".join(f"  | {row['name']}" for row in opcode_rows)
    access_arms = "\n".join(
        f"  | .{row['name']} => .{row['access']}" for row in opcode_rows)
    lanes_arms = "\n".join(
        f"  | .{row['name']} => .{row['lanes']}" for row in opcode_rows)
    index_arms = "\n".join(
        f"  | .{row['name']} => {row['codeIndex']}" for row in opcode_rows)
    return f'''-- Generated by generate_arm64_dq_mem_spec.py from arm64_dq_mem_spec.json.
import Std
namespace KProgFormal.GeneratedArm64DqMem
/-- The four vector memory-transfer opcodes this contract spans. -/
inductive Op where
{op_ctors}
deriving DecidableEq, Repr
/-- Whether the opcode loads into or stores from the SIMD register. -/
inductive Access where
  | load
  | store
deriving DecidableEq, Repr
/-- How many 64-bit lanes the opcode moves. -/
inductive Lanes where
  | one
  | two
deriving DecidableEq, Repr
/-- The access direction of each opcode. -/
def access : Op -> Access
{access_arms}
/-- The number of 64-bit lanes each opcode moves. -/
def lanes : Op -> Lanes
{lanes_arms}
/-- The arm index of the opcode in the four-way dispatch chain, decoded from the
opcode code, so the chain order is a checked fact. -/
def armIndex : Op -> Nat
{index_arms}
/-- The number of lanes a lane count moves. -/
def laneCount : Lanes -> Nat
  | .one => 1
  | .two => 2
/-- The byte offset of the `n`-th transferred lane: the lane index scaled by the
64-bit lane width, so `n = 0` is offset 0 and `n = 1` is offset 8. -/
def transfer (_ : Op) (n : Nat) : Nat :=
  n * 8
end KProgFormal.GeneratedArm64DqMem
'''


def render_c(opcode_rows: list[dict]) -> str:
    op_asserts = "\n".join(
        f'_Static_assert({row["define"]} == {row["code"]}U, '
        f'"arm64 D0/Q0 {row["name"]} opcode drift");'
        for row in opcode_rows)
    def cont(text: str) -> str:
        return "\t" + text.ljust(63) + "\\"
    index_branches = "\n".join(
        cont("else if ((OP) == %s)" % row["define"]) + "\n" +
        cont("\t__kprog_a64_dq_idx = %dU;" % row["codeIndex"])
        for row in opcode_rows[1:-1])
    return f'''/* Generated by generate_arm64_dq_mem_spec.py from arm64_dq_mem_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_DQ_MEM_H
#define KPROG_FORMAL_GENERATED_ARM64_DQ_MEM_H
/*
 * AArch64 vector `.D0` / `.Q0` memory-transfer contract. The four bodies move
 * the SIMD low lane (`.D0`) or both 64-bit lanes (`.Q0`) to or from memory. The
 * address offset (MEM_BASE_OFF) and the pre/post base adjustment (MEM_PRE /
 * MEM_POST) stay in the macros with their own proved contracts; this contract
 * fixes which lanes each opcode transfers and in which order. Every lane is a
 * full 64-bit scalar access.
 */
{op_asserts}
/*
 * The lane stride: every transferred lane is a 64-bit access, and the high lane
 * of a `.Q0` transfer follows the low lane by one lane stride.
 */
#define KPROG_ARM64_DQ_MEM_LANE_STRIDE {LANE_STRIDE}
#define KPROG_ARM64_DQ_MEM_HIGH_LANE_STRIDE {HIGH_LANE_STRIDE}
_Static_assert(KPROG_ARM64_DQ_MEM_LANE_STRIDE == 8U,
\t       "arm64 D0/Q0 lane stride drift");
/*
 * Access direction of each opcode: 0 loads into the SIMD register, 1 stores
 * from it.
 */
#define KPROG_ARM64_DQ_MEM_ACCESS_LOAD 0U
#define KPROG_ARM64_DQ_MEM_ACCESS_STORE 1U
#define KPROG_ARM64_DQ_MEM_OP_LOAD_D0_ACCESS KPROG_ARM64_DQ_MEM_ACCESS_LOAD
#define KPROG_ARM64_DQ_MEM_OP_LOAD_Q0_ACCESS KPROG_ARM64_DQ_MEM_ACCESS_LOAD
#define KPROG_ARM64_DQ_MEM_OP_STORE_D0_ACCESS KPROG_ARM64_DQ_MEM_ACCESS_STORE
#define KPROG_ARM64_DQ_MEM_OP_STORE_Q0_ACCESS KPROG_ARM64_DQ_MEM_ACCESS_STORE
/*
 * Lane count of each opcode: 1 moves the low lane only (`.D0`), 2 moves the low
 * lane then the high lane (`.Q0`).
 */
#define KPROG_ARM64_DQ_MEM_OP_LOAD_D0_LANES 1U
#define KPROG_ARM64_DQ_MEM_OP_LOAD_Q0_LANES 2U
#define KPROG_ARM64_DQ_MEM_OP_STORE_D0_LANES 1U
#define KPROG_ARM64_DQ_MEM_OP_STORE_Q0_LANES 2U
/*
 * The arm index of each opcode in the four-way `OP == LOAD_D0 / LOAD_Q0 /
 * STORE_D0 / STORE_Q0` chain, decoded from the opcode code so the chain order is
 * a checked fact.
 */
#define KPROG_ARM64_DQ_MEM_OP_LOAD_D0_INDEX 0U
#define KPROG_ARM64_DQ_MEM_OP_LOAD_Q0_INDEX 1U
#define KPROG_ARM64_DQ_MEM_OP_STORE_D0_INDEX 2U
#define KPROG_ARM64_DQ_MEM_OP_STORE_Q0_INDEX 3U
#define KPROG_ARM64_DQ_MEM_INDEX(OP)                                  \\
\t({{                                                              \\
{cont("__u32 __kprog_a64_dq_idx;")}
{cont("if ((OP) == %s)" % opcode_rows[0]["define"])}
{cont("\t__kprog_a64_dq_idx = %dU;" % opcode_rows[0]["codeIndex"])}
{index_branches}
{cont("else")}
{cont("\t__kprog_a64_dq_idx = %dU;" % opcode_rows[-1]["codeIndex"])}
{cont("__kprog_a64_dq_idx;")}
\t}})                                                              \\
\t/* the compound expression yields the arm index */
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rows = load()
    for path, expected in ((LEAN, render_lean(rows)),
                           (CHEADER, render_c(rows))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 D0/Q0 contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
