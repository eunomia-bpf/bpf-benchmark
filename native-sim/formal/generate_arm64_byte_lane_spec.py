#!/usr/bin/env python3
"""Generate the shared AArch64 byte-lane extraction contract.

The generated Lean definition `GeneratedArm64ByteLane.byteAt` and the C macro
`KPROG_ARM64_BYTE_AT` implement the single byte lane the simulator extracts when
it scatters a value into the stack byte array: byte `i` of a 64-bit word is
`(value >> 8*i) & 0xff`.

This is the inverse half of the generated load contract
(`GeneratedArm64LoadBytes.value`): the ladder reassembles exactly the lanes
`byteAt` extracts, which `KProgFormal/Arm64ByteLane.lean` proves. The eight lanes
are the closed set the stack scatter uses, so the lane index is a finite
enumeration and the C macro is a total eight-way switch.

The C macro evaluates the value exactly once and writes no NZCV.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_byte_lane_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64ByteLane.lean"
CHEADER = ROOT / "generated/arm64_byte_lane.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64ByteLane",
    "lanes": [
        {"name": "lane0", "index": 0},
        {"name": "lane1", "index": 1},
        {"name": "lane2", "index": 2},
        {"name": "lane3", "index": 3},
        {"name": "lane4", "index": 4},
        {"name": "lane5", "index": 5},
        {"name": "lane6", "index": 6},
        {"name": "lane7", "index": 7},
    ],
}


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 byte-lane specification: {data!r}")
    lanes = EXPECTED["lanes"]
    if [row["name"] for row in lanes] != [f"lane{i}" for i in range(8)]:
        raise SystemExit(f"invalid arm64 byte-lane order: {lanes!r}")
    if [row["index"] for row in lanes] != list(range(8)):
        raise SystemExit(f"invalid arm64 byte-lane indices: {lanes!r}")
    return lanes


def render_lean(lanes: list[dict]) -> str:
    ctors = "\n".join(f"  | {row['name']}" for row in lanes)
    indices = "\n".join(
        f"  | .{row['name']} => {row['index']}" for row in lanes)
    shifted = "\n".join(
        f"  | .{row['name']} => 8 * {row['index']}" for row in lanes)
    return f'''-- Generated by generate_arm64_byte_lane_spec.py from arm64_byte_lane_spec.json.
import Std
namespace KProgFormal.GeneratedArm64ByteLane
/-- The eight byte lanes of a 64-bit stack slot. -/
inductive ByteLane where
{ctors}
deriving DecidableEq, Repr
/-- The lane number `0..7`. -/
def index : ByteLane -> Nat
{indices}
/-- The bit shift `8 * lane` that places the lane in the word. -/
def shift : ByteLane -> Nat
{shifted}
/-- The byte a lane extracts from a 64-bit word. -/
def byteAt (lane : ByteLane) (value : BitVec 64) : BitVec 8 :=
  ((value >>> shift lane).setWidth 8)
end KProgFormal.GeneratedArm64ByteLane
'''


def render_c(lanes: list[dict]) -> str:
    body = [
        "\t({",
        "\t\t__u64 __kprog_a64_bl_lane = (LANE);",
        "\t\t__u64 __kprog_a64_bl_value = (VALUE);",
        "\t\t__u64 __kprog_a64_bl_shift = 0;",
        "",
        "\t\tswitch (__kprog_a64_bl_lane) {",
    ]
    for row in lanes:
        body.append(f"\t\tcase {row['index']}U:                          ")
        body.append(f"\t\t\t__kprog_a64_bl_shift = {8 * row['index']};")
        body.append("\t\t\tbreak;")
    body += [
        "\t\tdefault:",
        "\t\t\tUNSUPPORTED;",
        "\t\t\tbreak;",
        "\t\t}",
        "\t\t(__u8)(__kprog_a64_bl_value >> __kprog_a64_bl_shift);",
        "\t})",
    ]
    continued = " \\\n".join(body)
    return f'''/* Generated by generate_arm64_byte_lane_spec.py from arm64_byte_lane_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_BYTE_LANE_H
#define KPROG_FORMAL_GENERATED_ARM64_BYTE_LANE_H
/*
 * AArch64 byte-lane extraction: the byte a lane takes from a 64-bit word. This
 * is the inverse of the generated little-endian load ladder: the ladder
 * reassembles exactly these lanes, which KProgFormal/Arm64ByteLane.lean proves.
 * The eight lanes are the closed set the stack byte scatter uses; a lane outside
 * 0..7 reaches the caller-supplied unsupported arm.
 */
/*
 * LANE is the byte lane 0..7 and VALUE the 64-bit source word. VALUE is
 * evaluated exactly once and no NZCV is written. The result is a __u8 byte.
 */
#define KPROG_ARM64_BYTE_AT(LANE, VALUE, UNSUPPORTED)                       \\
{continued}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    lanes = load()
    for path, expected in ((LEAN, render_lean(lanes)), (CHEADER, render_c(lanes))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 byte-lane contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
