#!/usr/bin/env python3
"""Generate the shared AArch64 memory access-dispatch contract.

The generated Lean tables `GeneratedArm64MemDispatch.valueSrc` / `valueTag` and
the C predicates `KPROG_ARM64_MEM_READ_SRC` / `KPROG_ARM64_MEM_READ_TAG`
classify a load by the base register's memory space and the access width:

  - a stack / stack-pointer base always reads through the stack helper and keeps
    the stack value tag;
  - an ABI base at width 64 does a pointer load and tags the result with the
    generated ABI kind's packet/packet-end tag;
  - a reloc-address base at width 64 reads the base pointer and tags the result
    as a map pointer;
  - every other base does an ordinary byte-ladder load and yields a scalar tag.

The classification is a closed table over the four spaces and the two width
cases, so each C predicate is total and has no unsupported arm. The ABI packet
tag itself stays in `KPROG_ABI_LOAD_TAG` (generated/abi_load.h); this contract
selects *which* tag source applies, it does not recompute the ABI tag.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_mem_dispatch_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64MemDispatch.lean"
CHEADER = ROOT / "generated/arm64_mem_dispatch.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64MemDispatch",
    "spaces": [
        {"name": "stack", "src": "stackRead", "tag": "stackTag",
         "src_define": "KPROG_ARM64_MEM_SRC_STACK",
         "tag_define": "KPROG_ARM64_MEM_TAG_STACK",
         "tag_macro": "ARM64_SIM_TAG_STACK", "w64_only": False},
        {"name": "abi", "src": "abiPtrLoad", "tag": "abiTag",
         "src_define": "KPROG_ARM64_MEM_SRC_ABI_PTR_LOAD",
         "tag_define": "KPROG_ARM64_MEM_TAG_ABI",
         "tag_macro": "ARM64_SIM_TAG_ABI", "w64_only": True},
        {"name": "reloc", "src": "relocPtr", "tag": "mapPtr",
         "src_define": "KPROG_ARM64_MEM_SRC_RELOC_PTR",
         "tag_define": "KPROG_ARM64_MEM_TAG_MAP_PTR",
         "tag_macro": "ARM64_SIM_TAG_RELOC_ADDR", "w64_only": True},
        {"name": "normal", "src": "normalLoad", "tag": "scalar",
         "src_define": "KPROG_ARM64_MEM_SRC_NORMAL_LOAD",
         "tag_define": "KPROG_ARM64_MEM_TAG_SCALAR",
         "tag_macro": "ARM64_SIM_TAG_SCALAR", "w64_only": False},
    ],
}


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 mem-dispatch specification: {data!r}")
    spaces = EXPECTED["spaces"]
    if [row["name"] for row in spaces] != ["stack", "abi", "reloc", "normal"]:
        raise SystemExit(f"invalid arm64 mem-dispatch order: {spaces!r}")
    return spaces


def render_lean(spaces: list[dict]) -> str:
    ctors = "\n".join(f"  | {row['name']}" for row in spaces)
    # Peano-style exhaustive table: for each (space, width64) pair, the value
    # source and the result tag, with the w64-only spaces falling back.
    def table(key: str, fallback: str) -> str:
        rows = []
        for row in spaces:
            rows.append(f"  | .{row['name']}, true => .{row[key]}")
            rows.append(f"  | .{row['name']}, false => "
                        f".{fallback if row['w64_only'] else row[key]}")
        return "\n".join(rows)
    return f'''-- Generated by generate_arm64_mem_dispatch_spec.py from arm64_mem_dispatch_spec.json.
import Std
namespace KProgFormal.GeneratedArm64MemDispatch
/-- The memory space a load base register addresses. -/
inductive Space where
{ctors}
deriving DecidableEq, Repr
/-- The value source a load selects. -/
inductive ValueSrc where
  | stackRead
  | abiPtrLoad
  | relocPtr
  | normalLoad
deriving DecidableEq, Repr
/-- The result tag a load selects (before the ABI kind refines it). -/
inductive ResultTag where
  | stackTag
  | abiTag
  | mapPtr
  | scalar
deriving DecidableEq, Repr
/-- Independent value-source table over the four spaces and the two width cases.
The `w64_only` spaces fall back to the ordinary load off width 64. -/
def valueSrc : Space -> Bool -> ValueSrc
{table('src', 'normalLoad')}
/-- Independent result-tag table; the `w64_only` spaces fall back to the scalar
tag off width 64. -/
def valueTag : Space -> Bool -> ResultTag
{table('tag', 'scalar')}
end KProgFormal.GeneratedArm64MemDispatch
'''


def render_c(spaces: list[dict]) -> str:
    w64 = [row for row in spaces if row["w64_only"]]
    src_body = [
        "\t\t__u8 __kprog_a64_md_src;                                      \\",
        "\t\tif ((BASE_IS_SP) || (TAG) == ARM64_SIM_TAG_STACK)              \\",
        "\t\t\t__kprog_a64_md_src = KPROG_ARM64_MEM_SRC_STACK;            \\",
    ]
    tag_body = [
        "\t\t__u8 __kprog_a64_md_tag;                                      \\",
        "\t\tif ((BASE_IS_SP) || (TAG) == ARM64_SIM_TAG_STACK)              \\",
        "\t\t\t__kprog_a64_md_tag = KPROG_ARM64_MEM_TAG_STACK;            \\",
    ]
    for row in w64:
        src_body += [
            f"\t\telse if ((TAG) == {row['tag_macro']} &&                    \\",
            "\t\t\t (WIDTH) == ARM64_WIDTH_64)                             \\",
            f"\t\t\t__kprog_a64_md_src = {row['src_define']};              \\",
        ]
        tag_body += [
            f"\t\telse if ((TAG) == {row['tag_macro']} &&                    \\",
            "\t\t\t (WIDTH) == ARM64_WIDTH_64)                             \\",
            f"\t\t\t__kprog_a64_md_tag = {row['tag_define']};              \\",
        ]
    src_body += [
        "\t\telse                                                        \\",
        "\t\t\t__kprog_a64_md_src = KPROG_ARM64_MEM_SRC_NORMAL_LOAD;       \\",
        "\t\t__kprog_a64_md_src;                                         \\",
    ]
    tag_body += [
        "\t\telse                                                        \\",
        "\t\t\t__kprog_a64_md_tag = KPROG_ARM64_MEM_TAG_SCALAR;          \\",
        "\t\t__kprog_a64_md_tag;                                         \\",
    ]
    src_cont = "\n".join(src_body)
    tag_cont = "\n".join(tag_body)
    return f'''/* Generated by generate_arm64_mem_dispatch_spec.py from arm64_mem_dispatch_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_MEM_DISPATCH_H
#define KPROG_FORMAL_GENERATED_ARM64_MEM_DISPATCH_H
/*
 * AArch64 memory access-dispatch classification. The four memory spaces and the
 * two width cases are a closed table, so each predicate is total and has no
 * unsupported arm. `KPROG_ARM64_MEM_SRC_*` names the value source the read path
 * must use; `KPROG_ARM64_MEM_TAG_*` names the result-tag source (the ABI tag
 * itself is still computed by KPROG_ABI_LOAD_TAG).
 */
#define KPROG_ARM64_MEM_SRC_STACK 0U
#define KPROG_ARM64_MEM_SRC_ABI_PTR_LOAD 1U
#define KPROG_ARM64_MEM_SRC_RELOC_PTR 2U
#define KPROG_ARM64_MEM_SRC_NORMAL_LOAD 3U
#define KPROG_ARM64_MEM_TAG_STACK 0U
#define KPROG_ARM64_MEM_TAG_ABI 1U
#define KPROG_ARM64_MEM_TAG_MAP_PTR 2U
#define KPROG_ARM64_MEM_TAG_SCALAR 3U
/*
 * BASE_IS_SP is true for the stack pointer; TAG is the base register's memory
 * tag; WIDTH is the ARM64_WIDTH_* access code. Each predicate evaluates its
 * inputs and writes no NZCV.
 */
#define KPROG_ARM64_MEM_READ_SRC(BASE_IS_SP, TAG, WIDTH)                    \\
\t({{                                                                 \\
{src_cont}
\t}})
#define KPROG_ARM64_MEM_READ_TAG(BASE_IS_SP, TAG, WIDTH)                    \\
\t({{                                                                 \\
{tag_cont}
\t}})
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spaces = load()
    for path, expected in ((LEAN, render_lean(spaces)),
                           (CHEADER, render_c(spaces))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 mem-dispatch contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
