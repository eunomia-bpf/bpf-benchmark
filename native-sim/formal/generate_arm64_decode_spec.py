#!/usr/bin/env python3
"""Generate the shared AArch64 mnemonic-to-code decode tables for C, Lean, Python.

Binds the mnemonic strings the artifact encoder accepts to their numeric
simulator codes, so the encoder, the C simulator constants, and the Lean model
share one generated source:
  - ALU:   add/sub/and/bic/eor/orr  -> ARM64_ALU_*
  - SHIFT: lsl/lsr/asr/ror          -> ARM64_SHIFT_*
  - MOD:   ""/lsl/lsr/asr/ror/uxtw/sxtw/uxth/sxth/uxtb/sxtb -> ARM64_MOD_*
  - BITFIELD: ubfx/sbfx/ubfiz/bfxil/bfi -> ARM64_BITFIELD_*

The C header emits the same macro names the simulator already uses, so the
hand-written constant block is replaced by a generated one; the Lean module
exposes the tables as enumerations with independent agreement theorems; the
Python module replaces the encoder's hand-written dicts.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_decode_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64Decode.lean"
C_HEADER = ROOT / "generated/arm64_decode.h"
PYTHON = ROOT.parent / "arm64/micro-prog/generated_arm64_decode.py"

EXPECTED = {
    "alu": [("add", "ARM64_ALU_ADD", 0), ("sub", "ARM64_ALU_SUB", 1),
            ("and", "ARM64_ALU_AND", 2), ("bic", "ARM64_ALU_BIC", 3),
            ("eor", "ARM64_ALU_EOR", 4), ("orr", "ARM64_ALU_ORR", 5)],
    "shift": [("lsl", "ARM64_SHIFT_LSL", 0), ("lsr", "ARM64_SHIFT_LSR", 1),
              ("asr", "ARM64_SHIFT_ASR", 2), ("ror", "ARM64_SHIFT_ROR", 3)],
    "mod": [("", "ARM64_MOD_NONE", 0), ("lsl", "ARM64_MOD_LSL", 1),
            ("lsr", "ARM64_MOD_LSR", 2), ("asr", "ARM64_MOD_ASR", 3),
            ("ror", "ARM64_MOD_ROR", 4), ("uxtw", "ARM64_MOD_UXTW", 5),
            ("sxtw", "ARM64_MOD_SXTW", 6), ("uxth", "ARM64_MOD_UXTH", 7),
            ("sxth", "ARM64_MOD_SXTH", 8), ("uxtb", "ARM64_MOD_UXTB", 9),
            ("sxtb", "ARM64_MOD_SXTB", 10)],
    "bitfield": [("ubfx", "ARM64_BITFIELD_UBFX", 0),
                 ("sbfx", "ARM64_BITFIELD_SBFX", 1),
                 ("ubfiz", "ARM64_BITFIELD_UBFIZ", 2),
                 ("bfxil", "ARM64_BITFIELD_BFXIL", 3),
                 ("bfi", "ARM64_BITFIELD_BFI", 4)],
}

LEAN_NAMESPACES = {
    "alu": ("GeneratedArm64AluDecode", "Alu", "ARM64 ALU operation"),
    "shift": ("GeneratedArm64ShiftDecode", "Shift", "AArch64 shift kind"),
    "mod": ("GeneratedArm64ModDecode", "Mod", "AArch64 extend/shift modifier"),
    "bitfield": ("GeneratedArm64BitfieldDecode", "Bitfield",
                 "AArch64 bitfield operation"),
}


def load() -> dict[str, list]:
    data = json.loads(SPEC.read_text())
    if (set(data) != {"schema_version", "operation", "tables"}
            or data["schema_version"] != 1
            or data["operation"] != "arm64Decode"):
        raise SystemExit(f"invalid arm64 decode specification: {data!r}")
    tables = data["tables"]
    if set(tables) != set(EXPECTED):
        raise SystemExit(f"invalid arm64 decode table set: {tables!r}")
    for name, expected in EXPECTED.items():
        rows = tables[name]
        if len(rows) != len(expected):
            raise SystemExit(f"invalid arm64 {name} table: {rows!r}")
        for row, e in zip(rows, expected, strict=True):
            if set(row) != {"mnemonic", "macro", "code"}:
                raise SystemExit(f"non-canonical arm64 {name} row: {row!r}")
            if (row["mnemonic"], row["macro"], row["code"]) != e:
                raise SystemExit(f"non-canonical arm64 {name} row: {row!r}")
    return tables


def lean_name(name: str, table: str) -> str:
    if table == "mod" and name == "":
        return "none"
    return name


def render_lean(tables: dict[str, list]) -> str:
    parts = ["-- Generated by generate_arm64_decode_spec.py from arm64_decode_spec.json.",
             "import Std"]
    for table, rows in tables.items():
        ns, ty, doc = LEAN_NAMESPACES[table]
        ctors = "\n".join(f"  | {lean_name(r['mnemonic'], table)}" for r in rows)
        codes = "\n".join(
            f"  | .{lean_name(r['mnemonic'], table)} => {r['code']}" for r in rows)
        mnem = "\n".join(
            f"  | .{lean_name(r['mnemonic'], table)} => \"{r['mnemonic']}\""
            for r in rows)
        parts.append(f'''namespace KProgFormal.{ns}
/-- {doc}. -/
inductive {ty}
{ctors}
  deriving DecidableEq, Repr
def code : {ty} -> Nat
{codes}
def mnemonic : {ty} -> String
{mnem}
end KProgFormal.{ns}
''')
    return "\n".join(parts) + "\n"


def render_c(tables: dict[str, list]) -> str:
    blocks = []
    for table, rows in tables.items():
        defs = "\n".join(f"#define {r['macro']} {r['code']}U" for r in rows)
        blocks.append(defs)
    body = "\n\n".join(blocks)
    return f'''/* Generated by generate_arm64_decode_spec.py from arm64_decode_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_DECODE_H
#define KPROG_FORMAL_GENERATED_ARM64_DECODE_H
{body}
#endif
'''


def render_python(tables: dict[str, list]) -> str:
    lines = ["# Generated by generate_arm64_decode_spec.py from arm64_decode_spec.json."]
    for table, rows in tables.items():
        var = {"alu": "ALU", "shift": "SHIFT", "mod": "MOD",
               "bitfield": "BITFIELD"}[table]
        entries = "\n".join(
            f'    {r["mnemonic"]!r}: {r["macro"]!r},' for r in rows)
        lines.append(f"{var} = {{\n{entries}\n}}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    tables = load()
    outputs = (
        (LEAN, render_lean(tables)),
        (C_HEADER, render_c(tables)),
        (PYTHON, render_python(tables)),
    )
    for path, expected in outputs:
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(f"generated arm64 decode contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
