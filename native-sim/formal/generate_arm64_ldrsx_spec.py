#!/usr/bin/env python3
"""Generate the shared AArch64 sign-extending-load width contract.

The three load-sign-extend handlers (`LDRSB`, `LDRSW`, `LDRSH`) each read a fixed
memory width and then sign-extend the loaded value into the destination. The load
width is the ISA decision this contract pins: a byte load sign-extends from bit 7,
a halfword load from bit 15, and a word load from bit 31, independent of the
destination access width. The handlers already fixed the memory read at the right
width in the surrounding body; this contract supplies the *load* width code so a
mislabeled load (e.g. a word read for `LDRSB`) is observable.

The generated Lean `GeneratedArm64LdrSx.loadWidth` and the C macro
`KPROG_ARM64_LDRSX_LOAD_WIDTH` return the `ARM64_WIDTH_*` code for each opcode:
w8 for `LDRSB`, w16 for `LDRSH`, w32 for `LDRSW`. The three opcode numbers are
re-checked against native-sim/arm64/arm64_sim.h, so a drift there fails `--check`.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_ldrsx_spec.json"
SIM_HEADER = ROOT.parent / "arm64/arm64_sim.h"
LEAN = ROOT / "KProgFormal/GeneratedArm64LdrSx.lean"
CHEADER = ROOT / "generated/arm64_ldrsx.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64LdrSx",
    "operations": [
        {"name": "ldrSb", "code": 54, "width": "w8", "macro": "ARM64_OP_LDRSB"},
        {"name": "ldrSw", "code": 57, "width": "w32", "macro": "ARM64_OP_LDRSW"},
        {"name": "ldrSh", "code": 63, "width": "w16", "macro": "ARM64_OP_LDRSH"},
    ],
}

WIDTH_CODE = {"w8": 1, "w16": 2, "w32": 4, "w64": 8}
WIDTH_MACRO = {"w8": "ARM64_WIDTH_8", "w16": "ARM64_WIDTH_16",
               "w32": "ARM64_WIDTH_32", "w64": "ARM64_WIDTH_64"}

OPCODE_DEFINE = re.compile(
    r"^#define\s+(ARM64_OP_[A-Z0-9_]+)\s+0x([0-9a-fA-F]+)U\s*$", re.M)


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 ldrsx specification: {data!r}")
    ops = EXPECTED["operations"]
    if [row["name"] for row in ops] != ["ldrSb", "ldrSw", "ldrSh"]:
        raise SystemExit(f"invalid arm64 ldrsx order: {ops!r}")
    if [row["macro"] for row in ops] != [
            "ARM64_OP_LDRSB", "ARM64_OP_LDRSW", "ARM64_OP_LDRSH"]:
        raise SystemExit(f"invalid arm64 ldrsx macros: {ops!r}")
    for row in ops:
        if row["width"] not in WIDTH_CODE:
            raise SystemExit(f"invalid arm64 ldrsx width: {row!r}")
    if [row["width"] for row in ops] != ["w8", "w32", "w16"]:
        raise SystemExit(f"invalid arm64 ldrsx load widths: {ops!r}")
    opcodes = {name: int(value, 16)
               for name, value in OPCODE_DEFINE.findall(SIM_HEADER.read_text())}
    if not opcodes:
        raise SystemExit(
            f"no ARM64_OP_* opcode definitions found in {SIM_HEADER}")
    for row in ops:
        if opcodes.get(row["macro"]) != row["code"]:
            raise SystemExit(
                "arm64 ldrsx opcodes drift from native-sim/arm64/arm64_sim.h: "
                f"spec={row['macro']}={row['code']:#x} "
                f"sim={opcodes.get(row['macro'])}")
    return ops


def render_lean(ops: list[dict]) -> str:
    ctors = "\n".join(f"  | {row['name']}" for row in ops)
    codes = "\n".join(f"  | .{row['name']} => {row['code']}" for row in ops)
    suffix = {"w8": "B", "w16": "H", "w32": "W", "w64": "X"}
    mnemonics = "\n".join(
        f"  | .{row['name']} => \"LDRS{suffix[row['width']]}\""
        for row in ops)
    arms = "\n".join(
        f"  | .{row['name']} => .{row['width']}" for row in ops)
    return f'''-- Generated by generate_arm64_ldrsx_spec.py from arm64_ldrsx_spec.json.
import KProgFormal.GeneratedArm64Width
namespace KProgFormal.GeneratedArm64LdrSx
open KProgFormal.GeneratedArm64Width (Width)
/-- The three AArch64 sign-extending load opcodes. -/
inductive LdrSx where
{ctors}
deriving DecidableEq, Repr
/-- The ARM64_OP_* opcode number the load carries in arm64_sim.h. -/
def code : LdrSx -> Nat
{codes}
/-- The AArch64 mnemonic of the load. -/
def mnemonic : LdrSx -> String
{mnemonics}
/-- The width of the memory value the load reads before sign-extending it into
the destination: a byte for LDRSB, a halfword for LDRSH, a word for LDRSW. This
is the *load* width, fixed by the opcode and independent of the destination
access width, so a mislabeled load reads the wrong number of bytes. -/
def loadWidth (op : LdrSx) : Width :=
  match op with
{arms}
/-- Sign extension is applied by the shared extract/reverse/extend contract, so
every arm here reads exactly one memory value and writes no NZCV. -/
def flagsUnchanged (op : LdrSx) : Bool :=
  match op with
  | _ => true
end KProgFormal.GeneratedArm64LdrSx
'''


def render_c(ops: list[dict]) -> str:
    codes = "\n".join(
        f"_Static_assert({row['macro']} == {row['code']}U, "
        '"arm64 ldrsx code drift");'
        for row in ops)
    handled = " || \\\n\t".join(
        f"((OP) == {row['macro']})" for row in ops)
    coverage = "\n".join(
        f"_Static_assert(KPROG_ARM64_LDRSX_HANDLED({row['macro']}), "
        '"arm64 ldrsx coverage drift");'
        for row in ops)
    body = [
        "\t({",
        "\t\t__u64 __kprog_a64_ldrsx_op = (OP);",
        "\t\t__u64 __kprog_a64_ldrsx_width = 0;",
        "",
        "\t\tswitch (__kprog_a64_ldrsx_op) {",
    ]
    for row in ops:
        body.append(f"\t\tcase {row['code']}U:                          ")
        body.append(
            f"\t\t\t__kprog_a64_ldrsx_width = {WIDTH_MACRO[row['width']]};")
        body.append("\t\t\tbreak;")
    body += [
        "\t\tdefault:",
        "\t\t\tUNSUPPORTED;",
        "\t\t\tbreak;",
        "\t\t}",
        "\t\t__kprog_a64_ldrsx_width;",
        "\t})",
    ]
    continued = " \\\n".join(body)
    return f'''/* Generated by generate_arm64_ldrsx_spec.py from arm64_ldrsx_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_LDRSX_H
#define KPROG_FORMAL_GENERATED_ARM64_LDRSX_H
/*
 * The load width each sign-extending load opcode reads before sign-extending the
 * value into the destination: a byte for LDRSB, a halfword for LDRSH, a word for
 * LDRSW. This is the *load* width, fixed by the opcode and independent of the
 * destination access width, so a mislabeled load reads the wrong number of bytes.
 * An opcode outside the family reaches the caller-supplied unsupported arm.
 */
#include "arm64_width.h"
{codes}
#define KPROG_ARM64_LDRSX_HANDLED(OP)                                       \\
\t({handled})
{coverage}
/*
 * The numeric case labels 54U, 57U, and 63U track the ARM64_OP_LDRSB,
 * ARM64_OP_LDRSW, and ARM64_OP_LDRSH values defined in
 * native-sim/arm64/arm64_sim.h. OP is the opcode; OP is read once. The result is
 * the ARM64_WIDTH_* code of the value the load must read, which the handler then
 * sign-extends into the destination.
 */
#define KPROG_ARM64_LDRSX_LOAD_WIDTH(OP, UNSUPPORTED)                       \\
{continued}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    ops = load()
    for path, expected in ((LEAN, render_lean(ops)), (CHEADER, render_c(ops))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 ldrsx contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
