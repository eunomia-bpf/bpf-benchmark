#!/usr/bin/env python3
"""Generate the packed x86-64 AUX word layout for Lean and C.

Every x86 simulator instruction carries a 32-bit AUX word whose four bytes are
fixed by this contract:

  bits  0-7  index register number (`X86_REG_NONE` == 0xff means "no index")
  bits  8-15 scale exponent (base-2 log of the addressing scale factor)
  bits 16-23 memory width code (`X86_WIDTH_*`) or a register source byte lane
  bits 24-31 ALU opcode / source byte shift / condition code, per opcode

The bytes are packed little-endian, so field byte `k` occupies bits `8k`-`8k+7`
and the layout is never wider than the 32-bit word. The generator emits

  - a Lean `GeneratedX86MemAux` module whose `pack` is the C-shaped masked-or
    expression and whose four field decoders are byte extractions, plus the
    `indexNone` sentinel; and
  - the C `KPROG_X86_MEM_AUX` packer and the four `KPROG_X86_MEM_AUX_*`
    decoders that `x86/x86_sim.h` aliases its `X86_MEM_AUX*` / `X86_REG_AUX_*`
    macros to, so the simulator's addressing-mode, memory-width, source-lane,
    ALU-opcode, and condition-code fields all share one machine-checked layout.

`KProgFormal/X86MemAux.lean` proves the C-shaped packer equal to an independent
byte-concatenation specification and proves each field's roundtrip, the
sentinel roundtrip, and that the four fields are pairwise non-interfering.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_mem_aux_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86MemAux.lean"
CHEADER = ROOT / "generated/x86_mem_aux.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "x86MemAux",
    "word_bits": 32,
    "field_bits": 8,
    "fields": [
        {"name": "index", "shift": 0},
        {"name": "scale_log2", "shift": 8},
        {"name": "mem_width", "shift": 16},
        {"name": "op", "shift": 24},
    ],
    "index_none": "0xff",
}

# Lean/C identifier per spec field name.
LEAN_NAME = {
    "index": "index",
    "scale_log2": "scaleLog2",
    "mem_width": "memWidth",
    "op": "op",
}
C_NAME = {
    "index": "INDEX",
    "scale_log2": "SCALE_LOG2",
    "mem_width": "MEM_WIDTH",
    "op": "OP",
}


def load() -> dict:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 memory AUX specification: {data!r}")
    return EXPECTED


def render_lean(spec: dict) -> str:
    word = spec["word_bits"]
    width = spec["field_bits"]
    fields = spec["fields"]
    args = " ".join(LEAN_NAME[f["name"]] for f in fields)
    # C-shaped packer: mask each field and OR its shifted byte into place.
    expr = f"BitVec.and {LEAN_NAME[fields[0]['name']]} 0xff"
    for field in fields[1:]:
        name = LEAN_NAME[field["name"]]
        shift = field["shift"]
        expr = (f"BitVec.or ({expr})\n"
                f"    (BitVec.shiftLeft (BitVec.and {name} 0xff) {shift})")
    decoders = []
    for field in fields:
        name = LEAN_NAME[field["name"]]
        shift = field["shift"]
        if shift == 0:
            decoders.append(
                f"def {name} (aux : BitVec {word}) : BitVec {word} :=\n"
                f"  BitVec.and aux 0xff")
        else:
            decoders.append(
                f"def {name} (aux : BitVec {word}) : BitVec {word} :=\n"
                f"  BitVec.and (aux >>> {shift}) 0xff")
    decoder_text = "\n".join(decoders)
    return f'''-- Generated by generate_x86_mem_aux_spec.py from x86_mem_aux_spec.json.
import Std
namespace KProgFormal.GeneratedX86MemAux
/-- Pack the four {width}-bit AUX field bytes little-endian: index in bits 0-7,
scale exponent in bits 8-15, memory width in bits 16-23, and the opcode/tag
byte in bits 24-31. Each argument is masked to its byte first. -/
def pack ({args} : BitVec {word}) : BitVec {word} :=
  {expr}
{decoder_text}
/-- The `index` field value that means "no index register" (`X86_REG_NONE`). -/
def indexNone : BitVec {word} := {spec["index_none"]}
end KProgFormal.GeneratedX86MemAux
'''


def render_c(spec: dict) -> str:
    fields = spec["fields"]
    args = ", ".join(C_NAME[f["name"]] for f in fields)
    terms = []
    for field in fields:
        name = C_NAME[field["name"]]
        shift = field["shift"]
        term = f"((__u32)({name}) & 0xffU)"
        if shift:
            term = f"({term} << {shift})"
        terms.append(term)
    packer = " | \\\n\t ".join(terms)
    decoders = []
    for field in fields:
        name = C_NAME[field["name"]]
        shift = field["shift"]
        if shift == 0:
            decoders.append(
                f"#define KPROG_X86_MEM_AUX_{name}(AUX) "
                f"((__u8)((AUX) & 0xffU))")
        else:
            decoders.append(
                f"#define KPROG_X86_MEM_AUX_{name}(AUX) "
                f"((__u8)(((AUX) >> {shift}) & 0xffU))")
    decoder_text = "\n".join(decoders)
    none = int(spec["index_none"], 16)
    return f'''/* Generated by generate_x86_mem_aux_spec.py from x86_mem_aux_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_MEM_AUX_H
#define KPROG_FORMAL_GENERATED_X86_MEM_AUX_H
/*
 * Packed x86-64 simulator AUX word, four bytes little-endian:
 *   bits  0-7  index register number ({spec["index_none"]} == no index, X86_REG_NONE)
 *   bits  8-15 scale exponent (base-2 log of the addressing scale factor)
 *   bits 16-23 memory width code (X86_WIDTH_*) or a register source byte lane
 *   bits 24-31 ALU opcode / source byte shift / condition code, per opcode
 * Every argument is masked to its byte, so field bytes never bleed into one
 * another; the decoders extract the same bytes back.
 */
#define KPROG_X86_MEM_AUX({args}) \\
\t({packer})
{decoder_text}
#define KPROG_X86_MEM_AUX_INDEX_NONE {none:#x}U
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = load()
    for path, expected in ((LEAN, render_lean(spec)), (CHEADER, render_c(spec))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated x86 memory AUX contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
