#!/usr/bin/env python3
"""Generate the shared AArch64 ALU op-step (result) contract for Lean and C.

The generated Lean definition `GeneratedArm64AluResult.result` and the C macro
`KPROG_ALU64_RESULT` implement the six ALU result formulas shared by the C
simulator's op-step handlers (plain ALU immediate/register plus the flag
handlers SUBS/ADDS/ANDS/TST/BICS/CMN/CMP). The per-op expressions are the
spec's `lean` and `c` strings; the six operations and their numeric codes must
match the ALU table of arm64_decode_spec.json exactly, so the numeric case
labels in the C macro track the ARM64_ALU_* constants of the generated
arm64_decode.h without including it.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_alu_result_spec.json"
DECODE_SPEC = ROOT / "arm64_decode_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64AluResult.lean"
CHEADER = ROOT / "generated/arm64_alu_result.h"
EXPECTED = {
    "schema_version": 1,
    "operation": "arm64AluResult",
    "operations": [
        {"name": "add", "code": 0, "lean": "lhs + rhs", "c": "(LHS) + (RHS)"},
        {"name": "sub", "code": 1, "lean": "lhs - rhs", "c": "(LHS) - (RHS)"},
        {"name": "and", "code": 2, "lean": "lhs &&& rhs", "c": "(LHS) & (RHS)"},
        {"name": "bic", "code": 3, "lean": "lhs &&& ~~~ rhs",
         "c": "(LHS) & ~(RHS)"},
        {"name": "eor", "code": 4, "lean": "lhs ^^^ rhs", "c": "(LHS) ^ (RHS)"},
        {"name": "orr", "code": 5, "lean": "lhs ||| rhs", "c": "(LHS) | (RHS)"},
    ],
}


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 alu result specification: {data!r}")
    ops = EXPECTED["operations"]
    if [row["name"] for row in ops] != ["add", "sub", "and", "bic", "eor", "orr"]:
        raise SystemExit(f"invalid arm64 alu operation order: {ops!r}")
    if [row["code"] for row in ops] != [0, 1, 2, 3, 4, 5]:
        raise SystemExit(f"invalid arm64 alu result codes: {ops!r}")
    decode = json.loads(DECODE_SPEC.read_text())
    if (set(decode) != {"schema_version", "operation", "tables"}
            or decode["schema_version"] != 1
            or decode["operation"] != "arm64Decode"):
        raise SystemExit(f"invalid arm64 decode specification: {decode!r}")
    alu_table = decode["tables"]["alu"]
    if [tuple(row[key] for key in ("mnemonic", "macro", "code"))
            for row in alu_table] != [
            (row["name"], "ARM64_ALU_" + row["name"].upper(), row["code"])
            for row in ops]:
        raise SystemExit(
            "arm64 alu result codes drift from the arm64 decode ALU table: "
            f"result={[ (row['name'], row['code']) for row in ops]} "
            f"decode={[(row['mnemonic'], row['code']) for row in alu_table]}")
    return ops


def render_lean(ops: list[dict]) -> str:
    arms = "\n".join(
        f"  | .{row['name']} => {row['lean']}" for row in ops)
    return f'''-- Generated by generate_arm64_alu_result_spec.py from arm64_alu_result_spec.json.
import KProgFormal.GeneratedArm64Decode
namespace KProgFormal.GeneratedArm64AluResult
open GeneratedArm64AluDecode (Alu)
/-- Shared AArch64 ALU op-step result. The match arms follow the generated
Arm64Decode Alu codes; this single result definition is the op-step contract. -/
def result (op : Alu) (lhs rhs : BitVec 64) : BitVec 64 :=
  match op with
{arms}
end KProgFormal.GeneratedArm64AluResult
'''


def render_c(ops: list[dict]) -> str:
    body = ["\t({", "\t\t__u64 __kprog_alu64_res = 0;", "\t\tswitch (OP) {"]
    for row in ops:
        body.append(f"\t\tcase {row['code']}U:                          ")
        body.append(f"\t\t\t__kprog_alu64_res = {row['c']};")
        body.append("\t\t\tbreak;")
    body += [
        "\t\tdefault:",
        "\t\t\tUNSUPPORTED;",
        "\t\t\tbreak;",
        "\t\t}",
        "\t\t__kprog_alu64_res;",
    ]
    continued = " \\\n".join(body)
    head = '''/* Generated by generate_arm64_alu_result_spec.py from arm64_alu_result_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_ALU_RESULT_H
#define KPROG_FORMAL_GENERATED_ARM64_ALU_RESULT_H
/*
 * The numeric case labels 0U..5U track the ARM64_ALU_* values defined in
 * generated/arm64_decode.h. This header intentionally does not include
 * arm64_decode.h, so it stays usable standalone; load() re-checks the codes
 * against arm64_decode_spec.json and exits 1 if they drift.
 */
#define KPROG_ALU64_RESULT(OP, LHS, RHS, UNSUPPORTED)                       \\
'''
    return head + continued + " \\\n\t})\n#endif\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    ops = load()
    for path, expected in ((LEAN, render_lean(ops)),
                           (CHEADER, render_c(ops))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(f"generated arm64 alu result contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
