#!/usr/bin/env python3
"""Generate the shared x86 register operand-read contract."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_reg_read_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86RegRead.lean"
C_HEADER = ROOT / "generated/x86_reg_read.h"
EXPECTED = {
    "schema_version": 1,
    "operation": "x86RegRead",
    "byte_lanes": [
        {"name": "low", "shift": 0},
        {"name": "high", "shift": 8},
    ],
    "widths": [
        {"name": "w8", "bits": 8},
        {"name": "w16", "bits": 16},
        {"name": "w32", "bits": 32},
        {"name": "w64", "bits": 64},
    ],
}


def load() -> None:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 register-read specification: {data!r}")


def render_lean() -> str:
    return '''-- Generated by generate_x86_reg_read_spec.py from x86_reg_read_spec.json.
import KProgFormal.GeneratedX86Width
import KProgFormal.GeneratedX86RegWrite
namespace KProgFormal.GeneratedX86RegRead
abbrev ByteLane := GeneratedX86RegWrite.ByteLane
def readAt (value : BitVec 64) (width : GeneratedX86Width.Width)
    (lane : ByteLane) : BitVec 64 :=
  match width, lane with
  | .w8, .low => BitVec.and value 0xff
  | .w8, .high => BitVec.and (value >>> 8) 0xff
  | .w16, _ => BitVec.and value 0xffff
  | .w32, _ => BitVec.and value 0xffffffff
  | .w64, _ => value
end KProgFormal.GeneratedX86RegRead
'''


def render_c() -> str:
    return '''/* Generated by generate_x86_reg_read_spec.py from x86_reg_read_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_REG_READ_H
#define KPROG_FORMAL_GENERATED_X86_REG_READ_H
#define KPROG_X86_READ_REG_AT(VALUE, WIDTH, BYTE_SHIFT)                    \\
\tKPROG_X86_APPLY_WIDTH(                                               \\
\t\t(VALUE) >> ((WIDTH) == X86_WIDTH_8 ? (BYTE_SHIFT) : 0U),   \\
\t\t(WIDTH))
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    load()
    for path, expected in ((LEAN, render_lean()), (C_HEADER, render_c())):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated x86 register-read contract is stale: {path}"
                )
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
