#!/usr/bin/env python3
"""Generate the shared x86 POPCNT population-count contract.

The generated Lean definition `GeneratedX86Popcount.value` and the C function
`kprog_x86_popcount_value` implement the 64-bit population count the simulator's
POPCNT handler applies to the narrowed source operand. The implementation is the
standard SWAR reduction; the independent statement groups the input into eight
byte lanes and sums each lane's bit walk, so the proof relates the SWAR constants
to an explicit bit enumeration rather than restating the same trick.

The C function evaluates its operand once and writes no flags.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_popcount_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86Popcount.lean"
C_HEADER = ROOT / "generated/x86_popcount.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "x86Popcount",
    "bits": 64,
    "lanes": 8,
    "shape": "swar",
}


def load() -> None:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 popcount specification: {data!r}")


def render_lean() -> str:
    return '''-- Generated by generate_x86_popcount_spec.py from x86_popcount_spec.json.
import Std
namespace KProgFormal.GeneratedX86Popcount
/-- The SWAR population count of a 64-bit word: the standard pairwise reduction
followed by the byte-gather multiply. -/
def value (x : BitVec 64) : BitVec 64 :=
  let v1 := x - ((x >>> 1) &&& 0x5555555555555555)
  let v2 := (v1 &&& 0x3333333333333333) + ((v1 >>> 2) &&& 0x3333333333333333)
  let v3 := (v2 + (v2 >>> 4)) &&& 0x0f0f0f0f0f0f0f0f
  (v3 * 0x0101010101010101) >>> 56
end KProgFormal.GeneratedX86Popcount
'''


def render_c() -> str:
    return '''/* Generated by generate_x86_popcount_spec.py from x86_popcount_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_POPCOUNT_H
#define KPROG_FORMAL_GENERATED_X86_POPCOUNT_H
/*
 * x86 POPCNT: the population count of the 64-bit operand, computed by the
 * standard SWAR reduction. The operand is evaluated once and no flags are
 * written here (the handler sets CF/OF/SF/ZF separately).
 */
static __always_inline __u64 kprog_x86_popcount_value(__u64 value)
{
\tvalue = value - ((value >> 1) & 0x5555555555555555ULL);
\tvalue = (value & 0x3333333333333333ULL) +
\t\t((value >> 2) & 0x3333333333333333ULL);
\tvalue = (value + (value >> 4)) & 0x0f0f0f0f0f0f0f0fULL;
\treturn (value * 0x0101010101010101ULL) >> 56;
}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    load()
    for path, expected in ((LEAN, render_lean()), (C_HEADER, render_c())):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated x86 popcount contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
