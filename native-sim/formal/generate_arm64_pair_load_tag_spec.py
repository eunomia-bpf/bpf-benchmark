#!/usr/bin/env python3
"""Generate the shared AArch64 pair-load provenance-preservation contract.

The `LDP` handler (`ARM64_OP_LDP`) reads two 64-bit slots, each with its own
memory-read provenance tag, and decides per slot whether the destination is
written through the tag-copy register write (attaching that slot's tag) or the
tag-dropping width-narrowed scalar write. The simulator inlined an outer pair gate
(`width == 64 && (tagLo != SCALAR || tagHi != SCALAR)`) around two per-slot
`tag != SCALAR` decisions; the routing decision is the generated contract.

The generated Lean `routeMask` mirrors that gate-then-per-slot structure, and the
contract proves it equals an independent per-slot rule keyed on the width's bit
count and each tag's scalar class; the generated C macro
`KPROG_ARM64_PAIR_LOAD_TAG_ROUTE` returns the two-bit routing mask (bit 0 = low
slot, bit 1 = high slot). The opcode number is re-checked against
native-sim/arm64/arm64_sim.h, so a drift there fails `--check`.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_pair_load_tag_spec.json"
SIM_HEADER = ROOT.parent / "arm64/arm64_sim.h"
LEAN = ROOT / "KProgFormal/GeneratedArm64PairLoadTag.lean"
CHEADER = ROOT / "generated/arm64_pair_load_tag.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64PairLoadTag",
    "opcode": {"name": "ldp", "macro": "ARM64_OP_LDP", "code": 33},
    "slot_count": 2,
    "preserve_rule": "pair_gate_then_per_slot_tag_class",
}

OPCODE_DEFINE = re.compile(
    r"^#define\s+(ARM64_OP_[A-Z0-9_]+)\s+0x([0-9a-fA-F]+)U\s*$", re.M)


def load() -> dict:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 pair-load-tag specification: {data!r}")
    opcode = EXPECTED["opcode"]
    if opcode["name"] != "ldp" or EXPECTED["slot_count"] != 2:
        raise SystemExit(f"invalid arm64 pair-load-tag specification: {data!r}")
    if EXPECTED["preserve_rule"] != "pair_gate_then_per_slot_tag_class":
        raise SystemExit(f"invalid arm64 pair-load-tag preserve rule: {EXPECTED!r}")
    opcodes = {name: int(value, 16)
               for name, value in OPCODE_DEFINE.findall(SIM_HEADER.read_text())}
    if not opcodes:
        raise SystemExit(
            f"no ARM64_OP_* opcode definitions found in {SIM_HEADER}")
    if opcodes.get(opcode["macro"]) != opcode["code"]:
        raise SystemExit(
            "arm64 pair-load-tag opcode drifts from native-sim/arm64/arm64_sim.h: "
            f"spec={opcode['macro']}={opcode['code']:#x} "
            f"sim={opcodes.get(opcode['macro'])}")
    return opcode


def render_lean(opcode: dict) -> str:
    return f'''-- Generated by generate_arm64_pair_load_tag_spec.py from arm64_pair_load_tag_spec.json.
import KProgFormal.GeneratedArm64Width
namespace KProgFormal.GeneratedArm64PairLoadTag
open KProgFormal.GeneratedArm64Width (Width)
/-- The ARM64_OP_* opcode number the pair load carries in arm64_sim.h. -/
def code : Nat := {opcode['code']}
/-- The number of slots a pair load transfers: the low slot then the high slot. -/
def slotCount : Nat := {EXPECTED['slot_count']}
/-- Whether one slot of a pair load preserves its memory-read provenance tag: it
does exactly at doubleword width and when the tag is not the bare scalar tag. -/
def slotPreserve (width : Width) (tagIsScalar : Bool) : Bool :=
  width == .w64 && !tagIsScalar
/-- The outer pair gate the handler inlined: the per-slot paths are reached only
at doubleword width and only when at least one slot tag is non-scalar. -/
def pairGate (width : Width) (loScalar hiScalar : Bool) : Bool :=
  width == .w64 && (!loScalar || !hiScalar)
/-- The two-bit routing mask the generated C returns, mirroring the handler's
gate-then-per-slot structure: bit 0 selects the tag-copy write for the low slot,
bit 1 for the high slot, and the gate clears both when it is false. -/
def routeMask (width : Width) (loScalar hiScalar : Bool) : Nat :=
  if pairGate width loScalar hiScalar then
    (if slotPreserve width loScalar then 1 else 0) +
      (if slotPreserve width hiScalar then 2 else 0)
  else 0
end KProgFormal.GeneratedArm64PairLoadTag
'''


def render_c(opcode: dict) -> str:
    return f'''/* Generated by generate_arm64_pair_load_tag_spec.py from arm64_pair_load_tag_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_PAIR_LOAD_TAG_H
#define KPROG_FORMAL_GENERATED_ARM64_PAIR_LOAD_TAG_H
/*
 * The routing decision of the AArch64 pair load: the outer pair gate
 * (`width == 64 && (tagLo != SCALAR || tagHi != SCALAR)`) guarding two per-slot
 * tag-class decisions. The result is a two-bit mask: bit 0 selects the tag-copy
 * register write for the low slot (attaching TAG_LO), bit 1 for the high slot
 * (attaching TAG_HI); a clear bit selects the tag-dropping width-narrowed scalar
 * write.
 * An opcode outside the family reaches the caller-supplied unsupported arm.
 */
#include "arm64_width.h"
_Static_assert(ARM64_OP_LDP == {opcode['code']}U, "arm64 pair-load-tag code drift");
/*
 * The numeric case label {opcode['code']}U tracks the ARM64_OP_LDP value defined in
 * native-sim/arm64/arm64_sim.h. OP is the opcode, TAG_LO/TAG_HI the memory-read
 * provenance tags of the low and high slots, WIDTH the access width code; OP,
 * TAG_LO, TAG_HI and WIDTH are each read once. The handler then writes the low
 * slot to DST through KPROG_ARM64_PAIR_LOAD_TAG_ROUTE_LOW(mask) and the high slot
 * to SRC through KPROG_ARM64_PAIR_LOAD_TAG_ROUTE_HIGH(mask).
 */
#define KPROG_ARM64_PAIR_LOAD_TAG_ROUTE(OP, TAG_LO, TAG_HI, WIDTH, UNSUPPORTED)\\
\t({{ \\
\t\t__u64 __kprog_a64_plt_op = (OP); \\
\t\t__u64 __kprog_a64_plt_lo = (TAG_LO); \\
\t\t__u64 __kprog_a64_plt_hi = (TAG_HI); \\
\t\t__u64 __kprog_a64_plt_width = (WIDTH); \\
\t\t__u64 __kprog_a64_plt_mask = 0; \\
\\
\t\tswitch (__kprog_a64_plt_op) {{ \\
\t\tcase {opcode['code']}U:                            \\
\t\t\tif (__kprog_a64_plt_width == ARM64_WIDTH_64 && \\
\t\t\t    (__kprog_a64_plt_lo != ARM64_SIM_TAG_SCALAR || \\
\t\t\t     __kprog_a64_plt_hi != ARM64_SIM_TAG_SCALAR)) {{ \\
\t\t\t\tif (__kprog_a64_plt_lo != ARM64_SIM_TAG_SCALAR)\\
\t\t\t\t\t__kprog_a64_plt_mask |= 1U; \\
\t\t\t\tif (__kprog_a64_plt_hi != ARM64_SIM_TAG_SCALAR)\\
\t\t\t\t\t__kprog_a64_plt_mask |= 2U; \\
\t\t\t}} \\
\t\t\tbreak; \\
\t\tdefault: \\
\t\t\tUNSUPPORTED; \\
\t\t\tbreak; \\
\t\t}} \\
\t\t__kprog_a64_plt_mask; \\
\t}})
/*
 * The two slot route bits of the mask produced by
 * KPROG_ARM64_PAIR_LOAD_TAG_ROUTE: the low slot (bit 0) and the high slot
 * (bit 1). Each is read once.
 */
#define KPROG_ARM64_PAIR_LOAD_TAG_ROUTE_LOW(MASK) (((MASK) & 1U) != 0U)
#define KPROG_ARM64_PAIR_LOAD_TAG_ROUTE_HIGH(MASK) (((MASK) & 2U) != 0U)
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    opcode = load()
    for path, expected in ((LEAN, render_lean(opcode)), (CHEADER, render_c(opcode))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 pair-load-tag contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
