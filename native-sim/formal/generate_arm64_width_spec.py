#!/usr/bin/env python3
"""Generate the shared AArch64 width/narrowing contract for Lean and C.

AArch64 uses the same four simulator width encodings as x86 (the ReverseSim
subsets both encode W/X as 32/64 and reuse 8/16 for byte/halfword accesses), so
the width table is identical in structure but carries its own generated source
for the ARM64 simulator rather than importing the x86 one.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_width_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64Width.lean"
CHEADER = ROOT / "generated/arm64_width.h"
EXPECTED = [
    ("w8", 1, 8, "0xff", "0x80"),
    ("w16", 2, 16, "0xffff", "0x8000"),
    ("w32", 4, 32, "0xffffffff", "0x80000000"),
    ("w64", 8, 64, "0xffffffffffffffff", "0x8000000000000000"),
]


def load():
    data = json.loads(SPEC.read_text())
    if (set(data) != {"schema_version", "operation", "widths", "effective"}
            or data["schema_version"] != 1 or data["operation"] != "arm64Width"):
        raise SystemExit(f"invalid arm64 width specification: {data!r}")
    if len(data["widths"]) != 4:
        raise SystemExit(f"invalid arm64 width list: {data['widths']!r}")
    for w, e in zip(data["widths"], EXPECTED, strict=True):
        if (set(w) != {"name", "code", "bits", "mask", "sign_mask"}
                or (w["name"], w["code"], w["bits"], w["mask"], w["sign_mask"]) != e):
            raise SystemExit(f"non-canonical arm64 width: {w!r}")
    if set(data["effective"]) != {"absent_code", "default_name"}:
        raise SystemExit(f"invalid arm64 effective width resolution: {data['effective']!r}")
    ac = data["effective"]["absent_code"]
    names = [w["name"] for w in data["widths"]]
    codes_ = [w["code"] for w in data["widths"]]
    if ac != 0:
        raise SystemExit(f"non-canonical arm64 effective absent code: {data['effective']!r}")
    if ac in codes_:
        raise SystemExit(f"arm64 effective absent code collides with a width code: {data['effective']!r}")
    if data["effective"]["default_name"] not in names:
        raise SystemExit(f"unknown arm64 effective default width: {data['effective']!r}")
    default = [w for w in data["widths"] if w["name"] == data["effective"]["default_name"]][0]
    if default["bits"] != 64:
        raise SystemExit(f"arm64 effective default must be the 64-bit width: {default!r}")
    return data["widths"], data["effective"]


def render_lean(ws, eff):
    cs = "\n".join(f"  | {w['name']}" for w in ws)
    codes = "\n".join(f"  | .{w['name']} => {w['code']}" for w in ws)
    ms = "\n".join(f"  | .{w['name']} => BitVec.ofNat 64 {w['mask']}" for w in ws)
    signs = "\n".join(f"  | .{w['name']} => BitVec.ofNat 64 {w['sign_mask']}" for w in ws)
    bs = "\n".join(f"  | .{w['name']} => {w['bits']}" for w in ws)
    default = [w for w in ws if w["name"] == eff["default_name"]][0]
    return f'''-- Generated by generate_arm64_width_spec.py from arm64_width_spec.json.
import Std
namespace KProgFormal.GeneratedArm64Width
inductive Width
{cs}
  deriving DecidableEq, Repr
def code : Width -> Nat
{codes}
def mask : Width -> BitVec 64
{ms}
def signMask : Width -> BitVec 64
{signs}
def bits : Width -> Nat
{bs}
def narrow (value : BitVec 64) (width : Width) := BitVec.and value (mask width)
def zero (value : BitVec 64) (width : Width) : Bool := narrow value width == 0
def sign (value : BitVec 64) (width : Width) : Bool := (narrow value width).getLsbD (bits width - 1)
/-- The decoded width code that means "absent": a body that leaves its width
field empty falls back to the default code. -/
def absentCode : Nat := {eff["absent_code"]}
/-- The decoded width code an absent width field resolves to: the {default["bits"]}-bit width. -/
def defaultCode : Nat := {default["code"]}
/-- Resolve a decoded width code to the code a body operates at. The absent code
({eff["absent_code"]}) falls back to {default["code"]} (the {default["bits"]}-bit width); every other code is used as
decoded, exactly as the simulator's inline fallback did. -/
def effective (code : Nat) : Nat :=
  if code = absentCode then defaultCode else code
end KProgFormal.GeneratedArm64Width
'''


def render_c(ws, eff):
    assertions = "\n".join(
        f'_Static_assert(ARM64_WIDTH_{w["bits"]} == {w["code"]}U, "arm64 width code drift");'
        for w in ws)
    masks = " \\\n".join(
        f"\t((WIDTH) == ARM64_WIDTH_{w['bits']} ? {w['mask']}ULL :" for w in ws[:-1])
    signs = " \\\n".join(
        f"\t((WIDTH) == ARM64_WIDTH_{w['bits']} ? {w['sign_mask']}ULL :" for w in ws[:-1])
    bits = " \\\n".join(
        f"\t((WIDTH) == ARM64_WIDTH_{w['bits']} ? {w['bits']}U :" for w in ws[:-1])
    closes = ")" * 3
    default = [w for w in ws if w["name"] == eff["default_name"]][0]
    return f'''/* Generated by generate_arm64_width_spec.py from arm64_width_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_WIDTH_H
#define KPROG_FORMAL_GENERATED_ARM64_WIDTH_H
{assertions}
#define KPROG_ARM64_WIDTH_MASK(WIDTH)                                       \\
{masks} \\
\t 0xffffffffffffffffULL{closes}
#define KPROG_ARM64_WIDTH_SIGN_MASK(WIDTH)                                  \\
{signs} \\
\t 0x8000000000000000ULL{closes}
#define KPROG_ARM64_WIDTH_BITS(WIDTH)                                       \\
{bits} \\
\t 64U{closes}
#define KPROG_ARM64_APPLY_WIDTH(VALUE, WIDTH) ((VALUE) & KPROG_ARM64_WIDTH_MASK(WIDTH))
/* The decoded width code that means "absent": a body that leaves its width
 * field empty falls back to the default code. */
#define KPROG_ARM64_WIDTH_ABSENT_CODE {eff["absent_code"]}U
#define KPROG_ARM64_WIDTH_EFFECTIVE_DEFAULT ARM64_WIDTH_{default["bits"]}
/* Resolve a decoded width code to the code a body operates at: the absent code
 * ({eff["absent_code"]}) falls back to the {default["bits"]}-bit default, every other code is used as
 * decoded. The operand is evaluated as the body evaluates it. */
#define KPROG_ARM64_WIDTH_EFFECTIVE(CODE)                                   \\
\t((CODE) != KPROG_ARM64_WIDTH_ABSENT_CODE ? (CODE) :                     \\
\t KPROG_ARM64_WIDTH_EFFECTIVE_DEFAULT)
#endif
'''


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    ws, eff = load()
    for path, expected in ((LEAN, render_lean(ws, eff)), (CHEADER, render_c(ws, eff))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(f"generated arm64 width contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
