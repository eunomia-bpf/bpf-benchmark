#!/usr/bin/env python3
"""Generate shared x86 SHL/SHR/SAR/ROL result semantics for Lean and C."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_shift_result_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86ShiftResult.lean"
C_HEADER = ROOT / "generated/x86_shift_result.h"
EXPECTED = {
    "schema_version": 1,
    "operation": "x86ShiftResult",
    "operations": ["shl", "shr", "sar", "rol"],
    "count": "x86ShiftCount",
    "operand": "narrow",
    "sar": "unsigned_sign_fill",
}


def load() -> None:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 shift-result specification: {data!r}")


def render_lean() -> str:
    return '''-- Generated by generate_x86_shift_result_spec.py from x86_shift_result_spec.json.
import KProgFormal.GeneratedX86ShiftCount
namespace KProgFormal.GeneratedX86ShiftResult
open GeneratedX86Width
def shl (value rhs : BitVec 64) (width : Width) : BitVec 64 :=
  let count := GeneratedX86ShiftCount.count rhs width
  narrow (narrow value width <<< count) width
def shr (value rhs : BitVec 64) (width : Width) : BitVec 64 :=
  let count := GeneratedX86ShiftCount.count rhs width
  narrow value width >>> count
def sar (value rhs : BitVec 64) (width : Width) : BitVec 64 :=
  let count := GeneratedX86ShiftCount.count rhs width
  let narrowed := narrow value width
  if count = 0 then narrowed
  else
    let shifted := narrowed >>> count
    if BitVec.and narrowed (signMask width) != 0 then
      BitVec.or shifted (BitVec.xor (mask width) (mask width >>> count))
    else shifted
def rol (value rhs : BitVec 64) (width : Width) : BitVec 64 :=
  let bits := bits width
  let count := BitVec.and (GeneratedX86ShiftCount.count rhs width)
    (BitVec.ofNat 64 (bits - 1))
  let narrowed := narrow value width
  if count = 0 then narrowed
  else narrow ((narrowed <<< count) |||
    (narrowed >>> (BitVec.ofNat 64 bits - count))) width
end KProgFormal.GeneratedX86ShiftResult
'''


def render_c() -> str:
    return '''/* Generated by generate_x86_shift_result_spec.py from x86_shift_result_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_SHIFT_RESULT_H
#define KPROG_FORMAL_GENERATED_X86_SHIFT_RESULT_H
static __always_inline __u64 kprog_x86_shl_result(__u64 value, __u64 rhs,
                                                   __u8 width)
{
\t__u8 count = KPROG_X86_SHIFT_COUNT(rhs, width);
\t__u64 mask = KPROG_X86_WIDTH_MASK(width);
\t__u64 narrowed = value & mask;

\treturn (narrowed << count) & mask;
}

static __always_inline __u64 kprog_x86_shr_result(__u64 value, __u64 rhs,
                                                   __u8 width)
{
\t__u8 count = KPROG_X86_SHIFT_COUNT(rhs, width);
\t__u64 narrowed = value & KPROG_X86_WIDTH_MASK(width);

\treturn narrowed >> count;
}

static __always_inline __u64 kprog_x86_sar_result(__u64 value, __u64 rhs,
                                                   __u8 width)
{
\t__u8 count = KPROG_X86_SHIFT_COUNT(rhs, width);
\t__u64 mask = KPROG_X86_WIDTH_MASK(width);
\t__u64 narrowed = value & mask;
\t__u64 shifted;

\tif (count == 0)
\t\treturn narrowed;
\tshifted = narrowed >> count;
\tif (narrowed & KPROG_X86_WIDTH_SIGN_MASK(width))
\t\tshifted |= mask ^ (mask >> count);
\treturn shifted;
}

static __always_inline __u64 kprog_x86_rol_result(__u64 value, __u64 rhs,
                                                   __u8 width)
{
\t__u32 bits = KPROG_X86_WIDTH_BITS(width);
\t__u64 mask = KPROG_X86_WIDTH_MASK(width);
\t__u64 count = KPROG_X86_SHIFT_COUNT(rhs, width) & (bits - 1);
\t__u64 narrowed = value & mask;

\tif (count == 0)
\t\treturn narrowed;
\treturn ((narrowed << count) | (narrowed >> (bits - count))) & mask;
}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    load()
    for path, expected in ((LEAN, render_lean()), (C_HEADER, render_c())):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(f"generated x86 shift-result contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
