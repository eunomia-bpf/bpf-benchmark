#!/usr/bin/env python3
"""Generate the x86-64 `ANDN` / `ANDN_MEM` handler-composition contract.

`ANDN` (`X86_OP_ANDN`, `0x3d`) and `ANDN_MEM` (`X86_OP_ANDN_MEM`, `0x44`)
are two `X86_SIM_L_EXEC` arms sharing one result shape, `(~src1) & src2`, so
this contract carries a per-opcode table. It pins the facts the two bodies
share and the one fact that separates them:

  * the *destination write* width is the `FLAGS`-resolved width,
    `FLAGS ? FLAGS : 64`, for both bodies;
  * `ANDN` reads its second operand from a register (`AUX`); `ANDN_MEM` reads
    it from memory at a *second, independently selected* width —
    `X86_MEM_AUX_MEM_WIDTH(AUX)`, falling back to the resolved `FLAGS` width
    when that field is absent (zero);
  * both take `CF = OF = 0` and derive `ZF`/`SF` from the result at the
    resolved write width; and
  * both write the destination through the partial-register primitive.

The load width is the binding asymmetry: a body whose memory read width
tracked the `FLAGS` code (as the write width does) would still produce a
plausible value, but would read the wrong number of bytes whenever the AUX
field names a width the `FLAGS` code does not.

The two `X86_SIM_L_EXEC_ANDN` / `X86_SIM_L_EXEC_ANDN_MEM` bodies route through
this contract: they share one `X86_SIM_L_EXEC_ANDN_STEP` composition that
selects the second-operand source through `KPROG_X86_ANDN_SOURCE`, the
destination write width through `KPROG_X86_ANDN_WRITE_WIDTH`, and the
memory-read width through `KPROG_X86_ANDN_MEM_WIDTH`, while the complement/and,
the flag production, and the register writeback stay in the composed body.

Outputs (both regenerated whole, `--check` rejects any stale copy):
  * `KProgFormal/GeneratedX86Andn.lean`
  * `generated/x86_andn.h`
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_andn_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86Andn.lean"
CHEADER = ROOT / "generated/x86_andn.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "x86Andn",
    "selector": "flags_resolved_write_width_then_aux_mem_width_or_write_width_then_complement_and",
    "opcodes": [
        {"name": "andn", "define": "X86_OP_ANDN", "code": "0x3d",
         "source": "registerRead"},
        {"name": "andnMem", "define": "X86_OP_ANDN_MEM", "code": "0x44",
         "source": "memoryRead"},
    ],
    "mem_width_arms": [
        {"name": "auxField", "absent": False,
         "define": "KPROG_X86_ANDN_MEM_WIDTH_AUX"},
        {"name": "flagsFallback", "absent": True,
         "define": "KPROG_X86_ANDN_MEM_WIDTH_FLAGS"},
    ],
    "write_width_default": "b64",
}

OP_ORDER = ("andn", "andnMem")
OP_DEFINES = {"andn": "X86_OP_ANDN", "andnMem": "X86_OP_ANDN_MEM"}
OP_CODES = {"andn": "0x3d", "andnMem": "0x44"}
OP_SOURCES = {"andn": "registerRead", "andnMem": "memoryRead"}

ARM_ORDER = ("auxField", "flagsFallback")
ARM_ABSENT = {"auxField": False, "flagsFallback": True}
ARM_DEFINES = {"auxField": "KPROG_X86_ANDN_MEM_WIDTH_AUX",
               "flagsFallback": "KPROG_X86_ANDN_MEM_WIDTH_FLAGS"}

WRITE_WIDTH_DEFAULT = "b64"


def load():
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 andn specification: {data!r}")
    ops = data["opcodes"]
    if [row["name"] for row in ops] != list(OP_ORDER):
        raise SystemExit(f"invalid x86 andn opcodes: {ops!r}")
    if [row["define"] for row in ops] != [OP_DEFINES[n] for n in OP_ORDER]:
        raise SystemExit(f"invalid x86 andn opcode defines: {ops!r}")
    if [row["code"] for row in ops] != [OP_CODES[n] for n in OP_ORDER]:
        raise SystemExit(f"invalid x86 andn opcode codes: {ops!r}")
    if [row["source"] for row in ops] != [OP_SOURCES[n] for n in OP_ORDER]:
        raise SystemExit(f"invalid x86 andn opcode sources: {ops!r}")
    if len({row["define"] for row in ops}) != len(ops):
        raise SystemExit(f"duplicate x86 andn opcode: {ops!r}")
    arms = data["mem_width_arms"]
    if [row["name"] for row in arms] != list(ARM_ORDER):
        raise SystemExit(f"invalid x86 andn mem-width arms: {arms!r}")
    if [row["absent"] for row in arms] != [ARM_ABSENT[n] for n in ARM_ORDER]:
        raise SystemExit(f"invalid x86 andn mem-width absence: {arms!r}")
    if len({row["define"] for row in arms}) != len(arms):
        raise SystemExit(f"duplicate x86 andn mem-width arm: {arms!r}")
    if data["write_width_default"] != WRITE_WIDTH_DEFAULT:
        raise SystemExit(f"invalid x86 andn write width default: {data!r}")
    return data


def render_lean(data, opcode_rows, arm_rows) -> str:
    op_ctors = "\n".join(f"  | {row['name']}" for row in opcode_rows)
    op_src_arms = "\n".join(
        f"  | .{row['name']} => .{row['source']}" for row in opcode_rows)
    arm_ctors = "\n".join(f"  | {row['name']}" for row in arm_rows)
    return f'''-- Generated by generate_x86_andn_spec.py from x86_andn_spec.json.
import Std
import KProgFormal.GeneratedX86Store
namespace KProgFormal.GeneratedX86Andn
open GeneratedX86Store (Code)
/-- The two ANDN opcodes this contract spans: `ANDN` reads its second operand
from a register, `ANDN_MEM` reads it from memory. -/
inductive Op where
{op_ctors}
deriving DecidableEq, Repr
/-- Where each opcode reads its second source operand. -/
inductive Source where
  | registerRead
  | memoryRead
deriving DecidableEq, Repr
/-- The second-operand source each opcode uses: `ANDN` a register read,
`ANDN_MEM` a memory read at the independently selected memory width. -/
def source : Op -> Source
{op_src_arms}
/-- The width a body falls back to when its opcode carries the "absent" FLAGS
code 0. -/
def writeWidthDefault : GeneratedX86Store.Code := .{WRITE_WIDTH_DEFAULT}
/-- The resolved destination write width: the opcode's FLAGS code itself, or 64
bits when it carries none. -/
def resolveWidth : Code -> Code
  | .absent => .b64
  | .b8 => .b8
  | .b16 => .b16
  | .b32 => .b32
  | .b64 => .b64
/-- The two arms of the memory-read width selection: the AUX field's own width,
or the resolved FLAGS fallback the body takes when the field is absent (zero). -/
inductive MemWidthArm where
{arm_ctors}
deriving DecidableEq, Repr
/-- The arm a memory read takes from the raw AUX width code: the field's own
width when the code names one, the resolved-`FLAGS` fallback when the code is
the absent code 0. -/
def memWidthArm : Code -> MemWidthArm
  | .absent => .flagsFallback
  | .b8 => .auxField
  | .b16 => .auxField
  | .b32 => .auxField
  | .b64 => .auxField
end KProgFormal.GeneratedX86Andn
'''


OP_CODES_SYMBOL = {"andn": "opAndn", "andnMem": "opAndnMem"}


def render_c(data, opcode_rows, arm_rows) -> str:
    op_asserts = "\n".join(
        f'_Static_assert({row["define"]} == {row["code"]}U, '
        f'"x86 andn {row["name"]} opcode drift");'
        for row in opcode_rows)
    op_source_defines = "\n".join(
        f'#define KPROG_X86_ANDN_OP_{row["define"][len("X86_OP_"):]}_SOURCE '
        f'KPROG_X86_ANDN_SOURCE_'
        f'{"MEMORY" if row["source"] == "memoryRead" else "REGISTER"}'
        for row in opcode_rows)
    arm_defines = "\n".join(
        f'#define {row["define"]} {1 if row["absent"] else 0}U'
        for row in arm_rows)
    lines = [
        "/* Generated by generate_x86_andn_spec.py from x86_andn_spec.json. */",
        "#ifndef KPROG_FORMAL_GENERATED_X86_ANDN_H",
        "#define KPROG_FORMAL_GENERATED_X86_ANDN_H",
        "/*",
        " * x86-64 `ANDN` / `ANDN_MEM` handler-composition contract. Both bodies",
        " * compute `(~src1) & src2`, take CF=OF=0, derive ZF/SF from the result at",
        " * the FLAGS-resolved write width, and write the destination through the",
        " * partial-register primitive. `ANDN` reads src2 from a register (`AUX`);",
        " * `ANDN_MEM` reads it from memory at `X86_MEM_AUX_MEM_WIDTH(AUX)`, falling",
        " * back to the resolved FLAGS width when that field is absent - a second,",
        " * independently selected width that is *not* the destination write width.",
        " * The contract selects the two opcodes, the second-operand source, and the",
        " * memory-width arm; the complement/and, the flag production, and the",
        " * register writeback stay in the one shared `X86_SIM_L_EXEC_ANDN_STEP`",
        " * composition the two bodies route through.",
        " */",
        op_asserts,
        "/* The FLAGS width codes, including the 0 \"absent\" code. */",
        "#define X86_WIDTH_8 1U",
        "#define X86_WIDTH_16 2U",
        "#define X86_WIDTH_32 4U",
        "#define X86_WIDTH_64 8U",
        "_Static_assert(X86_WIDTH_64 == 8U, \"x86 width code drift\");",
        "/* The width a body falls back to when its FLAGS code is absent. */",
        "#define KPROG_X86_ANDN_WRITE_WIDTH_DEFAULT X86_WIDTH_64",
        "/*",
        " * The second-operand source of each opcode. The two are distinct: only the",
        " * memory form consults a memory width at all.",
        " */",
        "#define KPROG_X86_ANDN_SOURCE_REGISTER 0U",
        "#define KPROG_X86_ANDN_SOURCE_MEMORY 1U",
        op_source_defines,
        "#define KPROG_X86_ANDN_SOURCE(OP_IS_MEMORY) \\",
        "\t((OP_IS_MEMORY) ? KPROG_X86_ANDN_SOURCE_MEMORY : \\",
        "\t\t  KPROG_X86_ANDN_SOURCE_REGISTER)",
        "/*",
        " * The two memory-read width arms, as table entries: the AUX field's own",
        " * width when the field names one, the resolved FLAGS fallback when it is",
        " * absent.",
        " */",
        arm_defines,
        "#define KPROG_X86_ANDN_MEM_WIDTH_ARM(AUX_WIDTH_IS_ABSENT) \\",
        "\t((AUX_WIDTH_IS_ABSENT) ? KPROG_X86_ANDN_MEM_WIDTH_FLAGS : \\",
        "\t\t KPROG_X86_ANDN_MEM_WIDTH_AUX)",
        "/*",
        " * FLAGS is the opcode's width code, with 0 the \"absent\" code; the resolved",
        " * write width is the code itself, or the 64-bit default when it is absent -",
        " * exactly the resolution both bodies apply. The input is evaluated as the",
        " * body evaluates it.",
        " */",
        "#define KPROG_X86_ANDN_WRITE_WIDTH(FLAGS) \\",
        "\t((FLAGS) ? (FLAGS) : KPROG_X86_ANDN_WRITE_WIDTH_DEFAULT)",
        "/*",
        " * The independently selected memory-read width: the AUX field's own width",
        " * when the field names one, else the resolved FLAGS write width. This is",
        " * the width the memory form reads at - *not* the destination write width.",
        " * The arm table selects which; the AUX code and FLAGS code are each",
        " * evaluated as the body evaluates them.",
        " */",
        "#define KPROG_X86_ANDN_MEM_WIDTH(AUX_WIDTH_CODE, FLAGS) \\",
        "\t(KPROG_X86_ANDN_MEM_WIDTH_ARM((AUX_WIDTH_CODE) == 0U) == \\",
        "\t\t KPROG_X86_ANDN_MEM_WIDTH_FLAGS ? KPROG_X86_ANDN_WRITE_WIDTH(FLAGS) : \\",
        "\t\t (AUX_WIDTH_CODE))",
        "#endif",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = load()
    opcode_rows = [{"name": n, "define": OP_DEFINES[n], "code": OP_CODES[n],
                    "source": OP_SOURCES[n]} for n in OP_ORDER]
    arm_rows = [{"name": n, "define": ARM_DEFINES[n], "absent": ARM_ABSENT[n]}
                for n in ARM_ORDER]
    for path, expected in ((LEAN, render_lean(data, opcode_rows, arm_rows)),
                           (CHEADER, render_c(data, opcode_rows, arm_rows))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated x86 andn contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
