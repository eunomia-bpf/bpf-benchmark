/*
 * Host cross-check for the x86-64 `ANDN` / `ANDN_MEM` handler contract.
 *
 * The module under test is `generated/x86_andn.h`. It fixes which opcode
 * reads its second operand from a register and which from memory, the width a
 * body writes its destination at (`FLAGS ? FLAGS : 64`), and the
 * *independently selected* memory-read width of the memory form:
 * `X86_MEM_AUX_MEM_WIDTH(AUX)` when the AUX field names one, and the resolved
 * FLAGS write width when that field is absent.
 *
 * The two C handlers restate this logic inline — `X86_SIM_L_EXEC_ANDN` /
 * `X86_SIM_L_EXEC_ANDN_MEM` in `x86_sim_local_bpf.h` — and the generated
 * header is not on their include path, so this host cross-check is the tie
 * between the two: it drives the contract through the generated macros and
 * restates the same bodies from the raw opcode bit, and the two must agree
 * byte for byte on the whole register file, the memory word the memory form
 * reads, the destination register, and the flags.
 *
 * The value-producing helpers the bodies use (`X86_SIM_L_READ_REG`,
 * `X86_SIM_L_READ_MEM_VALUE` at a scalar-tagged, non-stack base,
 * `X86_SIM_L_SET_LOGIC_FLAGS`, `X86_SIM_L_WRITE_REG_WIDTH`) are hand-modelled
 * here: a register read is the register's 64-bit value, the memory read is the
 * generated byte-ladder load at the memory width, the flag production is the
 * shared logic-flag contract, and the writeback is the partial-register
 * write.
 */
typedef unsigned char __u8;
typedef unsigned short __u16;
typedef unsigned int __u32;
typedef unsigned long long __u64;
typedef signed char __s8;
typedef short __s16;
typedef int __s32;
typedef signed long long __s64;

/* The generated headers define __always_inline functions in the kernel build;
 * provide the attribute for the host build. */
#ifndef __always_inline
#define __always_inline inline __attribute__((always_inline))
#endif

#define X86_WIDTH_8 1U
#define X86_WIDTH_16 2U
#define X86_WIDTH_32 4U
#define X86_WIDTH_64 8U

#define X86_RAX 0U
#define X86_RCX 1U
#define X86_RDX 2U
#define X86_RBX 3U
#define X86_RSI 6U
#define X86_RDI 7U
#define X86_REG_NONE 0xffU

#define X86_OP_ANDN 0x3dU
#define X86_OP_ANDN_MEM 0x44U

#define X86_SIM_TAG_SCALAR 0U

#include "generated/x86_andn.h"
#include "generated/x86_width.h"
#include "generated/x86_reg_write.h"
#include "generated/x86_logic_flags.h"
#include "generated/x86_mem_access.h"

#include <stdint.h>
#include <stdio.h>
#include <string.h>

/* ------------------------------------------------------------------ */
/* A deterministic register file, source memory and flags model.       */
/*                                                                    */
/* Register "pointers" hold byte offsets into `oracle_mem`, so the     */
/* memory form's base-plus-displacement address stays inside the array */
/* at every address the model forms.                                   */
/* ------------------------------------------------------------------ */

#define ORACLE_REGS 16U
#define ORACLE_MEM_BYTES 4096U

struct oracle_reg {
	union {
		__u8 b[8];
		__u16 w;
		void *ptr;
	} u;
	__u8 tag;
};

static struct oracle_reg oracle_regs[ORACLE_REGS];
static struct oracle_reg pristine_regs[ORACLE_REGS];
static struct oracle_reg result_regs[ORACLE_REGS];

static __u8 oracle_mem[ORACLE_MEM_BYTES];
static __u8 pristine_mem[ORACLE_MEM_BYTES];
static __u8 result_mem[ORACLE_MEM_BYTES];

static __u8 oracle_synthetic(__u64 index)
{
	return (__u8)((index * 131U + 17U) ^ (index >> 5));
}

static void oracle_reset(void)
{
	unsigned i;
	__u64 j;

	for (i = 0; i < ORACLE_REGS; i++) {
		oracle_regs[i].u.ptr =
			(void *)(long)(0x2a00ULL + (__u64)i * 0x20ULL);
		oracle_regs[i].tag = (__u8)(i % 6U);
	}
	for (j = 0; j < ORACLE_MEM_BYTES; j++)
		oracle_mem[j] = (__u8)oracle_synthetic(j + 7U);
}

static void oracle_snapshot_pristine(void)
{
	memcpy(pristine_regs, oracle_regs, sizeof(pristine_regs));
	memcpy(pristine_mem, oracle_mem, ORACLE_MEM_BYTES);
}

static void oracle_restore_pristine(void)
{
	memcpy(oracle_regs, pristine_regs, sizeof(pristine_regs));
	memcpy(oracle_mem, pristine_mem, ORACLE_MEM_BYTES);
}

static __u64 oracle_reg_value(unsigned index)
{
	return (__u64)(uintptr_t)oracle_regs[index].u.ptr;
}

/* ------------------------------------------------------------------ */
/* Hand-written models, independent of the macros under test.          */
/* ------------------------------------------------------------------ */

/* The width mask, restated from the raw codes rather than taken from the
 * generated x86_width.h. */
static __u64 oracle_mask(unsigned width)
{
	if (width == X86_WIDTH_8)
		return 0xffULL;
	if (width == X86_WIDTH_16)
		return 0xffffULL;
	if (width == X86_WIDTH_32)
		return 0xffffffffULL;
	return 0xffffffffffffffffULL;
}

static unsigned oracle_bits(unsigned width)
{
	if (width == X86_WIDTH_8)
		return 8U;
	if (width == X86_WIDTH_16)
		return 16U;
	if (width == X86_WIDTH_32)
		return 32U;
	return 64U;
}

/* The little-endian byte ladder the body's load contract performs: the
 * bytes at the address, summed `byte i << (8*i)` and narrowed. */
static __u64 oracle_load(__u64 addr, unsigned width)
{
	const __u8 *p = (const __u8 *)(uintptr_t)addr;
	__u64 v = 0;
	unsigned i;

	for (i = 0; i < width; i++)
		v |= (__u64)p[i] << (8 * i);
	return v & oracle_mask(width);
}

/* The partial-register writeback the sim performs: 8- and 16-bit writes keep
 * the destination's upper bytes, a 32-bit write zeroes the upper half, and a
 * 64-bit write replaces the register. */
static __u64 oracle_write(__u64 old, __u64 value, unsigned width)
{
	if (width == X86_WIDTH_8)
		return (old & ~0xffULL) | (value & 0xffULL);
	if (width == X86_WIDTH_16)
		return (old & ~0xffffULL) | (value & 0xffffULL);
	if (width == X86_WIDTH_32)
		return value & 0xffffffffULL;
	return value;
}

/* ------------------------------------------------------------------ */
/* Part 1: the generated tables vs. the oracle.                       */
/* ------------------------------------------------------------------ */

static unsigned part1(void)
{
	static const unsigned codes[5] = { 0U, X86_WIDTH_8, X86_WIDTH_16,
					   X86_WIDTH_32, X86_WIDTH_64 };
	unsigned cases = 0;
	unsigned ci;
	unsigned ai;

	if (KPROG_X86_ANDN_WRITE_WIDTH_DEFAULT != X86_WIDTH_64) {
		fprintf(stderr, "andn default write width is %u, want 64-bit\n",
			KPROG_X86_ANDN_WRITE_WIDTH_DEFAULT);
		return 0;
	}
	cases++;

	/* The two opcodes read their second operand from different places. */
	if (KPROG_X86_ANDN_OP_ANDN_SOURCE != KPROG_X86_ANDN_SOURCE_REGISTER) {
		fprintf(stderr, "andn register source code drift\n");
		return 0;
	}
	cases++;

	if (KPROG_X86_ANDN_OP_ANDN_MEM_SOURCE != KPROG_X86_ANDN_SOURCE_MEMORY) {
		fprintf(stderr, "andn memory source code drift\n");
		return 0;
	}
	cases++;

	if (KPROG_X86_ANDN_SOURCE_REGISTER == KPROG_X86_ANDN_SOURCE_MEMORY) {
		fprintf(stderr, "andn source codes collide\n");
		return 0;
	}
	cases++;

	/* The memory-width arm codes are distinct table rows. */
	if (KPROG_X86_ANDN_MEM_WIDTH_AUX == KPROG_X86_ANDN_MEM_WIDTH_FLAGS) {
		fprintf(stderr, "andn memory-width arms collide\n");
		return 0;
	}
	cases++;

	for (ci = 0; ci < 5U; ci++) {
		unsigned want = codes[ci] ? codes[ci] : X86_WIDTH_64;
		unsigned got = KPROG_X86_ANDN_WRITE_WIDTH(codes[ci]);

		if (got != want) {
			fprintf(stderr, "andn write width mismatch flags=%u "
					"got=%u want=%u\n",
				codes[ci], got, want);
			return 0;
		}
		cases++;
	}

	for (ai = 0; ai < 5U; ai++) {
		unsigned src = KPROG_X86_ANDN_SOURCE(ai != 0U);

		if (src != (ai != 0U ? KPROG_X86_ANDN_SOURCE_MEMORY
				     : KPROG_X86_ANDN_SOURCE_REGISTER)) {
			fprintf(stderr, "andn source select drift\n");
			return 0;
		}
		cases++;
	}

	for (ci = 0; ci < 5U; ci++) {
		for (ai = 0; ai < 5U; ai++) {
			unsigned write =
				codes[ci] ? codes[ci] : X86_WIDTH_64;
			unsigned want = codes[ai] ? codes[ai] : write;
			unsigned got =
				KPROG_X86_ANDN_MEM_WIDTH(codes[ai], codes[ci]);

			if (got != want) {
				fprintf(stderr, "andn memory width mismatch "
						"aux=%u flags=%u got=%u want=%u\n",
					codes[ai], codes[ci], got, want);
				return 0;
			}
			cases++;
		}
	}

	/* The macro is not a constant: an absent AUX field resolves to the
	 * FLAGS write width, while a named field stays its own width. */
	if (KPROG_X86_ANDN_MEM_WIDTH(0U, X86_WIDTH_16) != X86_WIDTH_16) {
		fprintf(stderr, "andn absent AUX width did not fall back\n");
		return 0;
	}
	cases++;

	if (KPROG_X86_ANDN_MEM_WIDTH(X86_WIDTH_64, X86_WIDTH_16) ==
	    X86_WIDTH_16) {
		fprintf(stderr, "andn named AUX width collapsed to write width\n");
		return 0;
	}
	cases++;

	return cases;
}

/* ------------------------------------------------------------------ */
/* Part 2: the full composition vs. the hand-written bodies.          */
/*                                                                    */
/* `contract_step` runs the bodies through the generated tables;      */
/* `model_step` restates them from the raw opcode bit. They must agree */
/* on the whole register file, the memory word, and the flags.         */
/* ------------------------------------------------------------------ */

struct andn_effect {
	unsigned source;
	unsigned write_width;
	unsigned mem_width;
	__u64 src1;
	__u64 src2;
	__u64 result;
	__u64 dst;
	__u8 dst_tag;
	__u8 cf;
	__u8 zf;
	__u8 sf;
	__u8 of;
};

static struct andn_effect contract_step(unsigned op_is_mem, unsigned flags,
					unsigned aux_width, unsigned src1_reg,
					unsigned base_reg, unsigned dst_reg,
					__s64 imm)
{
	unsigned source = KPROG_X86_ANDN_SOURCE(op_is_mem);
	unsigned write_width = KPROG_X86_ANDN_WRITE_WIDTH(flags);
	unsigned mem_width = KPROG_X86_ANDN_MEM_WIDTH(aux_width, flags);
	struct andn_effect r;
	__u64 masked;
	__u8 bit;

	r.source = source;
	r.write_width = write_width;
	r.mem_width = 0U;
	r.src1 = oracle_reg_value(src1_reg);
	if (source == KPROG_X86_ANDN_SOURCE_MEMORY) {
		__u64 addr = oracle_reg_value(base_reg) + (__u64)imm;

		r.mem_width = mem_width;
		r.src2 = KPROG_X86_MEM_LOAD((void *)(uintptr_t)addr,
					    mem_width);
	} else {
		r.src2 = oracle_reg_value(base_reg);
	}

	r.result = (~r.src1) & r.src2;

	/* The shared logic-flag production at the *write* width. */
	masked = KPROG_X86_APPLY_WIDTH(r.result, write_width);
	bit = (__u8)((masked >> (oracle_bits(write_width) - 1U)) & 1U);
	{
		__u8 cf = 1U;
		__u8 zf = 1U;
		__u8 sf = 1U;
		__u8 of = 1U;

		KPROG_X86_SET_LOGIC_FLAGS(cf, zf, sf, of, masked == 0U, bit);
		r.cf = cf;
		r.zf = zf;
		r.sf = sf;
		r.of = of;
	}

	/* The partial-register destination write at the write width. */
	if (write_width == X86_WIDTH_8)
		KPROG_X86_WRITE_REG8(oracle_regs[dst_reg].u,
				     oracle_regs[dst_reg].tag, r.result, 0U,
				     X86_SIM_TAG_SCALAR);
	else if (write_width == X86_WIDTH_16)
		KPROG_X86_WRITE_REG16(oracle_regs[dst_reg].u,
				      oracle_regs[dst_reg].tag, r.result,
				      X86_SIM_TAG_SCALAR);
	else if (write_width == X86_WIDTH_32)
		KPROG_X86_WRITE_REG32(oracle_regs[dst_reg].u,
				      oracle_regs[dst_reg].tag, r.result,
				      X86_SIM_TAG_SCALAR);
	else
		KPROG_X86_WRITE_REG64(oracle_regs[dst_reg].u,
				      oracle_regs[dst_reg].tag, r.result,
				      X86_SIM_TAG_SCALAR);

	r.dst = oracle_reg_value(dst_reg);
	r.dst_tag = oracle_regs[dst_reg].tag;
	return r;
}

static struct andn_effect model_step(unsigned op_is_mem, unsigned flags,
				     unsigned aux_width, unsigned src1_reg,
				     unsigned base_reg, unsigned dst_reg,
				     __s64 imm)
{
	unsigned write_width = flags ? flags : X86_WIDTH_64;
	unsigned mem_width = aux_width ? aux_width : write_width;
	struct andn_effect r;
	__u64 masked;

	r.source = op_is_mem ? KPROG_X86_ANDN_SOURCE_MEMORY
			     : KPROG_X86_ANDN_SOURCE_REGISTER;
	r.write_width = write_width;
	r.mem_width = 0U;
	r.src1 = oracle_reg_value(src1_reg);
	if (op_is_mem) {
		__u64 addr = oracle_reg_value(base_reg) + (__u64)imm;

		r.mem_width = mem_width;
		r.src2 = oracle_load(addr, mem_width);
	} else {
		r.src2 = oracle_reg_value(base_reg);
	}

	r.result = (~r.src1) & r.src2;
	masked = r.result & oracle_mask(write_width);
	r.cf = 0U;
	r.zf = masked == 0U;
	r.sf = (__u8)((masked >> (oracle_bits(write_width) - 1U)) & 1U);
	r.of = 0U;

	oracle_regs[dst_reg].u.ptr = (void *)(long)oracle_write(
		oracle_reg_value(dst_reg), r.result, write_width);
	oracle_regs[dst_reg].tag = X86_SIM_TAG_SCALAR;

	r.dst = oracle_reg_value(dst_reg);
	r.dst_tag = oracle_regs[dst_reg].tag;
	return r;
}

static unsigned part2(void)
{
	static const unsigned flags_codes[5] = { 0U, X86_WIDTH_8, X86_WIDTH_16,
						 X86_WIDTH_32, X86_WIDTH_64 };
	static const unsigned aux_widths[5] = { 0U, X86_WIDTH_8, X86_WIDTH_16,
						X86_WIDTH_32, X86_WIDTH_64 };
	static const __s64 imms[4] = { 0, 4, 8, -4 };
	static const unsigned src1_regs[3] = { X86_RAX, X86_RSI, 11U };
	static const unsigned dst_regs[3] = { X86_RCX, X86_RDX, 9U };
	unsigned cases = 0;
	unsigned op;
	unsigned fi;
	unsigned ai;
	unsigned mi;
	unsigned si;
	unsigned di;

	for (op = 0; op < 2U; op++) {
		for (fi = 0; fi < 5U; fi++) {
			for (ai = 0; ai < 5U; ai++) {
				for (mi = 0; mi < 4U; mi++) {
					for (si = 0; si < 3U; si++) {
						for (di = 0; di < 3U; di++) {
							struct andn_effect got;
							struct andn_effect want;

							oracle_restore_pristine();
							oracle_regs[X86_RBX].u.ptr =
								(void *)(uintptr_t)&oracle_mem[64];
							oracle_regs[X86_RBX].tag =
								X86_SIM_TAG_SCALAR;
							got = contract_step(
								op, flags_codes[fi],
								aux_widths[ai],
								src1_regs[si],
								X86_RBX,
								dst_regs[di],
								imms[mi]);
							memcpy(result_regs,
							       oracle_regs,
							       sizeof(oracle_regs));
							memcpy(result_mem,
							       oracle_mem,
							       ORACLE_MEM_BYTES);

							oracle_restore_pristine();
							oracle_regs[X86_RBX].u.ptr =
								(void *)(uintptr_t)&oracle_mem[64];
							oracle_regs[X86_RBX].tag =
								X86_SIM_TAG_SCALAR;
							want = model_step(
								op, flags_codes[fi],
								aux_widths[ai],
								src1_regs[si],
								X86_RBX,
								dst_regs[di],
								imms[mi]);

							if (got.source != want.source ||
							    got.write_width != want.write_width ||
							    got.mem_width != want.mem_width ||
							    got.src1 != want.src1 ||
							    got.src2 != want.src2 ||
							    got.result != want.result ||
							    got.dst != want.dst ||
							    got.dst_tag != want.dst_tag ||
							    got.cf != want.cf ||
							    got.zf != want.zf ||
							    got.sf != want.sf ||
							    got.of != want.of ||
							    memcmp(result_regs, oracle_regs,
								   sizeof(oracle_regs)) ||
							    memcmp(result_mem, oracle_mem,
								   ORACLE_MEM_BYTES)) {
								fprintf(stderr,
									"andn mismatch mem=%u flags=%u aux=%u\n",
									op,
									flags_codes[fi],
									aux_widths[ai]);
								return 0;
							}
							cases++;
						}
					}
				}
			}
		}
	}
	return cases;
}

/* ------------------------------------------------------------------ */
/* Part 3: pins on the facts the composition is about.                */
/* ------------------------------------------------------------------ */

static unsigned part3(void)
{
	unsigned cases = 0;

	/* Pin 1: the register form reads its second operand from a register
	 * and never consults a memory width, whatever the AUX code. */
	{
		struct andn_effect e;

		oracle_restore_pristine();
		e = contract_step(0U, X86_WIDTH_64, X86_WIDTH_64, X86_RAX,
				  X86_RBX, X86_RCX, 0);
		if (e.source != KPROG_X86_ANDN_SOURCE_REGISTER)
			return 0;
		if (e.mem_width != 0U)
			return 0;
		if (e.src2 != oracle_reg_value(X86_RBX) &&
		    e.src2 != (__u64)(uintptr_t)pristine_regs[X86_RBX].u.ptr)
			return 0;
		cases++;
	}

	/* Pin 2: the memory form reads at the *named* AUX width, not the
	 * FLAGS write width, so the two widths diverge. */
	{
		struct andn_effect narrow_read;
		struct andn_effect wide_read;

		oracle_restore_pristine();
		oracle_regs[X86_RBX].u.ptr =
			(void *)(uintptr_t)&oracle_mem[64];
		oracle_regs[X86_RBX].tag = X86_SIM_TAG_SCALAR;
		narrow_read = contract_step(1U, X86_WIDTH_64, X86_WIDTH_16,
					    X86_RAX, X86_RBX, X86_RCX, 0);
		if (narrow_read.mem_width != X86_WIDTH_16)
			return 0;
		if (narrow_read.write_width != X86_WIDTH_64)
			return 0;

		oracle_restore_pristine();
		oracle_regs[X86_RBX].u.ptr =
			(void *)(uintptr_t)&oracle_mem[64];
		oracle_regs[X86_RBX].tag = X86_SIM_TAG_SCALAR;
		wide_read = contract_step(1U, X86_WIDTH_64, X86_WIDTH_64,
					  X86_RAX, X86_RBX, X86_RCX, 0);
		if (wide_read.mem_width != X86_WIDTH_64)
			return 0;

		if (narrow_read.src2 == wide_read.src2)
			return 0;
		cases++;
	}

	/* Pin 3: an absent AUX width falls back to the resolved FLAGS write
	 * width — a narrow FLAGS code reads narrow, an absent one reads 64. */
	{
		struct andn_effect e16;
		struct andn_effect eabsent;

		oracle_restore_pristine();
		oracle_regs[X86_RBX].u.ptr =
			(void *)(uintptr_t)&oracle_mem[64];
		oracle_regs[X86_RBX].tag = X86_SIM_TAG_SCALAR;
		e16 = contract_step(1U, X86_WIDTH_16, 0U, X86_RAX, X86_RBX,
				    X86_RCX, 0);
		if (e16.mem_width != X86_WIDTH_16)
			return 0;

		oracle_restore_pristine();
		oracle_regs[X86_RBX].u.ptr =
			(void *)(uintptr_t)&oracle_mem[64];
		oracle_regs[X86_RBX].tag = X86_SIM_TAG_SCALAR;
		eabsent = contract_step(1U, 0U, 0U, X86_RAX, X86_RBX,
					X86_RCX, 0);
		if (eabsent.mem_width != X86_WIDTH_64)
			return 0;
		cases++;
	}

	/* Pin 4: the flags are the logic-flag production at the write width:
	 * CF and OF are always false, ZF and SF track the narrowed result. */
	{
		struct andn_effect e;

		oracle_restore_pristine();
		e = contract_step(0U, X86_WIDTH_16, 0U, X86_RAX, X86_RBX,
				  X86_RCX, 0);
		if (e.cf != 0U || e.of != 0U)
			return 0;
		if (e.zf != (e.result & 0xffffULL ? 0U : 1U))
			return 0;
		if (e.sf != (__u8)(((e.result & 0xffffULL) >> 15) & 1U))
			return 0;
		cases++;
	}

	/* Pin 5: the destination write is the partial-register write at the
	 * *write* width — a narrow write preserves the upper bytes and
	 * scalarizes the tag. */
	{
		struct andn_effect e;
		__u64 old;

		oracle_restore_pristine();
		old = oracle_reg_value(X86_RCX);
		oracle_regs[X86_RCX].tag = 5U;
		e = contract_step(0U, X86_WIDTH_8, 0U, X86_RAX, X86_RBX,
				  X86_RCX, 0);
		if (e.write_width != X86_WIDTH_8)
			return 0;
		if (e.dst != ((old & ~0xffULL) | (e.result & 0xffULL)))
			return 0;
		if (e.dst_tag != X86_SIM_TAG_SCALAR)
			return 0;
		cases++;
	}

	/* Pin 6: `ANDN` writes no memory: the memory word is untouched even
	 * by the memory-reading form. */
	{
		struct andn_effect e;

		oracle_restore_pristine();
		oracle_regs[X86_RBX].u.ptr =
			(void *)(uintptr_t)&oracle_mem[64];
		oracle_regs[X86_RBX].tag = X86_SIM_TAG_SCALAR;
		e = contract_step(1U, X86_WIDTH_64, X86_WIDTH_32, X86_RAX,
				  X86_RBX, X86_RCX, 8);
		if (memcmp(oracle_mem, pristine_mem, ORACLE_MEM_BYTES))
			return 0;
		if (e.result != ((~e.src1) & e.src2))
			return 0;
		cases++;
	}

	/* Pin 7: the register form leaves memory untouched and reads src2
	 * from the auxiliary register. */
	{
		struct andn_effect e;
		__u64 aux;

		oracle_restore_pristine();
		aux = oracle_reg_value(X86_RBX);
		e = contract_step(0U, X86_WIDTH_32, 0U, X86_RAX, X86_RBX,
				  X86_RCX, 0);
		if (e.src2 != aux)
			return 0;
		if (memcmp(oracle_mem, pristine_mem, ORACLE_MEM_BYTES))
			return 0;
		cases++;
	}

	return cases;
}

int main(void)
{
	unsigned c1;
	unsigned c2;
	unsigned c3;

	oracle_reset();
	oracle_snapshot_pristine();

	/* Each part returns zero exactly when a case failed, so any zero is a
	 * failure even though the readiness line still prints. */
	c1 = part1();
	if (c1 == 0U)
		return 1;
	oracle_restore_pristine();
	c2 = part2();
	if (c2 == 0U)
		return 1;
	oracle_restore_pristine();
	c3 = part3();
	if (c3 == 0U)
		return 1;
	oracle_restore_pristine();

	printf("x86 andn handler host cross-check: OK (%u cases)\n",
	       c1 + c2 + c3);
	return 0;
}
