#!/usr/bin/env python3
"""Generate the shared AArch64 vector/register move (FMOV) contract.

The generated Lean definition `GeneratedArm64Fmov.value` and the C macro
`KPROG_ARM64_FMOV_VALUE` implement the four FMOV directions the simulator
applies between a general-purpose register and the vector register `v0`:

  - D_FROM_X and S_FROM_W: load `v0` from the source register;
  - X_FROM_D and W_FROM_S: move `v0` (width-applied) into the destination.

The direction is the only free choice, so the contract is a four-arm selection
over the `ARM64_FMOV_*` codes, which `load()` re-checks against
native-sim/arm64/arm64_sim.h. The C macro evaluates the source exactly once and
writes no NZCV; the caller applies the destination width for the register-writing
arms.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_fmov_spec.json"
SIM_HEADER = ROOT.parent / "arm64/arm64_sim.h"
LEAN = ROOT / "KProgFormal/GeneratedArm64Fmov.lean"
CHEADER = ROOT / "generated/arm64_fmov.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64Fmov",
    "directions": [
        {"name": "d_from_x", "code": 0, "macro": "ARM64_FMOV_D_FROM_X",
         "writes_reg": False},
        {"name": "x_from_d", "code": 1, "macro": "ARM64_FMOV_X_FROM_D",
         "writes_reg": True},
        {"name": "s_from_w", "code": 2, "macro": "ARM64_FMOV_S_FROM_W",
         "writes_reg": False},
        {"name": "w_from_s", "code": 3, "macro": "ARM64_FMOV_W_FROM_S",
         "writes_reg": True},
    ],
}

DEFINE = re.compile(
    r"^#define\s+(ARM64_FMOV_[A-Z0-9_]+)\s+(\d+)U\s*$", re.M)


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 fmov specification: {data!r}")
    dirs = EXPECTED["directions"]
    names = [row["name"] for row in dirs]
    if names != ["d_from_x", "x_from_d", "s_from_w", "w_from_s"]:
        raise SystemExit(f"invalid arm64 fmov order: {dirs!r}")
    if [row["code"] for row in dirs] != [0, 1, 2, 3]:
        raise SystemExit(f"invalid arm64 fmov codes: {dirs!r}")
    defines = {name: int(value)
               for name, value in DEFINE.findall(SIM_HEADER.read_text())}
    if not defines:
        raise SystemExit(
            f"no ARM64_FMOV_* definitions found in {SIM_HEADER}")
    for row in dirs:
        if defines.get(row["macro"]) != row["code"]:
            raise SystemExit(
                "arm64 fmov codes drift from native-sim/arm64/arm64_sim.h: "
                f"spec={row['macro']}={row['code']} "
                f"sim={defines.get(row['macro'])}")
    return dirs


def render_lean(dirs: list[dict]) -> str:
    ctors = "\n".join(f"  | {row['name']}" for row in dirs)
    codes = "\n".join(f"  | .{row['name']} => {row['code']}" for row in dirs)
    mnemonics = "\n".join(
        f"  | .{row['name']} => \"{row['name'].upper()}\"" for row in dirs)
    writes = "\n".join(
        f"  | .{row['name']} => {'true' if row['writes_reg'] else 'false'}"
        for row in dirs)
    arms = "\n".join(
        f"  | .{row['name']} => "
        f"{'v0' if row['writes_reg'] else 'src'}" for row in dirs)
    return f'''-- Generated by generate_arm64_fmov_spec.py from arm64_fmov_spec.json.
import Std
namespace KProgFormal.GeneratedArm64Fmov
/-- The four AArch64 FMOV directions between a general-purpose register and the
vector register `v0`. -/
inductive Fmov where
{ctors}
deriving DecidableEq, Repr
/-- The ARM64_FMOV_* code of the direction. -/
def code : Fmov -> Nat
{codes}
/-- The AArch64 mnemonic of the direction. -/
def mnemonic : Fmov -> String
{mnemonics}
/-- Whether the direction writes the general-purpose register (rather than the
vector register). -/
def writesReg : Fmov -> Bool
{writes}
/-- Shared AArch64 FMOV value: the selection the handler applies to `v0`.
`v0` is the current vector-register value and `src` is the general-purpose
source register (already read at the destination width). -/
def value (dir : Fmov) (v0 src : BitVec 64) : BitVec 64 :=
  match dir with
{arms}
end KProgFormal.GeneratedArm64Fmov
'''


def render_c(dirs: list[dict]) -> str:
    codes = "\n".join(
        f"_Static_assert({row['macro']} == {row['code']}U, "
        '"arm64 fmov code drift");'
        for row in dirs)
    handled = " || \\\n\t".join(
        f"((DIR) == {row['macro']})" for row in dirs)
    coverage = "\n".join(
        f"_Static_assert(KPROG_ARM64_FMOV_HANDLED({row['macro']}), "
        '"arm64 fmov coverage drift");'
        for row in dirs)
    body = [
        "\t({",
        "\t\t__u64 __kprog_a64_fmov_dir = (DIR);",
        "\t\t__u64 __kprog_a64_fmov_v0 = (V0);",
        "\t\t__u64 __kprog_a64_fmov_src = (SRC);",
        "\t\t__u64 __kprog_a64_fmov_result = 0;",
        "",
        "\t\tswitch (__kprog_a64_fmov_dir) {",
    ]
    for row in dirs:
        body.append(f"\t\tcase {row['code']}U:                          ")
        body.append("\t\t\t__kprog_a64_fmov_result = "
                    + ("__kprog_a64_fmov_v0;"
                       if row["writes_reg"] else "__kprog_a64_fmov_src;"))
        body.append("\t\t\tbreak;")
    body += [
        "\t\tdefault:",
        "\t\t\tUNSUPPORTED;",
        "\t\t\tbreak;",
        "\t\t}",
        "\t\t__kprog_a64_fmov_result;",
        "\t})",
    ]
    continued = " \\\n".join(body)
    return f'''/* Generated by generate_arm64_fmov_spec.py from arm64_fmov_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_FMOV_H
#define KPROG_FORMAL_GENERATED_ARM64_FMOV_H
/*
 * The four arms are the AArch64 FMOV directions between a general-purpose
 * register and the vector register `v0`. Every ARM64_FMOV_* code has exactly one
 * arm; a code outside the four reaches the caller-supplied unsupported arm.
 */
{codes}
#define KPROG_ARM64_FMOV_HANDLED(DIR)                                       \\
\t({handled})
{coverage}
/*
 * DIR is one of the four ARM64_FMOV_* codes; V0 is the current vector-register
 * value and SRC the general-purpose source register (read at the destination
 * width). V0 and SRC are each evaluated exactly once and no NZCV is written.
 * The result is either the new `v0` or the value to write into the destination
 * register, depending on the direction; the caller applies the width.
 */
#define KPROG_ARM64_FMOV_VALUE(DIR, V0, SRC, UNSUPPORTED)                   \\
{continued}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    dirs = load()
    for path, expected in ((LEAN, render_lean(dirs)), (CHEADER, render_c(dirs))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 fmov contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
