#!/usr/bin/env python3
"""Generate the shared x86 SHL/SHR/SAR/ROL flag transition."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_shift_flags_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86ShiftFlags.lean"
C_HEADER = ROOT / "generated/x86_shift_flags.h"
EXPECTED = {
    "schema_version": 1,
    "operation": "x86ShiftFlags",
    "operations": ["shl", "shr", "sar", "rol"],
    "masked_count_zero": "preserve_all",
    "shift": {
        "zf": "result_zero",
        "sf": "result_sign",
        "shl_shr_cf": "last_shifted_bit_when_count_lt_width",
        "sar_cf": "last_shifted_bit_with_sign_saturation",
        "of": "defined_when_masked_count_one",
    },
    "rol": {
        "zf": "preserve",
        "sf": "preserve",
        "cf": "result_lsb_when_masked_count_nonzero",
        "of": "result_msb_xor_cf_when_masked_count_one",
    },
    "undefined_policy": {
        "shl_shr_cf_count_eq_width": "last_shifted_bit",
        "shl_shr_cf_count_gt_width": "zero",
        "of_outside_masked_count_one": "preserve",
    },
}


def load() -> None:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 shift-flags specification: {data!r}")


def render_lean() -> str:
    return '''-- Generated by generate_x86_shift_flags_spec.py from x86_shift_flags_spec.json.
import KProgFormal.GeneratedX86ShiftCount
import KProgFormal.GeneratedX86Width
namespace KProgFormal.GeneratedX86ShiftFlags
inductive Op | shl | shr | sar | rol
  deriving DecidableEq, Repr
structure Flags where
  cf : Bool
  zf : Bool
  sf : Bool
  of : Bool
  deriving DecidableEq, Repr
def shlCf (a : BitVec 64) (count bits : Nat) : Bool :=
  if count <= bits then a.getLsbD (bits - count) else false
def rightCf (a : BitVec 64) (count bits : Nat) (arithmetic : Bool) : Bool :=
  if count <= bits then a.getLsbD (count - 1)
  else if arithmetic then a.getLsbD (bits - 1) else false
def apply (op : Op) (value rhs result : BitVec 64)
    (width : GeneratedX86Width.Width) (old : Flags) : Flags :=
  let count := (GeneratedX86ShiftCount.count rhs width).toNat
  let bits := GeneratedX86Width.bits width
  let a := GeneratedX86Width.narrow value width
  let r := GeneratedX86Width.narrow result width
  let sign := GeneratedX86Width.sign r width
  if count = 0 then old
  else match op with
    | .rol =>
        let cf := r.getLsbD 0
        { cf := cf, zf := old.zf, sf := old.sf,
          of := if count = 1 then sign != cf else old.of }
    | .shl =>
        let cf := shlCf a count bits
        { cf := cf, zf := r == 0, sf := sign,
          of := if count = 1 then sign != cf else old.of }
    | .shr =>
        { cf := rightCf a count bits false, zf := r == 0, sf := sign,
          of := if count = 1 then GeneratedX86Width.sign a width else old.of }
    | .sar =>
        { cf := rightCf a count bits true, zf := r == 0, sf := sign,
          of := if count = 1 then false else old.of }
end KProgFormal.GeneratedX86ShiftFlags
'''


def render_c() -> str:
    return r'''/* Generated by generate_x86_shift_flags_spec.py from x86_shift_flags_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_SHIFT_FLAGS_H
#define KPROG_FORMAL_GENERATED_X86_SHIFT_FLAGS_H
#define KPROG_X86_SET_SHIFT_FLAGS(C_CF,C_ZF,C_SF,C_OF,A,COUNT,R,BITS,SIGN,ALU) \
	do {                                                               \
		if ((COUNT) != 0) {                                         \
			if ((ALU) == X86_ALU_ROL) {                         \
				(C_CF) = (R) & 1;                              \
				if ((COUNT) == 1)                              \
					(C_OF) = (((R) & (SIGN)) != 0) ^ (C_CF); \
			} else {                                              \
				(C_ZF) = (R) == 0;                              \
				(C_SF) = ((R) & (SIGN)) != 0;                   \
				if ((ALU) == X86_ALU_SHL) {                     \
					(C_CF) = (COUNT) <= (BITS) ?               \
						((A) >> ((BITS) - (COUNT))) & 1 : 0; \
					if ((COUNT) == 1)                          \
						(C_OF) = (C_SF) ^ (C_CF);            \
				} else if ((ALU) == X86_ALU_SHR) {              \
					(C_CF) = (COUNT) <= (BITS) ?               \
						((A) >> ((COUNT) - 1)) & 1 : 0;      \
					if ((COUNT) == 1)                          \
						(C_OF) = ((A) & (SIGN)) != 0;       \
				} else {                                          \
					(C_CF) = (COUNT) <= (BITS) ?               \
						((A) >> ((COUNT) - 1)) & 1 :          \
						((A) & (SIGN)) != 0;                   \
					if ((COUNT) == 1)                          \
						(C_OF) = 0;                         \
				}                                                   \
			}                                                           \
		}                                                                 \
	} while (0)
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    load()
    for path, expected in ((LEAN, render_lean()), (C_HEADER, render_c())):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(f"generated x86 shift-flags contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
