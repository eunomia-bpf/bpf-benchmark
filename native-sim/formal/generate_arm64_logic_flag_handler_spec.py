#!/usr/bin/env python3
"""Generate shared AND/BIC flag-setting handler composition for C and Lean."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_logic_flag_handler_spec.json"
DECODE_SPEC = ROOT / "arm64_decode_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64LogicFlagHandler.lean"
CHEADER = ROOT / "generated/arm64_logic_flag_handler.h"
EXPECTED = {
    "schema_version": 1,
    "operation": "arm64LogicFlagHandler",
    "families": [
        {"name": "and", "code": 2, "alu": "and"},
        {"name": "bic", "code": 3, "alu": "bic"},
    ],
    "modes": [
        {"name": "writeback", "writes_destination": True},
        {"name": "test", "writes_destination": False},
    ],
}


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 logic flag handler specification: {data!r}")
    decode = json.loads(DECODE_SPEC.read_text())
    alu = decode.get("tables", {}).get("alu", [])
    codes = {row.get("mnemonic"): row.get("code") for row in alu}
    for row in data["families"]:
        if codes.get(row["alu"]) != row["code"]:
            raise SystemExit(
                f"arm64 logic flag family drifts from ALU decode table: {row!r}")
    return data["families"]


def render_lean(families: list[dict]) -> str:
    family_ctors = "\n".join(f"  | {row['name']}" for row in families)
    family_codes = "\n".join(
        f"  | .{row['name']} => {row['code']}" for row in families)
    op_arms = "\n".join(
        f"  | .{row['name']} => .{row['alu']}" for row in families)
    return f'''-- Generated by generate_arm64_logic_flag_handler_spec.py from arm64_logic_flag_handler_spec.json.
import KProgFormal.GeneratedArm64AluResult
import KProgFormal.GeneratedArm64Flags

namespace KProgFormal.GeneratedArm64LogicFlagHandler

inductive Family
{family_ctors}
  deriving DecidableEq, Repr

inductive Mode
  | writeback
  | test
  deriving DecidableEq, Repr

def code : Family -> Nat
{family_codes}

def alu : Family -> GeneratedArm64AluDecode.Alu
{op_arms}

structure Step where
  value : BitVec 64
  flags : GeneratedArm64Flags.Flags
  deriving DecidableEq, Repr

def apply (family : Family) (lhs rhs : BitVec 64)
    (width : GeneratedArm64Width.Width) : Step :=
  let value := GeneratedArm64AluResult.result (alu family) lhs rhs
  {{ value := value, flags := GeneratedArm64Flags.applyLogic value width }}

end KProgFormal.GeneratedArm64LogicFlagHandler
'''


def render_c(families: list[dict]) -> str:
    constants = "\n".join(
        f"#define KPROG_ARM64_LOGIC_FAMILY_{row['name'].upper()} {row['code']}U"
        for row in families)
    cases: list[str] = []
    for row in families:
        upper = row["name"].upper()
        cases.extend([
            f"\t\tcase KPROG_ARM64_LOGIC_FAMILY_{upper}:",
            f"\t\t\t(RESULT) = KPROG_ALU64_RESULT(ARM64_ALU_{upper}, (LHS), (RHS), UNSUPPORTED);",
            "\t\t\tbreak;",
        ])
    lines = [
        "#define KPROG_ARM64_EXEC_LOGIC_FLAGS(FAMILY, RESULT, C_N, C_Z, C_C, C_V, LHS, RHS, WIDTH, UNSUPPORTED)",
        "\tdo {",
        "\t\tswitch (FAMILY) {",
        *cases,
        "\t\tdefault:",
        "\t\t\tUNSUPPORTED;",
        "\t\t\tbreak;",
        "\t\t}",
        "\t\tKPROG_ARM64_SET_LOGIC_FLAGS((C_N), (C_Z), (C_C), (C_V), (RESULT), (WIDTH));",
        "\t} while (0)",
    ]
    macro = " \\\n".join(lines)
    return f'''/* Generated by generate_arm64_logic_flag_handler_spec.py from arm64_logic_flag_handler_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_LOGIC_FLAG_HANDLER_H
#define KPROG_FORMAL_GENERATED_ARM64_LOGIC_FLAG_HANDLER_H

{constants}

{macro}

#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    families = load()
    for path, expected in ((LEAN, render_lean(families)),
                           (CHEADER, render_c(families))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 logic flag handler contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
