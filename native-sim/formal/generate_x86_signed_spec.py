#!/usr/bin/env python3
"""Generate the shared x86 signed-value contract (sign extension and signed abs).

The generated Lean definitions `GeneratedX86Signed.signExtend` and
`GeneratedX86Signed.absWidth` and the C functions `kprog_x86_sign_extend_value`
and `kprog_x86_abs_width_value` implement the two width-parameterised signed
operations the simulator's IMUL handlers rely on:

  - sign extension of the narrowed operand from the access width's sign bit, used
    to widen the immediate/register operand before an imul;
  - the width-domain magnitude, used to build the IMUL overflow flags.

The width is one of the four `X86_WIDTH_*` codes, so both have a closed set of
arms and no unsupported case. Neither writes flags.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_signed_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86Signed.lean"
C_HEADER = ROOT / "generated/x86_signed.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "x86Signed",
    "widths": [
        {"name": "w8", "mask": "0xff", "sign": "0x80", "bits": 8},
        {"name": "w16", "mask": "0xffff", "sign": "0x8000", "bits": 16},
        {"name": "w32", "mask": "0xffffffff", "sign": "0x80000000", "bits": 32},
        {"name": "w64", "mask": "0xffffffffffffffff",
         "sign": "0x8000000000000000", "bits": 64},
    ],
}


def load() -> None:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 signed specification: {data!r}")
    widths = EXPECTED["widths"]
    if [row["bits"] for row in widths] != [8, 16, 32, 64]:
        raise SystemExit(f"invalid x86 signed widths: {widths!r}")


def render_lean() -> str:
    return '''-- Generated by generate_x86_signed_spec.py from x86_signed_spec.json.
import KProgFormal.GeneratedX86Width
namespace KProgFormal.GeneratedX86Signed
open GeneratedX86Width (Width mask narrow signMask)
/-- Sign extension of the narrowed operand from the access width's sign bit. A
64-bit width is the identity. -/
def signExtend (value : BitVec 64) : Width -> BitVec 64
  | .w8 => (((value &&& 0xff) ^^^ 0x80) - 0x80)
  | .w16 => ((value &&& 0xffff) ^^^ 0x8000) - 0x8000
  | .w32 => ((value &&& 0xffffffff) ^^^ 0x80000000) - 0x80000000
  | .w64 => value
/-- Magnitude of the narrowed operand in the access width's domain: negate when
the width's sign bit is set, then re-narrow. -/
def absWidth (value : BitVec 64) : Width -> BitVec 64
  | .w8 =>
      let n := value &&& 0xff
      if (n &&& 0x80) != 0 then ((~~~n) + 1) &&& 0xff else n
  | .w16 =>
      let n := value &&& 0xffff
      if (n &&& 0x8000) != 0 then ((~~~n) + 1) &&& 0xffff else n
  | .w32 =>
      let n := value &&& 0xffffffff
      if (n &&& 0x80000000) != 0 then ((~~~n) + 1) &&& 0xffffffff else n
  | .w64 =>
      let n := value
      if (n &&& 0x8000000000000000) != 0 then ((~~~n) + 1) else n
end KProgFormal.GeneratedX86Signed
'''


def render_c() -> str:
    return '''/* Generated by generate_x86_signed_spec.py from x86_signed_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_SIGNED_H
#define KPROG_FORMAL_GENERATED_X86_SIGNED_H
/*
 * x86 signed-value helpers: sign extension of the narrowed operand from the
 * access width's sign bit, and the width-domain magnitude. The width set is
 * closed (the four X86_WIDTH_* codes) and every case is handled, so there is no
 * unsupported arm. Neither writes flags.
 */
static __always_inline __u64 kprog_x86_sign_extend_value(__u64 value,
                                                          __u8 width)
{
\tif (width == X86_WIDTH_8)
\t\treturn (__u64)(__s64)(__s8)(value & 0xffULL);
\tif (width == X86_WIDTH_16)
\t\treturn (__u64)(__s64)(__s16)(value & 0xffffULL);
\tif (width == X86_WIDTH_32)
\t\treturn (__u64)(__s64)(__s32)(value & 0xffffffffULL);
\treturn value;
}

static __always_inline __u64 kprog_x86_abs_width_value(__u64 value,
                                                        __u8 width)
{
\t__u64 narrowed = value & KPROG_X86_WIDTH_MASK(width);

\tif (narrowed & KPROG_X86_WIDTH_SIGN_MASK(width))
\t\treturn ((~narrowed) + 1) & KPROG_X86_WIDTH_MASK(width);
\treturn narrowed;
}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    load()
    for path, expected in ((LEAN, render_lean()), (C_HEADER, render_c())):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated x86 signed contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
