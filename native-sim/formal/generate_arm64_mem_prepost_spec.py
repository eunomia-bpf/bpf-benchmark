#!/usr/bin/env python3
"""Generate the shared AArch64 pre/post-indexed address-writeback contract.

The generated Lean step `GeneratedArm64MemPrepost` and the C macro
`KPROG_ARM64_MEM_PREPOST_*` describe how the simulator decodes the packed
memory-flag byte of an `ARM64_AUX_MEM` operand into the address-writeback form:

  * the offset access contributes the immediate, so it gates the immediate on
    `MEM_PRE | MEM_POST` being clear (`suppress`);
  * a pre-indexed access (`MEM_PRE` set) applies the immediate *before* the
    access and a post-indexed access (`MEM_POST` set) applies it *after*,
    independently, so both bits are separate facts and `MEM_PRE | MEM_POST`
    set with the same immediate applies it twice.

The flag byte lives in the top byte of the packed `AUX` word (`>> 24`, the same
`ARM64_SIM_L_MEM_FLAGS` decode the macros use), which `load()` re-checks against
native-sim/arm64/arm64_sim.h. The two writeback steps and the offset gate each
evaluate the immediate once and write no NZCV; the caller supplies the base
register writeback. This contract is distinct from `arm64_mem_offset_refines`,
which is stated over an already-decoded `prepost` Bool.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_mem_prepost_spec.json"
SIM_HEADER = ROOT.parent / "arm64/arm64_sim.h"
LEAN = ROOT / "KProgFormal/GeneratedArm64MemPrepost.lean"
CHEADER = ROOT / "generated/arm64_mem_prepost.h"

PRE_BIT = 1
POST_BIT = 2
FLAGS_SHIFT = 24
FLAGS_MASK = 255

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64MemPrepost",
    "selector": "independent_pre_post_flag_gates_and_offset_suppression",
    "pre_bit": PRE_BIT,
    "post_bit": POST_BIT,
    "flags_shift": FLAGS_SHIFT,
    "flags_mask": FLAGS_MASK,
}


def load() -> dict:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 pre/post specification: {data!r}")
    if data["pre_bit"] != PRE_BIT or data["post_bit"] != POST_BIT:
        raise SystemExit(f"invalid arm64 pre/post bits: {data!r}")
    if data["flags_shift"] != FLAGS_SHIFT or data["flags_mask"] != FLAGS_MASK:
        raise SystemExit(f"invalid arm64 pre/post flag decode: {data!r}")
    text = SIM_HEADER.read_text()
    for name, value in (("ARM64_MEM_PRE", PRE_BIT), ("ARM64_MEM_POST", POST_BIT)):
        if f"#define {name} {value}U" not in text:
            raise SystemExit(
                f"arm64 pre/post flag drift from native-sim/arm64/arm64_sim.h: "
                f"{name} != {value}")
    return data


def render_lean(spec: dict) -> str:
    shift = spec["flags_shift"]
    mask = spec["flags_mask"]
    return f'''-- Generated by generate_arm64_mem_prepost_spec.py from arm64_mem_prepost_spec.json.
import Std
namespace KProgFormal.GeneratedArm64MemPrepost
/-- The packed memory-flag byte of an `ARM64_AUX_MEM` operand: the top byte of the
`AUX` word, matching `ARM64_SIM_L_MEM_FLAGS`. -/
def flags (aux : BitVec 32) : BitVec 8 :=
  BitVec.ofNat 8 (aux.toNat >>> {shift})
/-- Whether a pre-indexed writeback applies before the access: `MEM_PRE` set. -/
def preWriteback (aux : BitVec 32) : Bool :=
  (flags aux).toNat &&& {spec["pre_bit"]} != 0
/-- Whether a post-indexed writeback applies after the access: `MEM_POST` set. -/
def postWriteback (aux : BitVec 32) : Bool :=
  (flags aux).toNat &&& {spec["post_bit"]} != 0
/-- Whether the address offset ignores the immediate: a pre- or post-indexed
access applies the immediate as its own writeback, so the offset carries no
immediate. -/
def suppressOffset (aux : BitVec 32) : Bool :=
  preWriteback aux || postWriteback aux
/-- The immediate the pre-indexed writeback applies (or zero if absent). -/
def preDelta (aux : BitVec 32) (imm : BitVec 64) : BitVec 64 :=
  if preWriteback aux then imm else 0
/-- The immediate the post-indexed writeback applies (or zero if absent). -/
def postDelta (aux : BitVec 32) (imm : BitVec 64) : BitVec 64 :=
  if postWriteback aux then imm else 0
/-- The independent statement over the raw flag byte and the immediate: the two
writeback deltas are the immediate gated by each bit, and the offset is
suppressed exactly when either bit is set. -/
def preDeltaSpec (flags : Nat) (imm : BitVec 64) : BitVec 64 :=
  if flags &&& {spec["pre_bit"]} != 0 then imm else 0
def postDeltaSpec (flags : Nat) (imm : BitVec 64) : BitVec 64 :=
  if flags &&& {spec["post_bit"]} != 0 then imm else 0
def suppressOffsetSpec (flags : Nat) : Bool :=
  flags &&& {spec["pre_bit"]} != 0 || flags &&& {spec["post_bit"]} != 0
/-- The independent writeback-form ordinal over the raw flag byte: how many
writebacks the byte requests, `0` for an offset access, `1` for a single pre- or
post-indexed writeback, and `2` when both bits are set. -/
def writebackFormSpec (flags : Nat) : Nat :=
  (if flags &&& {spec["pre_bit"]} != 0 then 1 else 0) +
  (if flags &&& {spec["post_bit"]} != 0 then 1 else 0)
end KProgFormal.GeneratedArm64MemPrepost
'''


def render_c(spec: dict) -> str:
    shift = spec["flags_shift"]
    mask = spec["flags_mask"]
    pre = spec["pre_bit"]
    post = spec["post_bit"]
    return f'''/* Generated by generate_arm64_mem_prepost_spec.py from arm64_mem_prepost_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_MEM_PREPOST_H
#define KPROG_FORMAL_GENERATED_ARM64_MEM_PREPOST_H
/*
 * AArch64 pre/post-indexed address writeback. The packed memory-flag byte of an
 * `ARM64_AUX_MEM` operand is its top byte. A pre-indexed access (MEM_PRE) applies
 * the immediate before the access, a post-indexed access (MEM_POST) applies it
 * after, and an offset access contributes the immediate in the address offset.
 * MEM_PRE and MEM_POST are independent bits: MEM_PRE | MEM_POST set applies the
 * same immediate twice. Each macro reads the flag byte once; no NZCV is written.
 */
#define KPROG_ARM64_MEM_PRE_BIT {pre}U
#define KPROG_ARM64_MEM_POST_BIT {post}U
#define KPROG_ARM64_MEM_FLAGS_SHIFT {shift}U
#define KPROG_ARM64_MEM_FLAGS_MASK {mask}U
_Static_assert(KPROG_ARM64_MEM_PRE_BIT == {pre}U,
\t       "arm64 pre-bit drift");
_Static_assert(KPROG_ARM64_MEM_POST_BIT == {post}U,
\t       "arm64 post-bit drift");
/*
 * The flag byte of an `AUX` operand: the top byte, matching MEM_FLAGS.
 */
#define KPROG_ARM64_MEM_PREPOST_FLAGS(AUX)                             \\
\t((__u32)(((AUX) >> KPROG_ARM64_MEM_FLAGS_SHIFT) &                     \\
\t\tKPROG_ARM64_MEM_FLAGS_MASK))
/*
 * Whether the address offset suppresses the immediate: true for a pre- or
 * post-indexed access, which applies the immediate as its own writeback.
 */
#define KPROG_ARM64_MEM_PREPOST_SUPPRESS(AUX)                          \\
\t((KPROG_ARM64_MEM_PREPOST_FLAGS(AUX) & KPROG_ARM64_MEM_PRE_BIT) ||    \\
\t (KPROG_ARM64_MEM_PREPOST_FLAGS(AUX) & KPROG_ARM64_MEM_POST_BIT))
/*
 * The immediate the pre-indexed writeback applies (or zero if absent) and the
 * one the post-indexed writeback applies (or zero if absent).
 */
#define KPROG_ARM64_MEM_PREPOST_PRE_DELTA(AUX, IMM)                    \\
\t((KPROG_ARM64_MEM_PREPOST_FLAGS(AUX) & KPROG_ARM64_MEM_PRE_BIT)       \\
\t\t ? (IMM) : 0)
#define KPROG_ARM64_MEM_PREPOST_POST_DELTA(AUX, IMM)                   \\
\t((KPROG_ARM64_MEM_PREPOST_FLAGS(AUX) & KPROG_ARM64_MEM_POST_BIT)      \\
\t\t ? (IMM) : 0)
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = load()
    for path, expected in ((LEAN, render_lean(spec)), (CHEADER, render_c(spec))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 pre/post contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
