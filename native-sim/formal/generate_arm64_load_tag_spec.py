#!/usr/bin/env python3
"""Generate the shared AArch64 plain-load provenance-preservation contract.

The ordinary `LDR` handler (`ARM64_OP_LOAD`) makes one routing decision: when the
destination is written through the tag-copy register write
(`ARM64_SIM_L_WRITE_REG_PTR_TAG`, which attaches the memory-read provenance tag)
or through the tag-dropping width-narrowed scalar write. The simulator inlined
this as `if (width == ARM64_WIDTH_64 && tag != ARM64_SIM_TAG_SCALAR)`; the
decision is the generated contract.

The generated Lean `GeneratedArm64LoadTag.preserve` and the C macro
`KPROG_ARM64_LOAD_TAG_PRESERVE` return the routing bit from the access width and
the memory-read provenance tag: the tag survives only at doubleword width and only
when it is not the bare scalar tag. The opcode number is re-checked against
native-sim/arm64/arm64_sim.h, so a drift there fails `--check`.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_load_tag_spec.json"
SIM_HEADER = ROOT.parent / "arm64/arm64_sim.h"
LEAN = ROOT / "KProgFormal/GeneratedArm64LoadTag.lean"
CHEADER = ROOT / "generated/arm64_load_tag.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64LoadTag",
    "opcode": {"name": "load", "macro": "ARM64_OP_LOAD", "code": 31},
    "preserve_rule": "width_is_w64_and_tag_is_not_scalar",
}

WIDTH_CODE = {"w8": 1, "w16": 2, "w32": 4, "w64": 8}

OPCODE_DEFINE = re.compile(
    r"^#define\s+(ARM64_OP_[A-Z0-9_]+)\s+0x([0-9a-fA-F]+)U\s*$", re.M)


def load() -> dict:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 load-tag specification: {data!r}")
    opcode = EXPECTED["opcode"]
    if opcode["name"] != "load":
        raise SystemExit(f"invalid arm64 load-tag opcode name: {opcode!r}")
    if EXPECTED["preserve_rule"] != "width_is_w64_and_tag_is_not_scalar":
        raise SystemExit(f"invalid arm64 load-tag preserve rule: {EXPECTED!r}")
    opcodes = {name: int(value, 16)
               for name, value in OPCODE_DEFINE.findall(SIM_HEADER.read_text())}
    if not opcodes:
        raise SystemExit(
            f"no ARM64_OP_* opcode definitions found in {SIM_HEADER}")
    if opcodes.get(opcode["macro"]) != opcode["code"]:
        raise SystemExit(
            "arm64 load-tag opcode drifts from native-sim/arm64/arm64_sim.h: "
            f"spec={opcode['macro']}={opcode['code']:#x} "
            f"sim={opcodes.get(opcode['macro'])}")
    return opcode


def render_lean(opcode: dict) -> str:
    return f'''-- Generated by generate_arm64_load_tag_spec.py from arm64_load_tag_spec.json.
import KProgFormal.GeneratedArm64Width
namespace KProgFormal.GeneratedArm64LoadTag
open KProgFormal.GeneratedArm64Width (Width)
/-- The ARM64_OP_* opcode number the ordinary load carries in arm64_sim.h. -/
def code : Nat := {opcode['code']}
/-- Whether the ordinary load preserves the memory-read provenance tag: the tag
survives only at doubleword width and only when it is not the bare scalar tag. A
sub-word load is a scalar narrowing (so it drops the tag) and a doubleword load of
a scalar value has nothing to preserve, so both take the tag-dropping path. -/
def preserve (width : Width) (tagIsScalar : Bool) : Bool :=
  width == .w64 && !tagIsScalar
/-- The routing bit is determined by the width and the scalar-ness of the tag
alone, independent of the tag's identity. -/
theorem preserve_width_and_scalar_determined
    (w₁ w₂ : Width) (s₁ s₂ : Bool)
    (hw : w₁ = w₂) (hs : s₁ = s₂) :
    preserve w₁ s₁ = preserve w₂ s₂ := by
  simp [hw, hs]
end KProgFormal.GeneratedArm64LoadTag
'''


def render_c(opcode: dict) -> str:
    return f'''/* Generated by generate_arm64_load_tag_spec.py from arm64_load_tag_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_LOAD_TAG_H
#define KPROG_FORMAL_GENERATED_ARM64_LOAD_TAG_H
/*
 * The routing decision of the ordinary AArch64 load: whether the destination is
 * written by the tag-copy register write (which attaches the memory-read
 * provenance tag) or by the tag-dropping width-narrowed scalar write. The tag is
 * preserved only at doubleword width and only when it is not the bare scalar tag.
 * An opcode outside the family reaches the caller-supplied unsupported arm.
 */
#include "arm64_width.h"
_Static_assert(ARM64_OP_LOAD == {opcode['code']}U, "arm64 load-tag code drift");
/*
 * The numeric case label {opcode['code']}U tracks the ARM64_OP_LOAD value defined in
 * native-sim/arm64/arm64_sim.h. OP is the opcode, TAG the memory-read provenance
 * tag, WIDTH the access width code; OP, TAG and WIDTH are each read once. The
 * result is 1 when the destination must be written through
 * ARM64_SIM_L_WRITE_REG_PTR_TAG (attaching TAG) and 0 when it must be written
 * through ARM64_SIM_L_WRITE_REG_WIDTH (dropping TAG).
 */
#define KPROG_ARM64_LOAD_TAG_PRESERVE(OP, TAG, WIDTH, UNSUPPORTED)          \\
\t({{ \\
\t\t__u64 __kprog_a64_lt_op = (OP); \\
\t\t__u64 __kprog_a64_lt_tag = (TAG); \\
\t\t__u64 __kprog_a64_lt_width = (WIDTH); \\
\t\t__u64 __kprog_a64_lt_preserve = 0; \\
\\
\t\tswitch (__kprog_a64_lt_op) {{ \\
\t\tcase {opcode['code']}U:                            \\
\t\t\t__kprog_a64_lt_preserve = \\
\t\t\t\t__kprog_a64_lt_width == ARM64_WIDTH_64 && \\
\t\t\t\t__kprog_a64_lt_tag != ARM64_SIM_TAG_SCALAR; \\
\t\t\tbreak; \\
\t\tdefault: \\
\t\t\tUNSUPPORTED; \\
\t\t\tbreak; \\
\t\t}} \\
\t\t__kprog_a64_lt_preserve; \\
\t}})
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    opcode = load()
    for path, expected in ((LEAN, render_lean(opcode)), (CHEADER, render_c(opcode))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 load-tag contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
