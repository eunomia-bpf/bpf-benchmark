#!/usr/bin/env python3
"""Generate the shared x86 SBB flag transition for Lean and C."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parent;SPEC=ROOT/"x86_sbb_flags_spec.json";LEAN=ROOT/"KProgFormal/GeneratedX86SbbFlags.lean";CHEADER=ROOT/"generated/x86_sbb_flags.h";NAMES=["cf","zf","sf","of"];INPUTS={"a","b","sub","r","sign"}
def validate(e):
 if not isinstance(e,dict) or "op" not in e:raise SystemExit(f"invalid SBB flag expression: {e!r}")
 op=e["op"]
 if op=="input":
  if set(e)!={"op","name"} or e["name"] not in INPUTS:raise SystemExit(f"invalid SBB flag input: {e!r}")
 elif op in {"borrow","zero"}:
  if set(e)!={"op"}:raise SystemExit(f"invalid SBB atom: {e!r}")
 elif op=="nonzero":
  if set(e)!={"op","arg"}:raise SystemExit(f"invalid SBB unary: {e!r}")
  validate(e["arg"])
 elif op in {"lor","land","ult","eq","band","xor"}:
  if set(e)!={"op","lhs","rhs"}:raise SystemExit(f"invalid SBB binary: {e!r}")
  validate(e["lhs"]);validate(e["rhs"])
 else:raise SystemExit(f"unsupported SBB flag op: {e!r}")
def load():
 d=json.loads(SPEC.read_text())
 if set(d)!={"schema_version","operation","flags"} or d["schema_version"]!=1 or d["operation"]!="x86SbbFlags" or list(d["flags"])!=NAMES:raise SystemExit(f"invalid SBB flags spec: {d!r}")
 for e in d["flags"].values():validate(e)
 return d["flags"]
def render(e,lean):
 op=e["op"]
 if op=="input":return e["name"] if lean else e["name"].upper()
 if op=="borrow":return "borrow" if lean else "(!!(BORROW))"
 if op=="zero":return "0"
 if op=="nonzero":return f"({render(e['arg'],lean)} != 0)"
 l=render(e["lhs"],lean);r=render(e["rhs"],lean)
 if lean:
  if op in {"lor","land","eq"}:
   operator={"lor":"||","land":"&&","eq":"=="}[op];return f"({l} {operator} {r})"
  fn={"ult":"BitVec.ult","band":"BitVec.and","xor":"BitVec.xor"}[op];return f"({fn} {l} {r})"
 operator={"lor":"||","land":"&&","ult":"<","eq":"==","band":"&","xor":"^"}[op];return f"({l} {operator} {r})"
def lean_out(fs):
 vals=", ".join(f"{n} := {render(fs[n],True)}" for n in NAMES)
 return f'''-- Generated by generate_x86_sbb_flags_spec.py from x86_sbb_flags_spec.json.
import KProgFormal.GeneratedX86LogicFlags
namespace KProgFormal.GeneratedX86SbbFlags
def eval (a b sub r sign : BitVec 64) (borrow : Bool) : GeneratedX86LogicFlags.Flags := {{ {vals} }}
end KProgFormal.GeneratedX86SbbFlags
'''
def c_out(fs):
 vals=" \\\n".join(f"\t\t(C_{n.upper()}) = {render(fs[n],False)};" for n in NAMES)
 return f'''/* Generated by generate_x86_sbb_flags_spec.py from x86_sbb_flags_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_SBB_FLAGS_H
#define KPROG_FORMAL_GENERATED_X86_SBB_FLAGS_H
#define KPROG_X86_SET_SBB_FLAGS(C_CF,C_ZF,C_SF,C_OF,A,B,SUB,R,SIGN,BORROW)  \\
\tdo {{ \\
{vals} \\
\t}} while (0)
#endif
'''
def main():
 p=argparse.ArgumentParser();p.add_argument("--check",action="store_true");a=p.parse_args();fs=load()
 for path,want in ((LEAN,lean_out(fs)),(CHEADER,c_out(fs))):
  if a.check:
   if not path.is_file() or path.read_text()!=want:raise SystemExit(f"generated x86 SBB flags contract is stale: {path}")
  else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(want)
if __name__=="__main__":main()
