#!/usr/bin/env python3
"""Generate the shared parsed-mnemonic to x86 ALU-code contract."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_alu_decode_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86AluDecode.lean"
C_HEADER = ROOT / "generated/x86_alu_decode.h"
PYTHON = ROOT.parent / "x86/micro-prog/generated_x86_alu_decode.py"
EXPECTED = [
    ("add", "add", 0, "generic"),
    ("sub", "sub", 1, "generic"),
    ("xor", "xor", 2, "generic"),
    ("or", "or", 3, "generic"),
    ("and", "and", 4, "generic"),
    ("shl", "shl", 5, "generic"),
    ("shr", "shr", 6, "generic"),
    ("sar", "sar", 7, "generic"),
    ("rol", "rol", 8, "generic"),
    ("imul", "imul", 9, "generic"),
    ("inc", "inc", 10, "generic"),
    ("not", "not", 11, "generic"),
    ("sbb", "sbb", 12, "sbb"),
    ("dec", "dec", 13, "generic"),
    ("neg", "neg", 14, "generic"),
    ("adc", "adc", 15, "adc"),
]


def load() -> list[dict[str, object]]:
    data = json.loads(SPEC.read_text())
    if (set(data) != {"schema_version", "operation", "operations"}
            or data["schema_version"] != 1
            or data["operation"] != "x86AluDecode"):
        raise SystemExit(f"invalid x86 ALU decode specification: {data!r}")
    operations = data["operations"]
    if len(operations) != len(EXPECTED):
        raise SystemExit(f"invalid x86 ALU operation list: {operations!r}")
    for operation, expected in zip(operations, EXPECTED, strict=True):
        actual = (operation.get("mnemonic"), operation.get("name"),
                  operation.get("code"), operation.get("handler"))
        if (set(operation) != {"mnemonic", "name", "code", "handler"}
                or actual != expected):
            raise SystemExit(f"non-canonical x86 ALU operation: {operation!r}")
    return operations


def c_name(operation: dict[str, object]) -> str:
    return f"X86_ALU_{str(operation['name']).upper()}"


def render_lean(operations: list[dict[str, object]]) -> str:
    constructors = "\n".join(f"  | {op['name']}" for op in operations)
    codes = "\n".join(f"  | .{op['name']} => {op['code']}" for op in operations)
    mnemonics = "\n".join(
        f"  | .{op['name']} => \"{op['mnemonic']}\"" for op in operations)
    sbb_code = next(op["code"] for op in operations if op["handler"] == "sbb")
    adc_code = next(op["code"] for op in operations if op["handler"] == "adc")
    return f'''-- Generated by generate_x86_alu_decode_spec.py from x86_alu_decode_spec.json.
import Std
namespace KProgFormal.GeneratedX86AluDecode
inductive Handler
  | generic
  | sbb
  | adc
  deriving DecidableEq, Repr
inductive Alu
{constructors}
  deriving DecidableEq, Repr
def code : Alu -> Nat
{codes}
def mnemonic : Alu -> String
{mnemonics}
def handlerForCode (raw : BitVec 32) : Handler :=
  if raw == {sbb_code} then .sbb else if raw == {adc_code} then .adc else .generic
def handler (alu : Alu) : Handler := handlerForCode (BitVec.ofNat 32 (code alu))
end KProgFormal.GeneratedX86AluDecode
'''


def render_c(operations: list[dict[str, object]]) -> str:
    definitions = "\n".join(
        f"#define {c_name(op)} {op['code']}U" for op in operations)
    sbb_name = c_name(next(op for op in operations if op["handler"] == "sbb"))
    adc_name = c_name(next(op for op in operations if op["handler"] == "adc"))
    return f'''/* Generated by generate_x86_alu_decode_spec.py from x86_alu_decode_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_ALU_DECODE_H
#define KPROG_FORMAL_GENERATED_X86_ALU_DECODE_H
{definitions}
#define KPROG_X86_ALU_USES_SBB_HANDLER(ALU) ((ALU) == {sbb_name})
#define KPROG_X86_ALU_USES_ADC_HANDLER(ALU) ((ALU) == {adc_name})
#endif
'''


def render_python(operations: list[dict[str, object]]) -> str:
    entries = "\n".join(
        f'    "{op["mnemonic"]}": "{c_name(op)}",' for op in operations)
    return f'''# Generated by generate_x86_alu_decode_spec.py from x86_alu_decode_spec.json.
ALU_AUX = {{
{entries}
}}
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    operations = load()
    outputs = (
        (LEAN, render_lean(operations)),
        (C_HEADER, render_c(operations)),
        (PYTHON, render_python(operations)),
    )
    for path, expected in outputs:
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(f"generated x86 ALU decode contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
