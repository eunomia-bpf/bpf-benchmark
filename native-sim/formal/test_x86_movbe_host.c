/*
 * Host cross-check for the x86-64 `MOVBE_LOAD` / `MOVBE_STORE` handler
 * composition (`X86_OP_MOVBE_LOAD`, `0x28`, and `X86_OP_MOVBE_STORE`, `0x29`),
 * the bodies `X86_SIM_L_EXEC_MOVBE_LOAD` and `X86_SIM_L_EXEC_MOVBE_STORE`.
 *
 * Part 1 verifies the generated width contract KPROG_X86_MOVBE_WIDTH against an
 * independent oracle that restates the `FLAGS ? FLAGS : 64` fallback from the
 * raw codes, and checks that the resolved width is never the absent code.
 *
 * Part 2 verifies the load's arm source: the generated shared read-dispatch
 * table KPROG_X86_MEM_READ_SRC over all eight combinations of the three facts,
 * against an independent predicate nesting.
 *
 * Part 3 verifies the store's arm table KPROG_X86_MOVBE_ARM over the one fact
 * it consults — whether the base/destination register is the stack pointer.
 *
 * Part 4 drives the whole load body over a deterministic register, memory, and
 * stack model: it resolves the width, classifies the base through the generated
 * dispatch table, addresses through the generated offset contract, reads
 * through the generated little-endian load, the stack helper's restatement, or
 * the pointer read, reverses through the generated byte-reversal contract, and
 * writes through the generated partial-register write contracts. Every byte and
 * the tag of the destination must match a hand-written model of the C body.
 *
 * Part 5 drives the whole store body the same way: the generated displacement
 * contract, the generated offset contract, the generated byte-reversal
 * contract, the generated arm table, and the generated little-endian store or
 * the stack helper's restatement. Every byte of both the memory and the stack
 * model must match the hand-written model.
 *
 * The point of this oracle is the asymmetries the composition is about: both
 * forms resolve *one* width, used for the byte reversal, the memory access, and
 * the written size alike, so the store's stack arm does not re-derive an
 * effective width and the load has no second, AUX-sourced width; both forms
 * take the *whole* instruction-immediate artifact `(s64)IMM`, never the
 * immediate store's high-half slice `(s32)(IMM >> 32)`; the reversal happens
 * before the arm split; and the load always scalarizes through the
 * partial-register write, so it has no pointer-preserving arm and, unlike the
 * shared `MOV_LOAD`, no sign-extension arm.
 *
 * Build/run:
 *   cd native-sim/formal
 *   cc -Wall -Wextra -O2 -I. test_x86_movbe_host.c -o /tmp/t_mb && /tmp/t_mb
 */
typedef unsigned char __u8;
typedef unsigned short __u16;
typedef unsigned int __u32;
typedef unsigned long long __u64;
typedef signed char __s8;
typedef short __s16;
typedef int __s32;
typedef signed long long __s64;

/* The generated headers define __always_inline functions in the kernel build;
 * provide the attribute for the host build. */
#ifndef __always_inline
#define __always_inline inline __attribute__((always_inline))
#endif

#define X86_WIDTH_8 1U
#define X86_WIDTH_16 2U
#define X86_WIDTH_32 4U
#define X86_WIDTH_64 8U

#define X86_REG_NONE 0xffU
#define X86_RSP 4U

#define X86_OP_MOVBE_LOAD 0x28U
#define X86_OP_MOVBE_STORE 0x29U

#define X86_SIM_TAG_SCALAR 0U
#define X86_SIM_TAG_ABI 1U
#define X86_SIM_TAG_PACKET 2U
#define X86_SIM_TAG_STACK 4U
#define X86_SIM_TAG_MAP_PTR 5U

/* Restate the addressing AUX decoders x86_sim.h defines, so the oracle
 * exercises the same encoding the sim uses. */
#define X86_MEM_AUX(INDEX, SCALE_LOG2)                                      \
	(((__u32)(INDEX) & 0xffU) | (((__u32)(SCALE_LOG2) & 0xffU) << 8))
#define X86_MEM_AUX_INDEX(AUX) ((__u8)((AUX) & 0xffU))
#define X86_MEM_AUX_SCALE_LOG2(AUX) ((__u8)(((AUX) >> 8) & 0xffU))

#include "generated/x86_movbe.h"
#include "generated/x86_bswap.h"
#include "generated/x86_width.h"
#include "generated/x86_mem_access.h"
#include "generated/x86_mem_dispatch.h"
