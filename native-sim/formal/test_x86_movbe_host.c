#include <stdint.h>
#include <stdio.h>
#include <string.h>

/* ------------------------------------------------------------------ */
/* A deterministic register file, memory and stack model.             */
/*                                                                    */
/* Registers carry a byte view, a 16-bit view and a pointer view over */
/* the same eight bytes plus the tag byte, the way the register-write */
/* helpers expect; register "pointers" are held as byte offsets that  */
/* the oracle reduces modulo the memory buffer so the model stays     */
/* inside the arrays at every address it forms.                       */
/* ------------------------------------------------------------------ */

#define ORACLE_REGS 16U
#define ORACLE_BYTES 4096
#define ORACLE_STACK_BYTES 64U

struct oracle_reg {
	union {
		__u8 b[8];
		__u16 w;
		void *ptr;
	} u;
	__u8 tag;
};

static struct oracle_reg oracle_regs[ORACLE_REGS];
static struct oracle_reg pristine_regs[ORACLE_REGS];
static struct oracle_reg result_regs[ORACLE_REGS];

static __u8 oracle_mem[ORACLE_BYTES];
static __u8 oracle_stack[ORACLE_STACK_BYTES];

static __u8 pristine_mem[ORACLE_BYTES];
static __u8 pristine_stack[ORACLE_STACK_BYTES];

static __u8 result_mem[ORACLE_BYTES];
static __u8 result_stack[ORACLE_STACK_BYTES];

static __u64 oracle_synthetic(__u64 index)
{
	return (__u8)((index * 131U + 17U) ^ (index >> 5));
}

static void oracle_reset(void)
{
	unsigned i;
	__u64 j;

	for (i = 0; i < ORACLE_REGS; i++) {
		oracle_regs[i].u.ptr =
			(void *)(long)(0x200ULL + (__u64)i * 0x20ULL);
		oracle_regs[i].tag = (__u8)(i % 6U);
	}
	for (j = 0; j < ORACLE_BYTES; j++)
		oracle_mem[j] = (__u8)oracle_synthetic(j);
	for (j = 0; j < ORACLE_STACK_BYTES; j++)
		oracle_stack[j] = (__u8)oracle_synthetic(j + 7U);
}

/* The reduction an effective address is folded through so the model stays
 * inside the memory array; the reduction leaves room for the widest (8-byte)
 * load. Both paths share this convention; it is not part of the contract
 * under test. */
static unsigned oracle_slot(__u64 addr)
{
	return (unsigned)(addr % (ORACLE_BYTES - 8U));
}

static void oracle_snapshot_pristine(void)
{
	memcpy(pristine_regs, oracle_regs, sizeof(pristine_regs));
	memcpy(pristine_mem, oracle_mem, ORACLE_BYTES);
	memcpy(pristine_stack, oracle_stack, ORACLE_STACK_BYTES);
}

static void oracle_restore_pristine(void)
{
	memcpy(oracle_regs, pristine_regs, sizeof(pristine_regs));
	memcpy(oracle_mem, pristine_mem, ORACLE_BYTES);
	memcpy(oracle_stack, pristine_stack, ORACLE_STACK_BYTES);
}

static __u64 oracle_reg_value(unsigned index)
{
	return (__u64)(uintptr_t)oracle_regs[index].u.ptr;
}

/* ------------------------------------------------------------------ */
/* Hand-written models, independent of the macros under test.          */
/* ------------------------------------------------------------------ */

/* The width mask, restated from the raw codes rather than taken from the
 * generated x86_width.h. */
static __u64 oracle_mask(unsigned width)
{
	if (width == X86_WIDTH_8)
		return 0xffULL;
	if (width == X86_WIDTH_16)
		return 0xffffULL;
	if (width == X86_WIDTH_32)
		return 0xffffffffULL;
	return 0xffffffffffffffffULL;
}

/* The byte reversal, restated as a byte-reverse loop over the raw codes
 * rather than taken from the generated kprog_x86_bswap_value. */
static __u64 oracle_bswap(__u64 value, unsigned width)
{
	__u64 out = 0;
	unsigned i;

	for (i = 0; i < width; i++)
		out |= ((value >> (8U * i)) & 0xffULL) << (8U * (width - 1U - i));
	return out & oracle_mask(width);
}

/* The ordinary little-endian load: exactly `width` bytes, least significant
 * first, width-masked. */
static __u64 oracle_load(__u64 addr, unsigned width)
{
	__u64 v = 0;
	unsigned i;

	for (i = 0; i < width; i++)
		v |= (__u64)oracle_mem[oracle_slot(addr) + i] << (8 * i);
	return v & oracle_mask(width);
}

/* The 8-byte pointer read the ABI arm performs. */
static __u64 oracle_ptr_load(__u64 addr)
{
	__u64 v = 0;
	unsigned i;

	for (i = 0; i < 8U; i++)
		v |= (__u64)oracle_mem[oracle_slot(addr) + i] << (8 * i);
	return v;
}

/* The stack helper's load, restated: the frame index is the stack-relative
 * offset biased by the frame size, and the value is width-masked and read
 * little-endian. */
static __u64 oracle_stack_load(__s64 off, unsigned width)
{
	__u32 index = (__u32)((__s64)off + ORACLE_STACK_BYTES);
	__u64 v = 0;
	unsigned i;

	for (i = 0; i < width; i++)
		v |= (__u64)oracle_stack[(index + i) % ORACLE_STACK_BYTES]
		     << (8 * i);
	return v & oracle_mask(width);
}

/* The stack helper's store, restated. */
static void oracle_stack_store(__s64 off, unsigned width, __u64 value)
{
	__u32 index = (__u32)(off + ORACLE_STACK_BYTES);
	__u64 narrowed = value & oracle_mask(width);
	unsigned i;

	for (i = 0; i < width; i++)
		oracle_stack[(index + i) % ORACLE_STACK_BYTES] =
			(__u8)(narrowed >> (8 * i));
}

/* The ordinary little-endian store: exactly `width` bytes of the width-masked
 * value, least significant first. */
static void oracle_store(__u64 addr, unsigned width, __u64 value)
{
	unsigned base = oracle_slot(addr);
	__u64 narrowed = value & oracle_mask(width);
	unsigned i;

	for (i = 0; i < width; i++)
		oracle_mem[base + i] = (__u8)(narrowed >> (8 * i));
}

/* The partial-register writeback the sim performs: 8- and 16-bit writes keep
 * the destination's upper bytes, a 32-bit write zeroes the upper half, and a
 * 64-bit write replaces the register. */
static __u64 oracle_write(__u64 old, __u64 value, unsigned width)
{
	if (width == X86_WIDTH_8)
		return (old & ~0xffULL) | (value & 0xffULL);
	if (width == X86_WIDTH_16)
		return (old & ~0xffffULL) | (value & 0xffffULL);
	if (width == X86_WIDTH_32)
		return value & 0xffffffffULL;
	return value;
}

/* The base register the addressing mode names; a `NONE` base contributes the
 * null pointer and the default scalar tag, the way the sim's register-value
 * and register-tag switches fall through. */
static __u64 oracle_base_ptr(unsigned base)
{
	return base == X86_REG_NONE ? 0ULL
			: (__u64)(uintptr_t)oracle_regs[base].u.ptr;
}

static __u8 oracle_base_tag(unsigned base)
{
	return base == X86_REG_NONE ? X86_SIM_TAG_SCALAR
			: oracle_regs[base].tag;
}

/* The addressing offset, restated: the displacement, plus the scaled index
 * when the mode carries one. */
static __s64 oracle_mem_offset(__u32 aux, __s64 disp, __u64 index_value)
{
	__s64 off = disp;

	if (X86_MEM_AUX_INDEX(aux) != X86_REG_NONE)
		off += (__s64)(index_value << X86_MEM_AUX_SCALE_LOG2(aux));
	return off;
}

/* ------------------------------------------------------------------ */
/* Part 1: the generated width contract vs. the oracle.                */
/* ------------------------------------------------------------------ */

static unsigned part1(void)
{
	static const __u8 codes[6] = { 0U, X86_WIDTH_8, X86_WIDTH_16,
				       X86_WIDTH_32, X86_WIDTH_64, 9U };
	unsigned cases = 0;
	unsigned fi;

	for (fi = 0; fi < 6U; fi++) {
		__u8 flags = codes[fi];
		__u8 want = flags ? flags : X86_WIDTH_64;
		__u8 got = KPROG_X86_MOVBE_WIDTH(flags);

		if (got != want) {
			fprintf(stderr, "width mismatch flags=%u got=%u want=%u\n",
				flags, got, want);
			return 0;
		}
		if (got == KPROG_X86_MOVBE_WIDTH_ABSENT) {
			fprintf(stderr, "absent width flags=%u\n", flags);
			return 0;
		}
		cases++;
	}
	return cases;
}

/* ------------------------------------------------------------------ */
/* Part 2: the load's arm source (the shared read dispatch) vs. the   */
/* oracle.                                                            */
/* ------------------------------------------------------------------ */

static unsigned part2(void)
{
	unsigned cases = 0;
	unsigned r;
	unsigned a;
	unsigned w;

	for (r = 0; r < 2U; r++) {
		for (a = 0; a < 2U; a++) {
			for (w = 0; w < 2U; w++) {
				__u8 got = KPROG_X86_MEM_READ_SRC(
					r, a ? X86_SIM_TAG_ABI
					     : X86_SIM_TAG_SCALAR,
					w ? X86_WIDTH_64 : X86_WIDTH_32);
				__u8 want = r ? KPROG_X86_MEM_SRC_STACK
					      : (a && w)
							? KPROG_X86_MEM_SRC_ABI_PTR_LOAD
							: KPROG_X86_MEM_SRC_NORMAL_LOAD;

				if (got != want) {
					fprintf(stderr,
						"dispatch mismatch rsp=%u abi=%u "
						"w64=%u got=%u want=%u\n",
						r, a, w, got, want);
					return 0;
				}
				cases++;
			}
		}
	}
	return cases;
}

/* ------------------------------------------------------------------ */
/* Part 3: the store's arm table vs. the oracle.                      */
/* ------------------------------------------------------------------ */

static unsigned part3(void)
{
	unsigned cases = 0;
	int rsp;

	for (rsp = 0; rsp < 2; rsp++) {
		__u8 want = rsp ? KPROG_X86_MOVBE_ARM_STACK
				: KPROG_X86_MOVBE_ARM_MEMORY;
		__u8 got = KPROG_X86_MOVBE_ARM(rsp);

		if (got != want) {
			fprintf(stderr, "arm mismatch rsp=%d got=%u want=%u\n",
				rsp, got, want);
			return 0;
		}
		cases++;
	}
	return cases;
}

/* ------------------------------------------------------------------ */
/* Part 4: the full load composition vs. the hand-written body.       */
/*                                                                    */
/* `contract_step_load` resolves, classifies, addresses, reads,       */
/* reverses and writes through the generated contracts;               */
/* `model_step_load` restates the body from the raw fields. They must */
/* agree byte for byte in the destination register and its tag.       */
/* ------------------------------------------------------------------ */

struct movbe_load_effect {
	__u8 src_code;
	__u8 width;
	__u64 value;
	__u64 dst;
	__u8 dst_tag;
};

static struct movbe_load_effect contract_step_load(unsigned dst, unsigned base,
						   __u32 aux, __u8 flags,
						   __u64 imm,
						   __u64 index_value)
{
	__u8 width = KPROG_X86_MOVBE_WIDTH(flags);
	__u8 src_code = KPROG_X86_MEM_READ_SRC(
		base == X86_RSP, oracle_base_tag(base), width);
	__s64 disp = KPROG_X86_MOVBE_DISP(imm);
	__u64 base_ptr = oracle_base_ptr(base);
	__s64 off = KPROG_X86_MEM_OFFSET(
		aux, disp, index_value,
		X86_MEM_AUX_INDEX(aux) != X86_REG_NONE);
	__u64 addr = base_ptr + (__u64)off;
	__u64 raw;
	__u64 value;
	struct movbe_load_effect r;

	if (src_code == KPROG_X86_MEM_SRC_STACK)
		raw = oracle_stack_load((__s64)base_ptr + off, width);
	else if (src_code == KPROG_X86_MEM_SRC_ABI_PTR_LOAD)
		raw = (__u64)(long)*(void **)&oracle_mem[oracle_slot(addr)];
	else
		raw = KPROG_X86_MEM_LOAD(&oracle_mem[oracle_slot(addr)], width);

	value = kprog_x86_bswap_value(raw, width);

	if (width == X86_WIDTH_8)
		KPROG_X86_WRITE_REG8(oracle_regs[dst].u, oracle_regs[dst].tag,
				     value, 0U, X86_SIM_TAG_SCALAR);
	else if (width == X86_WIDTH_16)
		KPROG_X86_WRITE_REG16(oracle_regs[dst].u, oracle_regs[dst].tag,
				      value, X86_SIM_TAG_SCALAR);
	else if (width == X86_WIDTH_32)
		KPROG_X86_WRITE_REG32(oracle_regs[dst].u, oracle_regs[dst].tag,
				      value, X86_SIM_TAG_SCALAR);
	else
		KPROG_X86_WRITE_REG64(oracle_regs[dst].u, oracle_regs[dst].tag,
				      value, X86_SIM_TAG_SCALAR);

	r.src_code = src_code;
	r.width = width;
	r.value = value;
	r.dst = oracle_reg_value(dst);
	r.dst_tag = oracle_regs[dst].tag;
	return r;
}

static struct movbe_load_effect model_step_load(unsigned dst, unsigned base,
						__u32 aux, __u8 flags,
						__u64 imm, __u64 index_value)
{
	__u8 width = flags ? flags : X86_WIDTH_64;
	__u8 base_tag = oracle_base_tag(base);
	__u64 base_ptr = oracle_base_ptr(base);
	__s64 off = oracle_mem_offset(aux, (__s64)imm, index_value);
	__u64 addr = base_ptr + (__u64)off;
	__u64 old = oracle_reg_value(dst);
	__u64 raw;
	__u64 value;
	struct movbe_load_effect r;

	/* The arm is the raw predicate nesting: the stack-pointer test first,
	 * then the ABI tag gated on width 64, then the ordinary load. */
	if (base == X86_RSP) {
		r.src_code = KPROG_X86_MEM_SRC_STACK;
		raw = oracle_stack_load((__s64)base_ptr + off, width);
	} else if (base_tag == X86_SIM_TAG_ABI && width == X86_WIDTH_64) {
		r.src_code = KPROG_X86_MEM_SRC_ABI_PTR_LOAD;
		raw = oracle_ptr_load(addr);
	} else {
		r.src_code = KPROG_X86_MEM_SRC_NORMAL_LOAD;
		raw = oracle_load(addr, width);
	}

	value = oracle_bswap(raw, width);
	/* The writeback always scalarizes. */
	oracle_regs[dst].u.ptr = (void *)(long)oracle_write(old, value, width);
	oracle_regs[dst].tag = X86_SIM_TAG_SCALAR;

	r.width = width;
	r.value = value;
	r.dst = oracle_reg_value(dst);
	r.dst_tag = oracle_regs[dst].tag;
	return r;
}

static unsigned part4(void)
{
	static const __u8 width_codes[5] = { 0U, X86_WIDTH_8, X86_WIDTH_16,
					     X86_WIDTH_32, X86_WIDTH_64 };
	static const __u64 imms[4] = {
		0x1234001000000008ULL,
		0x0000000000000010ULL,
		0xffffffff00000008ULL,
		0x0000000000000018ULL,
	};
	static const unsigned bases[4] = { 1U, 2U, X86_RSP, X86_REG_NONE };
	static const __u8 base_tags[4] = { X86_SIM_TAG_SCALAR, X86_SIM_TAG_ABI,
		X86_SIM_TAG_STACK, X86_SIM_TAG_MAP_PTR };
	static const unsigned dsts[2] = { 5U, 9U };
	static const __u8 index_regs[3] = { X86_REG_NONE, 3U, 11U };
	unsigned cases = 0;
	unsigned bi;
	unsigned ti;
	unsigned fi;
	unsigned di;
	unsigned xi;
	unsigned ii;
	unsigned sc;

	for (bi = 0; bi < 4U; bi++) {
		for (ti = 0; ti < 4U; ti++) {
			for (fi = 0; fi < 5U; fi++) {
				for (di = 0; di < 4U; di++) {
					for (xi = 0; xi < 2U; xi++) {
							for (ii = 0; ii < 3U; ii++) {
								for (sc = 0; sc < 2U; sc++) {
								unsigned dst = dsts[xi];
								__u32 aux =
									index_regs[ii] ==
									 X86_REG_NONE
									? X86_MEM_AUX(X86_REG_NONE, 0U)
									: X86_MEM_AUX(index_regs[ii],
										       (sc == 0 ? 0U : (__u8)sc));
								__u64 index_value =
									0x1111111100000005ULL;
								struct movbe_load_effect got;
								struct movbe_load_effect want;

								oracle_restore_pristine();
								if (bi != 3U)
									oracle_regs[bases[bi]].tag =
										base_tags[ti];
								got = contract_step_load(dst, bases[bi], aux,
											 width_codes[fi], imms[di],
											 index_value);
								memcpy(result_regs, oracle_regs,
								       sizeof(oracle_regs));
								oracle_restore_pristine();
								if (bi != 3U)
									oracle_regs[bases[bi]].tag =
										base_tags[ti];
								want = model_step_load(dst, bases[bi], aux,
										       width_codes[fi], imms[di],
										       index_value);
								if (got.src_code != want.src_code ||
								    got.width != want.width ||
								    got.value != want.value ||
								    got.dst != want.dst ||
								    got.dst_tag != want.dst_tag ||
								    memcmp(result_regs, oracle_regs,
									   sizeof(oracle_regs))) {
									fprintf(stderr,
										"load handler mismatch "
										"base=%u tag=%u wcode=%u "
										"imm=%llx idx=%u scale=%u "
										"got=(%u,%u,%llx,%llx,%u) "
										"want=(%u,%u,%llx,%llx,%u)\n",
										bases[bi], base_tags[ti],
										width_codes[fi],
										(unsigned long long)imms[di],
									(unsigned)index_regs[ii], sc,
									got.src_code, got.width,
									(unsigned long long)got.value,
									(unsigned long long)got.dst, got.dst_tag,
									want.src_code, want.width,
									(unsigned long long)want.value,
									(unsigned long long)want.dst, want.dst_tag);
								return 0;
							}
							cases++;
							}
						}
					}
				}
			}
		}
	}
	return cases;
}

/* ------------------------------------------------------------------ */
/* Part 5: the full store composition vs. the hand-written body.      */
/*                                                                    */
/* The handler writes only memory, so the memory and stack buffers    */
/* are the state compared; the registers are read-only inputs.        */
/* ------------------------------------------------------------------ */

struct movbe_store_effect {
	__u8 arm;
	__u8 width;
	__u64 value;
	__u64 addr;
};

static struct movbe_store_effect contract_step_store(unsigned base,
						     unsigned src, __u32 aux,
						     __u8 flags, __u64 imm,
						     __u64 index_value)
{
	__u8 width = KPROG_X86_MOVBE_WIDTH(flags);
	__u8 arm = KPROG_X86_MOVBE_ARM(base == X86_RSP);
	__s64 disp = KPROG_X86_MOVBE_DISP(imm);
	__u64 base_ptr = oracle_base_ptr(base);
	__s64 off = KPROG_X86_MEM_OFFSET(
		aux, disp, index_value,
		X86_MEM_AUX_INDEX(aux) != X86_REG_NONE);
	__u64 value = kprog_x86_bswap_value(oracle_reg_value(src), width);
	struct movbe_store_effect r;

	r.arm = arm;
	r.width = width;
	r.value = value;
	r.addr = base_ptr + (__u64)off;

	if (arm == KPROG_X86_MOVBE_ARM_STACK)
		oracle_stack_store((__s64)base_ptr + off, width, value);
	else
		KPROG_X86_MEM_STORE(&oracle_mem[oracle_slot(r.addr)], width,
				    value);
	return r;
}

static struct movbe_store_effect model_step_store(unsigned base, unsigned src,
						  __u32 aux, __u8 flags,
						  __u64 imm, __u64 index_value)
{
	__u8 width = flags ? flags : X86_WIDTH_64;
	__u64 base_ptr = oracle_base_ptr(base);
	__s64 off = oracle_mem_offset(aux, (__s64)imm, index_value);
	__u64 value = oracle_bswap(oracle_reg_value(src), width);
	struct movbe_store_effect r;

	r.arm = base == X86_RSP ? KPROG_X86_MOVBE_ARM_STACK
				: KPROG_X86_MOVBE_ARM_MEMORY;
	r.width = width;
	r.value = value;
	r.addr = base_ptr + (__u64)off;

	if (r.arm == KPROG_X86_MOVBE_ARM_STACK)
		oracle_stack_store((__s64)base_ptr + off, width, value);
	else
		oracle_store(r.addr, width, value);
	return r;
}

static unsigned part5(void)
{
	static const __u8 width_codes[5] = { 0U, X86_WIDTH_8, X86_WIDTH_16,
					     X86_WIDTH_32, X86_WIDTH_64 };
	static const __u64 imms[3] = {
		0x8000001000000008ULL,
		0x0000000000000020ULL,
		0xffffffff00000010ULL,
	};
	static const unsigned bases[3] = { 1U, 2U, X86_RSP };
	static const unsigned srcs[3] = { 3U, 6U, 11U };
	static const __u8 index_regs[3] = { X86_REG_NONE, 3U, 11U };
	unsigned cases = 0;
	unsigned bi;
	unsigned si;
	unsigned fi;
	unsigned di;
	unsigned ii;
	unsigned sc;

	for (bi = 0; bi < 3U; bi++) {
		for (si = 0; si < 3U; si++) {
			for (fi = 0; fi < 5U; fi++) {
				for (di = 0; di < 3U; di++) {
					for (ii = 0; ii < 3U; ii++) {
						for (sc = 0; sc < 2U; sc++) {
							__u32 aux =
								index_regs[ii] ==
								 X86_REG_NONE
								? X86_MEM_AUX(X86_REG_NONE, 0U)
								: X86_MEM_AUX(index_regs[ii],
									       (sc == 0 ? 0U : (__u8)sc));
							__u64 index_value =
								0x1111111100000005ULL;
							struct movbe_store_effect got;
							struct movbe_store_effect want;

							oracle_restore_pristine();
							got = contract_step_store(bases[bi],
										  srcs[si], aux,
										  width_codes[fi], imms[di],
										  index_value);
							memcpy(result_mem, oracle_mem,
							       ORACLE_BYTES);
							memcpy(result_stack, oracle_stack,
							       ORACLE_STACK_BYTES);
							oracle_restore_pristine();
							want = model_step_store(bases[bi],
										srcs[si], aux,
										width_codes[fi], imms[di],
										index_value);
							if (got.arm != want.arm ||
							    got.width != want.width ||
							    got.value != want.value ||
							    got.addr != want.addr ||
							    memcmp(result_mem, oracle_mem,
								   ORACLE_BYTES) ||
							    memcmp(result_stack, oracle_stack,
								   ORACLE_STACK_BYTES)) {
								fprintf(stderr,
									"store handler mismatch "
									"base=%u src=%u wcode=%u "
									"imm=%llx idx=%u scale=%u "
									"got=(%u,%u,%llx,%llx) "
									"want=(%u,%u,%llx,%llx)\n",
									bases[bi], srcs[si],
									width_codes[fi],
									(unsigned long long)imms[di],
									(unsigned)index_regs[ii], sc,
									got.arm, got.width,
									(unsigned long long)got.value,
									(unsigned long long)got.addr,
									want.arm, want.width,
									(unsigned long long)want.value,
									(unsigned long long)want.addr);
								return 0;
							}
							cases++;
						}
					}
				}
			}
		}
	}
	return cases;
}

/* ------------------------------------------------------------------ */
/* Part 6: pins on the asymmetries the composition is about.          */
/* ------------------------------------------------------------------ */

static unsigned part6(void)
{
	unsigned cases = 0;

	/* Pin 1: the whole-artifact displacement and the immediate store's
	 * high-half slice are different slices of the same field. The MOVBE
	 * form must take the whole field. */
	{
		__u64 imm = 0x8000001000000008ULL;

		if (KPROG_X86_MOVBE_DISP(imm) != (__s64)imm)
			return 0;
		if (KPROG_X86_MOVBE_DISP(imm) ==
		    (__s64)(__s32)(imm >> 32))
			return 0;
		cases++;
	}

	/* Pin 2: the load at width 8 does not sign-extend — a reversal of the
	 * byte 0x80 stays 0x80, whereas the shared MOVSX load of the same
	 * byte would widen it to 0xffffffffffffff80. */
	{
		if (kprog_x86_bswap_value(0x80ULL, X86_WIDTH_8) != 0x80ULL)
			return 0;
		cases++;
	}

	/* Pin 3: an ABI-tagged 64-bit base takes the pointer arm — the load
	 * reads the pointer, not the ordinary bytes — and the writeback
	 * scalarizes the destination, so the load has no pointer-preserving
	 * arm. */
	{
		struct movbe_load_effect e;

		oracle_restore_pristine();
		oracle_regs[2].tag = X86_SIM_TAG_ABI;
		oracle_regs[0].tag = X86_SIM_TAG_MAP_PTR;
		oracle_regs[0].u.ptr = (void *)(long)0xdeadbeefdeadbeefULL;
		e = contract_step_load(0U, 2U, 0U, X86_WIDTH_64,
				       0x0000000000000010ULL, 0U);
		if (e.src_code != KPROG_X86_MEM_SRC_ABI_PTR_LOAD)
			return 0;
		if (oracle_regs[0].tag != X86_SIM_TAG_SCALAR)
			return 0;
		cases++;
	}

	/* Pin 4: the same ABI-tagged base off width 64 falls through to the
	 * ordinary load — the ABI arm is width-64-gated. */
	{
		struct movbe_load_effect e;

		oracle_restore_pristine();
		oracle_regs[2].tag = X86_SIM_TAG_ABI;
		e = contract_step_load(0U, 2U, 0U, X86_WIDTH_32,
				       0x0000000000000010ULL, 0U);
		if (e.src_code != KPROG_X86_MEM_SRC_NORMAL_LOAD)
			return 0;
		cases++;
	}

	/* Pin 5: the reversal is an involution at every width, so a load of
	 * what a store of the same width reversed recovers the width-masked
	 * original. */
	{
		static const __u8 widths[4] = { X86_WIDTH_8, X86_WIDTH_16,
						X86_WIDTH_32, X86_WIDTH_64 };
		unsigned wi;

		for (wi = 0; wi < 4U; wi++) {
			__u64 v = 0x0123456789abcdefULL;

			if (kprog_x86_bswap_value(
				    kprog_x86_bswap_value(v, widths[wi]),
				    widths[wi]) != (v & oracle_mask(widths[wi])))
				return 0;
			cases++;
		}
	}

	/* Pin 6: one resolved width rides the reversal, the memory access and
	 * the written size alike — a narrow width masks the value on both
	 * sides of the reversal, and a store at that width writes exactly its
	 * byte count. */
	{
		unsigned cases_before = cases;

		if ((kprog_x86_bswap_value(0xffffffffffffffffULL, X86_WIDTH_16) &
		     0xffffffffffff0000ULL) != 0)
			return 0;
		if (KPROG_X86_WIDTH_BITS(X86_WIDTH_16) / 8U != 2U)
			return 0;
		cases = cases_before + 1U;
	}

	return cases;
}

int main(void)
{
	unsigned total = 0U;

	oracle_reset();
	oracle_snapshot_pristine();

	total += part1();
	total += part2();
	total += part3();
	/* The store and load parts write memory and registers, so restore the
	 * model between parts. */
	oracle_restore_pristine();
	total += part4();
	oracle_restore_pristine();
	total += part5();
	oracle_restore_pristine();
	total += part6();

	printf("x86 movbe handler host cross-check: OK (%u cases)\n", total);
	return 0;
}
