#!/usr/bin/env python3
"""Generate the shared x86-64 effective-address offset contract.

The generated Lean definition `GeneratedX86MemOffset.value` and the C macro
`KPROG_X86_MEM_OFFSET` implement the offset the x86 simulator adds to a base
register before a load/store or before computing a LEA result:

  - a displacement-only access contributes the (already sign-extended)
    displacement;
  - an indexed access adds the index register value scaled by the addressing
    mode's scale factor.

Unlike the AArch64 contract, x86 encodes the scale as its base-2 logarithm
(`X86_MEM_AUX_SCALE_LOG2`), so the index contribution is a left shift rather
than a multiply; the two agree for every scale the arch encodes (1, 2, 4, 8 ->
0, 1, 2, 3). Both the C and the contract accumulate in the 64-bit
two's-complement domain: the C code adds `__s64` values and casts the shifted
`__u64` index to `__s64`, all of which produce the same bits as wrapping
64-bit addition, so the contract states the accumulation as `BitVec 64`
addition. `KProgFormal/X86MemOffset.lean` records that equivalence explicitly.

The C macro evaluates the displacement once and (only when an index is
present) the scale byte and the already-read index once; it writes no flags.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_mem_offset_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86MemOffset.lean"
CHEADER = ROOT / "generated/x86_mem_offset.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "x86MemOffset",
    "base": "disp",
    "indexed": "disp_plus_index_scaled",
    "scale": "shift_log2",
    "accumulate": "wrapping64",
}


def load() -> dict:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 memory-offset specification: {data!r}")
    return EXPECTED


def render_lean(spec: dict) -> str:
    return '''-- Generated by generate_x86_mem_offset_spec.py from x86_mem_offset_spec.json.
import Std
namespace KProgFormal.GeneratedX86MemOffset
/-- Shared x86-64 effective-address offset. `hasIndex` is true when the
addressing mode carries an index register, `scale` is the base-2 logarithm of
the scale factor (`X86_MEM_AUX_SCALE_LOG2`), `disp` is the sign-extended
displacement, and `index` is the index register's raw 64-bit value. The index
contribution is a left shift, not a multiply. -/
def value (hasIndex : Bool) (scale disp index : BitVec 64) : BitVec 64 :=
  let base := disp
  if hasIndex then base + (index <<< scale) else base
/-- The independent case table over `hasIndex`. -/
def valueSpec (hasIndex : Bool) (scale disp index : BitVec 64) : BitVec 64 :=
  match hasIndex with
  | true => disp + (index <<< scale)
  | false => disp
end KProgFormal.GeneratedX86MemOffset
'''


def render_c(spec: dict) -> str:
    body = [
        "\t({",
        "\t\t__s64 __kprog_x86_mo_disp = (DISP);",
        "\t\tint __kprog_x86_mo_has_index = (HAS_INDEX) ? 1 : 0;",
        "\t\t__s64 __kprog_x86_mo_result = __kprog_x86_mo_disp;",
        "",
        "\t\tif (__kprog_x86_mo_has_index) {",
        "\t\t\t__u8 __kprog_x86_mo_scale =",
        "\t\t\t\tX86_MEM_AUX_SCALE_LOG2(AUX);",
        "\t\t\t__u64 __kprog_x86_mo_index = (INDEX_VALUE);",
        "\t\t\t__kprog_x86_mo_result +=",
        "\t\t\t\t(__s64)(__kprog_x86_mo_index << __kprog_x86_mo_scale);",
        "\t\t}",
        "\t\t__kprog_x86_mo_result;",
        "\t})",
    ]
    continued = " \\\n".join(body)
    return f'''/* Generated by generate_x86_mem_offset_spec.py from x86_mem_offset_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_MEM_OFFSET_H
#define KPROG_FORMAL_GENERATED_X86_MEM_OFFSET_H
/*
 * x86-64 effective-address offset: a displacement-only access contributes the
 * sign-extended displacement, an indexed access additionally adds the index
 * register value scaled by the aux-encoded base-2 log of the scale factor. The
 * accumulation is 64-bit two's-complement wrapping, the same bit pattern as
 * the C code's signed `__s64` addition and `__u64` shift.
 */
/*
 * AUX carries the addressing mode (its `X86_MEM_AUX_SCALE_LOG2` byte is the
 * scale exponent); DISP is the sign-extended displacement; INDEX_VALUE is the
 * already-read raw 64-bit index register value; HAS_INDEX states whether the
 * mode carries an index. DISP, and (only when an index is present) AUX and
 * INDEX_VALUE are each evaluated exactly once; the index read is never
 * performed when HAS_INDEX is false. No flags are written. The result is the
 * raw 64-bit offset; the caller adds it to the base register.
 */
#define KPROG_X86_MEM_OFFSET(AUX, DISP, INDEX_VALUE, HAS_INDEX)             \\
{continued}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = load()
    for path, expected in ((LEAN, render_lean(spec)), (CHEADER, render_c(spec))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated x86 memory-offset contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
