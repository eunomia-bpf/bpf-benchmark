#!/usr/bin/env python3
"""Generate the shared AArch64 FMOV destination-routing contract.

The `FMOV` handler (`ARM64_OP_FMOV`) applies the generated value selection to
`v0` and then routes the result: a vector-destination direction writes `v0`,
while a register-destination direction writes the general-purpose destination
through the ordinary width-narrowed register write. The simulator inlined this as
`if ((AUX) == D_FROM_X || (AUX) == S_FROM_W) v0 = result; else WRITE_REG(...)`;
which file receives the result is the generated contract.

The generated Lean `vectorDestination` and the C macro
`KPROG_ARM64_FMOV_DEST_VECTOR` return whether a direction code routes to the
vector register (rather than the general-purpose destination). The direction and
opcode codes are re-checked against native-sim/arm64/arm64_sim.h, so a drift there
fails `--check`.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_fmov_dest_spec.json"
SIM_HEADER = ROOT.parent / "arm64/arm64_sim.h"
LEAN = ROOT / "KProgFormal/GeneratedArm64FmovDest.lean"
CHEADER = ROOT / "generated/arm64_fmov_dest.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64FmovDest",
    "opcode": {"name": "fmov", "macro": "ARM64_OP_FMOV", "code": 35},
    "directions": [
        {"name": "d_from_x", "code": 0, "macro": "ARM64_FMOV_D_FROM_X",
         "vector_destination": True},
        {"name": "x_from_d", "code": 1, "macro": "ARM64_FMOV_X_FROM_D",
         "vector_destination": False},
        {"name": "s_from_w", "code": 2, "macro": "ARM64_FMOV_S_FROM_W",
         "vector_destination": True},
        {"name": "w_from_s", "code": 3, "macro": "ARM64_FMOV_W_FROM_S",
         "vector_destination": False},
    ],
    "routing_rule": "vector_iff_even_direction_code",
}

OPCODE_DEFINE = re.compile(
    r"^#define\s+(ARM64_OP_[A-Z0-9_]+)\s+0x([0-9a-fA-F]+)U\s*$", re.M)
DIR_DEFINE = re.compile(
    r"^#define\s+(ARM64_FMOV_[A-Z0-9_]+)\s+(\d+)U\s*$", re.M)


def load() -> dict:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 fmov-dest specification: {data!r}")
    if EXPECTED["routing_rule"] != "vector_iff_even_direction_code":
        raise SystemExit(f"invalid arm64 fmov-dest routing rule: {EXPECTED!r}")
    dirs = EXPECTED["directions"]
    if [row["code"] for row in dirs] != [0, 1, 2, 3]:
        raise SystemExit(f"invalid arm64 fmov-dest codes: {dirs!r}")
    if [row["vector_destination"] for row in dirs] != [True, False, True, False]:
        raise SystemExit(f"invalid arm64 fmov-dest routing: {dirs!r}")
    text = SIM_HEADER.read_text()
    opcodes = {name: int(value, 16)
               for name, value in OPCODE_DEFINE.findall(text)}
    if not opcodes:
        raise SystemExit(f"no ARM64_OP_* opcode definitions in {SIM_HEADER}")
    op = EXPECTED["opcode"]
    if opcodes.get(op["macro"]) != op["code"]:
        raise SystemExit(
            "arm64 fmov-dest opcode drifts from native-sim/arm64/arm64_sim.h: "
            f"spec={op['macro']}={op['code']:#x} "
            f"sim={opcodes.get(op['macro'])}")
    defines = {name: int(value) for name, value in DIR_DEFINE.findall(text)}
    for row in dirs:
        if defines.get(row["macro"]) != row["code"]:
            raise SystemExit(
                "arm64 fmov-dest codes drift from native-sim/arm64/arm64_sim.h: "
                f"spec={row['macro']}={row['code']} "
                f"sim={defines.get(row['macro'])}")
    return {"opcode": op, "directions": dirs}


def render_lean(op: dict, dirs: list[dict]) -> str:
    arms = "\n".join(
        f"  | {row['code']} => {'true' if row['vector_destination'] else 'false'}"
        for row in dirs)
    return f'''-- Generated by generate_arm64_fmov_dest_spec.py from arm64_fmov_dest_spec.json.
namespace KProgFormal.GeneratedArm64FmovDest
/-- The ARM64_OP_* opcode number the FMOV carries in arm64_sim.h. -/
def code : Nat := {op['code']}
/-- Whether a FMOV direction code routes the moved value to the vector register
`v0` (rather than the general-purpose destination register). The four directions
pair up so that a direction whose register half holds the destination takes the
vector file and the other takes the general-purpose file. -/
def vectorDestination (dirCode : Nat) : Bool :=
  match dirCode with
{arms}
  | _ => false
end KProgFormal.GeneratedArm64FmovDest
'''


def render_c(op: dict, dirs: list[dict]) -> str:
    asserts = "\n".join(
        f'_Static_assert({row["macro"]} == {row["code"]}U, '
        '"arm64 fmov-dest code drift");' for row in dirs)
    cases = []
    for row in dirs:
        cases.append(f"\t\tcase {row['code']}U:")
        cases.append("\t\t\t__kprog_a64_fmd_v0 = "
                     + ("1U;" if row["vector_destination"] else "0U;"))
        cases.append("\t\t\tbreak;")
    body = [
        "\t({",
        "\t\t__u64 __kprog_a64_fmd_dir = (DIR);",
        "\t\t__u64 __kprog_a64_fmd_v0 = 0;",
        "",
        "\t\tswitch (__kprog_a64_fmd_dir) {",
    ] + cases + [
        "\t\tdefault:",
        "\t\t\tUNSUPPORTED;",
        "\t\t\tbreak;",
        "\t\t}",
        "\t\t__kprog_a64_fmd_v0;",
        "\t})",
    ]
    continued = " \\\n".join(body)
    return f'''/* Generated by generate_arm64_fmov_dest_spec.py from arm64_fmov_dest_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_FMOV_DEST_H
#define KPROG_FORMAL_GENERATED_ARM64_FMOV_DEST_H
/*
 * The destination-routing decision of the AArch64 FMOV: whether the moved value
 * is written to the vector register `v0` or to the general-purpose destination
 * register through the width-narrowed register write. A direction code outside
 * the four reaches the caller-supplied unsupported arm.
 */
_Static_assert(ARM64_OP_FMOV == {op['code']}U, "arm64 fmov-dest opcode drift");
{asserts}
/*
 * DIR is one of the four ARM64_FMOV_* direction codes; DIR is read once. The
 * result is 1 when the handler must assign the result to `v0` and 0 when it must
 * write the general-purpose destination through the width-narrowed register
 * write.
 */
#define KPROG_ARM64_FMOV_DEST_VECTOR(DIR, UNSUPPORTED)                      \\
{continued}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = load()
    outputs = ((LEAN, render_lean(data["opcode"], data["directions"])),
               (CHEADER, render_c(data["opcode"], data["directions"])))
    for path, expected in outputs:
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 fmov-dest contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
