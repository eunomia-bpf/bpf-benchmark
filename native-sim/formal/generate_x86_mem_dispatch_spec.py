#!/usr/bin/env python3
"""Generate the shared x86-64 memory read-dispatch contract.

The generated Lean table `GeneratedX86MemDispatch.valueSrc` and the C predicate
`KPROG_X86_MEM_READ_SRC` classify the value read by
`X86_SIM_L_READ_MEM_VALUE` — the single read body shared by the plain load and
store families — from three facts about the access:

  - whether the base register *is* the stack pointer (register identity);
  - whether the base register carries the ABI tag;
  - whether the effective access width is 64 bits.

The arms are:

  - a stack-pointer base always reads through the stack helper, at any width and
    whatever the base register's tag;
  - an ABI-tagged base at width 64 does a 64-bit pointer load;
  - every other access does an ordinary byte-ladder load at the access width.

The classification is a closed table over the three booleans, so the C
predicate is total and has no unsupported arm.

The x86 selector differs from the AArch64 one in that its *first* test is
register identity, not a memory tag: `X86_SIM_L_READ_MEM_VALUE` compares the
base register number against `X86_RSP`, while only the second test consults the
base register's tag. The stack arm therefore overrides the ABI arm for the
stack pointer even when the stack pointer is ABI-tagged, and there is no width
fallback that would let an ABI base reach the pointer load off width 64 — it
falls through to the ordinary load. There is also no reloc arm and no per-arm
result tag in this read body: the ABI packet tag refinement lives in
`X86_SIM_L_EXEC_MOV_LOAD`, not here, so this contract is a value-source table
only.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_mem_dispatch_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86MemDispatch.lean"
CHEADER = ROOT / "generated/x86_mem_dispatch.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "x86MemReadDispatch",
    "selector": "stack_pointer_identity_then_abi_tag_and_width_64",
    "rows": [
        {"is_rsp": True, "is_abi": True, "w64": True,
         "src": "stackRead", "src_define": "KPROG_X86_MEM_SRC_STACK"},
        {"is_rsp": True, "is_abi": True, "w64": False,
         "src": "stackRead", "src_define": "KPROG_X86_MEM_SRC_STACK"},
        {"is_rsp": True, "is_abi": False, "w64": True,
         "src": "stackRead", "src_define": "KPROG_X86_MEM_SRC_STACK"},
        {"is_rsp": True, "is_abi": False, "w64": False,
         "src": "stackRead", "src_define": "KPROG_X86_MEM_SRC_STACK"},
        {"is_rsp": False, "is_abi": True, "w64": True,
         "src": "abiPtrLoad", "src_define": "KPROG_X86_MEM_SRC_ABI_PTR_LOAD"},
        {"is_rsp": False, "is_abi": True, "w64": False,
         "src": "normalLoad", "src_define": "KPROG_X86_MEM_SRC_NORMAL_LOAD"},
        {"is_rsp": False, "is_abi": False, "w64": True,
         "src": "normalLoad", "src_define": "KPROG_X86_MEM_SRC_NORMAL_LOAD"},
        {"is_rsp": False, "is_abi": False, "w64": False,
         "src": "normalLoad", "src_define": "KPROG_X86_MEM_SRC_NORMAL_LOAD"},
    ],
}

ORDER = (True, True, True), (True, True, False), (True, False, True), \
    (True, False, False), (False, True, True), (False, True, False), \
    (False, False, True), (False, False, False)

SRC_DEFINES = {
    "stackRead": "KPROG_X86_MEM_SRC_STACK",
    "abiPtrLoad": "KPROG_X86_MEM_SRC_ABI_PTR_LOAD",
    "normalLoad": "KPROG_X86_MEM_SRC_NORMAL_LOAD",
}

SRC_CODES = {"stackRead": 0, "abiPtrLoad": 1, "normalLoad": 2}


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 mem-dispatch specification: {data!r}")
    rows = EXPECTED["rows"]
    if [(row["is_rsp"], row["is_abi"], row["w64"]) for row in rows] != \
            list(ORDER):
        raise SystemExit(f"invalid x86 mem-dispatch row order: {rows!r}")
    for row in rows:
        if row["src_define"] != SRC_DEFINES[row["src"]]:
            raise SystemExit(f"invalid x86 mem-dispatch define: {row!r}")
    return rows


def render_lean(rows: list[dict]) -> str:
    table = "\n".join(
        f"  | {'true' if row['is_rsp'] else 'false'}, "
        f"{'true' if row['is_abi'] else 'false'}, "
        f"{'true' if row['w64'] else 'false'} => .{row['src']}"
        for row in rows)
    return f'''-- Generated by generate_x86_mem_dispatch_spec.py from x86_mem_dispatch_spec.json.
import Std
namespace KProgFormal.GeneratedX86MemDispatch
/-- The value source the shared x86 memory read selects. -/
inductive ValueSrc where
  | stackRead
  | abiPtrLoad
  | normalLoad
deriving DecidableEq, Repr
/-- The generated value-source table over the three facts the C predicate
consults: whether the base register is the stack pointer (register identity),
whether its memory tag is the ABI tag, and whether the effective access width
is 64 bits. -/
def valueSrc : Bool -> Bool -> Bool -> ValueSrc
{table}
end KProgFormal.GeneratedX86MemDispatch
'''


def render_c(rows: list[dict]) -> str:
    defines = "\n".join(
        f"#define {name} {SRC_CODES[src]}U"
        for src, name in SRC_DEFINES.items())
    body = [
        "\t\t__u8 __kprog_x86_md_src;                                    \\",
        "\t\tif (BASE_IS_RSP)                                            \\",
        "\t\t\t__kprog_x86_md_src = KPROG_X86_MEM_SRC_STACK;           \\",
        "\t\telse if ((BASE_TAG) == X86_SIM_TAG_ABI &&                   \\",
        "\t\t\t (WIDTH) == X86_WIDTH_64)                             \\",
        "\t\t\t__kprog_x86_md_src = KPROG_X86_MEM_SRC_ABI_PTR_LOAD;    \\",
        "\t\telse                                                        \\",
        "\t\t\t__kprog_x86_md_src = KPROG_X86_MEM_SRC_NORMAL_LOAD;     \\",
        "\t\t__kprog_x86_md_src;                                         \\",
    ]
    cont = "\n".join(body)
    return f'''/* Generated by generate_x86_mem_dispatch_spec.py from x86_mem_dispatch_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_MEM_DISPATCH_H
#define KPROG_FORMAL_GENERATED_X86_MEM_DISPATCH_H
/*
 * x86-64 memory read-dispatch classification. The three selector facts form a
 * closed table, so the predicate is total and has no unsupported arm. Unlike
 * the AArch64 dispatch, the first test is register identity (is the base the
 * stack pointer) rather than a memory tag; the ABI test follows and is gated on
 * width 64, so an ABI base off width 64 falls through to the ordinary load.
 * `KPROG_X86_MEM_SRC_*` names the value source the read path must use. This
 * contract selects a value source only; the ABI packet tag refinement stays in
 * X86_SIM_L_EXEC_MOV_LOAD.
 */
{defines}
/*
 * BASE_IS_RSP is true when the base register is the stack pointer; BASE_TAG is
 * the base register's memory tag; WIDTH is the X86_WIDTH_* effective access
 * code. Each input is evaluated once and no flags are written.
 */
#define KPROG_X86_MEM_READ_SRC(BASE_IS_RSP, BASE_TAG, WIDTH)                \\
\t({{                                                                 \\
{cont}
\t}})
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rows = load()
    for path, expected in ((LEAN, render_lean(rows)), (CHEADER, render_c(rows))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated x86 mem-dispatch contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
