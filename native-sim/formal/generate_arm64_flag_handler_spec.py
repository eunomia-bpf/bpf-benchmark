#!/usr/bin/env python3
"""Generate shared ADD/SUB flag-setting handler composition for C and Lean."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_flag_handler_spec.json"
DECODE_SPEC = ROOT / "arm64_decode_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64FlagHandler.lean"
CHEADER = ROOT / "generated/arm64_flag_handler.h"
EXPECTED = {
    "schema_version": 1,
    "operation": "arm64ArithFlagHandler",
    "families": [
        {"name": "add", "code": 0, "alu": "add", "flags": "add"},
        {"name": "sub", "code": 1, "alu": "sub", "flags": "sub"},
    ],
    "modes": [
        {"name": "writeback", "writes_destination": True},
        {"name": "compare", "writes_destination": False},
    ],
}


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 flag handler specification: {data!r}")
    decode = json.loads(DECODE_SPEC.read_text())
    alu = decode.get("tables", {}).get("alu", [])
    codes = {row.get("mnemonic"): row.get("code") for row in alu}
    for row in data["families"]:
        if codes.get(row["alu"]) != row["code"]:
            raise SystemExit(
                f"arm64 flag family drifts from ALU decode table: {row!r}")
    return data["families"]


def render_lean(families: list[dict]) -> str:
    family_ctors = "\n".join(f"  | {row['name']}" for row in families)
    family_codes = "\n".join(
        f"  | .{row['name']} => {row['code']}" for row in families)
    result_arms = "\n".join(
        f"  | .{row['name']} => GeneratedArm64AluResult.result .{row['alu']} lhs rhs"
        for row in families)
    flag_arms = "\n".join(
        f"  | .{row['name']} => GeneratedArm64Flags.apply{row['flags'].title()} lhs rhs width"
        for row in families)
    return f'''-- Generated by generate_arm64_flag_handler_spec.py from arm64_flag_handler_spec.json.
import KProgFormal.GeneratedArm64AluResult
import KProgFormal.GeneratedArm64Flags

namespace KProgFormal.GeneratedArm64FlagHandler

inductive Family
{family_ctors}
  deriving DecidableEq, Repr

inductive Mode
  | writeback
  | compare
  deriving DecidableEq, Repr

def code : Family -> Nat
{family_codes}

structure Step where
  value : BitVec 64
  flags : GeneratedArm64Flags.Flags
  deriving DecidableEq, Repr

def result (family : Family) (lhs rhs : BitVec 64) : BitVec 64 :=
  match family with
{result_arms}

def flags (family : Family) (lhs rhs : BitVec 64)
    (width : GeneratedArm64Width.Width) : GeneratedArm64Flags.Flags :=
  match family with
{flag_arms}

def apply (family : Family) (lhs rhs : BitVec 64)
    (width : GeneratedArm64Width.Width) : Step :=
  {{ value := result family lhs rhs, flags := flags family lhs rhs width }}

end KProgFormal.GeneratedArm64FlagHandler
'''


def render_c(families: list[dict]) -> str:
    constants = "\n".join(
        f"#define KPROG_ARM64_ARITH_FAMILY_{row['name'].upper()} {row['code']}U"
        for row in families)
    write_cases: list[str] = []
    compare_cases: list[str] = []
    for row in families:
        upper = row["name"].upper()
        write_cases.extend([
            f"\t\tcase KPROG_ARM64_ARITH_FAMILY_{upper}:",
            f"\t\t\t(RESULT) = KPROG_ALU64_RESULT(ARM64_ALU_{upper}, (LHS), (RHS), UNSUPPORTED);",
            f"\t\t\tKPROG_ARM64_SET_{upper}_FLAGS((C_N), (C_Z), (C_C), (C_V), (LHS), (RHS), (WIDTH));",
            "\t\t\tbreak;",
        ])
        compare_cases.extend([
            f"\t\tcase KPROG_ARM64_ARITH_FAMILY_{upper}:",
            f"\t\t\tKPROG_ARM64_SET_{upper}_FLAGS((C_N), (C_Z), (C_C), (C_V), (LHS), (RHS), (WIDTH));",
            "\t\t\tbreak;",
        ])

    def macro(name: str, params: str, body: list[str]) -> str:
        lines = [f"#define {name}({params})", "\tdo {", "\t\tswitch (FAMILY) {"]
        lines.extend(body)
        lines.extend([
            "\t\tdefault:",
            "\t\t\tUNSUPPORTED;",
            "\t\t\tbreak;",
            "\t\t}",
            "\t} while (0)",
        ])
        return " \\\n".join(lines)

    write = macro(
        "KPROG_ARM64_EXEC_ARITH_WRITEBACK",
        "FAMILY, RESULT, C_N, C_Z, C_C, C_V, LHS, RHS, WIDTH, UNSUPPORTED",
        write_cases)
    compare = macro(
        "KPROG_ARM64_EXEC_ARITH_COMPARE",
        "FAMILY, C_N, C_Z, C_C, C_V, LHS, RHS, WIDTH, UNSUPPORTED",
        compare_cases)
    return f'''/* Generated by generate_arm64_flag_handler_spec.py from arm64_flag_handler_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_FLAG_HANDLER_H
#define KPROG_FORMAL_GENERATED_ARM64_FLAG_HANDLER_H

{constants}

{write}

{compare}

#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    families = load()
    for path, expected in ((LEAN, render_lean(families)),
                           (CHEADER, render_c(families))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 flag handler contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
