#!/usr/bin/env python3
"""Generate immediate/register RHS selection for the AArch64 ALU handler."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_alu_operand_spec.json"
MOD_SPEC = ROOT / "arm64_mod_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64AluOperand.lean"
CHEADER = ROOT / "generated/arm64_alu_operand.h"
EXPECTED = {
    "schema_version": 1,
    "operation": "arm64AluOperand",
    "modes": [
        {"name": "immediate", "uses_modifier": False},
        {"name": "register", "uses_modifier": True},
    ],
    "register_path": "source_modifier",
}


def load() -> None:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 ALU operand specification: {data!r}")
    mod = json.loads(MOD_SPEC.read_text())
    codes = [row.get("code") for row in mod.get("operations", [])]
    if codes != list(range(11)):
        raise SystemExit(f"arm64 ALU operand modifier table is not canonical: {codes!r}")


def render_lean() -> str:
    return '''-- Generated by generate_arm64_alu_operand_spec.py from arm64_alu_operand_spec.json.
import KProgFormal.GeneratedArm64Mod

namespace KProgFormal.GeneratedArm64AluOperand

inductive Mode
  | immediate
  | register
  deriving DecidableEq, Repr

def rhs (mode : Mode) (immediate : BitVec 64)
    (mod : GeneratedArm64ModDecode.Mod) (register shift : BitVec 64)
    (width : GeneratedArm64Width.Width) : BitVec 64 :=
  match mode with
  | .immediate => immediate
  | .register => GeneratedArm64Mod.value mod register shift width

end KProgFormal.GeneratedArm64AluOperand
'''


def render_c() -> str:
    return '''/* Generated by generate_arm64_alu_operand_spec.py from arm64_alu_operand_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_ALU_OPERAND_H
#define KPROG_FORMAL_GENERATED_ARM64_ALU_OPERAND_H

#define KPROG_ARM64_ALU_RHS(IS_IMMEDIATE, IMM, MOD, VALUE, SHIFT, WIDTH)    \\
\t((IS_IMMEDIATE) ? (__u64)(IMM) :                                    \\
\t KPROG_ARM64_MOD_VALUE((MOD), (VALUE), (SHIFT), (WIDTH)))

#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    load()
    for path, expected in ((LEAN, render_lean()), (CHEADER, render_c())):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 ALU operand contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
