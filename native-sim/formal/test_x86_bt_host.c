/*
 * Host cross-check for the x86-64 `BT` / `BT_IMM` / `BT_MEM_IMM` handler
 * contract.
 *
 * The module under test is `generated/x86_bt.h`. It fixes the one width a body
 * resolves (`FLAGS ? FLAGS : 64`) and the per-opcode facts that select the two
 * operands: which source the tested base comes from (a register for `BT` and
 * `BT_IMM`, memory for `BT_MEM_IMM`) and which source the bit index comes from
 * (a register for `BT`, the raw immediate for `BT_IMM`, the 32-bit-widened
 * immediate for `BT_MEM_IMM`).
 *
 * The three C handlers restate this logic inline — `X86_SIM_L_EXEC_BT` /
 * `X86_SIM_L_EXEC_BT_IMM` / `X86_SIM_L_EXEC_BT_MEM_IMM` in
 * `x86_sim_local_bpf.h` — and the generated header is not on their include
 * path, so this host cross-check is the tie between the two: it drives the
 * contract through the generated macros and restates the same bodies from the
 * raw opcode, and the two must agree on the tested bit and on every register
 * and flag the bodies leave alone.
 *
 * The value-producing helpers the bodies use (`X86_SIM_L_READ_REG`,
 * `X86_SIM_L_READ_MEM_VALUE` at a scalar-tagged base, `x86_width_bits`,
 * `kprog_x86_bt_value`, `x86_store_imm_value`, and the immediate widening) are
 * hand-modelled here: a register read is the register's 64-bit value, the
 * memory read is the generated byte-ladder load at the resolved width, the bit
 * test is the indexed shift-and-extract, and the immediate widening is the
 * 32-bit truncation.
 */
typedef unsigned char __u8;
typedef unsigned short __u16;
typedef unsigned int __u32;
typedef unsigned long long __u64;
typedef signed char __s8;
typedef short __s16;
typedef int __s32;
typedef signed long long __s64;

#ifndef __always_inline
#define __always_inline inline __attribute__((always_inline))
#endif

#define X86_RAX 0U
#define X86_RCX 1U
#define X86_RDX 2U
#define X86_RBX 3U
#define X86_RSI 6U
#define X86_RDI 7U
#define X86_REG_NONE 0xffU

#define X86_OP_BT 0x37U
#define X86_OP_BT_IMM 0x42U
#define X86_OP_BT_MEM_IMM 0x43U

#define X86_SIM_TAG_SCALAR 0U

#include "generated/x86_bt.h"
#include "generated/x86_width.h"
#include "generated/x86_bitops.h"
#include "generated/x86_immediate.h"
#include "generated/x86_mem_access.h"

#include <stdint.h>
#include <stdio.h>
#include <string.h>

#define ORACLE_CODES 5U

#define ORACLE_REGS 16U
#define ORACLE_MEM_BYTES 4096U

struct oracle_reg {
	union {
		__u8 b[8];
		__u16 w;
		void *ptr;
	} u;
	__u8 tag;
};

static struct oracle_reg oracle_regs[ORACLE_REGS];
static struct oracle_reg pristine_regs[ORACLE_REGS];
static struct oracle_reg result_regs[ORACLE_REGS];

static __u8 oracle_mem[ORACLE_MEM_BYTES];
static __u8 pristine_mem[ORACLE_MEM_BYTES];
static __u8 result_mem[ORACLE_MEM_BYTES];

static __u8 oracle_synthetic(__u64 index)
{
	return (__u8)((index * 131U + 17U) ^ (index >> 5));
}

static void oracle_reset(void)
{
	unsigned i;
	__u64 j;

	for (i = 0; i < ORACLE_REGS; i++) {
		oracle_regs[i].u.ptr =
			(void *)(long)(0x2a00ULL + (__u64)i * 0x20ULL);
		oracle_regs[i].tag = (__u8)(i % 6U);
	}
	for (j = 0; j < ORACLE_MEM_BYTES; j++)
		oracle_mem[j] = (__u8)oracle_synthetic(j + 7U);
}

static void oracle_snapshot_pristine(void)
{
	memcpy(pristine_regs, oracle_regs, sizeof(pristine_regs));
	memcpy(pristine_mem, oracle_mem, ORACLE_MEM_BYTES);
}

static void oracle_restore_pristine(void)
{
	memcpy(oracle_regs, pristine_regs, sizeof(pristine_regs));
	memcpy(oracle_mem, pristine_mem, ORACLE_MEM_BYTES);
}

static __u64 oracle_reg_value(unsigned index)
{
	return (__u64)(uintptr_t)oracle_regs[index].u.ptr;
}

/* ------------------------------------------------------------------ */
/* Hand-written models, independent of the macros under test.          */
/* ------------------------------------------------------------------ */

static __u64 oracle_mask(unsigned width)
{
	if (width == X86_WIDTH_8)
		return 0xffULL;
	if (width == X86_WIDTH_16)
		return 0xffffULL;
	if (width == X86_WIDTH_32)
		return 0xffffffffULL;
	return 0xffffffffffffffffULL;
}

static __u64 oracle_load(__u64 addr, unsigned width)
{
	const __u8 *p = (const __u8 *)(uintptr_t)addr;
	__u64 v = 0;
	unsigned i;

	for (i = 0; i < width; i++)
		v |= (__u64)p[i] << (8 * i);
	return v & oracle_mask(width);
}

/* The bit test the body's `kprog_x86_bt_value` performs: the index masked to
 * 63 for a 64-bit width and 31 otherwise, then the indexed bit of the narrowed
 * base. Restated independently of the generated x86_bitops.h. */
static __u8 oracle_bt(__u64 base, __u64 index, unsigned width)
{
	__u8 bit = (__u8)(index & (width == X86_WIDTH_64 ? 63U : 31U));

	return (__u8)(((base & oracle_mask(width)) >> bit) & 1U);
}

/* The immediate widening the `BT_MEM_IMM` body's `x86_store_imm_value((IMM),
 * X86_WIDTH_32)` performs: the low 32 bits, zero-extended. */
static __u64 oracle_imm32(__u64 value)
{
	return value & 0xffffffffULL;
}

/* ------------------------------------------------------------------ */
/* Part 1: the generated tables vs. the oracle.                       */
/* ------------------------------------------------------------------ */

static unsigned part1(void)
{
	static const unsigned codes[ORACLE_CODES] = { 0U, X86_WIDTH_8, X86_WIDTH_16,
						      X86_WIDTH_32, X86_WIDTH_64 };
	unsigned cases = 0;
	unsigned ci;

	if (KPROG_X86_BT_WRITE_WIDTH_DEFAULT != X86_WIDTH_64) {
		fprintf(stderr, "bt default width is %u, want 64-bit\n",
			KPROG_X86_BT_WRITE_WIDTH_DEFAULT);
		return 0;
	}
	cases++;

	if (KPROG_X86_BT_OP_BT_BASE_SOURCE != KPROG_X86_BT_BASE_REGISTER ||
	    KPROG_X86_BT_OP_BT_IMM_BASE_SOURCE != KPROG_X86_BT_BASE_REGISTER ||
	    KPROG_X86_BT_OP_BT_MEM_IMM_BASE_SOURCE != KPROG_X86_BT_BASE_MEMORY) {
		fprintf(stderr, "bt base source code drift\n");
		return 0;
	}
	cases++;

	if (KPROG_X86_BT_OP_BT_INDEX_SOURCE != KPROG_X86_BT_INDEX_REGISTER ||
	    KPROG_X86_BT_OP_BT_IMM_INDEX_SOURCE != KPROG_X86_BT_INDEX_IMMEDIATE ||
	    KPROG_X86_BT_OP_BT_MEM_IMM_INDEX_SOURCE != KPROG_X86_BT_INDEX_IMM32) {
		fprintf(stderr, "bt index source code drift\n");
		return 0;
	}
	cases++;

	if (KPROG_X86_BT_BASE_REGISTER == KPROG_X86_BT_BASE_MEMORY) {
		fprintf(stderr, "bt base source codes collide\n");
		return 0;
	}
	cases++;

	if (KPROG_X86_BT_INDEX_REGISTER == KPROG_X86_BT_INDEX_IMMEDIATE ||
	    KPROG_X86_BT_INDEX_IMMEDIATE == KPROG_X86_BT_INDEX_IMM32 ||
	    KPROG_X86_BT_INDEX_REGISTER == KPROG_X86_BT_INDEX_IMM32) {
		fprintf(stderr, "bt index source codes collide\n");
		return 0;
	}
	cases++;

	for (ci = 0; ci < ORACLE_CODES; ci++) {
		unsigned want = codes[ci] ? codes[ci] : X86_WIDTH_64;
		unsigned got = KPROG_X86_BT_WRITE_WIDTH(codes[ci]);

		if (got != want) {
			fprintf(stderr, "bt width mismatch flags=%u got=%u "
					"want=%u\n",
				codes[ci], got, want);
			return 0;
		}
		cases++;
	}

	for (ci = 0; ci < 2U; ci++) {
		unsigned bs = KPROG_X86_BT_BASE_SOURCE(ci != 0U);

		if (bs != (ci != 0U ? KPROG_X86_BT_BASE_MEMORY
				    : KPROG_X86_BT_BASE_REGISTER)) {
			fprintf(stderr, "bt base source select drift\n");
			return 0;
		}
		cases++;
	}

	/* The three-way index selector: memory -> imm32, else register or
	 * immediate by the second flag. */
	{
		unsigned got;

		got = KPROG_X86_BT_INDEX_SOURCE(1U, 0U);
		if (got != KPROG_X86_BT_INDEX_IMM32) {
			fprintf(stderr, "bt index source mem select drift\n");
			return 0;
		}
		got = KPROG_X86_BT_INDEX_SOURCE(0U, 1U);
		if (got != KPROG_X86_BT_INDEX_REGISTER) {
			fprintf(stderr, "bt index source reg select drift\n");
			return 0;
		}
		got = KPROG_X86_BT_INDEX_SOURCE(0U, 0U);
		if (got != KPROG_X86_BT_INDEX_IMMEDIATE) {
			fprintf(stderr, "bt index source imm select drift\n");
			return 0;
		}
		cases++;
	}

	return cases;
}

/* ------------------------------------------------------------------ */
/* Part 2: the full composition vs. the hand-written bodies.          */
/* ------------------------------------------------------------------ */

struct bt_effect {
	unsigned base_source;
	unsigned index_source;
	unsigned width;
	__u64 base;
	__u64 index;
	__u8 cf;
	__u64 dst;
	__u8 dst_tag;
	__u8 zf;
	__u8 sf;
	__u8 of;
};

static struct bt_effect contract_step(unsigned op, unsigned flags,
				      unsigned base_reg, unsigned index_reg,
				      __u64 raw_imm, unsigned base_ptr_reg,
				      unsigned dst_reg, __s64 disp,
				      __u8 zf_old, __u8 sf_old,
				      __u8 of_old)
{
	unsigned width = KPROG_X86_BT_WRITE_WIDTH(flags);
	unsigned base_source = KPROG_X86_BT_BASE_SOURCE(op == 2U);
	unsigned index_source =
		KPROG_X86_BT_INDEX_SOURCE(op == 2U, op == 0U);
	struct bt_effect r;

	r.base_source = base_source;
	r.index_source = index_source;
	r.width = width;
	if (base_source == KPROG_X86_BT_BASE_MEMORY)
		r.base = KPROG_X86_MEM_LOAD(
			(void *)(uintptr_t)(oracle_reg_value(base_ptr_reg) +
					    (__u64)disp),
			width);
	else
		r.base = oracle_reg_value(base_reg);

	if (index_source == KPROG_X86_BT_INDEX_REGISTER)
		r.index = oracle_reg_value(index_reg);
	else if (index_source == KPROG_X86_BT_INDEX_IMM32)
		r.index = KPROG_X86_IMMEDIATE_VALUE(raw_imm, X86_WIDTH_32);
	else
		r.index = raw_imm;

	r.cf = kprog_x86_bt_value(r.base, r.index, width);
	r.dst = oracle_reg_value(dst_reg);
	r.dst_tag = oracle_regs[dst_reg].tag;
	r.zf = zf_old;
	r.sf = sf_old;
	r.of = of_old;
	return r;
}

static struct bt_effect model_step(unsigned op, unsigned flags,
				   unsigned base_reg, unsigned index_reg,
				   __u64 raw_imm, unsigned base_ptr_reg,
				   unsigned dst_reg, __s64 disp,
				   __u8 zf_old, __u8 sf_old,
				   __u8 of_old)
{
	unsigned width = flags ? flags : X86_WIDTH_64;
	struct bt_effect r;

	r.base_source = op == 2U ? KPROG_X86_BT_BASE_MEMORY
				 : KPROG_X86_BT_BASE_REGISTER;
	r.index_source = op == 2U ? KPROG_X86_BT_INDEX_IMM32
				  : (op == 0U ? KPROG_X86_BT_INDEX_REGISTER
					      : KPROG_X86_BT_INDEX_IMMEDIATE);
	r.width = width;
	if (op == 2U)
		r.base = oracle_load(oracle_reg_value(base_ptr_reg) +
					     (__u64)disp,
				     width);
	else
		r.base = oracle_reg_value(base_reg);

	if (op == 0U)
		r.index = oracle_reg_value(index_reg);
	else if (op == 2U)
		r.index = oracle_imm32(raw_imm);
	else
		r.index = raw_imm;

	r.cf = oracle_bt(r.base, r.index, width);
	r.dst = oracle_reg_value(dst_reg);
	r.dst_tag = oracle_regs[dst_reg].tag;
	r.zf = zf_old;
	r.sf = sf_old;
	r.of = of_old;
	return r;
}

static unsigned part2(void)
{
	static const unsigned flags_codes[ORACLE_CODES] = { 0U, X86_WIDTH_8,
							    X86_WIDTH_16,
							    X86_WIDTH_32,
							    X86_WIDTH_64 };
	static const __u64 imms[4] = { 0, 4, 8, 0x1ff };
	static const __s64 disps[3] = { 0, 8, -8 };
	static const unsigned base_regs[3] = { X86_RAX, X86_RSI, 11U };
	static const unsigned index_regs[3] = { X86_RCX, X86_RDX, 12U };
	static const unsigned dst_regs[3] = { X86_RDI, X86_RBX, 9U };
	unsigned cases = 0;
	unsigned op;
	unsigned fi;
	unsigned mi;
	unsigned pi;
	unsigned bi;
	unsigned ii;
	unsigned di;

	for (op = 0; op < 3U; op++) {
		for (fi = 0; fi < ORACLE_CODES; fi++) {
			for (mi = 0; mi < 4U; mi++) {
				for (pi = 0; pi < 3U; pi++) {
					for (bi = 0; bi < 3U; bi++) {
						for (ii = 0; ii < 3U; ii++) {
							for (di = 0; di < 3U;
							     di++) {
								struct bt_effect got;
								struct bt_effect want;

								oracle_restore_pristine();
								oracle_regs[X86_RBX].u.ptr =
									(void *)(uintptr_t)&oracle_mem[64];
								oracle_regs[X86_RBX].tag =
									X86_SIM_TAG_SCALAR;
								got = contract_step(
									op,
									flags_codes[fi],
									base_regs[bi],
									index_regs[ii],
									imms[mi],
									X86_RBX,
									dst_regs[di],
									disps[pi],
									1U, 0U, 1U);
								memcpy(result_regs,
								       oracle_regs,
								       sizeof(oracle_regs));
								memcpy(result_mem,
								       oracle_mem,
								       ORACLE_MEM_BYTES);

								oracle_restore_pristine();
								oracle_regs[X86_RBX].u.ptr =
									(void *)(uintptr_t)&oracle_mem[64];
								oracle_regs[X86_RBX].tag =
									X86_SIM_TAG_SCALAR;
								want = model_step(
									op,
									flags_codes[fi],
									base_regs[bi],
									index_regs[ii],
									imms[mi],
									X86_RBX,
									dst_regs[di],
									disps[pi],
									1U, 0U, 1U);

								if (got.base_source != want.base_source ||
								    got.index_source != want.index_source ||
								    got.width != want.width ||
								    got.base != want.base ||
								    got.index != want.index ||
								    got.cf != want.cf ||
								    got.dst != want.dst ||
								    got.dst_tag != want.dst_tag ||
								    got.zf != want.zf ||
								    got.sf != want.sf ||
								    got.of != want.of ||
								    memcmp(result_regs, oracle_regs,
									   sizeof(oracle_regs)) ||
								    memcmp(result_mem, oracle_mem,
									   ORACLE_MEM_BYTES)) {
									fprintf(stderr,
										"bt mismatch op=%u flags=%u\n",
										op,
										flags_codes[fi]);
									return 0;
								}
								cases++;
							}
						}
					}
				}
			}
		}
	}
	return cases;
}

/* ------------------------------------------------------------------ */
/* Part 3: pins on the facts the composition is about.                */
/* ------------------------------------------------------------------ */

static unsigned part3(void)
{
	unsigned cases = 0;

	/* Pin 1: `BT` reads its base from SRC and its index from the register,
	 * touching neither memory nor any register. */
	{
		struct bt_effect e;
		__u64 base;

		oracle_restore_pristine();
		base = oracle_reg_value(X86_RAX);
		e = contract_step(0U, X86_WIDTH_64, X86_RAX, X86_RCX, 0, X86_RBX,
				  X86_RDX, 0, 0U, 0U, 0U);
		if (e.base_source != KPROG_X86_BT_BASE_REGISTER)
			return 0;
		if (e.index_source != KPROG_X86_BT_INDEX_REGISTER)
			return 0;
		if (e.base != base)
			return 0;
		if (e.index != oracle_reg_value(X86_RCX))
			return 0;
		if (memcmp(oracle_mem, pristine_mem, ORACLE_MEM_BYTES))
			return 0;
		cases++;
	}

	/* Pin 2: `BT_IMM` reads its base from SRC and its index from the raw
	 * immediate. */
	{
		struct bt_effect e;

		oracle_restore_pristine();
		e = contract_step(1U, X86_WIDTH_64, X86_RAX, X86_RCX,
				  0x100000003ULL, X86_RBX, X86_RDX, 0, 0U, 0U,
				  0U);
		if (e.base_source != KPROG_X86_BT_BASE_REGISTER)
			return 0;
		if (e.index_source != KPROG_X86_BT_INDEX_IMMEDIATE)
			return 0;
		if (e.index != 0x100000003ULL)
			return 0;
		cases++;
	}

	/* Pin 3: `BT_MEM_IMM` reads its base from memory at the resolved width
	 * and its index from the 32-bit-widened immediate. */
	{
		struct bt_effect e;
		__u64 addr;

		oracle_restore_pristine();
		oracle_regs[X86_RBX].u.ptr =
			(void *)(uintptr_t)&oracle_mem[64];
		oracle_regs[X86_RBX].tag = X86_SIM_TAG_SCALAR;
		addr = (__u64)(uintptr_t)&oracle_mem[64];
		e = contract_step(2U, X86_WIDTH_16, X86_RAX, X86_RCX,
				  0x100000003ULL, X86_RBX, X86_RDX, 0, 0U, 0U,
				  0U);
		if (e.base_source != KPROG_X86_BT_BASE_MEMORY)
			return 0;
		if (e.index_source != KPROG_X86_BT_INDEX_IMM32)
			return 0;
		if (e.width != X86_WIDTH_16)
			return 0;
		if (e.base != oracle_load(addr, X86_WIDTH_16))
			return 0;
		if (e.index != 3ULL)
			return 0;
		cases++;
	}

	/* Pin 4: **the index-width asymmetry.** `BT_MEM_IMM` drops the immediate's
	 * high bits while `BT_IMM` keeps them, so the two forms test different
	 * bits for the same raw immediate. */
	{
		struct bt_effect mem;
		struct bt_effect imm;

		oracle_restore_pristine();
		oracle_regs[X86_RBX].u.ptr =
			(void *)(uintptr_t)&oracle_mem[64];
		oracle_regs[X86_RBX].tag = X86_SIM_TAG_SCALAR;
		mem = contract_step(2U, X86_WIDTH_64, X86_RAX, X86_RCX,
				    0x100000001ULL, X86_RBX, X86_RDX, 0, 0U,
				    0U, 0U);
		imm = contract_step(1U, X86_WIDTH_64, X86_RAX, X86_RCX,
				    0x100000001ULL, X86_RBX, X86_RDX, 0, 0U,
				    0U, 0U);
		if (mem.index != 1ULL)
			return 0;
		if (imm.index != 0x100000001ULL)
			return 0;
		if (mem.index == imm.index)
			return 0;
		cases++;
	}

	/* Pin 5: only `CF` is written — ZF/SF/OF keep their incoming values. */
	{
		struct bt_effect e;

		oracle_restore_pristine();
		e = contract_step(0U, X86_WIDTH_64, X86_RAX, X86_RCX, 0, X86_RBX,
				  X86_RDX, 0, 1U, 1U, 1U);
		if (e.zf != 1U || e.sf != 1U || e.of != 1U)
			return 0;
		cases++;

		oracle_restore_pristine();
		e = contract_step(0U, X86_WIDTH_64, X86_RAX, X86_RCX, 0, X86_RBX,
				  X86_RDX, 0, 0U, 0U, 0U);
		if (e.zf != 0U || e.sf != 0U || e.of != 0U)
			return 0;
		cases++;
	}

	/* Pin 6: the bit test narrows the base to the resolved width first — an
	 * 8-bit `BT` with index 7 tests the byte's top bit. */
	{
		struct bt_effect e;

		oracle_restore_pristine();
		oracle_regs[X86_RAX].u.ptr = (void *)(long)0x80ULL;
		oracle_regs[X86_RAX].tag = X86_SIM_TAG_SCALAR;
		oracle_regs[X86_RCX].u.ptr = (void *)(long)7ULL;
		e = contract_step(0U, X86_WIDTH_8, X86_RAX, X86_RCX, 0, X86_RBX,
				  X86_RDX, 0, 0U, 0U, 0U);
		if (e.width != X86_WIDTH_8)
			return 0;
		if (e.cf != 1U)
			return 0;
		cases++;

		oracle_restore_pristine();
		oracle_regs[X86_RAX].u.ptr = (void *)(long)0x80ULL;
		oracle_regs[X86_RAX].tag = X86_SIM_TAG_SCALAR;
		oracle_regs[X86_RCX].u.ptr = (void *)(long)3ULL;
		e = contract_step(0U, X86_WIDTH_8, X86_RAX, X86_RCX, 0, X86_RBX,
				  X86_RDX, 0, 0U, 0U, 0U);
		if (e.cf != 0U)
			return 0;
		cases++;
	}

	/* Pin 7: an absent FLAGS code resolves to the 64-bit width, so the
	 * base is not narrowed. */
	{
		struct bt_effect e;

		oracle_restore_pristine();
		e = contract_step(0U, 0U, X86_RAX, X86_RCX, 0, X86_RBX, X86_RDX,
				  0, 0U, 0U, 0U);
		if (e.width != X86_WIDTH_64)
			return 0;
		cases++;
	}

	/* Pin 8: no `BT` form writes memory: the memory word is untouched even
	 * by the memory-reading form. */
	{
		struct bt_effect e;

		oracle_restore_pristine();
		oracle_regs[X86_RBX].u.ptr =
			(void *)(uintptr_t)&oracle_mem[64];
		oracle_regs[X86_RBX].tag = X86_SIM_TAG_SCALAR;
		e = contract_step(2U, X86_WIDTH_32, X86_RAX, X86_RCX, 8, X86_RBX,
				  X86_RDX, 8, 0U, 0U, 0U);
		if (e.base_source != KPROG_X86_BT_BASE_MEMORY)
			return 0;
		if (memcmp(oracle_mem, pristine_mem, ORACLE_MEM_BYTES))
			return 0;
		cases++;
	}

	return cases;
}

int main(void)
{
	unsigned c1;
	unsigned c2;
	unsigned c3;

	oracle_reset();
	oracle_snapshot_pristine();

	c1 = part1();
	if (c1 == 0U)
		return 1;
	oracle_restore_pristine();
	c2 = part2();
	if (c2 == 0U)
		return 1;
	oracle_restore_pristine();
	c3 = part3();
	if (c3 == 0U)
		return 1;
	oracle_restore_pristine();

	printf("x86 bt handler host cross-check: OK (%u cases)\n", c1 + c2 + c3);
	return 0;
}
