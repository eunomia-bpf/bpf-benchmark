/*
 * Host cross-check for the x86-64 shared `MOV_LOAD` handler composition
 * (`X86_SIM_L_EXEC_MOV_LOAD`, the single body shared by `X86_OP_MOV_LOAD`,
 * `X86_OP_MOV_LOAD_SCALAR`, and `X86_OP_MOVSX_LOAD`).
 *
 * Part 1 verifies the generated width-resolution contract
 * KPROG_X86_MOV_LOAD_WRITE_WIDTH / KPROG_X86_MOV_LOAD_MEM_WIDTH from
 * generated/x86_mov_load.h against an independent oracle that restates the two
 * fallbacks from the raw codes.
 *
 * Part 2 verifies the generated arm contract KPROG_X86_MOV_LOAD_ARM against an
 * independent oracle that restates the branch chain from the selector facts.
 *
 * Part 3 drives the whole handler over a deterministic memory, register, and
 * stack model: it resolves the two widths through the generated width macros,
 * selects the arm through the generated arm macro, computes the effective
 * address through the generated offset contract (KPROG_X86_MEM_OFFSET), loads
 * the ordinary lane through the generated byte-ladder contract
 * (KPROG_X86_MEM_LOAD), tags the ABI pointer arm through the generated
 * provenance contract (KPROG_ABI_LOAD_TAG), and cross-checks every result bit
 * for bit against a hand-written model of the C body.
 *
 * The point of this oracle is the two x86-specific asymmetries of the handler
 * against the shared read body: the first arm test is register *identity* (is
 * the base the stack pointer), so the stack arm overrides the ABI arm and
 * ignores the opcode's sign extension; and the ABI pointer arm is gated on the
 * plain `_MOV_LOAD` opcode *and* on both resolved widths being 64 bits, so an
 * ABI-tagged base reached by a narrow opcode falls through to the ordinary
 * scalar load.
 *
 * Build/run:
 *   cd native-sim/formal
 *   cc -Wall -Wextra -O2 -I. test_x86_mov_load_host.c -o /tmp/t_ml && /tmp/t_ml
 */
typedef unsigned char __u8;
typedef unsigned short __u16;
typedef unsigned int __u32;
typedef unsigned long long __u64;
typedef signed char __s8;
typedef short __s16;
typedef int __s32;
typedef signed long long __s64;

/* The generated headers define __always_inline functions in the kernel build;
 * provide the attribute for the host build. */
#ifndef __always_inline
#define __always_inline inline __attribute__((always_inline))
#endif

#define X86_WIDTH_8 1U
#define X86_WIDTH_16 2U
#define X86_WIDTH_32 4U
#define X86_WIDTH_64 8U

#define X86_REG_NONE 0xffU
#define X86_RSP 4U

#define X86_SIM_TAG_SCALAR 0U
#define X86_SIM_TAG_ABI 1U
#define X86_SIM_TAG_PACKET 2U
#define X86_SIM_TAG_STACK 4U
#define X86_SIM_TAG_MAP_PTR 5U

#define X86_OP_MOV_LOAD 0x06U
#define X86_OP_MOVSX_LOAD 0x22U

/* Restate the addressing AUX decoders x86_sim.h defines, so the oracle
 * exercises the same encoding the sim uses. */
#define X86_MEM_AUX(INDEX, SCALE_LOG2)                                      \
	(((__u32)(INDEX) & 0xffU) | (((__u32)(SCALE_LOG2) & 0xffU) << 8))
#define X86_MEM_AUX_INDEX(AUX) ((__u8)((AUX) & 0xffU))
#define X86_MEM_AUX_SCALE_LOG2(AUX) ((__u8)(((AUX) >> 8) & 0xffU))
#define X86_MEM_AUX_MEM_WIDTH(AUX) ((__u8)(((AUX) >> 16) & 0xffU))

#define X86_SIM_TAG_PACKET_END 3U

#include "generated/x86_mov_load.h"
#include "generated/x86_mem_offset.h"
#include "generated/x86_mem_access.h"
#include "generated/abi_load.h"
#include "generated/x86_width.h"

#include <stdint.h>
#include <stdio.h>
#include <string.h>

/* ------------------------------------------------------------------ */
/* A deterministic register file, memory and stack model.             */
/*                                                                    */
/* Register "pointers" are stored as byte offsets into `oracle_mem`   */
/* so the model stays inside the array at every address it forms.     */
/* ------------------------------------------------------------------ */

#define ORACLE_BYTES 4096
#define ORACLE_STACK_BYTES 64U

static __u8 oracle_mem[ORACLE_BYTES];
static __u8 oracle_stack[ORACLE_STACK_BYTES];

struct oracle_reg {
	__u64 value;
	__u8 tag;
};

/* The 16 GPR slots the handler indexes, in X86_SIM_L_FOR_EACH_GPR order:
 * rax rcx rdx rbx rsp rbp rsi rdi r8..r15. */
static struct oracle_reg oracle_regs[16];

static __u64 oracle_synthetic(__u64 index)
{
	return (__u8)((index * 131U + 17U) ^ (index >> 5));
}

static void oracle_reset(void)
{
	unsigned i;
	__u64 j;

	for (i = 0; i < 16; i++) {
		oracle_regs[i].value = 0;
		oracle_regs[i].tag = X86_SIM_TAG_SCALAR;
	}
	for (j = 0; j < ORACLE_BYTES; j++)
		oracle_mem[j] = (__u8)oracle_synthetic(j);
	for (j = 0; j < ORACLE_STACK_BYTES; j++)
		oracle_stack[j] = (__u8)oracle_synthetic(j + 7U);
}

/* ------------------------------------------------------------------ */
/* Hand-written models, independent of the macros under test.          */
/* ------------------------------------------------------------------ */

static __u64 oracle_load(__u64 addr, unsigned width)
{
	__u64 v = 0;
	unsigned i;

	for (i = 0; i < width; i++)
		v |= (__u64)oracle_mem[(addr + i) % ORACLE_BYTES] << (8 * i);
	return v & KPROG_X86_WIDTH_MASK(width);
}

static __u64 oracle_stack_load(__s64 off, unsigned width)
{
	__u32 index = (__u32)(off + ORACLE_STACK_BYTES);
	__u64 v = 0;
	unsigned i;

	for (i = 0; i < width; i++)
		v |= (__u64)oracle_stack[(index + i) % ORACLE_STACK_BYTES]
		     << (8 * i);
	return v & KPROG_X86_WIDTH_MASK(width);
}

static __u64 oracle_ptr_load(__u64 addr)
{
	void *p;

	memcpy(&p, &oracle_mem[addr % ORACLE_BYTES], sizeof(p));
	return (__u64)(uintptr_t)p;
}

static __u64 oracle_sign_extend(__u64 value, unsigned width)
{
	__u64 narrowed = value & KPROG_X86_WIDTH_MASK(width);

	if (narrowed & KPROG_X86_WIDTH_SIGN_MASK(width))
		return narrowed | ~KPROG_X86_WIDTH_MASK(width);
	return narrowed;
}

/* The partial-register writeback the sim performs: 8- and 16-bit writes keep
 * the destination's upper bytes, a 32-bit write zeroes the upper half, and a
 * 64-bit write replaces the register. */
static __u64 oracle_write(__u64 old, __u64 value, unsigned width)
{
	if (width == X86_WIDTH_8)
		return (old & ~0xffULL) | (value & 0xffULL);
	if (width == X86_WIDTH_16)
		return (old & ~0xffffULL) | (value & 0xffffULL);
	if (width == X86_WIDTH_32)
		return value & 0xffffffffULL;
	return value;
}

static __u8 oracle_abi_tag(unsigned kind, __s64 offset)
{
	if (kind == KPROG_ABI_KIND_XDP) {
		if (offset == KPROG_ABI_XDP_DATA_OFF)
			return X86_SIM_TAG_PACKET;
		if (offset == KPROG_ABI_XDP_DATA_END_OFF)
			return X86_SIM_TAG_PACKET_END;
		return X86_SIM_TAG_SCALAR;
	}
	if (offset == KPROG_ABI_SKB_DATA_OFF)
		return X86_SIM_TAG_PACKET;
	if (offset == KPROG_ABI_SKB_DATA_END_OFF)
		return X86_SIM_TAG_PACKET_END;
	return X86_SIM_TAG_SCALAR;
}

/* ------------------------------------------------------------------ */
/* Part 1: the generated width-resolution contract vs. the oracle.     */
/* ------------------------------------------------------------------ */

static unsigned part1(void)
{
	static const __u8 codes[5] = { 0U, X86_WIDTH_8, X86_WIDTH_16,
				       X86_WIDTH_32, X86_WIDTH_64 };
	unsigned cases = 0;
	unsigned ai, fi;

	for (ai = 0; ai < 5; ai++) {
		for (fi = 0; fi < 5; fi++) {
			__u8 flags = codes[fi];
			__u8 aux = codes[ai];
			__u8 write = flags ? flags : X86_WIDTH_64;
			__u8 mem = aux ? aux : write;
			__u8 got_write =
				KPROG_X86_MOV_LOAD_WRITE_WIDTH(flags);
			__u8 got_mem =
				KPROG_X86_MOV_LOAD_MEM_WIDTH(flags,
					X86_MEM_AUX(X86_REG_NONE, 0) |
					((__u32)aux << 16));

			if (got_write != write || got_mem != mem) {
				fprintf(stderr,
					"width mismatch aux=%u flags=%u "
					"got=(%u,%u) want=(%u,%u)\n",
					aux, flags, got_write, got_mem,
					write, mem);
				return 0;
			}
			if (got_write == KPROG_X86_MOV_LOAD_WIDTH_ABSENT ||
			    got_mem == KPROG_X86_MOV_LOAD_WIDTH_ABSENT) {
				fprintf(stderr,
					"absent width aux=%u flags=%u\n",
					aux, flags);
				return 0;
			}
			cases++;
		}
	}
	return cases;
}

/* ------------------------------------------------------------------ */
/* Part 2: the generated arm contract vs. the oracle.                  */
/* ------------------------------------------------------------------ */

static unsigned part2(void)
{
	unsigned cases = 0;
	unsigned mi, wi, oi, ti;
	int rsp;

	for (rsp = 0; rsp < 2; rsp++) {
		for (oi = 0; oi < 2; oi++) {
			for (mi = 0; mi < 2; mi++) {
				for (wi = 0; wi < 2; wi++) {
					for (ti = 0; ti < 2; ti++) {
						__u8 mem = mi ? X86_WIDTH_64
							      : X86_WIDTH_32;
						__u8 write = wi ? X86_WIDTH_64
								: X86_WIDTH_16;
						int is_mov =
							oi == 1;
						int abi = ti == 1;
						__u8 want;
						__u8 got;

						if (rsp)
							want =
							 KPROG_X86_MOV_LOAD_ARM_STACK;
						else if (is_mov && mem ==
							 X86_WIDTH_64 &&
							 write ==
							 X86_WIDTH_64 &&
							 abi)
							want =
							 KPROG_X86_MOV_LOAD_ARM_ABI_PTR;
						else
							want =
							 KPROG_X86_MOV_LOAD_ARM_ORDINARY;

						got = KPROG_X86_MOV_LOAD_ARM(
							rsp, is_mov, mem,
							write,
							abi ? X86_SIM_TAG_ABI
							    : X86_SIM_TAG_SCALAR);
						if (got != want) {
							fprintf(stderr,
								"arm mismatch "
								"rsp=%d mov=%d "
								"mem=%u w=%u "
								"abi=%d got=%u "
								"want=%u\n",
								rsp, is_mov, mem,
								write, abi, got,
								want);
							return 0;
						}
						cases++;
					}
				}
			}
		}
	}
	return cases;
}

/* ------------------------------------------------------------------ */
/* Part 3: the full handler composition vs. the hand-written body.     */
/*                                                                    */
/* `contract_step` resolves, selects, addresses, loads, tags and       */
/* writes through the generated contracts; `model_step` restates the   */
/* body from the raw fields. They must agree bit for bit.              */
/* ------------------------------------------------------------------ */

struct movl_result {
	__u64 bits;
	__u8 tag;
};

/* op: 0 = _MOV_LOAD, 1 = _MOV_LOAD_SCALAR, 2 = _MOVSX_LOAD. */
static struct movl_result contract_step(int base_index, __u8 base_tag, int op,
					__u32 aux, __u8 flags, __u64 imm,
					int store_disp, __u64 index_value,
					unsigned kind, __u64 dst_old)
{
	__u8 write = KPROG_X86_MOV_LOAD_WRITE_WIDTH(flags);
	__u8 mem = KPROG_X86_MOV_LOAD_MEM_WIDTH(flags, aux);
	int is_mov = op == 0;
	__u8 arm = KPROG_X86_MOV_LOAD_ARM(base_index == X86_RSP, is_mov, mem,
					  write, base_tag);
	__s64 disp = store_disp ? (__s32)(imm >> 32) : (__s64)imm;
	__s64 off;
	__u64 base_ptr = oracle_regs[base_index].value;
	__u64 addr;
	struct movl_result r;
	__u64 value;

	off = KPROG_X86_MEM_OFFSET(aux, disp, index_value,
				   X86_MEM_AUX_INDEX(aux) != X86_REG_NONE);
	addr = base_ptr + (__u64)off;

	if (arm == KPROG_X86_MOV_LOAD_ARM_STACK) {
		value = oracle_stack_load((__s64)base_ptr + off, mem);
		r.bits = oracle_write(dst_old, value, write);
		r.tag = X86_SIM_TAG_SCALAR;
		return r;
	}
	if (arm == KPROG_X86_MOV_LOAD_ARM_ABI_PTR) {
		r.bits = oracle_ptr_load(addr);
		r.tag = KPROG_ABI_LOAD_TAG(kind, off, X86_SIM_TAG_SCALAR,
					   X86_SIM_TAG_PACKET,
					   X86_SIM_TAG_PACKET_END);
		return r;
	}
	value = KPROG_X86_MEM_LOAD(&oracle_mem[addr % ORACLE_BYTES], mem);
	if (op == 2)
		value = oracle_sign_extend(value, mem);
	r.bits = oracle_write(dst_old, value, write);
	r.tag = X86_SIM_TAG_SCALAR;
	return r;
}

static struct movl_result model_step(int base_index, __u8 base_tag, int op,
				     __u32 aux, __u8 flags, __u64 imm,
				     int store_disp, __u64 index_value,
				     unsigned kind, __u64 dst_old)
{
	__u8 write = flags ? flags : X86_WIDTH_64;
	__u8 mem = X86_MEM_AUX_MEM_WIDTH(aux) ? X86_MEM_AUX_MEM_WIDTH(aux)
					      : write;
	__s64 disp = store_disp ? (__s32)(imm >> 32) : (__s64)imm;
	__s64 off = disp;
	__u64 base_ptr = oracle_regs[base_index].value;
	__u64 addr;
	struct movl_result r;
	__u64 value;

	if (X86_MEM_AUX_INDEX(aux) != X86_REG_NONE)
		off += (__s64)(index_value << X86_MEM_AUX_SCALE_LOG2(aux));
	addr = base_ptr + (__u64)off;

	if (base_index == X86_RSP) {
		value = oracle_stack_load((__s64)base_ptr + off, mem);
		r.bits = oracle_write(dst_old, value, write);
		r.tag = X86_SIM_TAG_SCALAR;
		return r;
	}
	if (op == 0 && mem == X86_WIDTH_64 && write == X86_WIDTH_64 &&
	    base_tag == X86_SIM_TAG_ABI) {
		r.bits = oracle_ptr_load(addr);
		r.tag = oracle_abi_tag(kind, off);
		return r;
	}
	value = oracle_load(addr, mem);
	if (op == 2)
		value = oracle_sign_extend(value, mem);
	r.bits = oracle_write(dst_old, value, write);
	r.tag = X86_SIM_TAG_SCALAR;
	return r;
}

static unsigned part3(void)
{
	static const __u8 codes[5] = { 0U, X86_WIDTH_8, X86_WIDTH_16,
				       X86_WIDTH_32, X86_WIDTH_64 };
	static const __u8 tags[4] = { X86_SIM_TAG_SCALAR, X86_SIM_TAG_ABI,
				      X86_SIM_TAG_STACK, X86_SIM_TAG_MAP_PTR };
	static const __u64 dst_olds[3] = {
		0x0000000000000000ULL,
		0xdeadbeefdeadbeefULL,
		0xffffffffffffffffULL,
	};
	unsigned cases = 0;
	unsigned ti, ai, fi, di, ki, gi;
	int bi, oi;

	for (bi = 0; bi < 16; bi++) {
		for (ti = 0; ti < 4; ti++) {
			for (oi = 0; oi < 3; oi++) {
				for (ai = 0; ai < 5; ai++) {
					for (fi = 0; fi < 5; fi++) {
						for (di = 0; di < 3; di++) {
							for (ki = 0; ki < 2; ki++) {
								for (gi = 0; gi < 3;
								     gi++) {
									__u32 aux =
									 codes[ai] << 16;
									__u64 imm;
									int sd;
									__u64 index_value;
									struct movl_result got;
									struct movl_result want;

									if (di == 2) {
										imm = 0x1234001000000008ULL;
										sd = 1;
									} else {
										imm = di ?
											0x0000000000000010ULL :
											0x0000000012340002ULL;
										sd = 0;
									}
									index_value =
									 (__u64)(cases % 97U) * 8U + 1U;
									got = contract_step(
										bi,
										tags[ti],
										oi,
										aux,
										codes[fi],
										imm,
										sd,
										index_value,
										ki,
										dst_olds[gi]);
									want = model_step(
										bi,
										tags[ti],
										oi,
										aux,
										codes[fi],
										imm,
										sd,
										index_value,
										ki,
										dst_olds[gi]);
									if (got.bits !=
									    want.bits ||
									    got.tag !=
									    want.tag) {
										fprintf(stderr,
											"handler mismatch "
											"base=%d tag=%u op=%d aux=%u "
											"flags=%u imm=%llx sd=%d "
											"kind=%u got=(%llx,%u) "
											"want=(%llx,%u)\n",
											bi,
											tags[ti],
											oi,
											aux,
											codes[fi],
											(unsigned long long)imm,
											sd,
											ki,
											(unsigned long long)got.bits,
											got.tag,
											(unsigned long long)want.bits,
											want.tag);
										return 0;
									}
									cases++;
								}
							}
						}
					}
				}
			}
		}
	}
	return cases;
}

/* A narrow ordinary load must not let bytes above the access width into the
 * product, and the ABI arm must survive the writeback untouched. These two
 * pins protect the asymmetries the composition is about. */
static unsigned part4(void)
{
	unsigned cases = 0;
	unsigned ti;

	for (ti = 0; ti < 4; ti++) {
		struct movl_result r = contract_step(
			X86_RSP + 1, X86_SIM_TAG_ABI, 0,
			(__u32)X86_WIDTH_64 << 16, X86_WIDTH_64,
			0x0000000000000008ULL, 0, 0, KPROG_ABI_KIND_XDP,
			0xdeadbeefdeadbeefULL);

		if (r.tag != X86_SIM_TAG_PACKET_END)
			return 0;
		cases++;
		(void)ti;
	}
	return cases;
}

int main(void)
{
	unsigned p1, p2, p3, p4;

	oracle_reset();
	oracle_regs[X86_RSP].value = 32U;
	oracle_regs[X86_RSP].tag = X86_SIM_TAG_STACK;

	p1 = part1();
	if (!p1) {
		fprintf(stderr, "part 1 failed\n");
		return 1;
	}
	p2 = part2();
	if (!p2) {
		fprintf(stderr, "part 2 failed\n");
		return 1;
	}
	p3 = part3();
	if (!p3) {
		fprintf(stderr, "part 3 failed\n");
		return 1;
	}
	p4 = part4();
	if (!p4) {
		fprintf(stderr, "part 4 failed\n");
		return 1;
	}

	printf("x86 mov-load handler host cross-check: OK (%u cases)\n",
	       p1 + p2 + p3 + p4);
	return 0;
}
