"""Generate per-directory provenance from raw metadata and introducing Git history."""
import json
import subprocess

from metrics import BUNDLE, js


def generate(rows, output):
    manifest = js(BUNDLE / 'inputs/data-manifest.json')
    result = []
    for entry in manifest:
        rel = entry['original_path']
        # Follow the metadata file through directory renames, back to first addition.
        log = subprocess.check_output(['git', 'log', '--follow', '--diff-filter=A',
                                       '--format=%H %aI', '--', rel + '/metadata.json'],
                                      cwd=BUNDLE.parents[2], text=True).strip().splitlines()
        if not log:
            raise RuntimeError(f'No introducing Git history for {rel}; use a full repository clone')
        commit, date = log[-1].split(' ', 1)
        if commit != entry['introduced_commit']:
            raise RuntimeError(f'Introducing history changed for {rel}: {commit}')
        m = js(BUNDLE / entry['bundle_path'] / 'metadata.json')
        prov, host = m.get('provenance', {}), m.get('host', {})
        claims = [dict(claim=r['claim'], file=r['source_file'], line=r['source_line'],
                       kind=r['kind'], value=r['claimed_value'], scope=r['scope'])
                  for r in rows if rel in r['current_data_paths'].split('; ')]
        cpu = prov.get('cpu_model', 'unknown')
        notes = []
        if '285K' in cpu:
            notes.append('Recorded Core Ultra 9 285K differs from paper Xeon Silver 4210R; paper VM sizing is not bound to this measurement.')
        if cpu == 'aarch64':
            notes.append('Recorded aarch64 does not identify Graviton generation or instance type; body declares t4g.small/Graviton2.')
        if not prov:
            notes.append('Corpus metadata has no CPU model, source commit, or kernel commit; do not infer these from micro runs.')
        if rel.endswith(('080836_924256', '094729_221231')):
            notes.append('Recorded bpf_stats=true differs from RQ2 stats-disabled wording. Suite status=error includes other apps; retain Katran measurements.')
        result.append((entry | dict(introduced_commit=commit, introduced_commit_date=date,
                           collection_date=m.get('started_at', m.get('generated_at', 'unknown')),
                           platform=m.get('run_type', host.get('platform', 'unknown')),
                           recorded_cpu=cpu, recorded_environment=prov.get('environment', 'unknown'),
                           recorded_source_commit=prov.get('repo_git_sha', host.get('git_sha', 'unknown')),
                           recorded_kernel_commit=prov.get('kernel_commit', 'unknown'),
                           recorded_kernel_version=host.get('kernel_version', 'unknown'),
                           recorded_status=m.get('status', 'unknown'),
                           recorded_samples=m.get('samples', m.get('defaults', {}).get('samples', 'unknown')),
                           recorded_bpf_stats=m.get('bpf_stats', 'unknown'), notes=notes, claims=claims)))
    (output / 'provenance.json').write_text(json.dumps(result, indent=2) + '\n')
    lines = ['# Data provenance', '',
             'Generated by `scripts/provenance.py` during `make`. Introducing commits come from',
             '`git log --follow --diff-filter=A -- <original>/metadata.json`, following renames.',
             'A Git addition date is not a collection date or a recorded source/kernel commit.', '',
             'Claim references point into the pinned `inputs/paper/` snapshot.', '']
    for e in result:
        lines += [f"## {e['bundle_path']}", '', f"Original: `{e['original_path']}`.", '',
                  f"Introduced by `{e['introduced_commit']}` ({e['introduced_commit_date']}).", '',
                  f"Collected: {e['collection_date']}; platform: {e['platform']}; CPU: {e['recorded_cpu']}; environment: {e['recorded_environment']}.", '',
                  f"Recorded source commit: `{e['recorded_source_commit']}`; kernel commit: `{e['recorded_kernel_commit']}`; kernel version: `{e['recorded_kernel_version']}`.", '',
                  f"Status: {e['recorded_status']}; samples: {e['recorded_samples']}; BPF stats: {e['recorded_bpf_stats']}; files: {e['files']}; bytes: {e['bytes']}.", '']
        lines += [n + '\n' for n in e['notes']]
        for c in e['claims']:
            file = c['file'].removeprefix('paper/')
            lines.append(f"- `{file}:{c['line']}` — {c['claim']} ({c['value']}; {c['scope']}).")
        lines += ['']
    (output / 'provenance.md').write_text('\n'.join(lines) + '\n')
    return result
