#!/usr/bin/env python3
"""Generate the shared x86-64 register-operand presence contract.

The generated Lean definitions `GeneratedX86RegPresence.arm` / `present` /
`absent` and the C macros `KPROG_X86_REG_PRESENT` / `KPROG_X86_REG_ABSENT` /
`KPROG_X86_REG_ARM` decide whether a decoded x86-64 register number names an
operand register:

  * the sentinel byte (`0xff`, `X86_REG_NONE`) names no register (the absent
    arm);
  * every other byte names a register (the present arm).

x86-64 has no architectural zero register, so unlike the AArch64 mirror the
contract has a single sentinel rather than a zero/sentinel pair. The
simulator's memory-operand bodies test the same `(REG) != X86_REG_NONE` (present)
and `(REG) == X86_REG_NONE` (absent) facts inline at more than a dozen sites;
routing each through `KPROG_X86_REG_PRESENT` / `KPROG_X86_REG_ABSENT` makes the
operand-presence decision a generated fact rather than a restated sentinel
comparison. `KProgFormal/X86RegPresence.lean` proves the generated predicates
equal independent `decide (reg ≠ 0xff)` / `decide (reg = 0xff)`, pins the
sentinel against the memory-index sentinel, and shows both arms are reachable.

The generated header is self-contained (no cross-include), exactly as the x86
and AArch64 memory-index mirrors.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_reg_presence_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86RegPresence.lean"
CHEADER = ROOT / "generated/x86_reg_presence.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "x86RegPresence",
    "reg_bits": 8,
    "sentinel": 255,
    "arms": [
        {"name": "present", "code": 0, "absent": False},
        {"name": "absent", "code": 1, "absent": True},
    ],
}


def load() -> dict:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 register-presence specification: {data!r}")
    arms = EXPECTED["arms"]
    if [row["name"] for row in arms] != ["present", "absent"]:
        raise SystemExit(f"invalid x86 register-presence arm order: {arms!r}")
    if [row["code"] for row in arms] != [0, 1]:
        raise SystemExit(f"invalid x86 register-presence arm codes: {arms!r}")
    if [row["absent"] for row in arms] != [False, True]:
        raise SystemExit(f"invalid x86 register-presence arm flags: {arms!r}")
    return EXPECTED


def render_lean(spec: dict) -> str:
    arms = spec["arms"]
    present_name = next(row["name"] for row in arms if not row["absent"])
    absent_name = next(row["name"] for row in arms if row["absent"])
    ctors = "\n".join(f"  | {row['name']}" for row in arms)
    absent_rows = "\n".join(
        f"  | .{row['name']} => "
        f"{'true' if row['absent'] else 'false'}" for row in arms)
    present_rows = "\n".join(
        f"  | .{row['name']} => "
        f"{'false' if row['absent'] else 'true'}" for row in arms)
    bits = spec["reg_bits"]
    sentinel = f"{spec['sentinel']:#x}"
    return f'''-- Generated by generate_x86_reg_presence_spec.py from x86_reg_presence_spec.json.
import Std
namespace KProgFormal.GeneratedX86RegPresence
/-- The two operand-register arms: a decoded register number that names an
operand register and one that names no register (the sentinel). -/
inductive Arm where
{ctors}
deriving DecidableEq, Repr
/-- The sentinel register byte that means "no register" (`X86_REG_NONE`), the
all-ones byte of a decoded register number. -/
def sentinel : BitVec {bits} := {sentinel}
/-- Whether an arm is the absent (no-register) arm. -/
def absent : Arm -> Bool
{absent_rows}
/-- The arm a decoded register number names: the sentinel byte is the absent arm
and every other byte names an operand register. -/
def arm (regByte : BitVec {bits}) : Arm :=
  if regByte = sentinel then .{absent_name} else .{present_name}
/-- Whether a decoded register number names an operand register: true for every
number but the sentinel. -/
def present (regByte : BitVec {bits}) : Bool :=
  match arm regByte with
{present_rows}
end KProgFormal.GeneratedX86RegPresence
'''


def render_c(spec: dict) -> str:
    arms = spec["arms"]
    arm_defines = "\n".join(
        f"#define KPROG_X86_REG_ARM_{row['name'].upper()} {row['code']}U"
        for row in arms)
    present_name = next(row["name"] for row in arms if not row["absent"]).upper()
    absent_name = next(row["name"] for row in arms if row["absent"]).upper()
    sentinel = f"{spec['sentinel']:#x}"
    return f'''/* Generated by generate_x86_reg_presence_spec.py from x86_reg_presence_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_REG_PRESENCE_H
#define KPROG_FORMAL_GENERATED_X86_REG_PRESENCE_H
/*
 * x86-64 operand-register presence: a decoded register number names an operand
 * register, or the sentinel byte (`0xff`, `X86_REG_NONE`) when the operand
 * carries none. x86-64 has no zero register, so a single sentinel decides the
 * two arms. `KProgFormal/X86RegPresence.lean` proves the presence and absence
 * tests equal independent `decide (reg != 0xff)` / `decide (reg == 0xff)`.
 */
/* The two operand-register arms. */
{arm_defines}
/* The all-ones byte that means "no register". */
#define KPROG_X86_REG_SENTINEL {sentinel}U
/*
 * REG is a decoded x86-64 register number. It is evaluated once; the result is
 * 1 exactly when REG names an operand register, 0 at the sentinel. No flags
 * written.
 */
#define KPROG_X86_REG_PRESENT(REG)                                          \\
\t((__u8)(((REG) != KPROG_X86_REG_SENTINEL) ? 1 : 0))
/*
 * The complement of KPROG_X86_REG_PRESENT: 1 exactly when REG is the sentinel,
 * 0 when REG names an operand register. Evaluated once; no flags written.
 */
#define KPROG_X86_REG_ABSENT(REG)                                           \\
\t((__u8)(((REG) == KPROG_X86_REG_SENTINEL) ? 1 : 0))
/*
 * The arm REG selects: the present arm when it names an operand register, the
 * absent arm at the sentinel. Evaluated once; no flags written.
 */
#define KPROG_X86_REG_ARM(REG)                                              \\
\t((__u8)(((REG) != KPROG_X86_REG_SENTINEL)                          \\
\t\t ? KPROG_X86_REG_ARM_{present_name}                          \\
\t\t : KPROG_X86_REG_ARM_{absent_name}))
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = load()
    for path, expected in ((LEAN, render_lean(spec)),
                           (CHEADER, render_c(spec))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated x86 register-presence contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
