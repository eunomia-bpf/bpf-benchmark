/*
 * Host cross-check for the x86-64 `BZHI` / `BZHI_MEM` handler contract.
 *
 * The module under test is `generated/x86_bzhi.h`. It fixes the one width a
 * body resolves (`FLAGS ? FLAGS : 64`) and the per-opcode fact that selects the
 * body's two inputs: `BZHI` reads its value from `SRC` and its count from
 * `COUNT`, `BZHI_MEM` reads its value from memory at the resolved width and its
 * count from the register the AUX shift byte names.
 *
 * The two C handlers restate this logic inline — `X86_SIM_L_EXEC_BZHI` /
 * `X86_SIM_L_EXEC_BZHI_MEM` in `x86_sim_local_bpf.h` — and the generated header
 * is not on their include path, so this host cross-check is the tie between the
 * two: it drives the contract through the generated macros and restates the
 * same bodies from the raw opcode bit, and the two must agree byte for byte on
 * the whole register file, the memory word the memory form reads, the
 * destination register, and the flags.
 *
 * The value-producing helpers the bodies use (`X86_SIM_L_READ_REG`,
 * `X86_SIM_L_READ_MEM_VALUE` at a scalar-tagged, non-stack base, `x86_width_bits`,
 * `kprog_x86_bzhi_value`, and `X86_SIM_L_WRITE_REG_WIDTH`) are hand-modelled
 * here: a register read is the register's 64-bit value, the memory read is the
 * generated byte-ladder load at the resolved width, the bit clear is the
 * exponent-built kept-mask, the flags are the hand-defined CF/SF/ZF/OF set, and
 * the writeback is the partial-register write.
 */
typedef unsigned char __u8;
typedef unsigned short __u16;
typedef unsigned int __u32;
typedef unsigned long long __u64;
typedef signed char __s8;
typedef short __s16;
typedef int __s32;
typedef signed long long __s64;

/* The generated headers define __always_inline functions in the kernel build;
 * provide the attribute for the host build. */
#ifndef __always_inline
#define __always_inline inline __attribute__((always_inline))
#endif

#define X86_RAX 0U
#define X86_RCX 1U
#define X86_RDX 2U
#define X86_RBX 3U
#define X86_RSI 6U
#define X86_RDI 7U
#define X86_REG_NONE 0xffU

#define X86_OP_BZHI 0x34U
#define X86_OP_BZHI_MEM 0x35U

#define X86_SIM_TAG_SCALAR 0U

#include "generated/x86_bzhi.h"
#include "generated/x86_width.h"
#include "generated/x86_reg_write.h"
#include "generated/x86_mem_access.h"
#include "generated/x86_bitops.h"

#include <stdint.h>
#include <stdio.h>
#include <string.h>

/* The FLAGS width codes the generated header defines locally. */
#define ORACLE_CODES 5U

/* ------------------------------------------------------------------ */
/* A deterministic register file, source memory and flags model.       */
/*                                                                    */
/* Register "pointers" hold byte offsets into `oracle_mem`, so the     */
/* memory form's base-plus-displacement address stays inside the array */
/* at every address the model forms.                                   */
/* ------------------------------------------------------------------ */

#define ORACLE_REGS 16U
#define ORACLE_MEM_BYTES 4096U

struct oracle_reg {
	union {
		__u8 b[8];
		__u16 w;
		void *ptr;
	} u;
	__u8 tag;
};

static struct oracle_reg oracle_regs[ORACLE_REGS];
static struct oracle_reg pristine_regs[ORACLE_REGS];
static struct oracle_reg result_regs[ORACLE_REGS];

static __u8 oracle_mem[ORACLE_MEM_BYTES];
static __u8 pristine_mem[ORACLE_MEM_BYTES];
static __u8 result_mem[ORACLE_MEM_BYTES];

static __u8 oracle_synthetic(__u64 index)
{
	return (__u8)((index * 131U + 17U) ^ (index >> 5));
}

static void oracle_reset(void)
{
	unsigned i;
	__u64 j;

	for (i = 0; i < ORACLE_REGS; i++) {
		oracle_regs[i].u.ptr =
			(void *)(long)(0x2a00ULL + (__u64)i * 0x20ULL);
		oracle_regs[i].tag = (__u8)(i % 6U);
	}
	for (j = 0; j < ORACLE_MEM_BYTES; j++)
		oracle_mem[j] = (__u8)oracle_synthetic(j + 7U);
}

static void oracle_snapshot_pristine(void)
{
	memcpy(pristine_regs, oracle_regs, sizeof(pristine_regs));
	memcpy(pristine_mem, oracle_mem, ORACLE_MEM_BYTES);
}

static void oracle_restore_pristine(void)
{
	memcpy(oracle_regs, pristine_regs, sizeof(pristine_regs));
	memcpy(oracle_mem, pristine_mem, ORACLE_MEM_BYTES);
}

static __u64 oracle_reg_value(unsigned index)
{
	return (__u64)(uintptr_t)oracle_regs[index].u.ptr;
}

/* ------------------------------------------------------------------ */
/* Hand-written models, independent of the macros under test.          */
/* ------------------------------------------------------------------ */

/* The width mask, restated from the raw codes rather than taken from the
 * generated x86_width.h. */
static __u64 oracle_mask(unsigned width)
{
	if (width == X86_WIDTH_8)
		return 0xffULL;
	if (width == X86_WIDTH_16)
		return 0xffffULL;
	if (width == X86_WIDTH_32)
		return 0xffffffffULL;
	return 0xffffffffffffffffULL;
}

static unsigned oracle_bits(unsigned width)
{
	if (width == X86_WIDTH_8)
		return 8U;
	if (width == X86_WIDTH_16)
		return 16U;
	if (width == X86_WIDTH_32)
		return 32U;
	return 64U;
}

/* The little-endian byte ladder the body's load contract performs: the
 * bytes at the address, summed `byte i << (8*i)` and narrowed. */
static __u64 oracle_load(__u64 addr, unsigned width)
{
	const __u8 *p = (const __u8 *)(uintptr_t)addr;
	__u64 v = 0;
	unsigned i;

	for (i = 0; i < width; i++)
		v |= (__u64)p[i] << (8 * i);
	return v & oracle_mask(width);
}

/* The partial-register writeback the sim performs: 8- and 16-bit writes keep
 * the destination's upper bytes, a 32-bit write zeroes the upper half, and a
 * 64-bit write replaces the register. */
static __u64 oracle_write(__u64 old, __u64 value, unsigned width)
{
	if (width == X86_WIDTH_8)
		return (old & ~0xffULL) | (value & 0xffULL);
	if (width == X86_WIDTH_16)
		return (old & ~0xffffULL) | (value & 0xffffULL);
	if (width == X86_WIDTH_32)
		return value & 0xffffffffULL;
	return value;
}

/* The bit clear the body's `kprog_x86_bzhi_value` performs: the byte-masked
 * count compared against the width's bit count, and the low count bits kept
 * through an exponent-built mask. Restated independently of the generated
 * x86_bitops.h. */
static __u64 oracle_bzhi(__u64 src, __u64 count, unsigned width)
{
	__u64 c = count & 0xffULL;
	__u64 result = src;

	if (c < (__u64)oracle_bits(width))
		result &= (c >= 64U) ? ~0ULL : ((1ULL << c) - 1ULL);
	return result & oracle_mask(width);
}

/* ------------------------------------------------------------------ */
/* Part 1: the generated tables vs. the oracle.                       */
/* ------------------------------------------------------------------ */

static unsigned part1(void)
{
	static const unsigned codes[ORACLE_CODES] = { 0U, X86_WIDTH_8, X86_WIDTH_16,
						      X86_WIDTH_32, X86_WIDTH_64 };
	unsigned cases = 0;
	unsigned ci;

	if (KPROG_X86_BZHI_WRITE_WIDTH_DEFAULT != X86_WIDTH_64) {
		fprintf(stderr, "bzhi default width is %u, want 64-bit\n",
			KPROG_X86_BZHI_WRITE_WIDTH_DEFAULT);
		return 0;
	}
	cases++;

	/* The two opcodes read their value and count from different places. */
	if (KPROG_X86_BZHI_OP_BZHI_VALUE_SOURCE !=
	    KPROG_X86_BZHI_VALUE_REGISTER) {
		fprintf(stderr, "bzhi register value source code drift\n");
		return 0;
	}
	cases++;

	if (KPROG_X86_BZHI_OP_BZHI_MEM_VALUE_SOURCE !=
	    KPROG_X86_BZHI_VALUE_MEMORY) {
		fprintf(stderr, "bzhi memory value source code drift\n");
		return 0;
	}
	cases++;

	if (KPROG_X86_BZHI_OP_BZHI_COUNT_SOURCE !=
	    KPROG_X86_BZHI_COUNT_REGISTER) {
		fprintf(stderr, "bzhi register count source code drift\n");
		return 0;
	}
	cases++;

	if (KPROG_X86_BZHI_OP_BZHI_MEM_COUNT_SOURCE !=
	    KPROG_X86_BZHI_COUNT_AUX_SHIFT) {
		fprintf(stderr, "bzhi aux count source code drift\n");
		return 0;
	}
	cases++;

	if (KPROG_X86_BZHI_VALUE_REGISTER == KPROG_X86_BZHI_VALUE_MEMORY) {
		fprintf(stderr, "bzhi value source codes collide\n");
		return 0;
	}
	cases++;

	if (KPROG_X86_BZHI_COUNT_REGISTER == KPROG_X86_BZHI_COUNT_AUX_SHIFT) {
		fprintf(stderr, "bzhi count source codes collide\n");
		return 0;
	}
	cases++;

	if (KPROG_X86_BZHI_COUNT_MASK != 0xffULL) {
		fprintf(stderr, "bzhi count mask drift\n");
		return 0;
	}
	cases++;

	for (ci = 0; ci < ORACLE_CODES; ci++) {
		unsigned want = codes[ci] ? codes[ci] : X86_WIDTH_64;
		unsigned got = KPROG_X86_BZHI_WRITE_WIDTH(codes[ci]);

		if (got != want) {
			fprintf(stderr, "bzhi width mismatch flags=%u got=%u "
					"want=%u\n",
				codes[ci], got, want);
			return 0;
		}
		cases++;
	}

	for (ci = 0; ci < 2U; ci++) {
		unsigned vs = KPROG_X86_BZHI_VALUE_SOURCE(ci != 0U);
		unsigned cs = KPROG_X86_BZHI_COUNT_SOURCE(ci != 0U);

		if (vs != (ci != 0U ? KPROG_X86_BZHI_VALUE_MEMORY
				    : KPROG_X86_BZHI_VALUE_REGISTER)) {
			fprintf(stderr, "bzhi value source select drift\n");
			return 0;
		}
		if (cs != (ci != 0U ? KPROG_X86_BZHI_COUNT_AUX_SHIFT
				    : KPROG_X86_BZHI_COUNT_REGISTER)) {
			fprintf(stderr, "bzhi count source select drift\n");
			return 0;
		}
		cases++;
	}

	return cases;
}

/* ------------------------------------------------------------------ */
/* Part 2: the full composition vs. the hand-written bodies.          */
/*                                                                    */
/* `contract_step` runs the bodies through the generated tables;      */
/* `model_step` restates them from the raw opcode bit. They must agree */
/* on the whole register file, the memory word, and the flags.         */
/* ------------------------------------------------------------------ */

struct bzhi_effect {
	unsigned value_source;
	unsigned count_source;
	unsigned width;
	__u64 value;
	__u64 count;
	__u64 result;
	__u64 dst;
	__u8 dst_tag;
	__u8 cf;
	__u8 zf;
	__u8 sf;
	__u8 of;
};

static struct bzhi_effect contract_step(unsigned op_is_mem, unsigned flags,
					unsigned src_reg, unsigned count_reg,
					unsigned aux_count_reg,
					unsigned base_reg, unsigned dst_reg,
					__s64 imm)
{
	unsigned value_source = KPROG_X86_BZHI_VALUE_SOURCE(op_is_mem);
	unsigned count_source = KPROG_X86_BZHI_COUNT_SOURCE(op_is_mem);
	unsigned width = KPROG_X86_BZHI_WRITE_WIDTH(flags);
	struct bzhi_effect r;

	r.value_source = value_source;
	r.count_source = count_source;
	r.width = width;
	if (value_source == KPROG_X86_BZHI_VALUE_MEMORY) {
		__u64 addr = oracle_reg_value(base_reg) + (__u64)imm;

		r.value = KPROG_X86_MEM_LOAD((void *)(uintptr_t)addr, width);
	} else {
		r.value = oracle_reg_value(src_reg);
	}

	if (count_source == KPROG_X86_BZHI_COUNT_AUX_SHIFT)
		r.count = oracle_reg_value(aux_count_reg) &
			  KPROG_X86_BZHI_COUNT_MASK;
	else
		r.count = oracle_reg_value(count_reg) &
			  KPROG_X86_BZHI_COUNT_MASK;

	/* The generated bit-clear helper, driven at the resolved width. */
	r.result = kprog_x86_bzhi_value(r.value, r.count, width);

	/* The hand-defined flags: CF from the masked count vs the width's bit
	 * count, SF/OF hard-zero, ZF the real zero test of the result. */
	r.cf = (__u8)(r.count >= (__u64)oracle_bits(width));
	r.of = 0U;
	r.sf = 0U;
	r.zf = (__u8)(r.result == 0U);

	/* The partial-register destination write at the resolved width. */
	if (width == X86_WIDTH_8)
		KPROG_X86_WRITE_REG8(oracle_regs[dst_reg].u,
				     oracle_regs[dst_reg].tag, r.result, 0U,
				     X86_SIM_TAG_SCALAR);
	else if (width == X86_WIDTH_16)
		KPROG_X86_WRITE_REG16(oracle_regs[dst_reg].u,
				      oracle_regs[dst_reg].tag, r.result,
				      X86_SIM_TAG_SCALAR);
	else if (width == X86_WIDTH_32)
		KPROG_X86_WRITE_REG32(oracle_regs[dst_reg].u,
				      oracle_regs[dst_reg].tag, r.result,
				      X86_SIM_TAG_SCALAR);
	else
		KPROG_X86_WRITE_REG64(oracle_regs[dst_reg].u,
				      oracle_regs[dst_reg].tag, r.result,
				      X86_SIM_TAG_SCALAR);

	r.dst = oracle_reg_value(dst_reg);
	r.dst_tag = oracle_regs[dst_reg].tag;
	return r;
}

static struct bzhi_effect model_step(unsigned op_is_mem, unsigned flags,
				     unsigned src_reg, unsigned count_reg,
				     unsigned aux_count_reg,
				     unsigned base_reg, unsigned dst_reg,
				     __s64 imm)
{
	unsigned width = flags ? flags : X86_WIDTH_64;
	struct bzhi_effect r;

	r.value_source = op_is_mem ? KPROG_X86_BZHI_VALUE_MEMORY
				   : KPROG_X86_BZHI_VALUE_REGISTER;
	r.count_source = op_is_mem ? KPROG_X86_BZHI_COUNT_AUX_SHIFT
				   : KPROG_X86_BZHI_COUNT_REGISTER;
	r.width = width;
	if (op_is_mem) {
		__u64 addr = oracle_reg_value(base_reg) + (__u64)imm;

		r.value = oracle_load(addr, width);
	} else {
		r.value = oracle_reg_value(src_reg);
	}

	if (op_is_mem)
		r.count = oracle_reg_value(aux_count_reg) & 0xffULL;
	else
		r.count = oracle_reg_value(count_reg) & 0xffULL;

	r.result = oracle_bzhi(r.value, r.count, width);
	r.cf = (__u8)(r.count >= (__u64)oracle_bits(width));
	r.of = 0U;
	r.sf = 0U;
	r.zf = (__u8)(r.result == 0U);

	oracle_regs[dst_reg].u.ptr = (void *)(long)oracle_write(
		oracle_reg_value(dst_reg), r.result, width);
	oracle_regs[dst_reg].tag = X86_SIM_TAG_SCALAR;

	r.dst = oracle_reg_value(dst_reg);
	r.dst_tag = oracle_regs[dst_reg].tag;
	return r;
}

static unsigned part2(void)
{
	static const unsigned flags_codes[ORACLE_CODES] = { 0U, X86_WIDTH_8,
							    X86_WIDTH_16,
							    X86_WIDTH_32,
							    X86_WIDTH_64 };
	static const __s64 imms[4] = { 0, 4, 8, -4 };
	static const unsigned src_regs[3] = { X86_RAX, X86_RSI, 11U };
	static const unsigned count_regs[3] = { X86_RCX, X86_RDX, 12U };
	static const unsigned aux_regs[3] = { X86_RDI, X86_RBX, 13U };
	static const unsigned dst_regs[3] = { X86_RCX, X86_RDX, 9U };
	unsigned cases = 0;
	unsigned op;
	unsigned fi;
	unsigned mi;
	unsigned si;
	unsigned ci;
	unsigned ai;
	unsigned di;

	for (op = 0; op < 2U; op++) {
		for (fi = 0; fi < ORACLE_CODES; fi++) {
			for (mi = 0; mi < 4U; mi++) {
				for (si = 0; si < 3U; si++) {
					for (ci = 0; ci < 3U; ci++) {
						for (ai = 0; ai < 3U; ai++) {
							for (di = 0; di < 3U;
							     di++) {
								struct bzhi_effect got;
								struct bzhi_effect want;

								oracle_restore_pristine();
								oracle_regs[X86_RBX].u.ptr =
									(void *)(uintptr_t)&oracle_mem[64];
								oracle_regs[X86_RBX].tag =
									X86_SIM_TAG_SCALAR;
								got = contract_step(
									op,
									flags_codes[fi],
									src_regs[si],
									count_regs[ci],
									aux_regs[ai],
									X86_RBX,
									dst_regs[di],
									imms[mi]);
								memcpy(result_regs,
								       oracle_regs,
								       sizeof(oracle_regs));
								memcpy(result_mem,
								       oracle_mem,
								       ORACLE_MEM_BYTES);

								oracle_restore_pristine();
								oracle_regs[X86_RBX].u.ptr =
									(void *)(uintptr_t)&oracle_mem[64];
								oracle_regs[X86_RBX].tag =
									X86_SIM_TAG_SCALAR;
								want = model_step(
									op,
									flags_codes[fi],
									src_regs[si],
									count_regs[ci],
									aux_regs[ai],
									X86_RBX,
									dst_regs[di],
									imms[mi]);

								if (got.value_source != want.value_source ||
								    got.count_source != want.count_source ||
								    got.width != want.width ||
								    got.value != want.value ||
								    got.count != want.count ||
								    got.result != want.result ||
								    got.dst != want.dst ||
								    got.dst_tag != want.dst_tag ||
								    got.cf != want.cf ||
								    got.zf != want.zf ||
								    got.sf != want.sf ||
								    got.of != want.of ||
								    memcmp(result_regs, oracle_regs,
									   sizeof(oracle_regs)) ||
								    memcmp(result_mem, oracle_mem,
									   ORACLE_MEM_BYTES)) {
									fprintf(stderr,
										"bzhi mismatch mem=%u flags=%u\n",
										op,
										flags_codes[fi]);
									return 0;
								}
								cases++;
							}
						}
					}
				}
			}
		}
	}
	return cases;
}

/* ------------------------------------------------------------------ */
/* Part 3: pins on the facts the composition is about.                */
/* ------------------------------------------------------------------ */

static unsigned part3(void)
{
	unsigned cases = 0;

	/* Pin 1: the register form reads its value from SRC, not memory. */
	{
		struct bzhi_effect e;
		__u64 src;

		oracle_restore_pristine();
		src = oracle_reg_value(X86_RAX);
		e = contract_step(0U, X86_WIDTH_64, X86_RAX, X86_RCX, X86_RDI,
				  X86_RBX, X86_RDX, 0);
		if (e.value_source != KPROG_X86_BZHI_VALUE_REGISTER)
			return 0;
		if (e.value != src)
			return 0;
		if (memcmp(oracle_mem, pristine_mem, ORACLE_MEM_BYTES))
			return 0;
		cases++;
	}

	/* Pin 2: the memory form reads its value from memory at the *resolved*
	 * width — the same width it writes, with no second AUX width. */
	{
		struct bzhi_effect e;
		__u64 addr;

		oracle_restore_pristine();
		oracle_regs[X86_RBX].u.ptr =
			(void *)(uintptr_t)&oracle_mem[64];
		oracle_regs[X86_RBX].tag = X86_SIM_TAG_SCALAR;
		addr = (__u64)(uintptr_t)&oracle_mem[64];
		e = contract_step(1U, X86_WIDTH_16, X86_RAX, X86_RCX, X86_RDI,
				  X86_RBX, X86_RDX, 0);
		if (e.value_source != KPROG_X86_BZHI_VALUE_MEMORY)
			return 0;
		if (e.width != X86_WIDTH_16)
			return 0;
		if (e.value != oracle_load(addr, X86_WIDTH_16))
			return 0;
		cases++;
	}

	/* Pin 3: the count is byte-masked — a register holding `0x1ff`
	 * behaves as `0xff`, keeping the whole value and reporting CF. */
	{
		struct bzhi_effect e;

		oracle_restore_pristine();
		oracle_regs[X86_RCX].u.ptr = (void *)(long)0x1ffULL;
		oracle_regs[X86_RCX].tag = X86_SIM_TAG_SCALAR;
		e = contract_step(0U, X86_WIDTH_8, X86_RAX, X86_RCX, X86_RDI,
				  X86_RBX, X86_RDX, 0);
		if (e.count != 0xffULL)
			return 0;
		if (e.result != (oracle_reg_value(X86_RAX) & 0xffULL))
			return 0;
		if (e.cf != 1U)
			return 0;
		cases++;
	}

	/* Pin 4: `BZHI_MEM` takes its count from the AUX-shift register, not
	 * from `COUNT`. Two count registers holding different values give
	 * different results. */
	{
		struct bzhi_effect e;
		__u64 want;

		oracle_restore_pristine();
		oracle_regs[X86_RBX].u.ptr =
			(void *)(uintptr_t)&oracle_mem[64];
		oracle_regs[X86_RBX].tag = X86_SIM_TAG_SCALAR;
		oracle_regs[X86_RDI].u.ptr = (void *)(long)4ULL;
		oracle_regs[X86_RDI].tag = X86_SIM_TAG_SCALAR;
		oracle_regs[X86_RCX].u.ptr = (void *)(long)16ULL;
		oracle_regs[X86_RCX].tag = X86_SIM_TAG_SCALAR;
		e = contract_step(1U, X86_WIDTH_64, X86_RAX, X86_RCX, X86_RDI,
				  X86_RBX, X86_RDX, 0);
		if (e.count_source != KPROG_X86_BZHI_COUNT_AUX_SHIFT)
			return 0;
		if (e.count != 4ULL)
			return 0;
		want = oracle_bzhi(oracle_load(
			oracle_reg_value(X86_RBX), X86_WIDTH_64), 4ULL,
			X86_WIDTH_64);
		if (e.result != want)
			return 0;
		cases++;
	}

	/* Pin 5: CF is the byte-masked count reaching the *width's* bit count,
	 * not any property of the result: count 8 carries an 8-bit BZHI but
	 * not a 64-bit one. */
	{
		struct bzhi_effect narrow;
		struct bzhi_effect wide;

		oracle_restore_pristine();
		oracle_regs[X86_RCX].u.ptr = (void *)(long)8ULL;
		oracle_regs[X86_RCX].tag = X86_SIM_TAG_SCALAR;
		narrow = contract_step(0U, X86_WIDTH_8, X86_RAX, X86_RCX,
				       X86_RDI, X86_RBX, X86_RDX, 0);
		if (narrow.cf != 1U)
			return 0;

		oracle_restore_pristine();
		oracle_regs[X86_RCX].u.ptr = (void *)(long)8ULL;
		oracle_regs[X86_RCX].tag = X86_SIM_TAG_SCALAR;
		wide = contract_step(0U, X86_WIDTH_64, X86_RAX, X86_RCX,
				     X86_RDI, X86_RBX, X86_RDX, 0);
		if (wide.cf != 0U)
			return 0;
		cases++;
	}

	/* Pin 6: SF is hardcoded 0 while ZF is the real zero test — the
	 * asymmetry against the shared logic-flag production. A value whose
	 * top bit is set keeps SF clear. */
	{
		struct bzhi_effect e;

		oracle_restore_pristine();
		oracle_regs[X86_RAX].u.ptr = (void *)(long)0x80ULL;
		oracle_regs[X86_RAX].tag = X86_SIM_TAG_SCALAR;
		oracle_regs[X86_RCX].u.ptr = (void *)(long)8ULL;
		oracle_regs[X86_RCX].tag = X86_SIM_TAG_SCALAR;
		e = contract_step(0U, X86_WIDTH_8, X86_RAX, X86_RCX, X86_RDI,
				  X86_RBX, X86_RDX, 0);
		if (e.result != 0x80ULL)
			return 0;
		if (e.sf != 0U)
			return 0;
		if (e.zf != 0U)
			return 0;
		cases++;

		oracle_restore_pristine();
		oracle_regs[X86_RAX].u.ptr = (void *)(long)0x80ULL;
		oracle_regs[X86_RAX].tag = X86_SIM_TAG_SCALAR;
		oracle_regs[X86_RCX].u.ptr = (void *)(long)4ULL;
		oracle_regs[X86_RCX].tag = X86_SIM_TAG_SCALAR;
		e = contract_step(0U, X86_WIDTH_8, X86_RAX, X86_RCX, X86_RDI,
				  X86_RBX, X86_RDX, 0);
		if (e.result != 0U)
			return 0;
		if (e.zf != 1U)
			return 0;
		if (e.sf != 0U)
			return 0;
		cases++;
	}

	/* Pin 7: the destination write is the partial-register write at the
	 * resolved width — a narrow write preserves the upper bytes. */
	{
		struct bzhi_effect e;
		__u64 old;

		oracle_restore_pristine();
		old = oracle_reg_value(X86_RDX);
		oracle_regs[X86_RDX].tag = 5U;
		e = contract_step(0U, X86_WIDTH_8, X86_RAX, X86_RCX, X86_RDI,
				  X86_RBX, X86_RDX, 0);
		if (e.width != X86_WIDTH_8)
			return 0;
		if (e.dst != ((old & ~0xffULL) | (e.result & 0xffULL)))
			return 0;
		if (e.dst_tag != X86_SIM_TAG_SCALAR)
			return 0;
		cases++;
	}

	/* Pin 8: BZHI writes no memory: the memory word is untouched even by
	 * the memory-reading form. */
	{
		struct bzhi_effect e;

		oracle_restore_pristine();
		oracle_regs[X86_RBX].u.ptr =
			(void *)(uintptr_t)&oracle_mem[64];
		oracle_regs[X86_RBX].tag = X86_SIM_TAG_SCALAR;
		e = contract_step(1U, X86_WIDTH_32, X86_RAX, X86_RCX, X86_RDI,
				  X86_RBX, X86_RDX, 8);
		if (e.result != oracle_bzhi(oracle_load(
			oracle_reg_value(X86_RBX) + 8ULL, X86_WIDTH_32),
			oracle_reg_value(X86_RDI) & 0xffULL, X86_WIDTH_32))
			return 0;
		if (memcmp(oracle_mem, pristine_mem, ORACLE_MEM_BYTES))
			return 0;
		cases++;
	}

	return cases;
}

int main(void)
{
	unsigned c1;
	unsigned c2;
	unsigned c3;

	oracle_reset();
	oracle_snapshot_pristine();

	/* Each part returns zero exactly when a case failed, so any zero is a
	 * failure even though the readiness line still prints. */
	c1 = part1();
	if (c1 == 0U)
		return 1;
	oracle_restore_pristine();
	c2 = part2();
	if (c2 == 0U)
		return 1;
	oracle_restore_pristine();
	c3 = part3();
	if (c3 == 0U)
		return 1;
	oracle_restore_pristine();

	printf("x86 bzhi handler host cross-check: OK (%u cases)\n",
	       c1 + c2 + c3);
	return 0;
}
