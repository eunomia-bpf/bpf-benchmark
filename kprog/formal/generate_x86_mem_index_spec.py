#!/usr/bin/env python3
"""Generate the shared x86-64 memory-index presence contract.

The generated Lean definitions `GeneratedX86MemIndex.arm` / `present` and the C
macros `KPROG_X86_MEM_INDEX_PRESENT` / `KPROG_X86_MEM_INDEX_ARM` decide whether
an addressing mode carries an index register from the low byte of the packed
`AUX` word:

  * the sentinel byte (`0xff`, `X86_REG_NONE`) names the absent arm;
  * every other byte names an index register and the present arm.

The simulator's `X86_SIM_L_MEM_OFFSET` resolves its index presence and its index
value from this one selector, so the presence flag the machine-checked
`KPROG_X86_MEM_OFFSET` consumes is a generated fact rather than a restated
sentinel comparison. `KProgFormal/X86MemIndex.lean` proves the selector equals an
independent `decide (indexByte != 0xff)` and that the two arms are exactly the
two `hasIndex` cases of the offset contract.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_mem_index_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86MemIndex.lean"
CHEADER = ROOT / "generated/x86_mem_index.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "x86MemIndex",
    "index_byte_bits": 8,
    "sentinel": 255,
    "arms": [
        {"name": "present", "code": 0, "absent": False},
        {"name": "absent", "code": 1, "absent": True},
    ],
}


def load() -> dict:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 memory-index specification: {data!r}")
    arms = EXPECTED["arms"]
    if [row["name"] for row in arms] != ["present", "absent"]:
        raise SystemExit(f"invalid x86 memory-index arm order: {arms!r}")
    if [row["code"] for row in arms] != [0, 1]:
        raise SystemExit(f"invalid x86 memory-index arm codes: {arms!r}")
    if [row["absent"] for row in arms] != [False, True]:
        raise SystemExit(f"invalid x86 memory-index arm flags: {arms!r}")
    return EXPECTED


def render_lean(spec: dict) -> str:
    arms = spec["arms"]
    present_name = next(row["name"] for row in arms if not row["absent"])
    absent_name = next(row["name"] for row in arms if row["absent"])
    ctors = "\n".join(f"  | {row['name']}" for row in arms)
    absent_rows = "\n".join(
        f"  | .{row['name']} => "
        f"{'true' if row['absent'] else 'false'}" for row in arms)
    present_rows = "\n".join(
        f"  | .{row['name']} => "
        f"{'false' if row['absent'] else 'true'}" for row in arms)
    bits = spec["index_byte_bits"]
    sentinel = f"{spec['sentinel']:#x}"
    return f'''-- Generated by generate_x86_mem_index_spec.py from x86_mem_index_spec.json.
import Std
namespace KProgFormal.GeneratedX86MemIndex
/-- The two addressing-mode index arms: a mode that names an index register and
one that does not, whose `AUX` index byte is the sentinel. -/
inductive Arm where
{ctors}
deriving DecidableEq, Repr
/-- The sentinel index byte that means "no index register" (`X86_REG_NONE`),
the all-ones byte of the `AUX` index field. -/
def indexSentinel : BitVec {bits} := {sentinel}
/-- Whether an arm is the absent (no-index) arm. -/
def absent : Arm -> Bool
{absent_rows}
/-- The arm an `AUX` index byte names: the sentinel byte is the absent arm and
every other byte names an index register. -/
def arm (indexByte : BitVec {bits}) : Arm :=
  if indexByte = indexSentinel then .{absent_name} else .{present_name}
/-- Whether the addressing mode carries an index register. -/
def present (indexByte : BitVec {bits}) : Bool :=
  match arm indexByte with
{present_rows}
end KProgFormal.GeneratedX86MemIndex
'''


def render_c(spec: dict) -> str:
    arms = spec["arms"]
    arm_defines = "\n".join(
        f"#define KPROG_X86_MEM_INDEX_ARM_{row['name'].upper()} {row['code']}U"
        for row in arms)
    present_name = next(row["name"] for row in arms if not row["absent"]).upper()
    absent_name = next(row["name"] for row in arms if row["absent"]).upper()
    sentinel = f"{spec['sentinel']:#x}"
    return f'''/* Generated by generate_x86_mem_index_spec.py from x86_mem_index_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_MEM_INDEX_H
#define KPROG_FORMAL_GENERATED_X86_MEM_INDEX_H
/*
 * x86-64 memory-index presence: the `AUX` word's low byte names an index
 * register, or the sentinel byte (`0xff`, `X86_REG_NONE`) when the addressing
 * mode carries none. `KProgFormal/X86MemIndex.lean` proves the presence test
 * equals an independent `decide (indexByte != 0xff)`.
 */
/* The two index arms. */
{arm_defines}
/* The all-ones byte that means "no index register". */
#define KPROG_X86_MEM_INDEX_SENTINEL {sentinel}U
/*
 * INDEX_BYTE is the `AUX` word's index field byte. It is evaluated once; the
 * result is 1 exactly when the byte names an index register. No flags written.
 */
#define KPROG_X86_MEM_INDEX_PRESENT(INDEX_BYTE)                             \\
\t((__u8)(((INDEX_BYTE) != KPROG_X86_MEM_INDEX_SENTINEL) ? 1 : 0))
/*
 * The arm INDEX_BYTE selects: the present arm when it names an index register,
 * the absent arm at the sentinel. Evaluated once; no flags written.
 */
#define KPROG_X86_MEM_INDEX_ARM(INDEX_BYTE)                                 \\
\t((__u8)(((INDEX_BYTE) != KPROG_X86_MEM_INDEX_SENTINEL)             \\
\t\t ? KPROG_X86_MEM_INDEX_ARM_{present_name}                         \\
\t\t : KPROG_X86_MEM_INDEX_ARM_{absent_name}))
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = load()
    for path, expected in ((LEAN, render_lean(spec)),
                           (CHEADER, render_c(spec))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated x86 memory-index contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
