#!/usr/bin/env python3
"""Generate the shared x86 addition flag transition for Lean and C."""
import argparse, json
from pathlib import Path
ROOT=Path(__file__).resolve().parent; SPEC=ROOT/"x86_add_flags_spec.json"; LEAN=ROOT/"KProgFormal/GeneratedX86AddFlags.lean"; CHEADER=ROOT/"generated/x86_add_flags.h"
NAMES=["cf","zf","sf","of"]; INPUTS={"a","b","r","sign"}
def validate(e):
 if not isinstance(e,dict) or "op" not in e: raise SystemExit(f"invalid addition flag expression: {e!r}")
 op=e["op"]
 if op=="input":
  if set(e)!={"op","name"} or e["name"] not in INPUTS: raise SystemExit(f"invalid addition input: {e!r}")
 elif op=="zero":
  if set(e)!={"op"}: raise SystemExit(f"invalid zero expression: {e!r}")
 elif op in {"nonzero","not"}:
  if set(e)!={"op","arg"}: raise SystemExit(f"invalid unary expression: {e!r}")
  validate(e["arg"])
 elif op in {"ult","eq","and","xor"}:
  if set(e)!={"op","lhs","rhs"}: raise SystemExit(f"invalid binary expression: {e!r}")
  validate(e["lhs"]); validate(e["rhs"])
 else: raise SystemExit(f"unsupported addition expression: {e!r}")
def load():
 d=json.loads(SPEC.read_text())
 if set(d)!={"schema_version","operation","flags"} or d["schema_version"]!=1 or d["operation"]!="x86AddFlags" or list(d["flags"])!=NAMES: raise SystemExit(f"invalid x86 addition specification: {d!r}")
 for e in d["flags"].values(): validate(e)
 return d["flags"]
def render(e,lean):
 op=e["op"]
 if op=="input": return e["name"] if lean else e["name"].upper()
 if op=="zero": return "0"
 if op=="nonzero": return f"({render(e['arg'],lean)} != 0)"
 if op=="not": return f"(BitVec.not {render(e['arg'],lean)})" if lean else f"(~{render(e['arg'],lean)})"
 l=render(e["lhs"],lean); r=render(e["rhs"],lean)
 if lean:
  if op=="eq": return f"({l} == {r})"
  fn={"ult":"BitVec.ult","and":"BitVec.and","xor":"BitVec.xor"}[op]
  return f"({fn} {l} {r})"
 operator={"ult":"<","eq":"==","and":"&","xor":"^"}[op]
 return f"({l} {operator} {r})"
def lean_out(fs):
 vals=", ".join(f"{n} := {render(fs[n],True)}" for n in NAMES)
 return f'''-- Generated by generate_x86_add_flags_spec.py from x86_add_flags_spec.json.
import KProgFormal.GeneratedX86LogicFlags
namespace KProgFormal.GeneratedX86AddFlags
def eval (a b r sign : BitVec 64) : GeneratedX86LogicFlags.Flags := {{ {vals} }}
end KProgFormal.GeneratedX86AddFlags
'''
def c_out(fs):
 vals=" \\\n".join(f"\t\t(C_{n.upper()}) = {render(fs[n],False)};" for n in NAMES)
 return f'''/* Generated by generate_x86_add_flags_spec.py from x86_add_flags_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_ADD_FLAGS_H
#define KPROG_FORMAL_GENERATED_X86_ADD_FLAGS_H
#define KPROG_X86_SET_ADD_FLAGS(C_CF,C_ZF,C_SF,C_OF,A,B,R,SIGN)             \\
\tdo {{ \\
{vals} \\
\t}} while (0)
#endif
'''
def main():
 p=argparse.ArgumentParser();p.add_argument("--check",action="store_true");a=p.parse_args();fs=load()
 for path,want in ((LEAN,lean_out(fs)),(CHEADER,c_out(fs))):
  if a.check:
   if not path.is_file() or path.read_text()!=want: raise SystemExit(f"generated x86 addition contract is stale: {path}")
  else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(want)
if __name__=="__main__":main()
