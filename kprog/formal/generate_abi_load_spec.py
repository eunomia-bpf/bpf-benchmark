#!/usr/bin/env python3
"""Render the shared entry-ABI load tag policy for Lean and C."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SPEC_PATH = ROOT / "abi_load_spec.json"
LEAN_PATH = ROOT / "KProgFormal" / "GeneratedAbiLoad.lean"
C_PATH = ROOT / "generated" / "abi_load.h"


def load_spec() -> dict[str, object]:
    spec = json.loads(SPEC_PATH.read_text())
    if set(spec) != {"schema_version", "operation", "kinds", "unknown_tag"}:
        raise SystemExit(f"invalid ABI-load specification fields: {spec!r}")
    if spec["schema_version"] != 1 or spec["operation"] != "abiLoad64Tag":
        raise SystemExit(f"unsupported ABI-load specification: {spec!r}")
    if spec["unknown_tag"] != "scalar":
        raise SystemExit(f"unsupported unknown ABI-load tag: {spec!r}")
    kinds = spec["kinds"]
    if not isinstance(kinds, list) or len(kinds) != 2:
        raise SystemExit(f"unsupported ABI kinds: {kinds!r}")
    expected_names = ["xdp", "skb"]
    for kind, expected_name in zip(kinds, expected_names, strict=True):
        if not isinstance(kind, dict) or set(kind) != {
                "name", "data_offset", "data_end_offset"}:
            raise SystemExit(f"invalid ABI kind: {kind!r}")
        if kind["name"] != expected_name:
            raise SystemExit(f"unexpected ABI kind order: {kind!r}")
        for field in ("data_offset", "data_end_offset"):
            if not isinstance(kind[field], int) or kind[field] < 0:
                raise SystemExit(f"invalid ABI offset: {kind!r}")
        if kind["data_offset"] == kind["data_end_offset"]:
            raise SystemExit(f"ambiguous ABI offsets: {kind!r}")
    return spec


def render_lean(spec: dict[str, object]) -> str:
    kinds = spec["kinds"]
    assert isinstance(kinds, list)
    xdp = kinds[0]
    skb = kinds[1]
    assert isinstance(xdp, dict) and isinstance(skb, dict)
    return f"""-- Generated by generate_abi_load_spec.py from abi_load_spec.json.
import Std

namespace KProgFormal.GeneratedAbiLoad

inductive Kind
  | xdp
  | skb
  deriving DecidableEq, Repr

def tag {{α : Type}} (scalar packet packetEnd : α) : Kind -> Int -> α
  | .xdp, offset =>
      if offset == {xdp['data_offset']} then packet
      else if offset == {xdp['data_end_offset']} then packetEnd
      else scalar
  | .skb, offset =>
      if offset == {skb['data_offset']} then packet
      else if offset == {skb['data_end_offset']} then packetEnd
      else scalar

end KProgFormal.GeneratedAbiLoad
"""


def render_c(spec: dict[str, object]) -> str:
    kinds = spec["kinds"]
    assert isinstance(kinds, list)
    xdp = kinds[0]
    skb = kinds[1]
    assert isinstance(xdp, dict) and isinstance(skb, dict)
    return f"""/* Generated by generate_abi_load_spec.py from abi_load_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ABI_LOAD_H
#define KPROG_FORMAL_GENERATED_ABI_LOAD_H

#define KPROG_ABI_KIND_XDP 0U
#define KPROG_ABI_KIND_SKB 1U
#define KPROG_ABI_XDP_DATA_OFF {xdp['data_offset']}LL
#define KPROG_ABI_XDP_DATA_END_OFF {xdp['data_end_offset']}LL
#define KPROG_ABI_SKB_DATA_OFF {skb['data_offset']}LL
#define KPROG_ABI_SKB_DATA_END_OFF {skb['data_end_offset']}LL

#define KPROG_ABI_LOAD_TAG(KIND, OFFSET, SCALAR, PACKET, PACKET_END)         \\
\t({{                                                                 \\
\t\t__u8 __kprog_abi_kind = (KIND);                            \\
\t\t__s64 __kprog_abi_offset = (OFFSET);                       \\
\t\t__u8 __kprog_abi_tag = (SCALAR);                           \\
\t\tif ((__kprog_abi_kind == KPROG_ABI_KIND_XDP &&             \\
\t\t     __kprog_abi_offset == KPROG_ABI_XDP_DATA_OFF) ||      \\
\t\t    (__kprog_abi_kind == KPROG_ABI_KIND_SKB &&             \\
\t\t     __kprog_abi_offset == KPROG_ABI_SKB_DATA_OFF))        \\
\t\t\t__kprog_abi_tag = (PACKET);                         \\
\t\telse if ((__kprog_abi_kind == KPROG_ABI_KIND_XDP &&        \\
\t\t          __kprog_abi_offset == KPROG_ABI_XDP_DATA_END_OFF) || \\
\t\t         (__kprog_abi_kind == KPROG_ABI_KIND_SKB &&        \\
\t\t          __kprog_abi_offset == KPROG_ABI_SKB_DATA_END_OFF)) \\
\t\t\t__kprog_abi_tag = (PACKET_END);                     \\
\t\t__kprog_abi_tag;                                           \\
\t}})

#endif
"""


def check(path: Path, expected: str) -> None:
    if not path.is_file() or path.read_text() != expected:
        raise SystemExit(f"generated ABI-load contract is stale: {path}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = load_spec()
    outputs = ((LEAN_PATH, render_lean(spec)), (C_PATH, render_c(spec)))
    if args.check:
        for path, expected in outputs:
            check(path, expected)
        return
    for path, contents in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents)


if __name__ == "__main__":
    main()
