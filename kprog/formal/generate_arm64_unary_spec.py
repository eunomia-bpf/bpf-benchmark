#!/usr/bin/env python3
"""Generate the shared AArch64 MVN/NEG unary value contract.

The generated Lean definition `GeneratedArm64Unary.value` and the C macro
`KPROG_ARM64_UNARY_VALUE` implement the two unary values the simulator applies
to a source register:

  - MVN: the bitwise complement of the source;
  - NEG: the two's-complement negation of the source.

Both the value and the destination write are width-aware: the result is
narrowed to the destination width (ARM64_WIDTH_32 or ARM64_WIDTH_64), exactly
the step `ARM64_SIM_L_WRITE_REG_WIDTH` performs on the value the C macro
produces. The contract therefore carries the `ARM64_OP_MVN`/`ARM64_OP_NEG`
opcode numbers, which `load()` re-checks against kprog/arm64/arm64_sim.h.

The C macro evaluates the value exactly once and writes no NZCV; the result is
the width-narrowed 64-bit value the caller stores back into the destination.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_unary_spec.json"
SIM_HEADER = ROOT.parent / "arm64/arm64_sim.h"
LEAN = ROOT / "KProgFormal/GeneratedArm64Unary.lean"
CHEADER = ROOT / "generated/arm64_unary.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64Unary",
    "operations": [
        {"name": "mvn", "code": 15, "macro": "ARM64_OP_MVN"},
        {"name": "neg", "code": 16, "macro": "ARM64_OP_NEG"},
    ],
}

OPCODE_DEFINE = re.compile(
    r"^#define\s+(ARM64_OP_[A-Z0-9_]+)\s+0x([0-9a-fA-F]+)U\s*$", re.M)

# C bodies. Each arm computes the raw 64-bit unary value; the destination
# narrowing is applied afterwards through KPROG_ARM64_WIDTH_MASK, so the macro
# result is exactly what WRITE_REG_WIDTH would store.
C_BODY = {
    "mvn": "\t\t\t__kprog_a64_un_result = ~__kprog_a64_un_value & "
           "__kprog_a64_un_wmask;",
    "neg": "\t\t\t__kprog_a64_un_result = "
           "(__u64)(0ULL - __kprog_a64_un_value) & __kprog_a64_un_wmask;",
}


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 unary specification: {data!r}")
    ops = EXPECTED["operations"]
    names = [row["name"] for row in ops]
    if names != ["mvn", "neg"]:
        raise SystemExit(f"invalid arm64 unary order: {ops!r}")
    if [row["macro"] for row in ops] != [
            "ARM64_OP_" + row["name"].upper() for row in ops]:
        raise SystemExit(f"invalid arm64 unary macros: {ops!r}")
    opcodes = {name: int(value, 16)
               for name, value in OPCODE_DEFINE.findall(SIM_HEADER.read_text())}
    if not opcodes:
        raise SystemExit(
            f"no ARM64_OP_* opcode definitions found in {SIM_HEADER}")
    for row in ops:
        if opcodes.get(row["macro"]) != row["code"]:
            raise SystemExit(
                "arm64 unary opcodes drift from kprog/arm64/"
                f"arm64_sim.h: spec={row['macro']}={row['code']:#x} "
                f"sim={row['macro']}={opcodes.get(row['macro'])}")
    return ops


def render_lean(ops: list[dict]) -> str:
    ctors = "\n".join(f"  | {row['name']}" for row in ops)
    codes = "\n".join(f"  | .{row['name']} => {row['code']}" for row in ops)
    mnemonics = "\n".join(
        f"  | .{row['name']} => \"{row['name'].upper()}\"" for row in ops)
    arms = {
        # MVN: the destination-width complement; `narrow` keeps only the low
        # `bits width` lanes, exactly the C `& __kprog_a64_un_wmask`.
        "mvn": (
            "  | .mvn =>\n"
            "    narrow (~~~src) width"),
        # NEG: the destination-width two's-complement negation; `0 - src`
        # wrapped at 64 bits then narrowed to the destination width.
        "neg": (
            "  | .neg =>\n"
            "    narrow (0 - src) width"),
    }
    body = "\n".join(arms[row["name"]] for row in ops)
    return f'''-- Generated by generate_arm64_unary_spec.py from arm64_unary_spec.json.
import Init.Data.BitVec
import KProgFormal.GeneratedArm64Width
namespace KProgFormal.GeneratedArm64Unary
open KProgFormal.GeneratedArm64Width (Width narrow)
/-- The two AArch64 unary values the simulator applies to a source register. -/
inductive Unary where
{ctors}
deriving DecidableEq, Repr
/-- The ARM64_OP_* opcode number the unary value carries in arm64_sim.h. -/
def code : Unary -> Nat
{codes}
/-- The AArch64 mnemonic of the unary value. -/
def mnemonic : Unary -> String
{mnemonics}
/-- Shared AArch64 unary value, narrowed to the destination width. MVN is the
complement of the source; NEG is its two's-complement negation. Both apply the
shared width `narrow`, exactly the C `& __kprog_a64_un_wmask` step. -/
def value (op : Unary) (src : BitVec 64) (width : Width) : BitVec 64 :=
  match op with
{body}
/-- The unary handlers write no NZCV, so the flag state threads through
unchanged. -/
def flagsUnchanged (op : Unary) : Bool :=
  match op with
  | .mvn => true
  | .neg => true
end KProgFormal.GeneratedArm64Unary
'''


def render_c(ops: list[dict]) -> str:
    codes = "\n".join(
        f"_Static_assert({row['macro']} == {row['code']}U, "
        '"arm64 unary code drift");'
        for row in ops)
    handled = " || \\\n\t".join(
        f"((OP) == {row['macro']})" for row in ops)
    coverage = "\n".join(
        f"_Static_assert(KPROG_ARM64_UNARY_HANDLED({row['macro']}), "
        '"arm64 unary coverage drift");'
        for row in ops)
    body = [
        "\t({",
        "\t\t__u64 __kprog_a64_un_op = (OP);",
        "\t\t__u64 __kprog_a64_un_value = (VALUE);",
        "\t\t__u64 __kprog_a64_un_width = (WIDTH);",
        "\t\t__u64 __kprog_a64_un_wmask = "
        "KPROG_ARM64_WIDTH_MASK(__kprog_a64_un_width);",
        "\t\t__u64 __kprog_a64_un_result = 0;",
        "",
        "\t\tswitch (__kprog_a64_un_op) {",
    ]
    for row in ops:
        body.append(f"\t\tcase {row['code']}U:                          ")
        body.append(C_BODY[row["name"]])
        body.append("\t\t\tbreak;")
    body += [
        "\t\tdefault:",
        "\t\t\tUNSUPPORTED;",
        "\t\t\tbreak;",
        "\t\t}",
        "\t\t__kprog_a64_un_result;",
        "\t})",
    ]
    continued = " \\\n".join(body)
    return f'''/* Generated by generate_arm64_unary_spec.py from arm64_unary_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_UNARY_H
#define KPROG_FORMAL_GENERATED_ARM64_UNARY_H
/*
 * The two arms are the AArch64 unary values the simulator applies to a source
 * register: MVN (bitwise complement) and NEG (two's-complement negation). Each
 * result is masked to the destination width, exactly the narrowing the caller's
 * register write performs. The complement/negation are inlined, so this header
 * calls no hand-written helper. An opcode outside the two reaches the
 * caller-supplied unsupported arm.
 */
#include "arm64_width.h"
{codes}
#define KPROG_ARM64_UNARY_HANDLED(OP)                                       \\
\t({handled})
{coverage}
/*
 * The numeric case labels 15U and 16U track the ARM64_OP_MVN/NEG values
 * defined in kprog/arm64/arm64_sim.h. OP is the opcode, VALUE the source
 * register contents and WIDTH the destination width code. VALUE is evaluated
 * exactly once and no arm writes NZCV. The result is the width-narrowed raw
 * 64-bit value the caller writes back.
 */
#define KPROG_ARM64_UNARY_VALUE(OP, VALUE, WIDTH, UNSUPPORTED)             \\
{continued}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    ops = load()
    for path, expected in ((LEAN, render_lean(ops)), (CHEADER, render_c(ops))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 unary contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
