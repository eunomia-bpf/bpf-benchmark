#!/usr/bin/env python3
"""Generate the shared AArch64 conditional-select pointer-path contract.

The conditional-select handler (`KPROG_ARM64_CSEL_HANDLED`) writes the
destination register through one of two register writes. The plain `CSEL` at
doubleword width is the only one that copies a source register's *provenance
tag* into the destination, through `ARM64_SIM_L_WRITE_REG_PTR_TAG`; every other
family member (CINC/CSET/CINV/CSINV/CSINC/CSETM/CSNEG) and every sub-word width
computes a fresh scalar and writes it through the tag-dropping width-narrowed
register write. This was inlined as `(OP) == ARM64_OP_CSEL && width == 64`; which
write path runs is the generated contract.

The generated Lean `GeneratedArm64CselPtr.ptrTagPath` and the C macro
`KPROG_ARM64_CSEL_PTR_TAG_PATH` implement that Boolean selection over the family
opcode table in `arm64_csel_spec.json` (the single source of truth for the eight
opcodes); the opcode numbers are re-checked against
kprog/arm64/arm64_sim.h, so a drift there fails `--check`.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_csel_ptr_spec.json"
FAMILY_SPEC = ROOT / "arm64_csel_spec.json"
SIM_HEADER = ROOT.parent / "arm64/arm64_sim.h"
LEAN = ROOT / "KProgFormal/GeneratedArm64CselPtr.lean"
CHEADER = ROOT / "generated/arm64_csel_ptr.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64CselPtr",
    "family_spec": "arm64_csel_spec.json",
    "pointer_rule": "ptr_tag_iff_csel_and_w64",
    "pointer_op": "csel",
}

OPCODE_DEFINE = re.compile(
    r"^#define\s+(ARM64_OP_[A-Z0-9_]+)\s+0x([0-9a-fA-F]+)U\s*$", re.M)


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 csel-ptr specification: {data!r}")
    family = json.loads(FAMILY_SPEC.read_text())
    ops = family.get("operations", [])
    if [row["name"] for row in ops] != [
            "csel", "cinc", "cset", "cinv", "csinv", "csinc", "csetm", "csneg"]:
        raise SystemExit(f"invalid arm64 csel family order: {ops!r}")
    pointer = [row for row in ops if row["name"] == EXPECTED["pointer_op"]]
    if len(pointer) != 1:
        raise SystemExit(
            f"arm64 csel-ptr pointer op {EXPECTED['pointer_op']!r} not unique")
    opcodes = {name: int(value, 16)
               for name, value in OPCODE_DEFINE.findall(SIM_HEADER.read_text())}
    if not opcodes:
        raise SystemExit(
            f"no ARM64_OP_* opcode definitions found in {SIM_HEADER}")
    for row in ops:
        if opcodes.get(row["macro"]) != row["code"]:
            raise SystemExit(
                "arm64 csel-ptr opcodes drift from "
                "kprog/arm64/arm64_sim.h: "
                f"spec={row['macro']}={row['code']} "
                f"sim={opcodes.get(row['macro'])}")
    return ops


def render_lean(ops: list[dict]) -> str:
    ptr = next(row for row in ops if row["name"] == EXPECTED["pointer_op"])
    arms = "\n".join(
        f"  | .{row['name']}, .w64 => "
        f"{'true' if row['name'] == ptr['name'] else 'false'}"
        for row in ops)
    return f'''-- Generated by generate_arm64_csel_ptr_spec.py from arm64_csel_ptr_spec.json.
import KProgFormal.GeneratedArm64Csel
import KProgFormal.GeneratedArm64Width
namespace KProgFormal.GeneratedArm64CselPtr
open KProgFormal.GeneratedArm64Csel (Csel)
open KProgFormal.GeneratedArm64Width (Width)
/-- Whether this (conditional-select, width) pair takes the tag-copy register
write (`ARM64_SIM_L_WRITE_REG_PTR_TAG`, copying the selected source register's
provenance tag) rather than the tag-dropping width-narrowed scalar write. Only
the plain `CSEL` at doubleword width carries a source provenance tag through:
CINC/CSET/CINV/CSINV/CSINC/CSETM/CSNEG compute a fresh scalar, and any sub-word
width is a scalar narrowing, so both drop the tag. -/
def ptrTagPath (op : Csel) (width : Width) : Bool :=
  match op, width with
{arms}
  | _, _ => false
end KProgFormal.GeneratedArm64CselPtr
'''


def render_c(ops: list[dict]) -> str:
    ptr = next(row for row in ops if row["name"] == EXPECTED["pointer_op"])
    codes = "\n".join(
        f'_Static_assert({row["macro"]} == {row["code"]}U, '
        '"arm64 csel-ptr code drift");' for row in ops)
    cases = []
    for row in ops:
        cases.append(f"\t\tcase {row['code']}U:")
        if row["name"] == ptr["name"]:
            cases.append("\t\t\t__kprog_a64_cp_path = "
                         "(__kprog_a64_cp_width == ARM64_WIDTH_64);")
        else:
            cases.append("\t\t\t__kprog_a64_cp_path = 0;")
        cases.append("\t\t\tbreak;")
    body = [
        "\t({",
        "\t\t__u64 __kprog_a64_cp_op = (OP);",
        "\t\t__u64 __kprog_a64_cp_width = (WIDTH);",
        "\t\t__u64 __kprog_a64_cp_path = 0;",
        "",
        "\t\tswitch (__kprog_a64_cp_op) {",
    ] + cases + [
        "\t\tdefault:",
        "\t\t\tUNSUPPORTED;",
        "\t\t\tbreak;",
        "\t\t}",
        "\t\t__kprog_a64_cp_path;",
        "\t})",
    ]
    continued = " \\\n".join(body)
    return f'''/* Generated by generate_arm64_csel_ptr_spec.py from arm64_csel_ptr_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_CSEL_PTR_H
#define KPROG_FORMAL_GENERATED_ARM64_CSEL_PTR_H
/*
 * The pointer-path decision shared by the eight AArch64 conditional-select
 * opcodes: whether the destination is written by the tag-copy register write
 * (which carries the selected source register's provenance) or by a
 * width-narrowed scalar write (which drops it). Only the plain CSEL at
 * doubleword width preserves provenance. An opcode outside the family reaches
 * the caller-supplied unsupported arm.
 */
#include "arm64_width.h"
{codes}
/*
 * OP is one of the eight ARM64_OP_CS* codes and WIDTH the access width code; OP
 * and WIDTH are each read once. The result is 1 when the destination must be
 * written through ARM64_SIM_L_WRITE_REG_PTR_TAG (copying the selected source
 * register's tag) and 0 when it must be written through
 * ARM64_SIM_L_WRITE_REG_WIDTH (dropping the tag).
 */
#define KPROG_ARM64_CSEL_PTR_TAG_PATH(OP, WIDTH, UNSUPPORTED)               \\
{continued}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    ops = load()
    outputs = ((LEAN, render_lean(ops)), (CHEADER, render_c(ops)))
    for path, expected in outputs:
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 csel-ptr contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
