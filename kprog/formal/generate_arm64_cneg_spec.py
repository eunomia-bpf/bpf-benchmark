#!/usr/bin/env python3
"""Generate the shared AArch64 condition-gated negation (CNEG) contract.

The generated Lean definition `GeneratedArm64Cneg.value` and the C macro
`KPROG_ARM64_CNEG_VALUE` implement the one AArch64 CNEG value the simulator
applies to a source register: the two's-complement negation of the source,
selected by an already evaluated condition result.

  - taken:      the source is negated (`0 - src`);
  - not taken:  the source passes through unchanged.

The negation is width-aware: the raw 64-bit result is narrowed to the
destination width (ARM64_WIDTH_32 or ARM64_WIDTH_64), exactly the step
`ARM64_SIM_L_WRITE_REG_WIDTH` performs on the value the C macro produces. The
contract therefore carries the `ARM64_OP_CNEG` opcode number, which `load()`
re-checks against kprog/arm64/arm64_sim.h.

The C macro evaluates the source and the condition exactly once and writes no
NZCV; the result is the width-narrowed 64-bit value the caller stores back into
the destination.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_cneg_spec.json"
SIM_HEADER = ROOT.parent / "arm64/arm64_sim.h"
LEAN = ROOT / "KProgFormal/GeneratedArm64Cneg.lean"
CHEADER = ROOT / "generated/arm64_cneg.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64Cneg",
    "operations": [
        {"name": "cneg", "code": 65, "macro": "ARM64_OP_CNEG"},
    ],
}

OPCODE_DEFINE = re.compile(
    r"^#define\s+(ARM64_OP_[A-Z0-9_]+)\s+0x([0-9a-fA-F]+)U\s*$", re.M)

# The C arm computes the raw 64-bit value; the destination narrowing is applied
# afterwards through KPROG_ARM64_WIDTH_MASK, so the macro result is exactly what
# WRITE_REG_WIDTH would store.
C_BODY = "\t\t\t__kprog_a64_cneg_result = (__kprog_a64_cneg_taken ? " \
         "(__u64)(0ULL - __kprog_a64_cneg_value) " \
         ": __kprog_a64_cneg_value) & __kprog_a64_cneg_wmask;"


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 cneg specification: {data!r}")
    ops = EXPECTED["operations"]
    names = [row["name"] for row in ops]
    if names != ["cneg"]:
        raise SystemExit(f"invalid arm64 cneg order: {ops!r}")
    if [row["macro"] for row in ops] != [
            "ARM64_OP_" + row["name"].upper() for row in ops]:
        raise SystemExit(f"invalid arm64 cneg macros: {ops!r}")
    opcodes = {name: int(value, 16)
               for name, value in OPCODE_DEFINE.findall(SIM_HEADER.read_text())}
    if not opcodes:
        raise SystemExit(
            f"no ARM64_OP_* opcode definitions found in {SIM_HEADER}")
    for row in ops:
        if opcodes.get(row["macro"]) != row["code"]:
            raise SystemExit(
                "arm64 cneg opcodes drift from kprog/arm64/"
                f"arm64_sim.h: spec={row['macro']}={row['code']:#x} "
                f"sim={row['macro']}={opcodes.get(row['macro'])}")
    return ops


def render_lean(ops: list[dict]) -> str:
    ctors = "\n".join(f"  | {row['name']}" for row in ops)
    codes = "\n".join(f"  | .{row['name']} => {row['code']}" for row in ops)
    mnemonics = "\n".join(
        f"  | .{row['name']} => \"{row['name'].upper()}\"" for row in ops)
    # CNEG: the destination-width negation selected on the condition; `narrow`
    # keeps only the low `bits width` lanes, exactly the C `& wmask` step.
    arms = "\n".join(
        "  | .cneg =>\n"
        "    narrow (if taken then 0 - src else src) width" for row in ops)
    return f'''-- Generated by generate_arm64_cneg_spec.py from arm64_cneg_spec.json.
import Init.Data.BitVec
import KProgFormal.GeneratedArm64Width
namespace KProgFormal.GeneratedArm64Cneg
open KProgFormal.GeneratedArm64Width (Width narrow)
/-- The AArch64 condition-gated negation value the simulator applies to a
source register. -/
inductive Cneg where
{ctors}
deriving DecidableEq, Repr
/-- The ARM64_OP_* opcode number the value carries in arm64_sim.h. -/
def code : Cneg -> Nat
{codes}
/-- The AArch64 mnemonic of the value. -/
def mnemonic : Cneg -> String
{mnemonics}
/-- Shared AArch64 CNEG value, narrowed to the destination width. `taken` is the
already evaluated condition result; on `taken` the source is negated, otherwise
it passes through. Both arms apply the shared width `narrow`, exactly the C
`& __kprog_a64_cneg_wmask` step. -/
def value (op : Cneg) (taken : Bool) (src : BitVec 64) (width : Width)
    : BitVec 64 :=
  match op with
{arms}
/-- The CNEG handler writes no NZCV, so the flag state threads through
unchanged. -/
def flagsUnchanged (op : Cneg) : Bool :=
  match op with
  | .cneg => true
end KProgFormal.GeneratedArm64Cneg
'''


def render_c(ops: list[dict]) -> str:
    codes = "\n".join(
        f"_Static_assert({row['macro']} == {row['code']}U, "
        '"arm64 cneg code drift");'
        for row in ops)
    handled = " || \\\n\t".join(
        f"((OP) == {row['macro']})" for row in ops)
    coverage = "\n".join(
        f"_Static_assert(KPROG_ARM64_CNEG_HANDLED({row['macro']}), "
        '"arm64 cneg coverage drift");'
        for row in ops)
    body = [
        "\t({",
        "\t\t__u64 __kprog_a64_cneg_op = (OP);",
        "\t\t__u64 __kprog_a64_cneg_value = (VALUE);",
        "\t\tint __kprog_a64_cneg_taken = (TAKEN) ? 1 : 0;",
        "\t\t__u64 __kprog_a64_cneg_width = (WIDTH);",
        "\t\t__u64 __kprog_a64_cneg_wmask = "
        "KPROG_ARM64_WIDTH_MASK(__kprog_a64_cneg_width);",
        "\t\t__u64 __kprog_a64_cneg_result = 0;",
        "",
        "\t\tswitch (__kprog_a64_cneg_op) {",
    ]
    for row in ops:
        body.append(f"\t\tcase {row['code']}U:                          ")
        body.append(C_BODY)
        body.append("\t\t\tbreak;")
    body += [
        "\t\tdefault:",
        "\t\t\tUNSUPPORTED;",
        "\t\t\tbreak;",
        "\t\t}",
        "\t\t__kprog_a64_cneg_result;",
        "\t})",
    ]
    continued = " \\\n".join(body)
    return f'''/* Generated by generate_arm64_cneg_spec.py from arm64_cneg_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_CNEG_H
#define KPROG_FORMAL_GENERATED_ARM64_CNEG_H
/*
 * The one arm is the AArch64 condition-gated negation (CNEG): on a taken
 * condition the source is negated, otherwise it passes through unchanged. The
 * result is masked to the destination width, exactly the narrowing the caller's
 * register write performs. The negation is inlined, so this header calls no
 * hand-written helper. An opcode outside the family reaches the caller-supplied
 * unsupported arm.
 */
#include "arm64_width.h"
{codes}
#define KPROG_ARM64_CNEG_HANDLED(OP)                                        \\
\t({handled})
{coverage}
/*
 * The numeric case label 65U tracks the ARM64_OP_CNEG value defined in
 * kprog/arm64/arm64_sim.h. OP is the opcode, VALUE the source register
 * contents, TAKEN the already evaluated condition result and WIDTH the
 * destination width code. VALUE and TAKEN are each evaluated exactly once and
 * no arm writes NZCV. The result is the width-narrowed raw 64-bit value the
 * caller writes back.
 */
#define KPROG_ARM64_CNEG_VALUE(OP, VALUE, TAKEN, WIDTH, UNSUPPORTED)        \\
{continued}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    ops = load()
    for path, expected in ((LEAN, render_lean(ops)), (CHEADER, render_c(ops))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 cneg contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
