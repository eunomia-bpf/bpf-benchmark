#!/usr/bin/env python3
"""Generate the shared AArch64 ADRP relocation-tag selection contract.

The generated Lean definition `GeneratedArm64Adrp.tag` and the C macro
`KPROG_ARM64_ADRP_TAG` implement the one decision the two ADRP opcodes make in
the simulator: which provenance tag the page-address write carries. The `GOT`
form tags the register as a relocation address (`ARM64_SIM_TAG_RELOC_ADDR`) and
the `RODATA` form as a read-only-data address (`ARM64_SIM_TAG_RODATA_ADDR`); the
immediate itself is written by the surrounding register write, which stays in the
trusted computing base.

The independent Lean statement indexes the tag by a Boolean rather than by the
opcode, so the refinement is not a restatement: it proves the generated two-arm
match equals the same selection expressed as a base plus an offset. The opcode
numbers and the tag values are re-checked at generation time against
kprog/arm64/arm64_sim.h, so a drift there fails `--check`.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_adrp_spec.json"
SIM_HEADER = ROOT.parent / "arm64/arm64_sim.h"
SIM_LOCAL_HEADER = ROOT.parent / "arm64/arm64_sim_local_bpf.h"
LEAN = ROOT / "KProgFormal/GeneratedArm64Adrp.lean"
CHEADER = ROOT / "generated/arm64_adrp.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64Adrp",
    "operations": [
        {"name": "got", "code": 38, "macro": "ARM64_OP_ADRP_GOT",
         "tag": 7, "tag_macro": "ARM64_SIM_TAG_RELOC_ADDR"},
        {"name": "rodata", "code": 39, "macro": "ARM64_OP_ADRP_RODATA",
         "tag": 8, "tag_macro": "ARM64_SIM_TAG_RODATA_ADDR"},
    ],
}

OPCODE_DEFINE = re.compile(
    r"^#define\s+(ARM64_OP_[A-Z0-9_]+)\s+0x([0-9a-fA-F]+)U\s*$", re.M)
TAG_DEFINE = re.compile(
    r"^#define\s+(ARM64_SIM_TAG_[A-Z0-9_]+)\s+(\d+)U\s*$", re.M)


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 adrp specification: {data!r}")
    ops = EXPECTED["operations"]
    if [row["name"] for row in ops] != ["got", "rodata"]:
        raise SystemExit(f"invalid arm64 adrp order: {ops!r}")
    if [row["tag"] for row in ops] != [7, 8]:
        raise SystemExit(f"invalid arm64 adrp tag table: {ops!r}")
    opcodes = {name: int(value, 16)
               for name, value in OPCODE_DEFINE.findall(SIM_HEADER.read_text())}
    tags = {name: int(value)
            for name, value in TAG_DEFINE.findall(SIM_LOCAL_HEADER.read_text())}
    if not opcodes or not tags:
        raise SystemExit(
            f"no ARM64_OP_*/tag definitions found in {SIM_HEADER}")
    for row in ops:
        if opcodes.get(row["macro"]) != row["code"]:
            raise SystemExit(
                "arm64 adrp opcodes drift from kprog/arm64/arm64_sim.h: "
                f"spec={row['macro']}={row['code']:#x} "
                f"sim={opcodes.get(row['macro'])}")
        if tags.get(row["tag_macro"]) != row["tag"]:
            raise SystemExit(
                "arm64 adrp tags drift from kprog/arm64/"
                "arm64_sim_local_bpf.h: "
                f"spec={row['tag_macro']}={row['tag']} "
                f"sim={tags.get(row['tag_macro'])}")
    return ops

def render_lean(ops: list[dict]) -> str:
    ctors = "\n".join(f"  | {row['name']}" for row in ops)
    codes = "\n".join(f"  | .{row['name']} => {row['code']}" for row in ops)
    mnemonics = "\n".join(f"  | .{row['name']} => \"ADRP\"" for row in ops)
    tags = "\n".join(f"  | .{row['name']} => {row['tag']}" for row in ops)
    is_got = "\n".join(
        f"  | .{row['name']} => {'true' if row['name'] == 'got' else 'false'}"
        for row in ops)
    return f'''-- Generated by generate_arm64_adrp_spec.py from arm64_adrp_spec.json.
import Std
namespace KProgFormal.GeneratedArm64Adrp
/-- The two ADRP relocation kinds the simulator tags. -/
inductive Op where
{ctors}
deriving DecidableEq, Repr
/-- The ARM64_OP_* opcode number the relocation kind carries in arm64_sim.h. -/
def code : Op -> Nat
{codes}
/-- The AArch64 mnemonic of the relocation kind. -/
def mnemonic : Op -> String
{mnemonics}
/-- Whether this kind is the GOT relocation. -/
def isGot : Op -> Bool
{is_got}
/-- The provenance tag the page-address write carries, a value of the
ARM64_SIM_TAG_* table in arm64_sim_local_bpf.h. -/
def tag : Op -> Nat
{tags}
end KProgFormal.GeneratedArm64Adrp
'''


def render_c(ops: list[dict]) -> str:
    codes = "\n".join(
        f"_Static_assert({row['macro']} == {row['code']}U, "
        '"arm64 adrp code drift");'
        for row in ops)
    tagstatic = "\n".join(
        f"_Static_assert({row['tag_macro']} == {row['tag']}U, "
        '"arm64 adrp tag drift");'
        for row in ops)
    handled = " || \\\n\t".join(
        f"((OP) == {row['macro']})" for row in ops)
    coverage = "\n".join(
        f"_Static_assert(KPROG_ARM64_ADRP_HANDLED({row['macro']}), "
        '"arm64 adrp coverage drift");'
        for row in ops)
    body = [
        "\t({",
        "\t\t__u8 __kprog_a64_adrp_op = (OP);",
        "\t\t__u8 __kprog_a64_adrp_tag = 0;",
        "",
        "\t\tswitch (__kprog_a64_adrp_op) {",
    ]
    for row in ops:
        body.append(f"\t\tcase {row['code']}U:                          ")
        body.append(f"\t\t\t__kprog_a64_adrp_tag = {row['tag_macro']};")
        body.append("\t\t\tbreak;")
    body += [
        "\t\tdefault:",
        "\t\t\tUNSUPPORTED;",
        "\t\t\tbreak;",
        "\t\t}",
        "\t\t__kprog_a64_adrp_tag;",
        "\t})",
    ]
    continued = " \\\n".join(body)
    return f'''/* Generated by generate_arm64_adrp_spec.py from arm64_adrp_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_ADRP_H
#define KPROG_FORMAL_GENERATED_ARM64_ADRP_H
/*
 * The two arms are the AArch64 ADRP relocation kinds: the GOT form tags the
 * page-address write as a relocation address and the RODATA form as a
 * read-only-data address. The selected tag is returned to the caller, which
 * performs the register write; the immediate page address itself stays outside
 * this contract. An opcode outside the family reaches the caller-supplied
 * unsupported arm.
 */
{codes}
{tagstatic}
#define KPROG_ARM64_ADRP_HANDLED(OP)                                        \\
\t({handled})
{coverage}
/*
 * The numeric case labels 38U and 39U track the ARM64_OP_ADRP_GOT and
 * ARM64_OP_ADRP_RODATA values defined in kprog/arm64/arm64_sim.h. OP is
 * the opcode; it is read once and no arm writes NZCV. The result is the
 * ARM64_SIM_TAG_* provenance tag the surrounding register write attaches.
 */
#define KPROG_ARM64_ADRP_TAG(OP, UNSUPPORTED)                               \\
{continued}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    ops = load()
    for path, expected in ((LEAN, render_lean(ops)), (CHEADER, render_c(ops))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 adrp contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
