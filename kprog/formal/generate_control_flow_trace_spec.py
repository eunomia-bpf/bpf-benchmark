#!/usr/bin/env python3
"""Generate the shared whole-program control-flow trace contract.

The generated Lean definitions `GeneratedControlFlowTrace.emittedStep` / `walk` /
`walkPolicy` and the C macro `KPROG_CONTROL_FLOW_EDGE_NEXT` name the *composition*
of the per-edge conditional-transfer emission into a whole-program path: a trace
is a list of conditional edges, each edge is emitted in one of the two directions
(`GeneratedX86BranchEmit.shape`), and the emitted code threads the program counter
through the walked edges.

  * `emittedStep` is the next program counter one conditional edge selects, given
    the already-evaluated predicate, the direction shape and the edge's candidate
    addresses; the fall-through advance is the generated `fallthrough_step`;
  * `walk` folds that step over a whole path;
  * `walkPolicy` folds it while recomputing the direction shape at every edge from
    the running program counter and the edge target, exactly as the simulator
    calls `KPROG_{X86,ARM64}_BRANCH_BACKWARD` at each conditional transfer.

`GeneratedControlFlowTrace.walk`/`walkPolicy` are the emitted-code walk;
`KProgFormal/ControlFlowTrace.lean` proves both equal `archWalk`, the
architectural walk stated over the shared `branchPc` next-PC model, for every
direction shape and every per-edge policy. This chains the per-edge
`x86_branch_emit_refines` / `arm64_branch_emit_refines` facts into a whole-program
trace theorem, so the simulator's per-edge direction computation is a
machine-checked whole-program no-op.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "control_flow_trace_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedControlFlowTrace.lean"
CHEADER = ROOT / "generated/control_flow_trace.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "controlFlowTrace",
    "composer": "sequential",
    "fallthrough_step": 1,
}


def load() -> dict:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid control-flow trace specification: {data!r}")
    if data["composer"] != "sequential":
        raise SystemExit(f"invalid control-flow trace composer: {data!r}")
    if data["fallthrough_step"] != 1:
        raise SystemExit(f"invalid control-flow fall-through step: {data!r}")
    return data


def render_lean(data: dict) -> str:
    step = data["fallthrough_step"]
    return f'''-- Generated by generate_control_flow_trace_spec.py from control_flow_trace_spec.json.
import KProgFormal.GeneratedX86BranchEmit
namespace KProgFormal.GeneratedControlFlowTrace
open GeneratedX86BranchEmit (Shape)
/-- The sequential fall-through advance the emitted code performs between adjacent
edges: a not-taken conditional transfer resumes at the next program counter. -/
def fallthroughStep : Nat := {step}
/-- The next program counter one conditional edge selects, given the
already-evaluated predicate, the direction shape and the edge's candidate
addresses. The fall-through resume is `pc + fallthroughStep`; both directions
select `target` exactly when the predicate holds, so this is the emitted-code
counterpart of the architectural `branchPc` at one edge. -/
def emittedStep (s : Shape) (taken : Bool) (pc target : Nat) : Nat :=
  GeneratedX86BranchEmit.nextPc s taken (pc + fallthroughStep) target
/-- Walk a whole trace: fold the emitted step over a path of conditional edges,
threading the program counter. -/
def walk (s : Shape) (pc : Nat) : List (Bool × Nat) -> Nat
  | [] => pc
  | (taken, target) :: rest => walk s (emittedStep s taken pc target) rest
/-- Walk a whole trace while recomputing the direction shape at every edge from
the running program counter and the edge target -- exactly as the simulator calls
its direction macro at each conditional transfer, so the shape may vary edge to
edge. -/
def walkPolicy (policy : Nat -> Nat -> Shape) (pc : Nat)
    (steps : List (Bool × Nat)) : Nat :=
  match steps with
  | [] => pc
  | (taken, target) :: rest =>
      walkPolicy policy (emittedStep (policy pc target) taken pc target) rest
end KProgFormal.GeneratedControlFlowTrace
'''


def render_c(data: dict) -> str:
    step = data["fallthrough_step"]
    return f'''/* Generated by generate_control_flow_trace_spec.py from control_flow_trace_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_CONTROL_FLOW_TRACE_H
#define KPROG_FORMAL_GENERATED_CONTROL_FLOW_TRACE_H
/*
 * Whole-program control-flow trace: the emitted code walks a path of conditional
 * edges, and at each edge selects the next program counter from the direction
 * shape, the already-evaluated predicate and the edge's candidate addresses. A
 * not-taken conditional transfer resumes at the next program counter; the
 * fall-through advance is this constant. KProgFormal/ControlFlowTrace.lean
 * proves the walked program counter equals the architectural branchPc walk for
 * every direction shape and every per-edge direction policy.
 */
#define KPROG_CONTROL_FLOW_SEQUENTIAL_STEP {step}U
#define KPROG_CONTROL_FLOW_EDGE_NEXT(TAKEN, PC, TARGET)                     \\
\t((unsigned long)(((TAKEN) != 0U) ? (TARGET)                             \\
\t                                 : ((PC) + KPROG_CONTROL_FLOW_SEQUENTIAL_STEP)))
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = load()
    for path, expected in ((LEAN, render_lean(data)), (CHEADER, render_c(data))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated control-flow trace contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
