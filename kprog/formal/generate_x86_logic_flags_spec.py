#!/usr/bin/env python3
"""Generate the shared x86 logical-result flag transition for Lean and C."""
import argparse, json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_logic_flags_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86LogicFlags.lean"
CHEADER = ROOT / "generated/x86_logic_flags.h"
NAMES = ["cf", "zf", "sf", "of"]

def load():
    data = json.loads(SPEC.read_text())
    if set(data) != {"schema_version", "operation", "flags"} or data["schema_version"] != 1 or data["operation"] != "x86LogicFlags":
        raise SystemExit(f"invalid x86 logical-flags specification: {data!r}")
    if list(data["flags"]) != NAMES:
        raise SystemExit(f"non-canonical x86 logical flag list: {data['flags']!r}")
    for expr in data["flags"].values():
        if expr not in ({"op":"const","value":False}, {"op":"input","name":"zero"}, {"op":"input","name":"sign"}):
            raise SystemExit(f"invalid x86 logical flag expression: {expr!r}")
    return data["flags"]

def expr(value, lean):
    if value["op"] == "input": return value["name"] if lean else value["name"].upper()
    return ("true" if value["value"] else "false") if lean else ("1" if value["value"] else "0")

def render_lean(flags):
    fields = "\n".join(f"  {name} : Bool" for name in NAMES)
    values = ", ".join(f"{name} := {expr(flags[name], True)}" for name in NAMES)
    return f'''-- Generated by generate_x86_logic_flags_spec.py from x86_logic_flags_spec.json.
import Std
namespace KProgFormal.GeneratedX86LogicFlags
structure Flags where
{fields}
  deriving DecidableEq, Repr
def eval (zero sign : Bool) : Flags := {{ {values} }}
end KProgFormal.GeneratedX86LogicFlags
'''

def render_c(flags):
    assigns = " \\\n".join(f"\t\t(C_{name.upper()}) = {expr(flags[name], False)};" for name in NAMES)
    return f'''/* Generated by generate_x86_logic_flags_spec.py from x86_logic_flags_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_LOGIC_FLAGS_H
#define KPROG_FORMAL_GENERATED_X86_LOGIC_FLAGS_H
#define KPROG_X86_SET_LOGIC_FLAGS(C_CF, C_ZF, C_SF, C_OF, ZERO, SIGN)       \\
\tdo {{ \\
{assigns} \\
\t}} while (0)
#endif
'''

def main():
    parser = argparse.ArgumentParser(); parser.add_argument("--check", action="store_true"); args = parser.parse_args()
    flags = load()
    for path, expected in ((LEAN, render_lean(flags)), (CHEADER, render_c(flags))):
        if args.check:
            if not path.is_file() or path.read_text() != expected: raise SystemExit(f"generated x86 logical-flags contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True); path.write_text(expected)
if __name__ == "__main__": main()
