#!/usr/bin/env python3
"""Generate the shared x86 shift-count masking contract for Lean and C."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_shift_count_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86ShiftCount.lean"
C_HEADER = ROOT / "generated/x86_shift_count.h"
EXPECTED = {
    "schema_version": 1,
    "operation": "x86ShiftCount",
    "non_64_mask": 31,
    "width_64_mask": 63,
}


def load() -> None:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 shift-count specification: {data!r}")


def render_lean() -> str:
    return '''-- Generated by generate_x86_shift_count_spec.py from x86_shift_count_spec.json.
import KProgFormal.GeneratedX86Width
namespace KProgFormal.GeneratedX86ShiftCount
def mask (width : GeneratedX86Width.Width) : BitVec 64 :=
  if width = .w64 then 63 else 31
def count (rhs : BitVec 64) (width : GeneratedX86Width.Width) : BitVec 64 :=
  BitVec.and rhs (mask width)
end KProgFormal.GeneratedX86ShiftCount
'''


def render_c() -> str:
    return '''/* Generated by generate_x86_shift_count_spec.py from x86_shift_count_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_SHIFT_COUNT_H
#define KPROG_FORMAL_GENERATED_X86_SHIFT_COUNT_H
#define KPROG_X86_SHIFT_COUNT(RHS, WIDTH)                                   \
\t((RHS) & ((WIDTH) == X86_WIDTH_64 ? 63U : 31U))
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    load()
    for path, expected in ((LEAN, render_lean()), (C_HEADER, render_c())):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(f"generated x86 shift-count contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
