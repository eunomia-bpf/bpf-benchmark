#!/usr/bin/env python3
"""Generate full native-width wrapping stack offsets; never alias at 2^32."""
import argparse
import json
from pathlib import Path

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64StackIndex",
    "index_base": "bias",
    "index_step": 1,
    "accumulate": "wrapping64",
    "index_mask_bits": 64,
}

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "contracts/arm64_stack_index_spec.json"
LEAN = ROOT / "KProgFormal/Generated/GeneratedArm64StackIndex.lean"
CHEADER = ROOT / "generated/arm64_stack_index.h"


def load() -> dict:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 stack-index specification: {data!r}")
    return EXPECTED


def render_lean(spec: dict) -> str:
    shift = spec["index_mask_bits"]
    return f'''-- Generated by generate_arm64_stack_index_spec.py from arm64_stack_index_spec.json.
import Std
namespace KProgFormal.GeneratedArm64StackIndex
/-- The arena byte index for an abstract frame offset `off` in an arena biased
by `bias` bytes: `bias + off`, retained in the C helpers' {shift}-bit index
type. `bias` is `ARM64_SIM_STACK_BIAS`. -/
def index (bias off : BitVec 64) : BitVec 64 :=
  bias + off
/-- The biased byte offset the stack pointer helper adds to the arena base, in
the C `(__s64)` index width (64 bits): `bias + off`, untruncated. -/
def ptrIndex (bias off : BitVec 64) : BitVec 64 :=
  bias + off
end KProgFormal.GeneratedArm64StackIndex
'''


def render_c(spec: dict) -> str:
    return '''/* Generated by generate_arm64_stack_index_spec.py from arm64_stack_index_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_STACK_INDEX_H
#define KPROG_FORMAL_GENERATED_ARM64_STACK_INDEX_H
#define KPROG_ARM64_STACK_INDEX(OFF, BIAS)                                  \\
\t((__u64)(BIAS) + (__u64)(OFF))
#define KPROG_ARM64_STACK_PTR_INDEX(OFF, BIAS)                              \\
\t((__s64)((__u64)(BIAS) + (__u64)(OFF)))
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    load()
    for path, expected in ((LEAN, render_lean(EXPECTED)), (CHEADER, render_c(EXPECTED))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 stack-index contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
