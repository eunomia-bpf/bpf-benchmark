#!/usr/bin/env python3
"""Generate the shared AArch64 little-endian byte-ladder load contract.

The generated Lean definition `GeneratedArm64LoadBytes.value` and the C macro
`KPROG_ARM64_LOAD_BYTES` implement the value the simulator assembles when it
reads a byte/halfword/word/doubleword from memory: the low `width` bytes of the
little-endian word, in their own byte lanes, with every higher byte zero.

The width is one of the four architectural `ARM64_WIDTH_*` codes, so the ladder
has a closed set of byte counts (1, 2, 4, 8) and no unsupported case. The C macro
reads the bytes through the supplied pointer exactly once each and writes no
NZCV.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "contracts/arm64_load_bytes_spec.json"
LEAN = ROOT / "KProgFormal/Generated/GeneratedArm64LoadBytes.lean"
CHEADER = ROOT / "generated/arm64_load_bytes.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64LoadBytes",
    "widths": [
        {"name": "w8", "bytes": 1, "width_code": 1},
        {"name": "w16", "bytes": 2, "width_code": 2},
        {"name": "w32", "bytes": 4, "width_code": 4},
        {"name": "w64", "bytes": 8, "width_code": 8},
    ],
}


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 load-bytes specification: {data!r}")
    widths = EXPECTED["widths"]
    if [row["name"] for row in widths] != ["w8", "w16", "w32", "w64"]:
        raise SystemExit(f"invalid arm64 load-bytes order: {widths!r}")
    if [row["bytes"] for row in widths] != [1, 2, 4, 8]:
        raise SystemExit(f"invalid arm64 load-bytes counts: {widths!r}")
    if [row["width_code"] for row in widths] != [1, 2, 4, 8]:
        raise SystemExit(f"invalid arm64 load-bytes codes: {widths!r}")
    return widths


def render_lean(widths: list[dict]) -> str:
    ctors = "\n".join(f"  | {row['name']}" for row in widths)
    codes = "\n".join(
        f"  | .{row['name']} => {row['width_code']}" for row in widths)
    byte_counts = "\n".join(
        f"  | .{row['name']} => {row['bytes']}" for row in widths)
    # value: assemble `n` byte lanes of the 64-bit source word. The source is
    # the raw byte sequence packed into a 64-bit word; lane i is byte i.
    arms = "\n".join(
        "  | .{name} =>\n    {expr}".format(
            name=row["name"],
            expr=" |||\n    ".join(
                f"(((value >>> {8 * i}) &&& 0xff) <<< {8 * i})"
                for i in range(row["bytes"])))
        for row in widths)
    return f'''-- Generated by generate_arm64_load_bytes_spec.py from arm64_load_bytes_spec.json.
import Std
namespace KProgFormal.GeneratedArm64LoadBytes
/-- The four architectural load widths, carrying their `ARM64_WIDTH_*` code and
their byte count. -/
inductive LoadWidth where
{ctors}
deriving DecidableEq, Repr
/-- The ARM64_WIDTH_* code of the load width. -/
def widthCode : LoadWidth -> Nat
{codes}
/-- The number of bytes the load width reads. -/
def byteCount : LoadWidth -> Nat
{byte_counts}
/-- Shared AArch64 little-endian load value: assemble the width's bytes from the
packed 64-bit source word into their own lanes, zeroing every higher lane. -/
def value (width : LoadWidth) (value : BitVec 64) : BitVec 64 :=
  match width with
{arms}
end KProgFormal.GeneratedArm64LoadBytes
'''


def render_c(widths: list[dict]) -> str:
    codes = "\n".join(
        f"_Static_assert(ARM64_WIDTH_{row['name'][1:]} == {row['width_code']}U, "
        '"arm64 load-bytes width code drift");'
        for row in widths)
    access = ["#if defined(__bpf__) || defined(__BPF__)",
        "#define KPROG_ARM64_LOAD_ACCESS(BITS, ADDR, OUT) " + chr(92),
        '\t__asm__ __volatile__("%0 = *(u" #BITS " *)(%1 + 0)" : "=r"(OUT) : "r"(ADDR) : "memory")',
        "#define KPROG_ARM64_LOAD_ACCESS_OFFSET(BITS, BASE, OFFSET, OUT) " + chr(92),
        "\tdo { " + chr(92),
        "\t\tif (__builtin_constant_p(OFFSET) && (OFFSET) >= -32768 && (OFFSET) <= 32767) { " + chr(92),
        "\t\t\tif ((OFFSET) < 0) " + chr(92),
        '\t\t\t\t__asm__ __volatile__("%0 = *(u" #BITS " *)(%1 - %2)" : "=r"(OUT) : "r"(BASE), "i"(-(OFFSET)) : "memory"); ' + chr(92),
        "\t\t\telse " + chr(92),
        '\t\t\t\t__asm__ __volatile__("%0 = *(u" #BITS " *)(%1 + %2)" : "=r"(OUT) : "r"(BASE), "i"(OFFSET) : "memory"); ' + chr(92),
        "\t\t} else " + chr(92),
        "\t\t\tKPROG_ARM64_LOAD_ACCESS(BITS, (const __u8 *)(BASE) + (OFFSET), OUT); " + chr(92),
        "\t} while (0)",
        "#else"]
    for row in widths:
        bits = row["bytes"] * 8
        access.append(f"typedef __u{bits} kprog_arm64_load_u{bits}_unaligned __attribute__((aligned(1),may_alias));")
    access += ["#define KPROG_ARM64_LOAD_ACCESS(BITS, ADDR, OUT) " + chr(92),
        "\t((OUT) = *(volatile const kprog_arm64_load_u##BITS##_unaligned *)(ADDR))",
        "#define KPROG_ARM64_LOAD_ACCESS_OFFSET(BITS, BASE, OFFSET, OUT) " + chr(92),
        "\tKPROG_ARM64_LOAD_ACCESS(BITS, (const __u8 *)(BASE) + (OFFSET), OUT)", "#endif"]
    access_text = "\n".join(access)
    body = [
        "\t({",
        "\t\tvolatile const __u8 *__kprog_a64_lb_addr =",
        "\t\t\t(volatile const __u8 *)(ADDR);",
        "\t\t__u8 __kprog_a64_lb_width = (WIDTH);",
        "\t\t__u64 __kprog_a64_lb_value;",
        "\t\tif (__kprog_a64_lb_width == ARM64_WIDTH_64)",
        "\t\t\tKPROG_ARM64_LOAD_ACCESS_OFFSET(64, __kprog_a64_lb_addr, (OFFSET), __kprog_a64_lb_value);",
        "\t\telse if (__kprog_a64_lb_width >= ARM64_WIDTH_32)",
        "\t\t\tKPROG_ARM64_LOAD_ACCESS_OFFSET(32, __kprog_a64_lb_addr, (OFFSET), __kprog_a64_lb_value);",
        "\t\telse if (__kprog_a64_lb_width >= ARM64_WIDTH_16)",
        "\t\t\tKPROG_ARM64_LOAD_ACCESS_OFFSET(16, __kprog_a64_lb_addr, (OFFSET), __kprog_a64_lb_value);",
        "\t\telse",
        "\t\t\tKPROG_ARM64_LOAD_ACCESS_OFFSET(8, __kprog_a64_lb_addr, (OFFSET), __kprog_a64_lb_value);",
        "\t\t__kprog_a64_lb_value;",
        "\t})",
    ]
    continued = " \\\n".join(body)
    return f'''/* Generated by generate_arm64_load_bytes_spec.py from arm64_load_bytes_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_LOAD_BYTES_H
#define KPROG_FORMAL_GENERATED_ARM64_LOAD_BYTES_H
/*
 * AArch64 little-endian load value: assemble the width's bytes from memory into
 * their own lanes, zeroing every higher lane. The width set is closed (the four
 * ARM64_WIDTH_* codes) and every case is handled, so there is no unsupported
 * arm.
 */
{codes}
{access_text}
/*
 * ADDR + OFFSET is the source address; WIDTH is one of the four ARM64_WIDTH_*
 * codes. One access reads exactly that width; no NZCV is written. The
 * result is the raw 64-bit value; the caller applies the destination width to
 * the *value* separately for the sign-extending loads.
 */
#define KPROG_ARM64_LOAD_BYTES_OFFSET(ADDR, OFFSET, WIDTH)                                 \\
{continued}
/* Keep constant displacements inside the BPF memory instruction: some context
 * types forbid pointer arithmetic even for a fixed, valid field offset.
 * Variable or out-of-encoding-range offsets use ordinary address arithmetic.
 * Both forms read exactly WIDTH bytes at ADDR + OFFSET. */
#define KPROG_ARM64_LOAD_BYTES(ADDR, WIDTH) \\
\tKPROG_ARM64_LOAD_BYTES_OFFSET((ADDR), 0, (WIDTH))
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    widths = load()
    for path, expected in ((LEAN, render_lean(widths)),
                           (CHEADER, render_c(widths))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 load-bytes contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
