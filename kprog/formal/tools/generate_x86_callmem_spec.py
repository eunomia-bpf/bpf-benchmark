#!/usr/bin/env python3
"""Generate exact-count copy/fill selectors; no simulator iteration bound."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
SPEC=ROOT/'contracts/x86_callmem_spec.json'
LEAN=ROOT/'KProgFormal/Generated/GeneratedX86CallMem.lean'
CHEADER=ROOT/'generated/x86_callmem.h'
ROWS=[('callMemcpy','X86_OP_CALL_MEMCPY','0x3f','copy','imm'),
      ('callMemcpyReg','X86_OP_CALL_MEMCPY_REG','0x46','copy','reg'),
      ('callMemset','X86_OP_CALL_MEMSET','0x3c','fill','imm'),
      ('callMemsetReg','X86_OP_CALL_MEMSET_REG','0x45','fill','reg')]
EXPECTED=dict(schema_version=1,operation='x86CallMemHandler',selector='opcode_kind_then_count_source',
 opcode_rows=[dict(op=o,op_define=d,op_code=c,kind=k,count_source=n) for o,d,c,k,n in ROWS],
 kind_rows=[dict(kind=k,kind_define='KPROG_X86_CALLMEM_'+k.upper()) for k in ('copy','fill')],
 count_source_rows=[dict(count_source=n,count_define='KPROG_X86_CALLMEM_COUNT_'+n.upper()) for n in ('imm','reg')])
def render_lean():
 nl=chr(10)
 ops=nl.join('  | '+r[0] for r in ROWS)
 kinds=nl.join('  | .'+r[0]+' => .'+r[3] for r in ROWS)
 counts=nl.join('  | .'+r[0]+' => .'+r[4] for r in ROWS)
 return f'''-- Generated by generate_x86_callmem_spec.py from x86_callmem_spec.json.
import Std
namespace KProgFormal.GeneratedX86CallMem
inductive Op where
{ops}
deriving DecidableEq, Repr
inductive Kind where
  | copy
  | fill
deriving DecidableEq, Repr
def kind : Op -> Kind
{kinds}
inductive CountSource where
  | imm
  | reg
deriving DecidableEq, Repr
/-- Length is the full artifact or RDX value. No independent cap is imposed. -/
def countSource : Op -> CountSource
{counts}
end KProgFormal.GeneratedX86CallMem
'''
def render_c():
 lines=['/* Generated by generate_x86_callmem_spec.py from x86_callmem_spec.json. */',
 '#ifndef KPROG_FORMAL_GENERATED_X86_CALLMEM_H','#define KPROG_FORMAL_GENERATED_X86_CALLMEM_H',
 '/* Every byte below the native count is processed; there is no simulator cap. */']
 lines += [f'_Static_assert({d} == {c}U, "x86 callmem {o} opcode drift");' for o,d,c,k,n in ROWS]
 lines += ['#define KPROG_X86_CALLMEM_COPY 0U','#define KPROG_X86_CALLMEM_FILL 1U',
 '#define KPROG_X86_CALLMEM_COUNT_IMM 0U','#define KPROG_X86_CALLMEM_COUNT_REG 1U',
 '#define KPROG_X86_CALLMEM_KIND(OP_IS_COPY) ((OP_IS_COPY) ? KPROG_X86_CALLMEM_COPY : KPROG_X86_CALLMEM_FILL)',
 '#define KPROG_X86_CALLMEM_COUNT_SOURCE(OP_IS_REG) ((OP_IS_REG) ? KPROG_X86_CALLMEM_COUNT_REG : KPROG_X86_CALLMEM_COUNT_IMM)',
 '#endif']
 return chr(10).join(lines)+chr(10)
def main():
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
 data=json.loads(SPEC.read_text())
 if data!=EXPECTED:raise SystemExit('invalid exact-count x86 callmem specification')
 for path,expected in [(LEAN,render_lean()),(CHEADER,render_c())]:
  if args.check:
   if path.read_text()!=expected:raise SystemExit('stale x86 callmem contract: '+str(path))
  else:path.write_text(expected)
if __name__=='__main__':main()
