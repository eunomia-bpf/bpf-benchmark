#!/usr/bin/env python3
"""Lower actual x86 encoder field construction to the universal producer model."""
import argparse
import hashlib
from pathlib import Path
import re
from extract_native_link_source import normalized

FORMAL = Path(__file__).resolve().parents[1]
REPO = FORMAL.parents[1]
OUTPUT = FORMAL/'KProgFormal/Generated/NativeLinkFields.lean'


def extract(root):
    path='kprog/x86/native_lab/native_link/src/x86.rs'
    source=(root/path).read_text()
    contracts=[
    '''let sym_base = blob.len();''',
    '''let off_in_sym = encoded.new_instruction_offsets.get(i).copied()
       .ok_or_else(|| anyhow!("missing offset for instruction {i} in {}", sym.name))? as usize;''',
    '''patches.push(PatchInfo { global_offset: sym_base + off_in_sym, kind: kind.clone(), });''',
    '''blob.extend_from_slice(&encoded.code_buffer);''',
    '''PatchKind::HelperPointer { target_addr } => {
       relocs.push(RelocRecord { offset: u32::try_from(p.global_offset+2)?,
        kind: NATIVE_LAB_RELOC_HELPER_POINTER, target: *target_addr, });
    }''',
    '''PatchKind::MapImmediate { name, imm_offset } => {
       let offset = p.global_offset.checked_add(*imm_offset)
        .ok_or_else(|| anyhow!("map immediate patch offset overflow"))?;
       if offset + 8 > blob.len() {
        bail!("map immediate patch at off {offset:#x} exceeds blob size");
       }
       map_patches.push(MapPatch { name: name.clone(), offset, });
    }''',
    '''for (id,target) in targets {
       relocs.push(RelocRecord { offset: u32::try_from(table+usize::try_from(*id)?*8)?,
        kind: NATIVE_LAB_RELOC_HELPER_POINTER, target: *target, });
    }''',
    ]
    code=normalized(source)
    for contract in contracts:
        if normalized(contract) not in code:
            raise ValueError('encoder field source grammar changed: '+contract.splitlines()[0])
    helper=re.search(r'PatchKind::HelperPointer \{ target_addr \} => \{\s*relocs.push\(RelocRecord \{\s*offset: u32::try_from\(p.global_offset\+(\d+)\)',source)[1]
    stride=re.search(r'offset: u32::try_from\(table\+usize::try_from\(\*id\)\?\*(\d+)\)',source)[1]
    kind=re.search(r'const NATIVE_LAB_RELOC_HELPER_POINTER: u32 = (\d+);',source)[1]
    receipt=hashlib.sha256('\n'.join(map(normalized,contracts)).encode()).hexdigest()
    return f'''-- Generated by tools/extract_native_field_source.py from {path}.
-- Recognized source field constructors sha256={receipt}
import KProgFormal.NativeLinkProducer
namespace KProgFormal.NativeLinkFields
open Reference NativeLinkProducer

def helperKind : BitVec 32 := {kind}
def helperField : Nat := {helper}
def helperTableStride : Nat := {stride}

/-- The encoded symbol starts at current blob length; iced provides its
instruction coordinate and the selected producer adds its field coordinate. -/
def fieldRecord (before : List Byte) (instruction : BitVec 32) (field : Nat)
    (kind : BitVec 32) (target : Word) : Record :=
  ⟨BitVec.ofNat 32 (before.length+instruction.toNat+field),kind,target⟩

def helperRecord (before : List Byte) (instruction : BitVec 32) (target : Word) : Record :=
  fieldRecord before instruction helperField helperKind target

/-- Complete checked map-immediate offset construction in the selected branch. -/
def mapFieldRecord (before : List Byte) (instruction : BitVec 32) (field : Nat)
    (kind : BitVec 32) (target : Word) : Record :=
  fieldRecord before instruction field kind target

/-- Sparse helper table slots retain their full selected target and ID. -/
def helperTableRecord (table identity : Nat) (target : Word) : Record :=
  ⟨BitVec.ofNat 32 (table+identity*helperTableStride),helperKind,target⟩
end KProgFormal.NativeLinkFields
'''


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check',action='store_true')
    p.add_argument('--root',type=Path,default=REPO)
    args=p.parse_args()
    expected=extract(args.root)
    if args.check:
        if OUTPUT.read_text()!=expected: raise SystemExit('native field extraction requires regeneration')
    else:OUTPUT.write_text(expected)
    print('native encoder field extraction: PASS')

if __name__=='__main__':main()
