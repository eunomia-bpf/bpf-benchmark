#!/usr/bin/env python3
"""Generate the shared AArch64 little-endian byte-ladder store contract.

The generated Lean definition `GeneratedArm64StoreBytes.image` and the C macro
`KPROG_ARM64_STORE_BYTES` implement what the simulator leaves in memory when it
writes a byte/halfword/word/doubleword to an address: the covered little-endian
word is the width's low bytes of the value, with every higher byte zero; the
bytes above the width are not touched.

The width is one of the four architectural `ARM64_WIDTH_*` codes, so the ladder
has a closed set of byte counts (1, 2, 4, 8) and no unsupported case. The C
macro writes each of the width's bytes through the supplied pointer exactly
once and writes no NZCV.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "contracts/arm64_store_bytes_spec.json"
LEAN = ROOT / "KProgFormal/Generated/GeneratedArm64StoreBytes.lean"
CHEADER = ROOT / "generated/arm64_store_bytes.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64StoreBytes",
    "widths": [
        {"name": "w8", "bytes": 1, "width_code": 1},
        {"name": "w16", "bytes": 2, "width_code": 2},
        {"name": "w32", "bytes": 4, "width_code": 4},
        {"name": "w64", "bytes": 8, "width_code": 8},
    ],
}


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 store-bytes specification: {data!r}")
    widths = EXPECTED["widths"]
    if [row["name"] for row in widths] != ["w8", "w16", "w32", "w64"]:
        raise SystemExit(f"invalid arm64 store-bytes order: {widths!r}")
    if [row["bytes"] for row in widths] != [1, 2, 4, 8]:
        raise SystemExit(f"invalid arm64 store-bytes counts: {widths!r}")
    if [row["width_code"] for row in widths] != [1, 2, 4, 8]:
        raise SystemExit(f"invalid arm64 store-bytes codes: {widths!r}")
    return widths


def render_lean(widths: list[dict]) -> str:
    ctors = "\n".join(f"  | {row['name']}" for row in widths)
    codes = "\n".join(
        f"  | .{row['name']} => {row['width_code']}" for row in widths)
    byte_counts = "\n".join(
        f"  | .{row['name']} => {row['bytes']}" for row in widths)
    # image: the covered little-endian word after a store of `n` bytes, as the
    # value masked to the width's low `n` bytes (every higher byte zero).
    arms = "\n".join(
        "  | .{name} =>\n    {expr}".format(
            name=row["name"],
            expr=("value" if row["bytes"] == 8
                  else f"value &&& 0x{(1 << (8 * row['bytes'])) - 1:x}"))
        for row in widths)
    return f'''-- Generated by generate_arm64_store_bytes_spec.py from arm64_store_bytes_spec.json.
import Std
namespace KProgFormal.GeneratedArm64StoreBytes
/-- The four architectural store widths, carrying their `ARM64_WIDTH_*` code
and their byte count. -/
inductive StoreWidth where
{ctors}
deriving DecidableEq, Repr
/-- The ARM64_WIDTH_* code of the store width. -/
def widthCode : StoreWidth -> Nat
{codes}
/-- The number of bytes the store width writes. -/
def byteCount : StoreWidth -> Nat
{byte_counts}
/-- Shared AArch64 little-endian store image: the covered word after writing the
width's low bytes of the value into memory, every higher byte zero. -/
def image (width : StoreWidth) (value : BitVec 64) : BitVec 64 :=
  match width with
{arms}
end KProgFormal.GeneratedArm64StoreBytes
'''


def render_c(widths: list[dict]) -> str:
    codes = "\n".join(
        f"_Static_assert(ARM64_WIDTH_{row['name'][1:]} == {row['width_code']}U, "
        '"arm64 store-bytes width code drift");'
        for row in widths)
    access = ["#if defined(__bpf__) || defined(__BPF__)",
        "#define KPROG_ARM64_STORE_ACCESS(BITS, ADDR, VALUE) " + chr(92),
        '\t__asm__ __volatile__("*(u" #BITS " *)(%0 + 0) = %1" : : "r"(ADDR), "r"(VALUE) : "memory")',
        "#else"]
    for row in widths:
        bits = row["bytes"] * 8
        access.append(f"typedef __u{bits} kprog_arm64_store_u{bits}_unaligned __attribute__((aligned(1),may_alias));")
    access += ["#define KPROG_ARM64_STORE_ACCESS(BITS, ADDR, VALUE) " + chr(92),
        "\t(*(volatile kprog_arm64_store_u##BITS##_unaligned *)(ADDR) = (__u##BITS)(VALUE))", "#endif"]
    access_text = "\n".join(access)
    body = [
        "\tdo {",
        "\t\tvolatile __u8 *__kprog_a64_sb_addr =",
        "\t\t\t(volatile __u8 *)(ADDR);",
        "\t\t__u8 __kprog_a64_sb_width = (WIDTH);",
        "\t\t__u64 __kprog_a64_sb_value =",
        "\t\t\tKPROG_ARM64_APPLY_WIDTH((VALUE), __kprog_a64_sb_width);",
        "\t\tif (__kprog_a64_sb_width == ARM64_WIDTH_64)",
        "\t\t\tKPROG_ARM64_STORE_ACCESS(64, __kprog_a64_sb_addr, __kprog_a64_sb_value);",
        "\t\telse if (__kprog_a64_sb_width >= ARM64_WIDTH_32)",
        "\t\t\tKPROG_ARM64_STORE_ACCESS(32, __kprog_a64_sb_addr, __kprog_a64_sb_value);",
        "\t\telse if (__kprog_a64_sb_width >= ARM64_WIDTH_16)",
        "\t\t\tKPROG_ARM64_STORE_ACCESS(16, __kprog_a64_sb_addr, __kprog_a64_sb_value);",
        "\t\telse",
        "\t\t\tKPROG_ARM64_STORE_ACCESS(8, __kprog_a64_sb_addr, __kprog_a64_sb_value);",
        "\t} while (0)",
    ]
    continued = " \\\n".join(body)
    return f'''/* Generated by generate_arm64_store_bytes_spec.py from arm64_store_bytes_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_STORE_BYTES_H
#define KPROG_FORMAL_GENERATED_ARM64_STORE_BYTES_H
/*
 * AArch64 little-endian store: write the width's low bytes of VALUE into memory
 * little-endian, leaving every higher byte untouched. The width set is closed
 * (the four ARM64_WIDTH_* codes) and every case is handled, so there is no
 * unsupported arm.
 */
{codes}
{access_text}
/*
 * ADDR is the (byte) destination address; WIDTH is one of the four
 * ARM64_WIDTH_* codes; VALUE is the raw source value (masked to the width
 * here). One access writes exactly that width; no NZCV is written.
 */
#define KPROG_ARM64_STORE_BYTES(ADDR, WIDTH, VALUE)                         \\
{continued}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    widths = load()
    for path, expected in ((LEAN, render_lean(widths)),
                           (CHEADER, render_c(widths))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 store-bytes contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
