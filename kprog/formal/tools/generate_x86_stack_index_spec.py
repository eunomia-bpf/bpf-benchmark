#!/usr/bin/env python3
"""Generate native-width wrapping frame indexes; distinct high bits must survive."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "contracts/x86_stack_index_spec.json"
LEAN = ROOT / "KProgFormal/Generated/GeneratedX86StackIndex.lean"
CHEADER = ROOT / "generated/x86_stack_index.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "x86StackIndex",
    "index_base": "capacity",
    "index_step": 1,
    "accumulate": "wrapping64",
    "index_mask_bits": 64,
}


def load() -> dict:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 stack-index specification: {data!r}")
    return EXPECTED


def render_lean(spec: dict) -> str:
    return '''-- Generated by generate_x86_stack_index_spec.py from x86_stack_index_spec.json.
import Std
namespace KProgFormal.GeneratedX86StackIndex
/-- The arena byte index for an abstract frame offset `off` in an arena of
`capacity` bytes: `off + capacity`, retained in the C helpers' 64-bit index
type. `capacity` is `X86_SIM_STACK_BYTES`. -/
def index (capacity off : BitVec 64) : BitVec 64 :=
  capacity + off
end KProgFormal.GeneratedX86StackIndex
'''


def render_c(spec: dict) -> str:
    return '''/* Generated by generate_x86_stack_index_spec.py from x86_stack_index_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_STACK_INDEX_H
#define KPROG_FORMAL_GENERATED_X86_STACK_INDEX_H
#define KPROG_X86_STACK_INDEX(OFF, CAPACITY)                               \\
\t((__u64)(OFF) + (__u64)(CAPACITY))
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    load()
    for path, expected in ((LEAN, render_lean(EXPECTED)), (CHEADER, render_c(EXPECTED))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(f"generated x86 stack-index contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
