#!/usr/bin/env python3
"""Extend the preserved four-flag condition/decode APIs with parity."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXPECTED = {"schema_version": 1, "operation": "x86FullCondition", "parity": [
    {"name": "p", "code": 10, "invert": False, "alias": "pe"},
    {"name": "np", "code": 11, "invert": True, "alias": "po"}]}


def outputs(spec):
    legacy = json.loads((ROOT / "contracts/x86_cond_spec.json").read_text())["conditions"]
    decode = json.loads((ROOT / "contracts/x86_cc_decode_spec.json").read_text())
    codes = [c["code"] for c in legacy] + [c["code"] for c in spec["parity"]]
    if sorted(codes) != list(range(16)):
        raise SystemExit("full conditions must cover each native code exactly once")
    lines = ["-- Generated by generate_x86_full_condition_spec.py.",
        "import KProgFormal.Generated.GeneratedX86Setcc", "namespace KProgFormal.GeneratedX86FullCondition",
        "def eval (code : BitVec 32) (cf zf sf of pf : Bool) : Option Bool :="]
    for c in spec["parity"]:
        lines.append(f"  if code = {c['code']} then some ({'!' if c['invert'] else ''}pf) else")
    for c in legacy:
        lines.append(f"  if code = {c['code']} then some (GeneratedX86Cond.eval cf zf sf of .{c['name']}) else")
    lines += ["  none", "", "def matched (code : BitVec 8) : BitVec 16 :="]
    for c in spec["parity"]:
        lines.append(f"  if code = {c['code']} then {c['code']} else")
    lines += ["  GeneratedX86Setcc.condMatchedCode code", "end KProgFormal.GeneratedX86FullCondition", ""]
    header = ["/* Generated by generate_x86_full_condition_spec.py. */",
        "#ifndef KPROG_FORMAL_GENERATED_X86_FULL_CONDITION_H",
        "#define KPROG_FORMAL_GENERATED_X86_FULL_CONDITION_H", '#include "x86_cond.h"', '#include "x86_setcc.h"']
    for c in spec["parity"]:
        header.append(f'_Static_assert(X86_CC_{c["name"].upper()} == {c["code"]}U, "native parity code drift");')
    header.append("#define KPROG_X86_EVAL_FULL_CC(CC, CF, ZF, SF, OF, PF) \\")
    for n, c in enumerate(spec["parity"]):
        header.append(f"    {'(' if n == 0 else ''}(CC) == X86_CC_{c['name'].upper()} ? {'!' if c['invert'] else ''}(PF) : \\")
    header += ["    KPROG_X86_EVAL_CC((CC), (CF), (ZF), (SF), (OF)))",
        "#define KPROG_X86_FULL_CONDITION_MATCHED(CC) \\"]
    for n, c in enumerate(spec["parity"]):
        header.append(f"    {'(' if n == 0 else ''}(CC) == X86_CC_{c['name'].upper()} ? {c['code']}U : \\")
    header += ["    (KPROG_X86_SETCC_COND_MATCHED(CC)))", "#endif", ""]
    python = ["# Generated by generate_x86_full_condition_spec.py.",
        "from generated_x86_cc_decode import CC_AUX as LEGACY_CC_AUX", "CC_AUX = {**LEGACY_CC_AUX,"]
    extra = [c["name"] for c in legacy if c["name"] not in decode["suffixes"]]
    for family in decode["families"]:
        for name in extra:
            python.append(f'    "{family}{name}": "X86_CC_{name.upper()}",')
        for c in spec["parity"]:
            for name in [c["name"], c["alias"]]:
                python.append(f'    "{family}{name}": "X86_CC_{c["name"].upper()}",')
    python += ["}", ""]
    return {ROOT / "KProgFormal/Generated/GeneratedX86FullCondition.lean": "\n".join(lines),
        ROOT / "generated/x86_full_condition.h": "\n".join(header),
        ROOT.parent / "x86/micro-prog/generated_x86_full_condition.py": "\n".join(python)}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = json.loads((ROOT / "contracts/x86_full_condition_spec.json").read_text())
    if spec != EXPECTED:
        raise SystemExit("invalid full x86 condition contract")
    for path, text in outputs(spec).items():
        if args.check:
            if not path.is_file() or path.read_text() != text:
                raise SystemExit(f"stale full x86 conditions: {path}")
        else:
            path.write_text(text)


if __name__ == "__main__":
    main()
