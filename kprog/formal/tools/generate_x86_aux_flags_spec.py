#!/usr/bin/env python3
"""Emit x86 low-byte even parity and nibble carry/borrow helpers for C/Lean."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "contracts/x86_aux_flags_spec.json"
EXPECTED = {"schema_version": 1, "operation": "x86AuxiliaryFlags",
            "parity": {"table": 38505, "fold_shift": 4, "index_mask": 15, "result_mask": 1},
            "auxiliary": {"mask": 16}}


def outputs(spec):
    p, auxiliary = spec["parity"], spec["auxiliary"]
    lean = f'''-- Generated by generate_x86_aux_flags_spec.py from x86_aux_flags_spec.json.
import Std
namespace KProgFormal.GeneratedX86AuxFlags
def parity (value : BitVec 64) : Bool :=
  ((({p['table']} : BitVec 64) >>> ((value ^^^ (value >>> {p['fold_shift']})) &&& {p['index_mask']})) &&& {p['result_mask']}) != 0

def auxiliary (left right result : BitVec 64) : Bool :=
  ((left ^^^ right ^^^ result) &&& {auxiliary['mask']}) != 0
end KProgFormal.GeneratedX86AuxFlags
'''
    header = f'''/* Generated by generate_x86_aux_flags_spec.py from x86_aux_flags_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_AUX_FLAGS_H
#define KPROG_FORMAL_GENERATED_X86_AUX_FLAGS_H
#define KPROG_X86_PARITY(VALUE) \\
    (({p['table']}U >> (((VALUE) ^ ((VALUE) >> {p['fold_shift']}U)) & {p['index_mask']}U)) & {p['result_mask']}U)
#define KPROG_X86_AUX_CARRY(LEFT, RIGHT, RESULT) \\
    ((((LEFT) ^ (RIGHT) ^ (RESULT)) & {auxiliary['mask']}U) != 0)
#endif
'''
    return {ROOT / "KProgFormal/Generated/GeneratedX86AuxFlags.lean": lean,
            ROOT / "generated/x86_aux_flags.h": header}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = json.loads(SPEC.read_text())
    if spec != EXPECTED:
        raise SystemExit(f"invalid x86 auxiliary flag contract: {spec!r}")
    for path, wanted in outputs(spec).items():
        if args.check:
            if not path.is_file() or path.read_text() != wanted:
                raise SystemExit(f"stale x86 auxiliary flags: {path}")
        else:
            path.write_text(wanted)


if __name__ == "__main__":
    main()
