#!/usr/bin/env python3
"""Generate the status projection of an explicit exclusive-store outcome.

The bound environment supplies failure as a Boolean for each dynamic visit.
This contract encodes its architectural zero/one status; it does not manufacture
a reservation, choose success, or establish platform atomicity and ordering.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "contracts/arm64_stlxr_spec.json"
SIM_HEADER = ROOT.parent / "arm64/arm64_sim.h"
LEAN = ROOT / "KProgFormal/Generated/GeneratedArm64Stlxr.lean"
CHEADER = ROOT / "generated/arm64_stlxr.h"

EXPECTED = {
    "schema_version": 2,
    "operation": "arm64Stlxr",
    "status_input": "failure_bool",
    "operations": [
        {"name": "stlxr", "code": 56, "macro": "ARM64_OP_STLXR"},
    ],
}

OPCODE_DEFINE = re.compile(
    r"^#define\s+(ARM64_OP_[A-Z0-9_]+)\s+0x([0-9a-fA-F]+)U\s*$", re.M)

C_BODY = "\t\t\t__kprog_a64_stlxr_result = " \
         "__kprog_a64_stlxr_failure & __kprog_a64_stlxr_wmask;"


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 stlxr specification: {data!r}")
    ops = EXPECTED["operations"]
    if [row["name"] for row in ops] != ["stlxr"]:
        raise SystemExit(f"invalid arm64 stlxr order: {ops!r}")
    if [row["macro"] for row in ops] != [
            "ARM64_OP_" + row["name"].upper() for row in ops]:
        raise SystemExit(f"invalid arm64 stlxr macros: {ops!r}")
    opcodes = {name: int(value, 16)
               for name, value in OPCODE_DEFINE.findall(SIM_HEADER.read_text())}
    if not opcodes:
        raise SystemExit(
            f"no ARM64_OP_* opcode definitions found in {SIM_HEADER}")
    for row in ops:
        if opcodes.get(row["macro"]) != row["code"]:
            raise SystemExit(
                "arm64 stlxr opcodes drift from kprog/arm64/arm64_sim.h: "
                f"spec={row['macro']}={row['code']:#x} "
                f"sim={opcodes.get(row['macro'])}")
    return ops


def render_lean(ops: list[dict]) -> str:
    ctors = "\n".join(f"  | {row['name']}" for row in ops)
    codes = "\n".join(f"  | .{row['name']} => {row['code']}" for row in ops)
    mnemonics = "\n".join(f"  | .{row['name']} => \"STLXR\"" for row in ops)
    arms = "\n".join(
        "  | .stlxr =>\n"
        "    narrow (if failure then 1 else 0) width" for row in ops)
    return f'''-- Generated by generate_arm64_stlxr_spec.py from arm64_stlxr_spec.json.
import Init.Data.BitVec
import KProgFormal.Generated.GeneratedArm64Width
namespace KProgFormal.GeneratedArm64Stlxr
open KProgFormal.GeneratedArm64Width (Width narrow)
/-- The one AArch64 exclusive-store status the simulator writes back. -/
inductive Stlxr where
{ctors}
deriving DecidableEq, Repr
/-- The ARM64_OP_* opcode number the status carries in arm64_sim.h. -/
def code : Stlxr -> Nat
{codes}
/-- The AArch64 mnemonic of the status. -/
def mnemonic : Stlxr -> String
{mnemonics}
/-- Architectural status for the explicit environment outcome, narrowed to
the destination width. False is success/zero, true is failure/one. -/
def value (op : Stlxr) (width : Width) (failure : Bool) : BitVec 64 :=
  match op with
{arms}
/-- STLXR writes the status register but no NZCV, so the flag state threads
through unchanged. -/
def flagsUnchanged (op : Stlxr) : Bool :=
  match op with
  | .stlxr => true
end KProgFormal.GeneratedArm64Stlxr
'''


def render_c(ops: list[dict]) -> str:
    codes = "\n".join(
        f"_Static_assert({row['macro']} == {row['code']}U, "
        '"arm64 stlxr code drift");'
        for row in ops)
    handled = " || \\\n\t".join(
        f"((OP) == {row['macro']})" for row in ops)
    coverage = "\n".join(
        f"_Static_assert(KPROG_ARM64_STLXR_HANDLED({row['macro']}), "
        '"arm64 stlxr coverage drift");'
        for row in ops)
    body = [
        "\t({",
        "\t\t__u64 __kprog_a64_stlxr_op = (OP);",
        "\t\t__u64 __kprog_a64_stlxr_width = (WIDTH);",
        "\t\t__u64 __kprog_a64_stlxr_failure = !!(FAILURE);",
        "\t\t__u64 __kprog_a64_stlxr_wmask = "
        "KPROG_ARM64_WIDTH_MASK(__kprog_a64_stlxr_width);",
        "\t\t__u64 __kprog_a64_stlxr_result = 0;",
        "",
        "\t\tswitch (__kprog_a64_stlxr_op) {",
    ]
    for row in ops:
        body.append(f"\t\tcase {row['code']}U:                          ")
        body.append(C_BODY)
        body.append("\t\t\tbreak;")
    body += [
        "\t\tdefault:",
        "\t\t\tUNSUPPORTED;",
        "\t\t\tbreak;",
        "\t\t}",
        "\t\t__kprog_a64_stlxr_result;",
        "\t})",
    ]
    continued = " \\\n".join(body)
    return f'''/* Generated by generate_arm64_stlxr_spec.py from arm64_stlxr_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_STLXR_H
#define KPROG_FORMAL_GENERATED_ARM64_STLXR_H
/*
 * Encode the explicitly supplied Boolean failure outcome as architectural
 * zero/one status. The caller obtains this outcome from the bound environment
 * and performs a memory write only for success. Unknown opcodes reach the
 * caller-supplied unsupported arm.
 */
#include "arm64_width.h"
{codes}
#define KPROG_ARM64_STLXR_HANDLED(OP)                                       \\
\t({handled})
{coverage}
/*
 * The numeric case label 56U tracks the ARM64_OP_STLXR value defined in
 * kprog/arm64/arm64_sim.h. OP is the opcode and WIDTH the destination
 * width code; FAILURE is a Boolean environment outcome. Each argument is read
 * once and no arm writes NZCV. The caller writes the result back at 32 bits.
 */
#define KPROG_ARM64_STLXR_VALUE(OP, WIDTH, FAILURE, UNSUPPORTED)            \\
{continued}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    ops = load()
    for path, expected in ((LEAN, render_lean(ops)), (CHEADER, render_c(ops))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 stlxr contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
