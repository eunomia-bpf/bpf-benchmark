#!/usr/bin/env python3
"""Generate the shared x86 double-precision shift contract (SHLD and SHRD).

The generated Lean definitions `GeneratedX86DoubleShift.shld` / `shrd` and the C
functions `kprog_x86_shld_value` / `kprog_x86_shrd_value` implement the two
double-precision shifts the simulator's `X86_SIM_L_EXEC_*SH*D_IMM` handlers
apply: SHLD shifts `dst` left, filling from the top of `src`; SHRD shifts `dst`
right, filling from the bottom of `src`.

Unlike the single-operand shifts, the count here is the simulator's
`KPROG_X86_SHIFT_COUNT` (masked to 63 for 64-bit and 31 otherwise), so for the
narrow widths the count can *exceed* the width and the `count >= bits` arm is
live: the result is then `src` shifted by `count - bits`. Both functions are
total over the four `X86_WIDTH_*` codes and write no flags (the handlers set them
separately).
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_doubleshift_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86DoubleShift.lean"
C_HEADER = ROOT / "generated/x86_doubleshift.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "x86DoubleShift",
    "operations": [
        {"name": "shld", "left": True},
        {"name": "shrd", "left": False},
    ],
}


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 double-shift specification: {data!r}")
    ops = EXPECTED["operations"]
    if [row["name"] for row in ops] != ["shld", "shrd"]:
        raise SystemExit(f"invalid x86 double-shift order: {ops!r}")
    if [row["left"] for row in ops] != [True, False]:
        raise SystemExit(f"invalid x86 double-shift directions: {ops!r}")
    return ops


def lean_arm(left: bool, bits: int, mask: str) -> str:
    """One match arm over the numeric width code, mirroring the C helper."""
    shift = "<<<" if left else ">>>"
    other = ">>>" if left else "<<<"
    return (f"  | {bits // 8} =>\n"
            f"      let k := shiftv &&& countMask {bits // 8}\n"
            f"      if k = 0 then dst &&& {mask}\n"
            f"      else if BitVec.ult k {bits} then "
            f"((((dst &&& {mask}) {shift} k) ||| "
            f"((src &&& {mask}) {other} ({bits} - k))) &&& {mask})\n"
            f"      else ((src &&& {mask}) {shift} (k - {bits})) &&& {mask}")


def lean_w64(left: bool) -> str:
    shift = "<<<" if left else ">>>"
    other = ">>>" if left else "<<<"
    return (f"  | 8 =>\n"
            f"      let k := shiftv &&& countMask 8\n"
            f"      if k = 0 then dst\n"
            f"      else if BitVec.ult k 64 then "
            f"((dst {shift} k) ||| (src {other} (64 - k)))\n"
            f"      else (src {shift} (k - 64))")


def render_lean(ops: list[dict]) -> str:
    widths = [(8, "0xff"), (16, "0xffff"), (32, "0xffffffff")]
    shld_arms = "\n".join(lean_arm(True, b, m) for b, m in widths)
    shrd_arms = "\n".join(lean_arm(False, b, m) for b, m in widths)
    return f'''-- Generated by generate_x86_doubleshift_spec.py from x86_doubleshift_spec.json.
namespace KProgFormal.GeneratedX86DoubleShift
/-- The width mask for an x86 width code (1/2/4/8 bytes). -/
def widthMask (widthCode : Nat) : BitVec 64 :=
  match widthCode with
  | 1 => 0xff
  | 2 => 0xffff
  | 4 => 0xffffffff
  | _ => 0xffffffffffffffff
/-- The hardware shift count mask: 63 for a 64-bit base, 31 otherwise. -/
def countMask (widthCode : Nat) : Nat :=
  if widthCode = 8 then 63 else 31
/-- The x86 SHLD result: shift `dst` left by the hardware-masked count, filling
from the top of `src`. A count at or above the width takes the whole result from
`src` shifted by the excess. -/
def shld (dst src shiftv : BitVec 64) : Nat -> BitVec 64
{shld_arms}
{lean_w64(True)}
  | _ => dst
/-- The x86 SHRD result: shift `dst` right by the hardware-masked count, filling
from the bottom of `src`. -/
def shrd (dst src shiftv : BitVec 64) : Nat -> BitVec 64
{shrd_arms}
{lean_w64(False)}
  | _ => dst
end KProgFormal.GeneratedX86DoubleShift
'''


def render_c(ops: list[dict]) -> str:
    def body(left: bool) -> str:
        shift = "<<" if left else ">>"
        other = ">>" if left else "<<"
        return (f"\t__u32 bits = KPROG_X86_WIDTH_BITS(width);\n"
                f"\t__u64 mask = KPROG_X86_WIDTH_MASK(width);\n"
                f"\t__u64 k = KPROG_X86_SHIFT_COUNT(shift_count, width);\n"
                f"\t__u64 d = dst & mask;\n"
                f"\t__u64 s = src & mask;\n"
                f"\n"
                f"\tif (k == 0)\n"
                f"\t\treturn d;\n"
                f"\tif (k >= bits)\n"
                f"\t\treturn (s {shift} (k - bits)) & mask;\n"
                f"\treturn ((d {shift} k) | (s {other} (bits - k))) & mask;")
    return f'''/* Generated by generate_x86_doubleshift_spec.py from x86_doubleshift_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_DOUBLESHIFT_H
#define KPROG_FORMAL_GENERATED_X86_DOUBLESHIFT_H
/*
 * x86 double-precision shifts. SHLD shifts `dst` left filling from the top of
 * `src`; SHRD shifts `dst` right filling from the bottom of `src`. The count is
 * the simulator's KPROG_X86_SHIFT_COUNT (63 for 64-bit, 31 otherwise), so for a
 * narrow width it can exceed the width and the `k >= bits` arm is live. Both are
 * total over the four X86_WIDTH_* codes and write no flags.
 */
static __always_inline __u64 kprog_x86_shld_value(__u64 dst, __u64 src,
                                                   __u64 shift_count,
                                                   __u8 width)
{{
{body(True)}
}}

static __always_inline __u64 kprog_x86_shrd_value(__u64 dst, __u64 src,
                                                   __u64 shift_count,
                                                   __u8 width)
{{
{body(False)}
}}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    ops = load()
    for path, expected in ((LEAN, render_lean(ops)), (C_HEADER, render_c(ops))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated x86 double-shift contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
