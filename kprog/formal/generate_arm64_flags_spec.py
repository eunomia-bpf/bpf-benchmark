#!/usr/bin/env python3
"""Generate the shared AArch64 ADD/SUB/logical NZCV transitions for Lean and C.

The AArch64 ReverseSim subset sets NZCV for three families:
  - ADD (and ADD-immediate): N=sign(res), Z=zero(res), C=unsigned carry-out,
    V=signed overflow;
  - SUB (and CMP, and SUB-immediate): N=sign(res), Z=zero(res), C=NOT borrow
    (i.e. lhs >= rhs), V=signed overflow;
  - logical (AND/ORR/EOR/BIC, MOV/TST): Cf=0, Vf=0, N=sign, Z=zero.

The generated C macro `KPROG_ARM64_SET_{ADD,SUB,LOGIC}_FLAGS` writes the four
NZCV booleans from already width-narrowed operands/result; the Lean module
exposes the same transition for the refinement theorem.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_flags_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64Flags.lean"
CHEADER = ROOT / "generated/arm64_flags.h"
EXPECTED = {
    "schema_version": 1,
    "operation": "arm64Flags",
    "families": {
        "add": {"n": "sign", "z": "zero", "c": "unsigned_carry_out",
                "v": "signed_overflow"},
        "sub": {"n": "sign", "z": "zero", "c": "not_borrow",
                "v": "signed_overflow"},
        "logical": {"n": "sign", "z": "zero", "c": "clear", "v": "clear"},
    },
    "width_rule": "zero_is_64",
    "overflow": "same_sign_operands_and_result_sign_differs_after_narrowing",
}


def load() -> None:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 flags specification: {data!r}")


def render_lean() -> str:
    return '''-- Generated by generate_arm64_flags_spec.py from arm64_flags_spec.json.
import KProgFormal.GeneratedArm64Width
namespace KProgFormal.GeneratedArm64Flags
structure Flags where
  n : Bool
  z : Bool
  c : Bool
  v : Bool
  deriving DecidableEq, Repr
/-- ADD: C is the unsigned carry out of the width-sized addition. -/
def addCarry (lhs rhs : BitVec 64) (width : GeneratedArm64Width.Width) : Bool :=
  GeneratedArm64Width.narrow lhs width > GeneratedArm64Width.mask width - GeneratedArm64Width.narrow rhs width
/-- ADD: V is set when both operands share a sign and the result differs. -/
def addOverflow (lhs rhs : BitVec 64) (width : GeneratedArm64Width.Width) : Bool :=
  let mask := GeneratedArm64Width.signMask width
  let l := GeneratedArm64Width.narrow lhs width
  let r := GeneratedArm64Width.narrow rhs width
  let res := GeneratedArm64Width.narrow (l + r) width
  ((l ^^^ r) &&& mask) == 0 && (((l ^^^ res) &&& mask) != 0)
def applyAdd (lhs rhs : BitVec 64) (width : GeneratedArm64Width.Width) : Flags :=
  let res := GeneratedArm64Width.narrow (GeneratedArm64Width.narrow lhs width
           + GeneratedArm64Width.narrow rhs width) width
  { n := GeneratedArm64Width.sign res width,
    z := res == 0,
    c := addCarry lhs rhs width,
    v := addOverflow lhs rhs width }
/-- SUB: C is NOT borrow, i.e. the unsigned `lhs >= rhs` relation. -/
def subCarry (lhs rhs : BitVec 64) (width : GeneratedArm64Width.Width) : Bool :=
  GeneratedArm64Width.narrow lhs width >= GeneratedArm64Width.narrow rhs width
/-- SUB: V is set when the operands differ in sign and the result differs. -/
def subOverflow (lhs rhs : BitVec 64) (width : GeneratedArm64Width.Width) : Bool :=
  let mask := GeneratedArm64Width.signMask width
  let l := GeneratedArm64Width.narrow lhs width
  let r := GeneratedArm64Width.narrow rhs width
  let res := GeneratedArm64Width.narrow (l - r) width
  (((l ^^^ r) &&& mask) != 0) && (((l ^^^ res) &&& mask) != 0)
def applySub (lhs rhs : BitVec 64) (width : GeneratedArm64Width.Width) : Flags :=
  let res := GeneratedArm64Width.narrow (GeneratedArm64Width.narrow lhs width
           - GeneratedArm64Width.narrow rhs width) width
  { n := GeneratedArm64Width.sign res width,
    z := res == 0,
    c := subCarry lhs rhs width,
    v := subOverflow lhs rhs width }
/-- Logical/logical-immediate: C and V are cleared. -/
def applyLogic (value : BitVec 64) (width : GeneratedArm64Width.Width) : Flags :=
  let res := GeneratedArm64Width.narrow value width
  { n := GeneratedArm64Width.sign res width, z := res == 0, c := false, v := false }
end KProgFormal.GeneratedArm64Flags
'''


def render_c() -> str:
    return r'''/* Generated by generate_arm64_flags_spec.py from arm64_flags_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_FLAGS_H
#define KPROG_FORMAL_GENERATED_ARM64_FLAGS_H
#define KPROG_ARM64_SET_ADD_FLAGS(C_N, C_Z, C_C, C_V, LHS, RHS, WIDTH)   \
	do {                                                                \
		__u64 __kprog_a64_add_mask = KPROG_ARM64_WIDTH_MASK(WIDTH);  \
		__u64 __kprog_a64_add_sign = KPROG_ARM64_WIDTH_SIGN_MASK(WIDTH);\
		__u64 __kprog_a64_add_lhs = (LHS) & __kprog_a64_add_mask;    \
		__u64 __kprog_a64_add_rhs = (RHS) & __kprog_a64_add_mask;    \
		__u64 __kprog_a64_add_res =                              \
			(__kprog_a64_add_lhs + __kprog_a64_add_rhs) &       \
			__kprog_a64_add_mask;                                \
		(C_Z) = __kprog_a64_add_res == 0;                            \
		(C_N) = (__kprog_a64_add_res & __kprog_a64_add_sign) != 0;   \
		(C_C) = __kprog_a64_add_lhs >                                  \
			__kprog_a64_add_mask - __kprog_a64_add_rhs;          \
		(C_V) = (~(__kprog_a64_add_lhs ^ __kprog_a64_add_rhs) &      \
			 (__kprog_a64_add_lhs ^ __kprog_a64_add_res) &       \
			 __kprog_a64_add_sign) != 0;                         \
	} while (0)
#define KPROG_ARM64_SET_SUB_FLAGS(C_N, C_Z, C_C, C_V, LHS, RHS, WIDTH)   \
	do {                                                                \
		__u64 __kprog_a64_sub_mask = KPROG_ARM64_WIDTH_MASK(WIDTH);  \
		__u64 __kprog_a64_sub_sign = KPROG_ARM64_WIDTH_SIGN_MASK(WIDTH);\
		__u64 __kprog_a64_sub_lhs = (LHS) & __kprog_a64_sub_mask;    \
		__u64 __kprog_a64_sub_rhs = (RHS) & __kprog_a64_sub_mask;    \
		__u64 __kprog_a64_sub_res =                              \
			(__kprog_a64_sub_lhs - __kprog_a64_sub_rhs) &       \
			__kprog_a64_sub_mask;                                \
		(C_Z) = __kprog_a64_sub_lhs == __kprog_a64_sub_rhs;          \
		(C_N) = (__kprog_a64_sub_res & __kprog_a64_sub_sign) != 0;   \
		(C_C) = __kprog_a64_sub_lhs >= __kprog_a64_sub_rhs;          \
		(C_V) = ((__kprog_a64_sub_lhs ^ __kprog_a64_sub_rhs) &       \
			 (__kprog_a64_sub_lhs ^ __kprog_a64_sub_res) &       \
			 __kprog_a64_sub_sign) != 0;                         \
	} while (0)
#define KPROG_ARM64_SET_LOGIC_FLAGS(C_N, C_Z, C_C, C_V, VALUE, WIDTH)    \
	do {                                                                \
		__u64 __kprog_a64_log_value =                            \
			(VALUE) & KPROG_ARM64_WIDTH_MASK(WIDTH);             \
		__u64 __kprog_a64_log_sign =                             \
			KPROG_ARM64_WIDTH_SIGN_MASK(WIDTH);                  \
		(C_Z) = __kprog_a64_log_value == 0;                          \
		(C_N) = (__kprog_a64_log_value & __kprog_a64_log_sign) != 0; \
		(C_C) = 0;                                                   \
		(C_V) = 0;                                                   \
	} while (0)
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    load()
    for path, expected in ((LEAN, render_lean()), (CHEADER, render_c())):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(f"generated arm64 flags contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
