#!/usr/bin/env python3
"""Generate x86 register-lane AUX packing for Lean, C, and the encoder."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_reg_lane_aux_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86RegLaneAux.lean"
C_HEADER = ROOT / "generated/x86_reg_lane_aux.h"
PYTHON = ROOT.parent / "x86/micro-prog/generated_x86_reg_lane_aux.py"
EXPECTED = {
    "schema_version": 1,
    "operation": "x86RegLaneAux",
    "fields": [
        {"name": "payload", "shift": 0, "mask": "0xff"},
        {"name": "dst_shift", "shift": 8, "mask": "0xff"},
        {"name": "src_shift", "shift": 16, "mask": "0xff"},
    ],
    "valid_byte_shifts": [0, 8],
}


def load() -> None:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 register-lane AUX specification: {data!r}")


def render_lean() -> str:
    return '''-- Generated by generate_x86_reg_lane_aux_spec.py from x86_reg_lane_aux_spec.json.
import Std
namespace KProgFormal.GeneratedX86RegLaneAux
def pack (payload dstShift srcShift : BitVec 32) : BitVec 32 :=
  BitVec.or (BitVec.and payload 0xff)
    (BitVec.or (BitVec.shiftLeft (BitVec.and dstShift 0xff) 8)
      (BitVec.shiftLeft (BitVec.and srcShift 0xff) 16))
def payload (aux : BitVec 32) : BitVec 32 := BitVec.and aux 0xff
def dstShift (aux : BitVec 32) : BitVec 32 := BitVec.and (aux >>> 8) 0xff
def srcShift (aux : BitVec 32) : BitVec 32 := BitVec.and (aux >>> 16) 0xff
end KProgFormal.GeneratedX86RegLaneAux
'''


def render_c() -> str:
    return '''/* Generated by generate_x86_reg_lane_aux_spec.py from x86_reg_lane_aux_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_REG_LANE_AUX_H
#define KPROG_FORMAL_GENERATED_X86_REG_LANE_AUX_H
#define KPROG_X86_REG_LANE_AUX(PAYLOAD, DST_SHIFT, SRC_SHIFT)              \\
\t(((__u32)(PAYLOAD) & 0xffU) | (((__u32)(DST_SHIFT) & 0xffU) << 8) | \\
\t (((__u32)(SRC_SHIFT) & 0xffU) << 16))
#define KPROG_X86_REG_LANE_AUX_PAYLOAD(AUX) ((__u8)((AUX) & 0xffU))
#define KPROG_X86_REG_LANE_AUX_DST_SHIFT(AUX)                              \\
\t((__u8)(((AUX) >> 8) & 0xffU))
#define KPROG_X86_REG_LANE_AUX_SRC_SHIFT(AUX)                              \\
\t((__u8)(((AUX) >> 16) & 0xffU))
#endif
'''


def render_python() -> str:
    return '''# Generated by generate_x86_reg_lane_aux_spec.py from x86_reg_lane_aux_spec.json.
VALID_BYTE_SHIFTS = frozenset({0, 8})


def c_reg_lane_aux(payload: str, dst_shift: int = 0, src_shift: int = 0) -> str:
    if dst_shift not in VALID_BYTE_SHIFTS or src_shift not in VALID_BYTE_SHIFTS:
        raise ValueError(
            f"invalid x86 byte lane shifts: dst={dst_shift} src={src_shift}"
        )
    if dst_shift == 0 and src_shift == 0:
        return payload
    return f"KPROG_X86_REG_LANE_AUX(({payload}), {dst_shift}, {src_shift})"
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    load()
    for path, expected in (
        (LEAN, render_lean()),
        (C_HEADER, render_c()),
        (PYTHON, render_python()),
    ):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated x86 register-lane AUX contract is stale: {path}"
                )
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
