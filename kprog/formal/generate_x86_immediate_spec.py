#!/usr/bin/env python3
"""Generate the shared x86 arithmetic-immediate decode contract."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_immediate_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86Immediate.lean"
CHEADER = ROOT / "generated/x86_immediate.h"
EXPECTED = {
    "schema_version": 1,
    "operation": "x86Immediate",
    "encoded_bits": 64,
    "instruction_bits": 32,
    "sign_extend_width": "w64",
}


def load() -> None:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 immediate specification: {data!r}")


def render_lean() -> str:
    return """-- Generated by generate_x86_immediate_spec.py from x86_immediate_spec.json.
import KProgFormal.GeneratedX86Width

namespace KProgFormal.GeneratedX86Immediate

def value (raw : BitVec 64) (width : GeneratedX86Width.Width) : BitVec 64 :=
  let imm32 := BitVec.and raw 0xffffffff
  match width with
  | .w64 => if BitVec.and imm32 0x80000000 != 0 then
      BitVec.or imm32 0xffffffff00000000 else imm32
  | _ => imm32

end KProgFormal.GeneratedX86Immediate
"""


def render_c() -> str:
    return """/* Generated by generate_x86_immediate_spec.py from x86_immediate_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_IMMEDIATE_H
#define KPROG_FORMAL_GENERATED_X86_IMMEDIATE_H
#define KPROG_X86_IMMEDIATE_VALUE(VALUE, WIDTH)                             \\
\t(((WIDTH) == X86_WIDTH_64 &&                                         \\
\t  (((VALUE) & 0x80000000ULL) != 0ULL)) ?                             \\
\t (((VALUE) & 0xffffffffULL) | 0xffffffff00000000ULL) :               \\
\t ((VALUE) & 0xffffffffULL))
#endif
"""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    load()
    for path, expected in ((LEAN, render_lean()), (CHEADER, render_c())):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(f"generated x86 immediate contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
