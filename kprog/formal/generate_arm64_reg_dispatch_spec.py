#!/usr/bin/env python3
"""Generate the shared AArch64 register-number -> dispatch-cell contract.

The generated Lean tables `GeneratedArm64RegDispatch.cellNumbers` /
`cellNames` and the C macros `KPROG_ARM64_GPR_CELL` / `KPROG_ARM64_GPR_COUNT`
bind each decoded AArch64 general-purpose register number to the dispatch cell
the simulator's `ARM64_SIM_L_FOR_EACH_GPR` X-macro order names:

  * the 31 GPRs are the register numbers `0..30`, in `x0 .. x30` order, so the
    dispatch cell index equals the register number;
  * the zero register (`31`, `ARM64_XZR`), the stack pointer (`32`, `ARM64_SP`)
    and the no-register sentinel (`0xff`, `ARM64_REG_NONE`) are not dispatch
    cells, so `cellOf` maps them to `none`.

The simulator binds a register number to a cell name only by the hand-written
order of `ARM64_SIM_L_FOR_EACH_GPR` in `arm64_sim_local_bpf.h`; the generated
header's `_Static_assert(ARM64_X<n> == <n>U, ...)` drift checks make that order
a machine-checked fact, and `KProgFormal/Arm64RegDispatch.lean` proves the
generated tables equal an independent `List.finRange` construction and that
`cellOf` maps exactly the GPR numbers (and neither the zero register nor the
sentinel) to a cell.

The generated header is included by `arm64_sim_local_bpf.h` after the
`ARM64_X0 .. ARM64_X30` decodes, exactly as the register-presence mirrors; the
host cross-check supplies the same number macros itself.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_reg_dispatch_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64RegDispatch.lean"
CHEADER = ROOT / "generated/arm64_reg_dispatch.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64RegDispatch",
    "reg_bits": 8,
    "gpr_count": 31,
    "cells": [{"name": f"x{n}", "number": n} for n in range(31)],
}


def load() -> dict:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 reg-dispatch specification: {data!r}")
    cells = EXPECTED["cells"]
    if [row["name"] for row in cells] != [f"x{n}" for n in range(31)]:
        raise SystemExit(f"invalid arm64 reg-dispatch cell order: {cells!r}")
    if [row["number"] for row in cells] != list(range(31)):
        raise SystemExit(f"invalid arm64 reg-dispatch cell numbers: {cells!r}")
    if len(cells) != EXPECTED["gpr_count"]:
        raise SystemExit("arm64 reg-dispatch cell count disagrees with gpr_count")
    return EXPECTED


def render_lean(spec: dict) -> str:
    cells = spec["cells"]
    bits = spec["reg_bits"]
    count = spec["gpr_count"]
    numbers = ", ".join(str(row["number"]) for row in cells)
    names = ", ".join(f'"{row["name"]}"' for row in cells)
    return f'''-- Generated by generate_arm64_reg_dispatch_spec.py from arm64_reg_dispatch_spec.json.
import Std
namespace KProgFormal.GeneratedArm64RegDispatch
/-- The number of AArch64 general-purpose registers the dispatch cell array
holds (`x0 .. x30`). -/
def gprCount : Nat := {count}
/-- The width in bits of a decoded AArch64 register number. -/
def regBits : Nat := {bits}
/-- The register number of each dispatch cell, in `ARM64_SIM_L_FOR_EACH_GPR`
order: cell `i` is register number `i`. -/
def cellNumbers : List Nat := [{numbers}]
/-- The state-field name of each dispatch cell, in `ARM64_SIM_L_FOR_EACH_GPR`
order: cell `i` names `x{{i}}`. -/
def cellNames : List String := [{names}]
/-- The dispatch cell a decoded register number names, or `none` when the number
is not a general-purpose register (the zero register `31`, the stack pointer
`32`, or the no-register sentinel `0xff`). -/
def cellOf (reg : BitVec {bits}) : Option Nat :=
  if reg.toNat < gprCount then some reg.toNat else none
/-- The register number a cell name names, in `ARM64_SIM_L_FOR_EACH_GPR` order. -/
def numberOfName (name : String) : Option Nat :=
  (cellNames.zip cellNumbers).lookup name
/-- The cell name a register number names, in `ARM64_SIM_L_FOR_EACH_GPR`
order. -/
def nameOfNumber (number : Nat) : Option String :=
  (cellNumbers.zip cellNames).lookup number
end KProgFormal.GeneratedArm64RegDispatch
'''


def render_c(spec: dict) -> str:
    cells = spec["cells"]
    count = spec["gpr_count"]
    last = count - 1
    drift = "\n".join(
        f'_Static_assert(ARM64_X{row["number"]} == {row["number"]}U, '
        f'"arm64 gpr dispatch number drift");'
        for row in cells)
    return f'''/* Generated by generate_arm64_reg_dispatch_spec.py from arm64_reg_dispatch_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_REG_DISPATCH_H
#define KPROG_FORMAL_GENERATED_ARM64_REG_DISPATCH_H
/*
 * AArch64 register-number -> dispatch-cell binding: the {count} general-purpose
 * registers are the register numbers `0 .. {last}`, in `x0 .. x{last}` order, so
 * the `ARM64_SIM_L_FOR_EACH_GPR` dispatch cell index equals the register
 * number. The zero register (`31`, `ARM64_XZR`), the stack pointer (`32`,
 * `ARM64_SP`) and the no-register sentinel (`0xff`, `ARM64_REG_NONE`) are not
 * dispatch cells.
 * `KProgFormal/Arm64RegDispatch.lean` proves the generated `cellNumbers` /
 * `cellNames` tables equal an independent `List.finRange` construction and that
 * `cellOf` maps exactly the general-purpose register numbers to a cell.
 * This header is included after the `ARM64_X0 .. ARM64_X{last}` decodes, so the
 * number drift checks bind the hand-written decode to the generated table.
 */
/* The number of GPR dispatch cells. */
#define KPROG_ARM64_GPR_COUNT {count}U
/*
 * The dispatch cell index a decoded register number names. The
 * `ARM64_SIM_L_FOR_EACH_GPR` order makes the cell index equal the register
 * number; evaluated once. Callers must have already excluded the non-GPR
 * numbers (the zero register, the stack pointer and the sentinel).
 */
#define KPROG_ARM64_GPR_CELL(REG) ((__u8)((REG)))
/* The hand-written register decode must equal the generated cell table. */
{drift}
_Static_assert(KPROG_ARM64_GPR_COUNT == {count}U,
\t       "arm64 gpr dispatch count drift");
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = load()
    for path, expected in ((LEAN, render_lean(spec)),
                           (CHEADER, render_c(spec))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 reg-dispatch contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
