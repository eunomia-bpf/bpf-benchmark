#!/usr/bin/env python3
"""Generate the shared x86 BSWAP / MOVBE byte-reversal contract.

The generated Lean definition `GeneratedX86Bswap.value` and the C function
`kprog_x86_bswap_value` implement the byte reversal the simulator applies for
the `BSWAP`, `MOVBE_LOAD`, and `MOVBE_STORE` handlers: reverse the byte order of
the access width, leaving the bytes above the width clear.

The width is one of the four `X86_WIDTH_*` codes, so the reversal has a closed
set of byte counts (1, 2, 4, 8) and no unsupported case. The C function
evaluates its operand once and writes no flags.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_bswap_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86Bswap.lean"
C_HEADER = ROOT / "generated/x86_bswap.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "x86Bswap",
    "widths": [
        {"name": "w8", "bytes": 1, "code": 1},
        {"name": "w16", "bytes": 2, "code": 2},
        {"name": "w32", "bytes": 4, "code": 4},
        {"name": "w64", "bytes": 8, "code": 8},
    ],
}


def load() -> None:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 bswap specification: {data!r}")
    widths = EXPECTED["widths"]
    if [row["bytes"] for row in widths] != [1, 2, 4, 8]:
        raise SystemExit(f"invalid x86 bswap widths: {widths!r}")
    if [row["code"] for row in widths] != [1, 2, 4, 8]:
        raise SystemExit(f"invalid x86 bswap codes: {widths!r}")


def render_lean() -> str:
    return '''-- Generated by generate_x86_bswap_spec.py from x86_bswap_spec.json.
import KProgFormal.GeneratedX86Width
namespace KProgFormal.GeneratedX86Bswap
open GeneratedX86Width (Width mask narrow)
/-- Shared x86 byte reversal: reverse the byte order of the access width, keeping
the bytes above the width clear. `none` leaves the value at the width's mask. -/
def value (v : BitVec 64) (width : Width) : BitVec 64 :=
  match width with
  | .w8 => v &&& mask .w8
  | .w16 => narrow (((v &&& 0xff) <<< 8) ||| ((v &&& 0xff00) >>> 8)) .w16
  | .w32 =>
      let r :=
        ((v &&& 0x00000000000000ff) <<< 56) |||
        ((v &&& 0x000000000000ff00) <<< 40) |||
        ((v &&& 0x0000000000ff0000) <<< 24) |||
        ((v &&& 0x00000000ff000000) <<< 8) |||
        ((v &&& 0x000000ff00000000) >>> 8) |||
        ((v &&& 0x0000ff0000000000) >>> 24) |||
        ((v &&& 0x00ff000000000000) >>> 40) |||
        ((v &&& 0xff00000000000000) >>> 56)
      r >>> 32
  | .w64 =>
      ((v &&& 0x00000000000000ff) <<< 56) |||
      ((v &&& 0x000000000000ff00) <<< 40) |||
      ((v &&& 0x0000000000ff0000) <<< 24) |||
      ((v &&& 0x00000000ff000000) <<< 8) |||
      ((v &&& 0x000000ff00000000) >>> 8) |||
      ((v &&& 0x0000ff0000000000) >>> 24) |||
      ((v &&& 0x00ff000000000000) >>> 40) |||
      ((v &&& 0xff00000000000000) >>> 56)
end KProgFormal.GeneratedX86Bswap
'''


def render_c() -> str:
    return '''/* Generated by generate_x86_bswap_spec.py from x86_bswap_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_BSWAP_H
#define KPROG_FORMAL_GENERATED_X86_BSWAP_H
/*
 * x86 byte reversal: reverse the byte order of the access width and clear the
 * bytes above it. The width set is closed (the four X86_WIDTH_* codes) and every
 * case is handled, so there is no unsupported arm.
 */
static __always_inline __u64 kprog_x86_bswap_value(__u64 value, __u8 width)
{
\tif (width == X86_WIDTH_8)
\t\treturn value & 0xffULL;
\tif (width == X86_WIDTH_16)
\t\treturn ((value & 0x00ffULL) << 8) | ((value & 0xff00ULL) >> 8);

\t__u64 swapped = ((value & 0x00000000000000ffULL) << 56) |
\t\t\t((value & 0x000000000000ff00ULL) << 40) |
\t\t\t((value & 0x0000000000ff0000ULL) << 24) |
\t\t\t((value & 0x00000000ff000000ULL) << 8) |
\t\t\t((value & 0x000000ff00000000ULL) >> 8) |
\t\t\t((value & 0x0000ff0000000000ULL) >> 24) |
\t\t\t((value & 0x00ff000000000000ULL) >> 40) |
\t\t\t((value & 0xff00000000000000ULL) >> 56);

\tif (width == X86_WIDTH_32)
\t\treturn swapped >> 32;
\treturn swapped;
}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    load()
    for path, expected in ((LEAN, render_lean()), (C_HEADER, render_c())):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated x86 bswap contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
