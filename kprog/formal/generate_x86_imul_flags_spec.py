#!/usr/bin/env python3
"""Generate the shared x86 IMUL overflow flag transition for Lean and C."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_imul_flags_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86ImulFlags.lean"
C_HEADER = ROOT / "generated/x86_imul_flags.h"
EXPECTED = {
    "schema_version": 1,
    "operation": "x86ImulFlags",
    "inputs": ["lhs", "rhs", "width"],
    "width_rule": "zero_is_64",
    "signed_abs": "narrowed_magnitude_of_signed_width_value",
    "limit": "sign_mask_when_signs_mixed_else_sign_mask_minus_one",
    "overflow": "a_abs_ne_zero_and_b_abs_gt_limit_over_a_abs",
    "fields": {"cf": "overflow", "of": "overflow", "zf": "preserve",
               "sf": "preserve"},
}


def load() -> None:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 IMUL-flags specification: {data!r}")


def render_lean() -> str:
    return '''-- Generated by generate_x86_imul_flags_spec.py from x86_imul_flags_spec.json.
import KProgFormal.GeneratedX86Width
namespace KProgFormal.GeneratedX86ImulFlags
structure Flags where
  cf : Bool
  zf : Bool
  sf : Bool
  of : Bool
  deriving DecidableEq, Repr
def signedAbs (value : BitVec 64) (width : GeneratedX86Width.Width) : BitVec 64 :=
  let v := GeneratedX86Width.narrow value width
  if GeneratedX86Width.sign v width then
    BitVec.and (BitVec.not v + 1) (GeneratedX86Width.mask width) else v
def mixedSign (lhs rhs : BitVec 64) (width : GeneratedX86Width.Width) : Bool :=
  GeneratedX86Width.sign lhs width != GeneratedX86Width.sign rhs width
def apply (lhs rhs : BitVec 64) (width : GeneratedX86Width.Width)
    (old : Flags) : Flags :=
  let aAbs := signedAbs lhs width
  let bAbs := signedAbs rhs width
  let sign := GeneratedX86Width.signMask width
  let limit := if mixedSign lhs rhs width then sign else sign - 1
  let overflow := aAbs != 0 && bAbs > limit / aAbs
  { cf := overflow, zf := old.zf, sf := old.sf, of := overflow }
end KProgFormal.GeneratedX86ImulFlags
'''


def render_c() -> str:
    return r'''/* Generated by generate_x86_imul_flags_spec.py from x86_imul_flags_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_IMUL_FLAGS_H
#define KPROG_FORMAL_GENERATED_X86_IMUL_FLAGS_H
#define KPROG_X86_SET_IMUL_FLAGS(C_CF,C_OF,A_ABS,B_ABS,LIMIT)         \
	do {                                                               \
		__u8 __kprog_imul_overflow = ((A_ABS) != 0 &&                  \
					(B_ABS) > (LIMIT) / (A_ABS));              \
		(C_CF) = __kprog_imul_overflow;                             \
		(C_OF) = __kprog_imul_overflow;                             \
	} while (0)
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    load()
    for path, expected in ((LEAN, render_lean()), (C_HEADER, render_c())):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(f"generated x86 IMUL-flags contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
