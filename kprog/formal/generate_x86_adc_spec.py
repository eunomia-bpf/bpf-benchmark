#!/usr/bin/env python3
"""Generate the shared x86 ADC result and flag transition for Lean and C."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parent;SPEC=ROOT/"x86_adc_spec.json";LEAN=ROOT/"KProgFormal/GeneratedX86Adc.lean";CHEADER=ROOT/"generated/x86_adc.h";FLAGS=["cf","zf","sf","of"]
def validate(e):
 if not isinstance(e,dict) or "op" not in e:raise SystemExit(f"invalid ADC expression: {e!r}")
 op=e["op"]
 if op=="input":
  if set(e)!={"op","name"} or e["name"] not in {"a","b","r","sign"}:raise SystemExit(f"invalid ADC input: {e!r}")
  return "word"
 if op in {"zero","carry_word"}:
  if set(e)!={"op"}:raise SystemExit(f"invalid ADC word atom: {e!r}")
  return "word"
 if op=="carry":
  if set(e)!={"op"}:raise SystemExit(f"invalid ADC carry atom: {e!r}")
  return "bool"
 if op in {"not","nonzero"}:
  if set(e)!={"op","arg"} or validate(e["arg"])!="word":raise SystemExit(f"ill-typed ADC unary: {e!r}")
  return "bool" if op=="nonzero" else "word"
 if op in {"add","band","xor","ult","weq"}:
  if set(e)!={"op","lhs","rhs"} or validate(e["lhs"])!="word" or validate(e["rhs"])!="word":raise SystemExit(f"ill-typed ADC word binary: {e!r}")
  return "bool" if op in {"ult","weq"} else "word"
 if op in {"land","lor"}:
  if set(e)!={"op","lhs","rhs"} or validate(e["lhs"])!="bool" or validate(e["rhs"])!="bool":raise SystemExit(f"ill-typed ADC bool binary: {e!r}")
  return "bool"
 raise SystemExit(f"unsupported ADC op: {e!r}")
def load():
 d=json.loads(SPEC.read_text())
 if set(d)!={"schema_version","operation","result","flags"} or d["schema_version"]!=1 or d["operation"]!="x86Adc" or list(d["flags"])!=FLAGS:raise SystemExit(f"invalid ADC spec: {d!r}")
 if validate(d["result"])!="word":raise SystemExit("ADC result is not a word")
 for e in d["flags"].values():
  if validate(e)!="bool":raise SystemExit(f"ADC flag is not boolean: {e!r}")
 return d
def render(e,lean):
 op=e["op"]
 if op=="input":return e["name"] if lean else e["name"].upper()
 if op=="zero":return "0"
 if op=="carry":return "carry" if lean else "(!!(CARRY))"
 if op=="carry_word":return "(if carry then 1 else 0)" if lean else "(!!(CARRY))"
 if op=="not":return f"(BitVec.not {render(e['arg'],lean)})" if lean else f"(~{render(e['arg'],lean)})"
 if op=="nonzero":return f"({render(e['arg'],lean)} != 0)"
 l=render(e["lhs"],lean);r=render(e["rhs"],lean)
 if lean:
  if op in {"land","lor","weq"}:operator={"land":"&&","lor":"||","weq":"=="}[op];return f"({l} {operator} {r})"
  fn={"add":None,"band":"BitVec.and","xor":"BitVec.xor","ult":"BitVec.ult"}[op]
  return f"({l} + {r})" if op=="add" else f"({fn} {l} {r})"
 operator={"add":"+","band":"&","xor":"^","ult":"<","weq":"==","land":"&&","lor":"||"}[op];return f"({l} {operator} {r})"
def lean_out(d):
 vals=", ".join(f"{n} := {render(d['flags'][n],True)}" for n in FLAGS)
 return f'''-- Generated by generate_x86_adc_spec.py from x86_adc_spec.json.
import KProgFormal.GeneratedX86LogicFlags
namespace KProgFormal.GeneratedX86Adc
def result (a b : BitVec 64) (carry : Bool) : BitVec 64 := {render(d['result'],True)}
def flags (a b r sign : BitVec 64) (carry : Bool) : GeneratedX86LogicFlags.Flags := {{ {vals} }}
end KProgFormal.GeneratedX86Adc
'''
def c_out(d):
 vals=" \\\n".join(f"\t\t(C_{n.upper()}) = {render(d['flags'][n],False)};" for n in FLAGS)
 return f'''/* Generated by generate_x86_adc_spec.py from x86_adc_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_ADC_H
#define KPROG_FORMAL_GENERATED_X86_ADC_H
#define KPROG_X86_ADC_RESULT(A,B,CARRY) {render(d['result'],False)}
#define KPROG_X86_SET_ADC_FLAGS(C_CF,C_ZF,C_SF,C_OF,A,B,R,SIGN,CARRY)       \\
\tdo {{ \\
{vals} \\
\t}} while (0)
#endif
'''
def main():
 p=argparse.ArgumentParser();p.add_argument("--check",action="store_true");a=p.parse_args();d=load()
 for path,want in ((LEAN,lean_out(d)),(CHEADER,c_out(d))):
  if a.check:
   if not path.is_file() or path.read_text()!=want:raise SystemExit(f"generated x86 ADC contract is stale: {path}")
  else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(want)
if __name__=="__main__":main()
