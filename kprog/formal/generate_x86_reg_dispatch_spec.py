#!/usr/bin/env python3
"""Generate the shared x86-64 register-number -> dispatch-cell contract.

The generated Lean tables `GeneratedX86RegDispatch.cellNumbers` / `cellNames`
and the C macros `KPROG_X86_GPR_CELL` / `KPROG_X86_GPR_COUNT` bind each decoded
x86-64 general-purpose register number to the dispatch cell the hand-written
`X86_SIM_L_FOR_EACH_GPR` X-macro order names:

  * the 16 GPRs are the register numbers `0..15`, in
    `rax rcx rdx rbx rsp rbp rsi rdi r8 .. r15` order, so the dispatch cell
    index equals the register number;
  * unlike AArch64 there is no zero register: the only register number that is
    not a dispatch cell is the no-register sentinel (`0xff`, `X86_REG_NONE`),
    and every other byte `16..254` names no cell either, so `cellOf` maps the
    whole byte range `16..255` to `none`.

The simulator binds a register number to a cell name by *two* independent
hand-written orders: the `X86_SIM_L_FOR_EACH_GPR` X-macro (the write dispatch
and the tag/pointer dispatch) and the `X86_SIM_L_REG_VALUE` ternary chain (the
read path, which does not use the X-macro). The generated header's
`_Static_assert(X86_R<n> == <n>U, ...)` drift checks pin the register decode to
the generated table, and `KProgFormal/X86RegDispatch.lean` proves the generated
tables equal an independent `List.finRange` construction, that `cellOf` maps
exactly the GPR numbers to a cell, and that both hand-written orders agree.

The generated header is included by `x86_sim_local_bpf.h` after the
`X86_RAX .. X86_R15` decodes, exactly as the AArch64 register-dispatch mirror.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_reg_dispatch_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86RegDispatch.lean"
CHEADER = ROOT / "generated/x86_reg_dispatch.h"

# The 16 GPR dispatch cells in `X86_SIM_L_FOR_EACH_GPR` order:
# (name, register define, register number).
_GPR_CELLS = [
    ("rax", "X86_RAX", 0), ("rcx", "X86_RCX", 1), ("rdx", "X86_RDX", 2),
    ("rbx", "X86_RBX", 3), ("rsp", "X86_RSP", 4), ("rbp", "X86_RBP", 5),
    ("rsi", "X86_RSI", 6), ("rdi", "X86_RDI", 7), ("r8", "X86_R8", 8),
    ("r9", "X86_R9", 9), ("r10", "X86_R10", 10), ("r11", "X86_R11", 11),
    ("r12", "X86_R12", 12), ("r13", "X86_R13", 13), ("r14", "X86_R14", 14),
    ("r15", "X86_R15", 15),
]
EXPECTED = {
    "schema_version": 1,
    "operation": "x86RegDispatch",
    "reg_bits": 8,
    "gpr_count": 16,
    "sentinel": 255,
    "cells": [{"name": name, "define": define, "number": number}
              for name, define, number in _GPR_CELLS],
}


def load() -> dict:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 reg-dispatch specification: {data!r}")
    cells = EXPECTED["cells"]
    if [row["name"] for row in cells] != [n for n, _d, _x in _GPR_CELLS]:
        raise SystemExit(f"invalid x86 reg-dispatch cell names: {cells!r}")
    if [row["define"] for row in cells] != [d for _n, d, _x in _GPR_CELLS]:
        raise SystemExit(f"invalid x86 reg-dispatch cell defines: {cells!r}")
    if [row["number"] for row in cells] != list(range(EXPECTED["gpr_count"])):
        raise SystemExit(f"invalid x86 reg-dispatch cell numbers: {cells!r}")
    if len(cells) != EXPECTED["gpr_count"]:
        raise SystemExit("x86 reg-dispatch cell count disagrees with gpr_count")
    return EXPECTED


def render_lean(spec: dict) -> str:
    cells = spec["cells"]
    bits = spec["reg_bits"]
    count = spec["gpr_count"]
    numbers = ", ".join(str(row["number"]) for row in cells)
    names = ", ".join(f'"{row["name"]}"' for row in cells)
    return f'''-- Generated by generate_x86_reg_dispatch_spec.py from x86_reg_dispatch_spec.json.
import Std
namespace KProgFormal.GeneratedX86RegDispatch
/-- The number of x86-64 general-purpose registers the dispatch cell array
holds (`rax .. r15`). -/
def gprCount : Nat := {count}
/-- The width in bits of a decoded x86-64 register number. -/
def regBits : Nat := {bits}
/-- The register number of each dispatch cell, in `X86_SIM_L_FOR_EACH_GPR`
order: cell `i` is register number `i`. -/
def cellNumbers : List Nat := [{numbers}]
/-- The state-field name of each dispatch cell, in `X86_SIM_L_FOR_EACH_GPR`
order. -/
def cellNames : List String := [{names}]
/-- The dispatch cell a decoded register number names, or `none` when the number
is not a general-purpose register (every byte `16..255`, including the
no-register sentinel `0xff`). -/
def cellOf (reg : BitVec {bits}) : Option Nat :=
  if reg.toNat < gprCount then some reg.toNat else none
/-- The register number a cell name names, in `X86_SIM_L_FOR_EACH_GPR` order. -/
def numberOfName (name : String) : Option Nat :=
  (cellNames.zip cellNumbers).lookup name
/-- The cell name a register number names, in `X86_SIM_L_FOR_EACH_GPR`
order. -/
def nameOfNumber (number : Nat) : Option String :=
  (cellNumbers.zip cellNames).lookup number
end KProgFormal.GeneratedX86RegDispatch
'''


def render_c(spec: dict) -> str:
    cells = spec["cells"]
    count = spec["gpr_count"]
    last = count - 1
    drift = "\n".join(
        f'_Static_assert({row["define"]} == {row["number"]}U, '
        f'"x86 gpr dispatch number drift");'
        for row in cells)
    return f'''/* Generated by generate_x86_reg_dispatch_spec.py from x86_reg_dispatch_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_REG_DISPATCH_H
#define KPROG_FORMAL_GENERATED_X86_REG_DISPATCH_H
/*
 * x86-64 register-number -> dispatch-cell binding: the {count} general-purpose
 * registers are the register numbers `0 .. {last}`, in
 * `rax rcx rdx rbx rsp rbp rsi rdi r8 .. r15` order, so the
 * `X86_SIM_L_FOR_EACH_GPR` dispatch cell index equals the register number.
 * Unlike AArch64 there is no zero register: the only register number that is
 * not a dispatch cell is the no-register sentinel (`0xff`, `X86_REG_NONE`).
 * `KProgFormal/X86RegDispatch.lean` proves the generated `cellNumbers` /
 * `cellNames` tables equal an independent `List.finRange` construction and that
 * `cellOf` maps exactly the general-purpose register numbers to a cell.
 * This header is included after the `X86_RAX .. X86_R15` decodes, so the number
 * drift checks bind the hand-written decode to the generated table.
 */
/* The number of GPR dispatch cells. */
#define KPROG_X86_GPR_COUNT {count}U
/*
 * The dispatch cell index a decoded register number names. The
 * `X86_SIM_L_FOR_EACH_GPR` order makes the cell index equal the register
 * number; evaluated once. Callers must have already excluded the numbers that
 * name no cell (the no-register sentinel and every byte above `{last}`).
 */
#define KPROG_X86_GPR_CELL(REG) ((__u8)((REG)))
/* The hand-written register decode must equal the generated cell table. */
{drift}
_Static_assert(KPROG_X86_GPR_COUNT == {count}U,
\t       "x86 gpr dispatch count drift");
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = load()
    for path, expected in ((LEAN, render_lean(spec)),
                           (CHEADER, render_c(spec))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated x86 reg-dispatch contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
