#!/usr/bin/env python3
"""Render the shared x86 condition-code semantics for Lean and C."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent
SPEC_PATH = ROOT / "x86_cond_spec.json"
LEAN_PATH = ROOT / "KProgFormal" / "GeneratedX86Cond.lean"
C_PATH = ROOT / "generated" / "x86_cond.h"
FLAGS = {"cf", "zf", "sf", "of"}
CONDITIONS = [("o", 0), ("no", 1), ("b", 2), ("ae", 3), ("e", 4),
              ("ne", 5), ("be", 6), ("a", 7), ("s", 8), ("ns", 9),
              ("l", 12), ("ge", 13), ("le", 14), ("g", 15)]


def validate_expr(expr: Any) -> None:
    if not isinstance(expr, dict) or not isinstance(expr.get("op"), str):
        raise SystemExit(f"invalid condition expression: {expr!r}")
    op = expr["op"]
    if op == "flag":
        if set(expr) != {"op", "name"} or expr["name"] not in FLAGS:
            raise SystemExit(f"invalid flag expression: {expr!r}")
    elif op == "not":
        if set(expr) != {"op", "arg"}:
            raise SystemExit(f"invalid not expression: {expr!r}")
        validate_expr(expr["arg"])
    elif op in {"and", "or"}:
        if set(expr) != {"op", "args"} or not isinstance(expr["args"], list) or len(expr["args"]) != 2:
            raise SystemExit(f"invalid binary expression: {expr!r}")
        for arg in expr["args"]:
            validate_expr(arg)
    elif op in {"eq", "ne"}:
        if set(expr) != {"op", "lhs", "rhs"}:
            raise SystemExit(f"invalid comparison expression: {expr!r}")
        validate_expr(expr["lhs"])
        validate_expr(expr["rhs"])
    else:
        raise SystemExit(f"unsupported condition operation: {expr!r}")


def load_spec() -> list[dict[str, Any]]:
    spec = json.loads(SPEC_PATH.read_text())
    if set(spec) != {"schema_version", "operation", "conditions"} or \
            spec["schema_version"] != 1 or spec["operation"] != "x86Condition":
        raise SystemExit(f"invalid x86 condition specification: {spec!r}")
    conditions = spec["conditions"]
    if not isinstance(conditions, list) or len(conditions) != len(CONDITIONS):
        raise SystemExit(f"invalid x86 condition list: {conditions!r}")
    for condition, (name, code) in zip(conditions, CONDITIONS, strict=True):
        if not isinstance(condition, dict) or set(condition) != {"name", "code", "predicate"}:
            raise SystemExit(f"invalid x86 condition: {condition!r}")
        if condition["name"] != name or condition["code"] != code:
            raise SystemExit(f"non-canonical x86 condition: {condition!r}")
        validate_expr(condition["predicate"])
    return conditions


def render_expr(expr: dict[str, Any], language: str) -> str:
    op = expr["op"]
    if op == "flag":
        return expr["name"] if language == "lean" else expr["name"].upper()
    if op == "not":
        return f"(!{render_expr(expr['arg'], language)})"
    if op in {"and", "or"}:
        lhs, rhs = (render_expr(arg, language) for arg in expr["args"])
        return f"({lhs} {'&&' if op == 'and' else '||'} {rhs})"
    lhs = render_expr(expr["lhs"], language)
    rhs = render_expr(expr["rhs"], language)
    return f"({lhs} {'==' if op == 'eq' else '!='} {rhs})"


def render_lean(conditions: list[dict[str, Any]]) -> str:
    constructors = "\n".join(f"  | {condition['name']}" for condition in conditions)
    cases = "\n".join(f"  | .{c['name']} => {render_expr(c['predicate'], 'lean')}" for c in conditions)
    return f"""-- Generated by generate_x86_cond_spec.py from x86_cond_spec.json.
import Std

namespace KProgFormal.GeneratedX86Cond

inductive Cond
{constructors}
  deriving DecidableEq, Repr

def eval (cf zf sf of : Bool) : Cond -> Bool
{cases}

end KProgFormal.GeneratedX86Cond
"""


def render_c(conditions: list[dict[str, Any]]) -> str:
    assertions = "\n".join(f'_Static_assert(X86_CC_{c["name"].upper()} == {c["code"]}U, "x86 condition code drift");' for c in conditions)
    lines = []
    for index, condition in enumerate(conditions):
        prefix = "\t((CC)" if index == 0 else "\t (CC)"
        lines.append(f"{prefix} == X86_CC_{condition['name'].upper()} ? {render_expr(condition['predicate'], 'c')} :")
    cases = " \\\n".join(lines)
    return f"""/* Generated by generate_x86_cond_spec.py from x86_cond_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_COND_H
#define KPROG_FORMAL_GENERATED_X86_COND_H

{assertions}

#define KPROG_X86_EVAL_CC(CC, CF, ZF, SF, OF)                               \\
{cases} \\
\t 0)

#endif
"""


def check(path: Path, expected: str) -> None:
    if not path.is_file() or path.read_text() != expected:
        raise SystemExit(f"generated x86 condition contract is stale: {path}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    conditions = load_spec()
    outputs = ((LEAN_PATH, render_lean(conditions)), (C_PATH, render_c(conditions)))
    if args.check:
        for path, expected in outputs:
            check(path, expected)
        return
    for path, contents in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents)


if __name__ == "__main__":
    main()
