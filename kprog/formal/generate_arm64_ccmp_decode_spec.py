#!/usr/bin/env python3
"""Generate the AArch64 CCMP operand-word (AUX) decode contract.

The CCMP arm of the local AArch64 simulator
(`kprog/arm64/arm64_sim_local_bpf.h`) extracts its two fields from the shared
packed `AUX` word: the condition code from lane 0 and the incoming-NZCV
fallback byte from lane 1. Both bytes come from the machine-checked four-byte
little-endian layout in `arm64_aux_spec.json`, and the condition codes come
from the shared condition contract `arm64_cond_spec.json`; both are re-read
here so this contract cannot drift from either.

Two outputs share one source:
  * `generated/arm64_ccmp_decode.h` — the C condition/NZCV byte selectors as
    plain masked shifts, usable from a `_Static_assert`, plus the
    `ARM64_AUX_CCMP` packer roundtrip assertions
  * `KProgFormal/GeneratedArm64CcmpDecode.lean` — the same two selectors as
    `BitVec` extractions
"""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_ccmp_decode_spec.json"
AUX_SPEC = ROOT / "arm64_aux_spec.json"
COND_SPEC = ROOT / "arm64_cond_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64CcmpDecode.lean"
CHEADER = ROOT / "generated/arm64_ccmp_decode.h"
EXPECTED = {
    "schema_version": 1,
    "operation": "arm64CcmpDecode",
    "condition_lane": 0,
    "nzcv_lane": 1,
    "condition_codes": 15,
    "condition_bytes": 1,
    "fallback_shrunk": False,
}


def cond_codes() -> list[tuple[str, int]]:
    """The `(name, code)` pairs of the shared condition contract, read from
    `arm64_cond_spec.json` rather than restated here."""
    spec = json.loads(COND_SPEC.read_text())
    if (set(spec) != {"schema_version", "operation", "conditions"}
            or spec["operation"] != "arm64Condition"):
        raise SystemExit(f"invalid AArch64 condition specification: {spec!r}")
    codes = [(condition["name"], condition["code"])
             for condition in spec["conditions"]]
    if [code for _, code in codes] != list(range(len(codes))):
        raise SystemExit(f"non-canonical AArch64 condition codes: {codes!r}")
    return codes


def aux_lanes() -> dict[int, int]:
    """The lane shift table of the shared AUX layout, read from
    `arm64_aux_spec.json` rather than restated here."""
    spec = json.loads(AUX_SPEC.read_text())
    if (set(spec) != {"schema_version", "operation", "word_bits", "field_bits",
                      "lanes", "reg_none"}
            or spec["operation"] != "arm64Aux"
            or spec["word_bits"] != 32
            or spec["field_bits"] != 8
            or sorted(lane["shift"] for lane in spec["lanes"]) != [0, 8, 16, 24]
            or spec["reg_none"] != "0xff"):
        raise SystemExit(f"invalid AArch64 AUX layout: {spec!r}")
    return {i: lane["shift"] for i, lane in enumerate(spec["lanes"])}


def load() -> tuple[int, int]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid AArch64 CCMP decode specification: {data!r}")
    lanes = aux_lanes()
    cond_lane = lanes[data["condition_lane"]]
    nzcv_lane = lanes[data["nzcv_lane"]]
    if len(cond_codes()) != data["condition_codes"]:
        raise SystemExit(
            "AArch64 CCMP decode condition count disagrees with the "
            "condition contract")
    return cond_lane, nzcv_lane


def render_lean(cond_lane: int, nzcv_lane: int) -> str:
    return f'''-- Generated by generate_arm64_ccmp_decode_spec.py from arm64_ccmp_decode_spec.json.
import KProgFormal.GeneratedArm64Aux

namespace KProgFormal.GeneratedArm64CcmpDecode

/-- The CCMP condition byte of a packed AUX word: lane {cond_lane},
bits {cond_lane} to {cond_lane + 7}. The CCMP handler consumes the low four
bits of this byte as the `GeneratedArm64Cond` selector. -/
def ccmpCond (aux : BitVec 32) : BitVec 32 :=
  BitVec.and (aux >>> {cond_lane}) 0xff

/-- The CCMP NZCV fallback byte of a packed AUX word: lane {nzcv_lane},
bits {nzcv_lane} to {nzcv_lane + 7}. -/
def ccmpNzcv (aux : BitVec 32) : BitVec 32 :=
  BitVec.and (aux >>> {nzcv_lane}) 0xff

'''


def render_c(cond_lane: int, nzcv_lane: int, cond_count: int) -> str:
    return f'''/* Generated by generate_arm64_ccmp_decode_spec.py from arm64_ccmp_decode_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_CCMP_DECODE_H
#define KPROG_FORMAL_GENERATED_ARM64_CCMP_DECODE_H

/*
 * The two CCMP fields of the shared packed AUX word, as plain masked shifts
 * so both are usable from a `_Static_assert`: lane {cond_lane}
 * (bits {cond_lane} to {cond_lane + 7}) is the condition byte whose low four
 * bits select `ARM64_COND_*`, lane {nzcv_lane}
 * (bits {nzcv_lane} to {nzcv_lane + 7}) is the fallback NZCV immediate. The
 * lane offsets are re-read from `arm64_aux_spec.json` and the condition
 * count from `arm64_cond_spec.json`, so neither can drift from the kernels
 * they cite.
 */
#define KPROG_ARM64_CCMP_CONDITION_COUNT {cond_count}U
#define KPROG_ARM64_CCMP_COND(AUX) ((__u8)(((AUX) >> {cond_lane}) & 0xffU))
#define KPROG_ARM64_CCMP_NZCV(AUX) ((__u8)(((AUX) >> {nzcv_lane}) & 0xffU))

/* A packed CCMP operand roundtrips: packing a `{cond_lane}`-shifted byte and
 * a `{nzcv_lane}`-shifted byte and decoding both lanes back re-derives them
 * exactly, at every byte value including the `ARM64_REG_NONE` sentinel, so
 * the condition byte cannot lean into the NZCV byte or vice versa. */
_Static_assert(KPROG_ARM64_CCMP_NZCV(ARM64_AUX_CCMP(
	KPROG_ARM64_CCMP_COND(ARM64_AUX_CCMP(0x55U, 0x96U)), 0xa7U)) == 0xa7U,
	       "AArch64 CCMP decode NZCV packer roundtrip drift");
_Static_assert(KPROG_ARM64_CCMP_COND(ARM64_AUX_CCMP(
	KPROG_ARM64_CCMP_COND(ARM64_AUX_CCMP(0x55U, 0x96U)), 0xa7U))
	== 0x55U,
	       "AArch64 CCMP decode condition packer roundtrip drift");

#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    cond_lane, nzcv_lane = load()
    cond_count = EXPECTED["condition_codes"]
    outputs = (
        (LEAN, render_lean(cond_lane, nzcv_lane)),
        (CHEADER, render_c(cond_lane, nzcv_lane, cond_count)),
    )
    for path, expected in outputs:
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 CCMP decode contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
