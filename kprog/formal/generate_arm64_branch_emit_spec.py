#!/usr/bin/env python3
"""Generate the shared AArch64 branch-emission bridge contract.

The generated Lean definitions `GeneratedArm64BranchEmit.shape` /
`nextPc` and the C macro `KPROG_ARM64_BRANCH_BACKWARD` name the *emitted* code
shape the generator writes for a control transfer, and state that both shapes
select the architectural next program counter:

  * a backward edge (target <= current) is emitted as
    `if (!taken) goto fallthrough; goto target;`;
  * a forward edge is emitted as `if (taken) goto target;` with a fall-through.

`GeneratedArm64BranchEmit.nextPc` gives the next PC each shape selects, and
`KProgFormal/Arm64BranchEmit.lean` proves it equals `branchPc`, the architectural
model the condition/branch predicate refinements already use. This is the bridge
from the proved predicates to the generator's actual `goto`/label emission.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_branch_emit_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64BranchEmit.lean"
CHEADER = ROOT / "generated/arm64_branch_emit.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64BranchEmit",
    "shapes": [
        {"name": "forward", "backward": False},
        {"name": "backward", "backward": True},
    ],
}


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 branch-emit specification: {data!r}")
    shapes = EXPECTED["shapes"]
    if [row["name"] for row in shapes] != ["forward", "backward"]:
        raise SystemExit(f"invalid arm64 branch-emit order: {shapes!r}")
    if [row["backward"] for row in shapes] != [False, True]:
        raise SystemExit(f"invalid arm64 branch-emit shapes: {shapes!r}")
    return shapes


def render_lean(shapes: list[dict]) -> str:
    ctors = "\n".join(f"  | {row['name']}" for row in shapes)
    backward = "\n".join(
        f"  | .{row['name']} => "
        f"{'true' if row['backward'] else 'false'}" for row in shapes)
    return f'''-- Generated by generate_arm64_branch_emit_spec.py from arm64_branch_emit_spec.json.
import Std
namespace KProgFormal.GeneratedArm64BranchEmit
/-- The two control-transfer code shapes the generator emits: a forward edge
(conditional jump with fall-through) and a backward edge (inverted conditional
jump to a local label, then an unconditional jump). -/
inductive Shape where
{ctors}
deriving DecidableEq, Repr
/-- Whether a shape is the backward-edge form. -/
def backward : Shape -> Bool
{backward}
/-- The shape the generator picks for a branch from `current` to `target`: a
target at or below the current address is a backward edge. -/
def shape (current target : Nat) : Shape :=
  if target <= current then .backward else .forward
/-- The next program counter the emitted code selects, given the already
evaluated predicate and the two candidate addresses. Both shapes branch to
`target` exactly when the predicate holds and fall through otherwise, so this is
the emitted-code counterpart of the architectural `branchPc`. -/
def nextPc (s : Shape) (taken : Bool) (fallthrough target : Nat) : Nat :=
  match s with
  | .forward => if taken then target else fallthrough
  | .backward => if taken then target else fallthrough
end KProgFormal.GeneratedArm64BranchEmit
'''


def render_c(shapes: list[dict]) -> str:
    return '''/* Generated by generate_arm64_branch_emit_spec.py from arm64_branch_emit_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_BRANCH_EMIT_H
#define KPROG_FORMAL_GENERATED_ARM64_BRANCH_EMIT_H
/*
 * AArch64 branch-emission shape: the generator emits a backward edge
 * (target <= current) as an inverted conditional jump to a local fall-through
 * label followed by an unconditional jump, and a forward edge as a plain
 * conditional jump with a fall-through. Both select the same next PC, which
 * KProgFormal/Arm64BranchEmit.lean proves equals the architectural branchPc.
 */
#define KPROG_ARM64_BRANCH_BACKWARD(CURRENT, TARGET)                        \\
\t((__u8)(((TARGET) <= (CURRENT)) ? 1 : 0))
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    shapes = load()
    for path, expected in ((LEAN, render_lean(shapes)), (CHEADER, render_c(shapes))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 branch-emit contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
