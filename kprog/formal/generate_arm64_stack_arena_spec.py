#!/usr/bin/env python3
"""Generate the shared AArch64 stack-arena storage-model contract.

The AArch64 simulator resolves a biased stack byte index to *storage* through a
union arena of two overlapping views (kprog/arm64/arm64_sim_local_bpf.h):

  union {
      __u8  b[160];
      __u64 q[20];
  } __a64_stack;

The stack helpers reach that storage three ways, and this contract fixes the
arithmetic each uses so it can be machine-checked:

  - the byte arena `b[]` is indexed directly by the 32-bit stack byte index;
  - the word arena `q[]` is indexed by that index shifted right 3, and is only
    ever used on the 64-bit path when the index is 8-aligned (the `& 7U`
    guard), so no byte-arena element is skipped;
  - the byte-arena read/write paths split/reassemble a 64-bit word byte by
    byte, little-endian, through the generated AArch64 byte-lane contract
    (`KPROG_ARM64_BYTE_AT`), whose inverse the load ladder already proves.

`KPROG_ARM64_STACK_WORDS` states the number of word slots the byte arena needs;
for the enabled 160-byte arena it is 20, and for the 1-byte disabled arena it is
1, so the word view always covers the byte view exactly.

A stack access reads or writes a *window* of `WIDTH` bytes starting at its
index, so the arena must hold `INDEX + WIDTH` bytes, not merely `INDEX`. The
contract also fixes that bound: an access fits when its end index is at most
the capacity, the C `INDEX + BYTES <= CAPACITY`, and a protocol that reaches
the arena without checking it over-runs the final `BYTES - 1` bytes.

The generated C macros evaluate no memory: they are pure index/bit
computations. `KProgFormal/Arm64StackArena.lean` restates each independently
and proves the two views address the same storage.
"""
import argparse
import json
from pathlib import Path

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64StackArena",
    "word_shift": 3,
    "word_mask": "0x7",
    "capacity_round": "ceil8",
    "arena_alias": "b-q-union",
    "window_guard": "index_plus_bytes_le_capacity",
}

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_stack_arena_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64StackArena.lean"
CHEADER = ROOT / "generated/arm64_stack_arena.h"


def load() -> dict:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 stack-arena specification: {data!r}")
    return EXPECTED


def render_lean(spec: dict) -> str:
    shift = spec["word_shift"]
    mask = int(spec["word_mask"], 16)
    return f'''-- Generated by generate_arm64_stack_arena_spec.py from arm64_stack_arena_spec.json.
import Std
namespace KProgFormal.GeneratedArm64StackArena
/-- Word-arena slot for a stack byte index: the index shifted right {shift}, the
C `INDEX >> {shift}`. Sound as a slot only when the index is {1 << shift}-aligned. -/
def wordIndex (index : BitVec 32) : BitVec 32 := index >>> {shift}

/-- The 64-bit fast-path guard: the index is {1 << shift}-aligned (its low {shift}
bits clear), the C `(INDEX & {mask}U) == 0U`. -/
def wordAligned (index : BitVec 32) : Bool := (index &&& {mask}) == 0

/-- Number of word slots the byte arena requires: the capacity rounded up to a
multiple of {1 << shift}, the C `((CAPACITY + {mask}U) / {1 << shift}U)`. -/
def words (capacity : BitVec 32) : BitVec 32 :=
  (capacity + {mask}) / {1 << shift}

/-- The first index past a `WIDTH`-byte access starting at `index`, the C
`(__u64)(INDEX) + (__u64)(WIDTH)`. Stated as a `Nat` sum because the C
comparison is widened to 64 bits, so an access near the top of the 32-bit
index space is measured exactly rather than wrapping. -/
def windowEnd (index width : BitVec 32) : Nat := index.toNat + width.toNat

/-- An access of `WIDTH` bytes at `index` stays inside an arena of `capacity`
bytes: its end index is at most the capacity, the C
`(__u64)(INDEX) + (__u64)(WIDTH) <= (__u64)(CAPACITY)`. -/
def windowFits (index width capacity : BitVec 32) : Bool :=
  decide (windowEnd index width ≤ capacity.toNat)
end KProgFormal.GeneratedArm64StackArena
'''


def render_c(spec: dict) -> str:
    shift = spec["word_shift"]
    mask = int(spec["word_mask"], 16)
    return f'''/* Generated by generate_arm64_stack_arena_spec.py from arm64_stack_arena_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_STACK_ARENA_H
#define KPROG_FORMAL_GENERATED_ARM64_STACK_ARENA_H
#define KPROG_ARM64_STACK_WORD_INDEX(INDEX) ((__u32)(INDEX) >> {shift})
#define KPROG_ARM64_STACK_WORD_ALIGNED(INDEX) \\
\t((((__u32)(INDEX) & {mask}U) == 0U) ? 1 : 0)
#define KPROG_ARM64_STACK_WORDS(CAPACITY) \\
\t(((__u32)(CAPACITY) + {mask}U) / {1 << shift}U)
#define KPROG_ARM64_STACK_TAG_SLOTS(CAPACITY) \\
\t(((__u32)(CAPACITY) + {mask}U) / {1 << shift}U)
/*
 * An access of BYTES bytes at INDEX fits an arena of CAPACITY bytes when the
 * first index past its window is at most CAPACITY. A caller that reaches the
 * arena without this guard over-runs the final BYTES - 1 bytes.
 */
#define KPROG_ARM64_STACK_WINDOW_END(INDEX, BYTES) \\
\t(((__u64)(__u32)(INDEX)) + ((__u64)(__u32)(BYTES)))
#define KPROG_ARM64_STACK_WINDOW_FITS(INDEX, BYTES, CAPACITY) \\
\t((KPROG_ARM64_STACK_WINDOW_END((INDEX), (BYTES)) <= (__u64)(__u32)(CAPACITY)) ? 1 : 0)
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = load()
    for path, expected in ((LEAN, render_lean(spec)), (CHEADER, render_c(spec))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 stack-arena contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
