#!/usr/bin/env python3
"""Generate the shared x86 bit-manipulation contract (BT and BZHI).

The generated Lean definitions `GeneratedX86Bitops.bt` / `bzhi` and the C
functions `kprog_x86_bt_value` / `kprog_x86_bzhi_value` implement the two
bit-indexed operations the simulator's `X86_SIM_L_EXEC_BT*` and
`X86_SIM_L_EXEC_BZHI*` handlers apply:

  - `bt`: the carry flag is the indexed bit of the narrowed base, where the index
    is hardware-masked to the width's bit count (63 for 64-bit, 31 otherwise);
  - `bzhi`: the base with every bit at or above the (byte-masked) index cleared,
    unless the index reaches the width, in which case the base is kept.

Both have a closed set of arms over the four `X86_WIDTH_*` codes and write no
flags other than the ones the caller derives from their results.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_bitops_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86Bitops.lean"
C_HEADER = ROOT / "generated/x86_bitops.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "x86Bitops",
    "widths": [
        {"name": "w8", "code": 1, "bits": 8, "index_mask": 31},
        {"name": "w16", "code": 2, "bits": 16, "index_mask": 31},
        {"name": "w32", "code": 4, "bits": 32, "index_mask": 31},
        {"name": "w64", "code": 8, "bits": 64, "index_mask": 63},
    ],
}


def load() -> None:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 bitops specification: {data!r}")
    widths = EXPECTED["widths"]
    if [row["bits"] for row in widths] != [8, 16, 32, 64]:
        raise SystemExit(f"invalid x86 bitops widths: {widths!r}")
    if [row["index_mask"] for row in widths] != [31, 31, 31, 63]:
        raise SystemExit(f"invalid x86 bitops index masks: {widths!r}")


def render_lean() -> str:
    return '''-- Generated by generate_x86_bitops_spec.py from x86_bitops_spec.json.
namespace KProgFormal.GeneratedX86Bitops
/-- The width mask for an x86 width code (1/2/4/8 bytes). -/
def widthMask (widthCode : Nat) : BitVec 64 :=
  match widthCode with
  | 1 => 0xff
  | 2 => 0xffff
  | 4 => 0xffffffff
  | _ => 0xffffffffffffffff
/-- The carry result of `bt`: the indexed bit of the narrowed base. The index is
masked to 63 for a 64-bit base and to 31 otherwise, which is exactly what the C
macro `X86_SIM_L_EXEC_BT*` computes (`__x86_l_width == X86_WIDTH_64 ? 63 : 31`).
This is *not* the width's bit count for the narrow widths: a sub-64-bit `bt` masks
the offset to 31 regardless of the access width, so an 8-bit `bt` with offset 8
tests bit 8 of the narrowed byte, which is always clear. -/
def bt (base index : BitVec 64) (widthCode : Nat) : Bool :=
  let bit := index &&& (if widthCode = 8 then 63 else 31)
  ((base &&& widthMask widthCode) >>> bit) &&& 1 != 0
/-- The result of `bzhi`: the narrowed base with every bit at or above the
byte-masked index cleared, or the whole base when the index reaches the width. -/
def bzhi (src count : BitVec 64) (widthCode : Nat) : BitVec 64 :=
  let b := widthCode * 8
  let c := count &&& 0xff
  let r := if BitVec.ult c (BitVec.ofNat 64 b)
           then src &&& ((BitVec.ofNat 64 1 <<< c) - 1)
           else src
  r &&& widthMask widthCode
end KProgFormal.GeneratedX86Bitops
'''


def render_c() -> str:
    return '''/* Generated by generate_x86_bitops_spec.py from x86_bitops_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_BITOPS_H
#define KPROG_FORMAL_GENERATED_X86_BITOPS_H
/*
 * x86 bit-manipulation helpers. `bt` returns the indexed bit of the narrowed
 * base (the handler assigns it to CF); `bzhi` returns the narrowed base with the
 * bits at or above the byte-masked index cleared (the handler derives CF from
 * whether the index reached the width). Both have a closed width set.
 */
static __always_inline __u8 kprog_x86_bt_value(__u64 base, __u64 index,
                                                __u8 width)
{
\t__u8 bit = (__u8)(index &
\t\t(width == X86_WIDTH_64 ? 63U : 31U));

\treturn (__u8)((KPROG_X86_APPLY_WIDTH(base, width) >> bit) & 1U);
}

static __always_inline __u64 kprog_x86_bzhi_value(__u64 src, __u64 count,
                                                   __u8 width)
{
\t__u32 bits = KPROG_X86_WIDTH_BITS(width);
\t__u64 c = count & 0xffULL;
\t__u64 result = src;

\tif (c < bits)
\t\tresult &= (1ULL << c) - 1ULL;
\treturn KPROG_X86_APPLY_WIDTH(result, width);
}
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    load()
    for path, expected in ((LEAN, render_lean()), (C_HEADER, render_c())):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated x86 bitops contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
