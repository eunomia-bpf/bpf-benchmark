#!/usr/bin/env python3
"""Generate the shared AArch64 write-register destination-presence contract.

The generated Lean definition `GeneratedArm64RegPresence.writable` and the C
macro `KPROG_ARM64_REG_WRITABLE` decide whether a decoded AArch64 register
number names a destination a write actually lands in:

  * the zero register (`31`, `ARM64_XZR`) discards the write;
  * the no-register sentinel (`0xff`, `ARM64_REG_NONE`) discards the write;
  * every other register number is a general-purpose register that receives it.

The simulator's three writeback bodies (`ARM64_SIM_L_WRITE_REG_WIDTH`,
`ARM64_SIM_L_WRITE_REG_PTR`, `ARM64_SIM_L_WRITE_REG_PTR_TAG`) each guard their
GPR dispatch on this exact `(REG) != ARM64_XZR && (REG) != ARM64_REG_NONE`
test. Routing that guard through `KPROG_ARM64_REG_WRITABLE` makes the
destination-presence decision a generated fact rather than a restated pair of
comparisons. `KProgFormal/Arm64RegPresence.lean` proves the generated predicate
equals an independent `decide (reg != 31 && reg != 0xff)`, pins the two lane
constants, and shows both discard arms are reachable.

The generated header is self-contained (no cross-include), exactly as the x86
and AArch64 memory-index mirrors; `Arm64RegPresence.lean` nonetheless proves
its zero/sentinel constants equal the values the register-number decode fixes.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_reg_presence_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64RegPresence.lean"
CHEADER = ROOT / "generated/arm64_reg_presence.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64RegPresence",
    "reg_bits": 8,
    "xzr_number": 31,
    "none_number": 255,
    "classes": [
        {"name": "gpr", "code": 0, "writable": True},
        {"name": "zero", "code": 1, "writable": False},
        {"name": "none", "code": 2, "writable": False},
    ],
}


def load() -> dict:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 reg-presence specification: {data!r}")
    classes = EXPECTED["classes"]
    if [row["name"] for row in classes] != ["gpr", "zero", "none"]:
        raise SystemExit(f"invalid arm64 reg-presence class order: {classes!r}")
    if [row["code"] for row in classes] != [0, 1, 2]:
        raise SystemExit(f"invalid arm64 reg-presence class codes: {classes!r}")
    if [row["writable"] for row in classes] != [True, False, False]:
        raise SystemExit(f"invalid arm64 reg-presence class flags: {classes!r}")
    if EXPECTED["xzr_number"] == EXPECTED["none_number"]:
        raise SystemExit("arm64 reg-presence zero and sentinel collide")
    return EXPECTED


def render_lean(spec: dict) -> str:
    classes = spec["classes"]
    ctors = "\n".join(f"  | {row['name']}" for row in classes)
    class_rows = "\n".join(
        f"  | .{row['name']} => {str(row['writable']).lower()}"
        for row in classes)
    bits = spec["reg_bits"]
    xzr = f"{spec['xzr_number']:#x}"
    none = f"{spec['none_number']:#x}"
    zero_name = next(row["name"] for row in classes if not row["writable"]
                     and row["name"] != "none")
    none_name = next(row["name"] for row in classes if row["name"] == "none")
    gpr_name = next(row["name"] for row in classes if row["writable"])
    return f'''-- Generated by generate_arm64_reg_presence_spec.py from arm64_reg_presence_spec.json.
import Std
namespace KProgFormal.GeneratedArm64RegPresence
/-- The destination classes a decoded AArch64 register number falls into: a
general-purpose register that receives a write, the zero register (`XZR`) that
discards it, and the no-register sentinel (`ARM64_REG_NONE`) that discards it. -/
inductive Class where
{ctors}
deriving DecidableEq, Repr
/-- The zero-register number (`ARM64_XZR`): a write to it is discarded. -/
def xzrNumber : BitVec {bits} := {xzr}
/-- The no-register sentinel (`ARM64_REG_NONE`): a write to it is discarded. -/
def noneNumber : BitVec {bits} := {none}
/-- The class a decoded register number names: the zero register and the
no-register sentinel are their own classes, every other number a GPR. -/
def classify (reg : BitVec {bits}) : Class :=
  if reg = xzrNumber then .{zero_name}
  else if reg = noneNumber then .{none_name}
  else .{gpr_name}
/-- Whether a write to register number `reg` lands in a destination: true for a
GPR, false for the zero register and the no-register sentinel. -/
def writable (reg : BitVec {bits}) : Bool :=
  match classify reg with
{class_rows}
end KProgFormal.GeneratedArm64RegPresence
'''


def render_c(spec: dict) -> str:
    classes = spec["classes"]
    class_defines = "\n".join(
        f"#define KPROG_ARM64_REG_CLASS_{row['name'].upper()} {row['code']}U"
        for row in classes)
    xzr = f"{spec['xzr_number']:#x}"
    none = f"{spec['none_number']:#x}"
    zero_name = next(row["name"] for row in classes if not row["writable"]
                     and row["name"] != "none").upper()
    none_name = next(row["name"] for row in classes if row["name"] == "none").upper()
    gpr_name = next(row["name"] for row in classes if row["writable"]).upper()
    return f'''/* Generated by generate_arm64_reg_presence_spec.py from arm64_reg_presence_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_REG_PRESENCE_H
#define KPROG_FORMAL_GENERATED_ARM64_REG_PRESENCE_H
/*
 * AArch64 write-register destination presence: a decoded register number is a
 * destination a write lands in unless it is the zero register (`31`,
 * `ARM64_XZR`) or the no-register sentinel (`0xff`, `ARM64_REG_NONE`).
 * `KProgFormal/Arm64RegPresence.lean` proves the presence test equals an
 * independent `decide (reg != 31 && reg != 0xff)`.
 */
/* The destination classes. */
{class_defines}
/* The zero register and the no-register sentinel. */
#define KPROG_ARM64_REG_XZR {xzr}U
#define KPROG_ARM64_REG_NONE {none}U
/*
 * REG is a decoded AArch64 register number. It is evaluated once; the result is
 * 1 exactly when a write to REG lands in a destination (a GPR), 0 for the zero
 * register and the no-register sentinel. No flags written.
 */
#define KPROG_ARM64_REG_WRITABLE(REG)                                       \\
\t((__u8)(((REG) != KPROG_ARM64_REG_XZR && (REG) != KPROG_ARM64_REG_NONE) \\
\t\t ? 1 : 0))
/*
 * The class REG names: a GPR, the zero register or the no-register sentinel.
 * Evaluated once; no flags written.
 */
#define KPROG_ARM64_REG_CLASS(REG)                                          \\
\t((__u8)(((REG) == KPROG_ARM64_REG_XZR) ? KPROG_ARM64_REG_CLASS_{zero_name} \\
\t\t : ((REG) == KPROG_ARM64_REG_NONE) ? KPROG_ARM64_REG_CLASS_{none_name} \\
\t\t : KPROG_ARM64_REG_CLASS_{gpr_name}))
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = load()
    for path, expected in ((LEAN, render_lean(spec)),
                           (CHEADER, render_c(spec))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 reg-presence contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
