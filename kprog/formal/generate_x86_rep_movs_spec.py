#!/usr/bin/env python3
"""Generate the x86-64 `REP MOVS` block-copy contract.

`REP MOVS` (`X86_OP_REP_MOVS`, `0x3a`) is a single `X86_SIM_L_EXEC` arm, so
unlike the two-opcode `PUSH`/`POP` composition it carries no per-opcode table.
What it pins is the shape of its three head-scratchers:

  * the copy width is the FLAGS-resolved width, `FLAGS ? FLAGS : 64` — the same
    resolution `POP` uses, but here it also fixes the *addressing stride*;
  * the element bound is the literal `64` loop bound, independent of the count
    the body copies (`X86_SIM_L_REP_MOVS_ONE` guards on `i < count`); and
  * the count the body copies is the raw instruction immediate `IMM` — not
    `RCX` — while the trailing `RCX` writeback zeroes `RCX` at the hardcoded
    64-bit width.

The two constants `copy_bound = 64` and `count_width = b64` are the plausible
bugs: a body that bounded the loop by `IMM`, or that zeroed `RCX` at the
FLAGS-resolved width, would still copy a plausible number of bytes. The
contract fixes them as literals; the FLAGS resolution, the loop, the byte
load/store, and the pointer arithmetic stay in the C handler.

Outputs (both regenerated whole, `--check` rejects any stale copy):
  * `KProgFormal/GeneratedX86RepMovs.lean`
  * `generated/x86_rep_movs.h`
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_rep_movs_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86RepMovs.lean"
CHEADER = ROOT / "generated/x86_rep_movs.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "x86RepMovs",
    "selector": "flags_resolved_copy_width_then_literal_bound_then_fixed_count_width",
    "op_define": "X86_OP_REP_MOVS",
    "op_code": "0x3a",
    "copy_bound": 64,
    "default_width": "b64",
    "count_width": "b64",
}

OP_DEFINE = "X86_OP_REP_MOVS"
OP_CODE = "0x3a"
COPY_BOUND = 64
DEFAULT_WIDTH = "b64"
COUNT_WIDTH = "b64"


def load():
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 rep_movs specification: {data!r}")
    if data["op_define"] != OP_DEFINE or data["op_code"] != OP_CODE:
        raise SystemExit(f"invalid x86 rep_movs opcode: {data!r}")
    # The bound and the count width are the independent facts: the body copies
    # at most `copy_bound` elements whatever the immediate says, and it zeroes
    # RCX at the *fixed* count width, not at the FLAGS-resolved copy width. A
    # spec that let the bound track the immediate, or the count width track the
    # FLAGS code, would have collapsed the two facts.
    if data["copy_bound"] != COPY_BOUND:
        raise SystemExit(f"invalid x86 rep_movs copy bound: {data!r}")
    if data["default_width"] != DEFAULT_WIDTH:
        raise SystemExit(f"invalid x86 rep_movs default width: {data!r}")
    if data["count_width"] != COUNT_WIDTH:
        raise SystemExit(f"invalid x86 rep_movs count width: {data!r}")
    return data


def render_lean(data) -> str:
    return f'''-- Generated by generate_x86_rep_movs_spec.py from x86_rep_movs_spec.json.
import Std
import KProgFormal.GeneratedX86Store
namespace KProgFormal.GeneratedX86RepMovs
open GeneratedX86Store (Code)
/-- The literal element bound the `REP MOVS` body iterates to, whatever count
the instruction immediate carries. The copy helper guards each element on the
count, so the body copies `min repMovsBound count` elements. -/
def repMovsBound : Nat := {COPY_BOUND}
/-- The width a `REP MOVS` body falls back to when its opcode carries the
"absent" FLAGS code 0. -/
def repMovsCopyWidthDefault : GeneratedX86Store.Code := .{DEFAULT_WIDTH}
/-- The fixed width at which the `REP MOVS` body zeroes `RCX` after the copy,
independent of the FLAGS-resolved copy width. -/
def repMovsCountWidth : GeneratedX86Store.Code := .{COUNT_WIDTH}
/-- The resolved copy width: the opcode's FLAGS code itself, or 64 bits when it
carries none. The same resolution the `POP` body applies, restated here so the
copy width does not silently depend on the pushpop module. -/
def resolveWidth : Code -> Code
  | .absent => .b64
  | .b8 => .b8
  | .b16 => .b16
  | .b32 => .b32
  | .b64 => .b64
/-- The number of elements the body actually copies: the literal bound capped
by the instruction immediate. -/
def repMovsElementCount (count : Nat) : Nat := min repMovsBound count
end KProgFormal.GeneratedX86RepMovs
'''


def render_c(data) -> str:
    return f'''/* Generated by generate_x86_rep_movs_spec.py from x86_rep_movs_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_REP_MOVS_H
#define KPROG_FORMAL_GENERATED_X86_REP_MOVS_H
/*
 * x86-64 `REP MOVS` block-copy contract. The copy width is the FLAGS-resolved
 * width `FLAGS ? FLAGS : 64`; the loop bound is the literal {COPY_BOUND}; the
 * count copied is the raw instruction immediate (not RCX); and the trailing
 * RCX writeback zeroes RCX at the fixed 64-bit width. The bound and the count
 * width are independent of the immediate and of the FLAGS code. The contract
 * selects these; the FLAGS resolution, the loop, the byte load/store, and the
 * pointer arithmetic stay in the C handler.
 */
_Static_assert({OP_DEFINE} == {OP_CODE}U, "x86 rep_movs opcode drift");
/* The FLAGS width codes, including the 0 "absent" code. */
#define X86_WIDTH_8 1U
#define X86_WIDTH_16 2U
#define X86_WIDTH_32 4U
#define X86_WIDTH_64 8U
_Static_assert(X86_WIDTH_64 == 8U, "x86 width code drift");
/* The literal element bound the body iterates to. */
#define KPROG_X86_REP_MOVS_BOUND {COPY_BOUND}U
/* The width a body falls back to when its FLAGS code is absent. */
#define KPROG_X86_REP_MOVS_COPY_WIDTH_DEFAULT X86_WIDTH_64
/* The fixed width at which the body zeroes RCX. */
#define KPROG_X86_REP_MOVS_COUNT_WIDTH X86_WIDTH_64
/*
 * FLAGS is the opcode's width code, with 0 the "absent" code; the resolved
 * copy width is the code itself, or the 64-bit default when it is absent —
 * exactly the resolution the body applies. The input is evaluated as the body
 * evaluates it.
 */
#define KPROG_X86_REP_MOVS_WIDTH(FLAGS)                                     \\
	((FLAGS) ? (FLAGS) : KPROG_X86_REP_MOVS_COPY_WIDTH_DEFAULT)
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = load()
    for path, expected in ((LEAN, render_lean(data)), (CHEADER, render_c(data))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated x86 rep_movs contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
