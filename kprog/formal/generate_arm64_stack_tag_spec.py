#!/usr/bin/env python3
"""Generate the shared AArch64 stack slot-tag selection contract.

The generated Lean definition `GeneratedArm64StackTag.value` and the C predicate
`KPROG_ARM64_STACK_TAG` decide whether a stack access carries the slot's stored
tag or the plain scalar tag. Only a 64-bit access at a qword-aligned stack slot
reads (or writes) the per-slot tag array; every other access is scalar, because a
sub-qword or unaligned access shares its slot with other values.

The two conditions (width is 64, offset is 8-aligned) are a closed pair, so the
predicate is total. The C predicate evaluates its inputs and writes no NZCV.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_stack_tag_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedArm64StackTag.lean"
CHEADER = ROOT / "generated/arm64_stack_tag.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64StackTag",
    "cases": [
        {"name": "qword", "w64": True, "aligned": True, "tagged": True},
        {"name": "sub_qword_aligned", "w64": False, "aligned": True, "tagged": False},
        {"name": "qword_unaligned", "w64": True, "aligned": False,
         "tagged": False},
        {"name": "sub_qword_unaligned", "w64": False, "aligned": False,
         "tagged": False},
    ],
}


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 stack-tag specification: {data!r}")
    cases = EXPECTED["cases"]
    if [row["name"] for row in cases] != [
            "qword", "sub_qword_aligned", "qword_unaligned", "sub_qword_unaligned"]:
        raise SystemExit(f"invalid arm64 stack-tag order: {cases!r}")
    if [row["tagged"] for row in cases] != [True, False, False, False]:
        raise SystemExit(f"invalid arm64 stack-tag table: {cases!r}")
    return cases


def render_lean(cases: list[dict]) -> str:
    ctors = "\n".join(f"  | {row['name']}" for row in cases)
    table = "\n".join(
        f"  | .{row['name']} => {'true' if row['tagged'] else 'false'}"
        for row in cases)
    # Arms are matched right-to-left: the last binder varies fastest.
    classify = []
    for w64 in (True, False):
        for aligned in (True, False):
            row = next(r for r in cases
                       if r["w64"] == w64 and r["aligned"] == aligned)
            classify.append(f"    | {'true' if w64 else 'false'}, "
                            f"{'true' if aligned else 'false'} => .{row['name']}")
    classify = "\n".join(classify)
    return f'''-- Generated by generate_arm64_stack_tag_spec.py from arm64_stack_tag_spec.json.
import Std
namespace KProgFormal.GeneratedArm64StackTag
/-- The four (width, alignment) cases a stack access can have. -/
inductive Case where
{ctors}
deriving DecidableEq, Repr
/-- Classify an access by whether it is 64-bit and whether its slot is
qword-aligned. -/
def classify (isW64 isAligned : Bool) : Case :=
  match isW64, isAligned with
{classify}
/-- Whether a case reads or writes the per-slot tag array. -/
def tagged : Case -> Bool
{table}
/-- Independent statement of the selection: a slot is tagged exactly when the
access is 64-bit and qword-aligned. -/
def taggedSpec (isW64 isAligned : Bool) : Bool := isW64 && isAligned
/-- The four-case table agrees with the independent `&&` statement for every
access: classifying then testing the table equals the direct conjunction. -/
theorem tagged_refines (isW64 isAligned : Bool) :
    tagged (classify isW64 isAligned) = taggedSpec isW64 isAligned := by
  cases isW64 <;> cases isAligned <;> rfl
end KProgFormal.GeneratedArm64StackTag
'''


def render_c(cases: list[dict]) -> str:
    return f'''/* Generated by generate_arm64_stack_tag_spec.py from arm64_stack_tag_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_STACK_TAG_H
#define KPROG_FORMAL_GENERATED_ARM64_STACK_TAG_H
/*
 * AArch64 stack slot-tag selection. Only a 64-bit access at a qword-aligned
 * stack slot carries the slot's stored tag; every other access is scalar. The
 * two conditions are a closed pair, so the predicate is total.
 */
/*
 * IS_W64 is true when the access width is 64 bits; IS_ALIGNED is true when the
 * stack slot index is 8-aligned. Both inputs are evaluated once and no NZCV is
 * written. The result is 1 when the slot tag applies, 0 otherwise.
 */
#define KPROG_ARM64_STACK_TAG(IS_W64, IS_ALIGNED)                           \\
\t((__u8)(((IS_W64) && (IS_ALIGNED)) ? 1 : 0))
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    cases = load()
    for path, expected in ((LEAN, render_lean(cases)),
                           (CHEADER, render_c(cases))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 stack-tag contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
