#!/usr/bin/env python3
"""Generate the shared x86-64 stack-arena storage-model contract.

The x86 simulator resolves an abstract frame offset to *storage* through a
union arena of two overlapping views (kprog/x86/x86_sim_local_bpf.h):

  union x86_sim_stack_mem {
      __u8  b[X86_SIM_STACK_BYTES];                 /* byte arena  */
      __u64 q[(X86_SIM_STACK_BYTES + 7U) / 8U];     /* word arena  */
  };

The stack helpers reach that storage three ways, and this contract fixes the
arithmetic each uses so it can be machine-checked:

  - the byte arena `b[]` is indexed directly by the 32-bit stack index;
  - the word arena `q[]` is indexed by that index shifted right 3, and is only
    ever used on the 64-bit path when the index is 8-aligned (the `& 7U`
    guard), so no byte-arena element is skipped;
  - the byte-arena read/write paths split/reassemble a 64-bit word byte by
    byte, little-endian.

`KPROG_X86_STACK_WORDS` states the number of word slots the byte arena needs.

The generated C macros evaluate no memory: they are pure index/bit
computations. `KProgFormal/X86StackArena.lean` restates each independently and
proves the two views address the same storage.
"""
import argparse
import json
from pathlib import Path
EXPECTED = {
    "schema_version": 1,
    "operation": "x86StackArena",
    "word_shift": 3,
    "word_mask": "0x7",
    "capacity_round": "ceil8",
    "arena_alias": "b-q-union",
    "assemble": "little_endian8",
}

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "x86_stack_arena_spec.json"
LEAN = ROOT / "KProgFormal/GeneratedX86StackArena.lean"
CHEADER = ROOT / "generated/x86_stack_arena.h"


def load() -> dict:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid x86 stack-arena specification: {data!r}")
    return EXPECTED


def render_lean(spec: dict) -> str:
    shift = spec["word_shift"]
    mask = int(spec["word_mask"], 16)
    return f'''-- Generated by generate_x86_stack_arena_spec.py from x86_stack_arena_spec.json.
import Std
namespace KProgFormal.GeneratedX86StackArena
/-- Word-arena slot for a byte index: the index shifted right {shift}, the C
`INDEX >> {shift}`. Sound as a slot only when the index is {1 << shift}-aligned. -/
def wordIndex (index : BitVec 32) : BitVec 32 := index >>> {shift}

/-- The 64-bit fast-path guard: the index is {1 << shift}-aligned (its low {shift}
bits clear), the C `(INDEX & {mask}U) == 0U`. -/
def wordAligned (index : BitVec 32) : Bool := (index &&& {mask}) == 0

/-- Byte `k` of a 64-bit word, little-endian, the C `(WORD >> (8U * K))`. -/
def byteAt (word : BitVec 64) (k : Nat) : BitVec 8 :=
  (word >>> (8 * k)).setWidth 8

/-- Assemble byte `k` little-endian into a 64-bit word at bit offset 8·`k`: the
C `((__u64)(BYTE) << (8U * K))`. -/
def assembleByte (byte : BitVec 8) (k : Nat) : BitVec 64 :=
  (byte.setWidth 64) <<< (8 * k)

/-- Number of word slots the byte arena requires: the capacity rounded up to a
multiple of {1 << shift}, the C `((CAPACITY + {mask}U) / {1 << shift}U)`. -/
def words (capacity : BitVec 32) : BitVec 32 :=
  (capacity + {mask}) / {1 << shift}
end KProgFormal.GeneratedX86StackArena
'''


def render_c(spec: dict) -> str:
    shift = spec["word_shift"]
    mask = int(spec["word_mask"], 16)
    return f'''/* Generated by generate_x86_stack_arena_spec.py from x86_stack_arena_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_STACK_ARENA_H
#define KPROG_FORMAL_GENERATED_X86_STACK_ARENA_H
#define KPROG_X86_STACK_WORD_INDEX(INDEX) ((__u32)(INDEX) >> {shift})
#define KPROG_X86_STACK_WORD_ALIGNED(INDEX) \\
\t((((__u32)(INDEX) & {mask}U) == 0U) ? 1 : 0)
#define KPROG_X86_STACK_BYTE(WORD, K) \\
\t((__u8)(((__u64)(WORD)) >> (8U * (__u32)(K))))
#define KPROG_X86_STACK_WORDS(CAPACITY) \\
\t(((__u32)(CAPACITY) + {mask}U) / {1 << shift}U)
#define KPROG_X86_STACK_ASSEMBLE(BYTE, K) \\
\t(((__u64)((__u8)(BYTE))) << (8U * (__u32)(K)))
#endif
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = load()
    for path, expected in ((LEAN, render_lean(spec)), (CHEADER, render_c(spec))):
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(f"generated x86 stack-arena contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
