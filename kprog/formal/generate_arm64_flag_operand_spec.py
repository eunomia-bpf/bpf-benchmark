#!/usr/bin/env python3
"""Generate the shared AArch64 flag-family operand-source contract.

The six NZCV-producing compare/arithmetic arm pairs of the AArch64 handler
(`SUBS`/`ADDS`/`CMP`/`TST`/`ANDS`/`CCMP`) each select their right-hand operand
from either the decoded immediate or the register form. In the handler this was
an inlined ternary per opcode

    __u64 rhs = (OP) == ARM64_OP_<F>_IMM ? (__u64)(IMM) : <register expression>;

This contract pins the ISA decision that the `_IMM` member of each pair selects
the immediate and the `_REG` member selects the caller-supplied register
expression. The numeric case labels are the `_IMM` codes of the six pairs; the
`_REG` codes are pinned as non-selected family members (they reach the register
arm through the caller's own dispatch, so the macro never sees them). The
immediate value, the register expression (modifier-rewritten for the
arithmetic/logical pairs, the bare `SRC` read for `CCMP`), and the surrounding
flag and writeback effects stay in the handler.

All twelve opcode numbers are re-checked against kprog/arm64/arm64_sim.h,
so a drift there fails `--check`.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "arm64_flag_operand_spec.json"
SIM_HEADER = ROOT.parent / "arm64/arm64_sim.h"
LEAN = ROOT / "KProgFormal/GeneratedArm64FlagOperand.lean"
CHEADER = ROOT / "generated/arm64_flag_operand.h"

EXPECTED = {
    "schema_version": 1,
    "operation": "arm64FlagOperand",
    "families": [
        {"name": "subs",
         "imm": {"name": "subsImm", "code": 48, "macro": "ARM64_OP_SUBS_IMM"},
         "reg": {"name": "subsReg", "code": 50, "macro": "ARM64_OP_SUBS_REG"}},
        {"name": "adds",
         "imm": {"name": "addsImm", "code": 49, "macro": "ARM64_OP_ADDS_IMM"},
         "reg": {"name": "addsReg", "code": 66, "macro": "ARM64_OP_ADDS_REG"}},
        {"name": "cmp",
         "imm": {"name": "cmpImm", "code": 22, "macro": "ARM64_OP_CMP_IMM"},
         "reg": {"name": "cmpReg", "code": 23, "macro": "ARM64_OP_CMP_REG"}},
        {"name": "tst",
         "imm": {"name": "tstImm", "code": 24, "macro": "ARM64_OP_TST_IMM"},
         "reg": {"name": "tstReg", "code": 25, "macro": "ARM64_OP_TST_REG"}},
        {"name": "ands",
         "imm": {"name": "andsImm", "code": 55, "macro": "ARM64_OP_ANDS_IMM"},
         "reg": {"name": "andsReg", "code": 45, "macro": "ARM64_OP_ANDS_REG"}},
        {"name": "ccmp",
         "imm": {"name": "ccmpImm", "code": 26, "macro": "ARM64_OP_CCMP_IMM"},
         "reg": {"name": "ccmpReg", "code": 27, "macro": "ARM64_OP_CCMP_REG"}},
    ],
}

OPCODE_DEFINE = re.compile(
    r"^#define\s+(ARM64_OP_[A-Z0-9_]+)\s+0x([0-9a-fA-F]+)U\s*$", re.M)


def load() -> list[dict]:
    data = json.loads(SPEC.read_text())
    if data != EXPECTED:
        raise SystemExit(f"invalid arm64 flag operand specification: {data!r}")
    families = EXPECTED["families"]
    names = [row["name"] for row in families]
    if names != ["subs", "adds", "cmp", "tst", "ands", "ccmp"]:
        raise SystemExit(f"invalid arm64 flag operand family order: {names!r}")
    opcodes = {name: int(value, 16)
               for name, value in OPCODE_DEFINE.findall(SIM_HEADER.read_text())}
    if not opcodes:
        raise SystemExit(
            f"no ARM64_OP_* opcode definitions found in {SIM_HEADER}")
    for row in families:
        for form in ("imm", "reg"):
            item = row[form]
            if opcodes.get(item["macro"]) != item["code"]:
                raise SystemExit(
                    "arm64 flag operand opcodes drift from "
                    "kprog/arm64/arm64_sim.h: "
                    f"spec={item['macro']}={item['code']} "
                    f"sim={opcodes.get(item['macro'])}")
    return families


def render_lean(families: list[dict]) -> str:
    ctors = "\n".join(
        f"  | {row['imm']['name']}\n  | {row['reg']['name']}" for row in families)
    imm_codes = "\n".join(
        f"  | .{row['imm']['name']} => {row['imm']['code']}" for row in families)
    reg_codes = "\n".join(
        f"  | .{row['reg']['name']} => {row['reg']['code']}" for row in families)
    selects = "\n".join(
        f"  | .{row['imm']['name']} => true\n  | .{row['reg']['name']} => false"
        for row in families)
    return f'''-- Generated by generate_arm64_flag_operand_spec.py from arm64_flag_operand_spec.json.
import KProgFormal.GeneratedArm64Width
namespace KProgFormal.GeneratedArm64FlagOperand
open KProgFormal.GeneratedArm64Width (Width)
/-- The twelve AArch64 flag-arm opcodes: the immediate and register member of each
of the six `SUBS`/`ADDS`/`CMP`/`TST`/`ANDS`/`CCMP` pairs. -/
inductive FlagOp where
{ctors}
deriving DecidableEq, Repr
/-- The ARM64_OP_* opcode number the flag arm carries in arm64_sim.h. -/
def code : FlagOp -> Nat
{imm_codes}
{reg_codes}
/-- Whether this opcode selects the decoded immediate as its right-hand operand
(rather than the caller-supplied register expression). Exactly the `_IMM` member
of each pair selects the immediate. -/
def immediate (op : FlagOp) : Bool :=
  match op with
{selects}
end KProgFormal.GeneratedArm64FlagOperand
'''


def render_c(families: list[dict]) -> str:
    asserts = []
    for row in families:
        for form in ("imm", "reg"):
            item = row[form]
            asserts.append(
                f'_Static_assert({item["macro"]} == {item["code"]}U, '
                '"arm64 flag operand code drift");')
    cases = []
    for row in families:
        cases.append(f"\t\tcase {row['imm']['code']}U:")
        cases.append("\t\t\t__kprog_a64_fo_rhs = (IMM);")
        cases.append("\t\t\tbreak;")
    body = [
        "\t({",
        "\t\t__u64 __kprog_a64_fo_rhs = (REG);",
        "",
        "\t\tswitch (OP) {",
    ] + cases + [
        "\t\tdefault:",
        "\t\t\tbreak;",
        "\t\t}",
        "\t\t__kprog_a64_fo_rhs;",
        "\t})",
    ]
    continued = " \\\n".join(body)
    return f'''/* Generated by generate_arm64_flag_operand_spec.py from arm64_flag_operand_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_ARM64_FLAG_OPERAND_H
#define KPROG_FORMAL_GENERATED_ARM64_FLAG_OPERAND_H
/*
 * The right-hand-operand selection shared by the six AArch64 flag-arm pairs
 * (SUBS/ADDS/CMP/TST/ANDS/CCMP): the `_IMM` member of each pair selects the
 * decoded immediate, every other (register) opcode selects the caller-supplied
 * register expression. The register expression is the caller's, because the
 * arithmetic/logical pairs rewrite it through the source modifier while CCMP
 * reads it directly. A code outside the six `_IMM` labels is not a selection and
 * returns the register expression.
 */
{chr(10).join(asserts)}
/*
 * OP is the arm opcode, IMM the decoded immediate and REG the register-form
 * right-hand expression. OP, IMM and REG are each evaluated exactly once, so a
 * register expression with a side effect still runs at most once. The result is
 * IMM exactly when OP is one of the six immediate case labels, and REG otherwise.
 */
#define KPROG_ARM64_FLAG_RHS(OP, IMM, REG)                                  \\
{continued}
#endif
'''

def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    families = load()
    outputs = ((LEAN, render_lean(families)), (CHEADER, render_c(families)))
    for path, expected in outputs:
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"generated arm64 flag operand contract is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
