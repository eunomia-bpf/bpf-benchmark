#!/usr/bin/env python3
"""Generate the shared x86 width/narrowing contract for Lean and C."""
import argparse, json
from pathlib import Path
ROOT=Path(__file__).resolve().parent
SPEC=ROOT/"x86_width_spec.json"; LEAN=ROOT/"KProgFormal/GeneratedX86Width.lean"; CHEADER=ROOT/"generated/x86_width.h"
EXPECTED=[
 ("w8",1,8,"0xff","0x80"),
 ("w16",2,16,"0xffff","0x8000"),
 ("w32",4,32,"0xffffffff","0x80000000"),
 ("w64",8,64,"0xffffffffffffffff","0x8000000000000000"),
]
def load():
 data=json.loads(SPEC.read_text())
 if set(data)!={"schema_version","operation","widths","effective"} or data["schema_version"]!=1 or data["operation"]!="x86Width": raise SystemExit(f"invalid x86 width specification: {data!r}")
 if len(data["widths"])!=4: raise SystemExit(f"invalid x86 width list: {data['widths']!r}")
 for w,e in zip(data["widths"],EXPECTED,strict=True):
  if set(w)!={"name","code","bits","mask","sign_mask"} or (w["name"],w["code"],w["bits"],w["mask"],w["sign_mask"])!=e: raise SystemExit(f"non-canonical x86 width: {w!r}")
 if set(data["effective"])!={"absent_code","default_name"}: raise SystemExit(f"invalid x86 effective width resolution: {data['effective']!r}")
 ac=data["effective"]["absent_code"]; names=[w["name"] for w in data["widths"]]; codes_=[w["code"] for w in data["widths"]]
 if ac!=0: raise SystemExit(f"non-canonical x86 effective absent code: {data['effective']!r}")
 if ac in codes_: raise SystemExit(f"x86 effective absent code collides with a width code: {data['effective']!r}")
 if data["effective"]["default_name"] not in names: raise SystemExit(f"unknown x86 effective default width: {data['effective']!r}")
 default=[w for w in data["widths"] if w["name"]==data["effective"]["default_name"]][0]
 if default["bits"]!=64: raise SystemExit(f"x86 effective default must be the 64-bit width: {default!r}")
 return data["widths"],data["effective"]
def render_lean(ws,eff):
 cs="\n".join(f"  | {w['name']}" for w in ws); codes="\n".join(f"  | .{w['name']} => {w['code']}" for w in ws); ms="\n".join(f"  | .{w['name']} => BitVec.ofNat 64 {w['mask']}" for w in ws); signs="\n".join(f"  | .{w['name']} => BitVec.ofNat 64 {w['sign_mask']}" for w in ws); bs="\n".join(f"  | .{w['name']} => {w['bits']}" for w in ws)
 default=[w for w in ws if w["name"]==eff["default_name"]][0]
 return f'''-- Generated by generate_x86_width_spec.py from x86_width_spec.json.
import Std
namespace KProgFormal.GeneratedX86Width
inductive Width
{cs}
  deriving DecidableEq, Repr
def code : Width -> Nat
{codes}
def mask : Width -> BitVec 64
{ms}
def signMask : Width -> BitVec 64
{signs}
def bits : Width -> Nat
{bs}
def narrow (value : BitVec 64) (width : Width) := BitVec.and value (mask width)
def zero (value : BitVec 64) (width : Width) : Bool := narrow value width == 0
def sign (value : BitVec 64) (width : Width) : Bool := (narrow value width).getLsbD (bits width - 1)
/-- The decoded width code that means "absent": a body that leaves its width
field empty falls back to the default code. -/
def absentCode : Nat := {eff["absent_code"]}
/-- The decoded width code an absent width field resolves to: the {default["bits"]}-bit width. -/
def defaultCode : Nat := {default["code"]}
/-- Resolve a decoded width code to the code a body operates at. The absent code
({eff["absent_code"]}) falls back to {default["code"]} (the {default["bits"]}-bit width); every other code is used as
decoded, exactly as the simulator's inline fallback did. -/
def effective (code : Nat) : Nat :=
  if code = absentCode then defaultCode else code
end KProgFormal.GeneratedX86Width
'''
def render_c(ws,eff):
 assertions="\n".join(f'_Static_assert(X86_WIDTH_{w["bits"]} == {w["code"]}U, "x86 width code drift");' for w in ws)
 masks=" \\\n".join(f"\t((WIDTH) == X86_WIDTH_{w['bits']} ? {w['mask']}ULL :" for w in ws[:-1]); signs=" \\\n".join(f"\t((WIDTH) == X86_WIDTH_{w['bits']} ? {w['sign_mask']}ULL :" for w in ws[:-1]); bits=" \\\n".join(f"\t((WIDTH) == X86_WIDTH_{w['bits']} ? {w['bits']}U :" for w in ws[:-1]); closes=")"*3
 default=[w for w in ws if w["name"]==eff["default_name"]][0]
 return f'''/* Generated by generate_x86_width_spec.py from x86_width_spec.json. */
#ifndef KPROG_FORMAL_GENERATED_X86_WIDTH_H
#define KPROG_FORMAL_GENERATED_X86_WIDTH_H
{assertions}
#define KPROG_X86_WIDTH_MASK(WIDTH)                                         \\
{masks} \\
\t 0xffffffffffffffffULL{closes}
#define KPROG_X86_WIDTH_SIGN_MASK(WIDTH)                                    \\
{signs} \\
\t 0x8000000000000000ULL{closes}
#define KPROG_X86_WIDTH_BITS(WIDTH)                                         \\
{bits} \\
\t 64U{closes}
#define KPROG_X86_APPLY_WIDTH(VALUE, WIDTH) ((VALUE) & KPROG_X86_WIDTH_MASK(WIDTH))
/* The decoded width code that means "absent": a body that leaves its width
 * field empty falls back to the default code. */
#define KPROG_X86_WIDTH_ABSENT_CODE {eff["absent_code"]}U
#define KPROG_X86_WIDTH_EFFECTIVE_DEFAULT X86_WIDTH_{default["bits"]}
/* Resolve a decoded width code to the code a body operates at: the absent code
 * ({eff["absent_code"]}) falls back to the {default["bits"]}-bit default, every other code is used as
 * decoded. The operand is evaluated as the body evaluates it. */
#define KPROG_X86_WIDTH_EFFECTIVE(CODE)                                     \\
\t((CODE) != KPROG_X86_WIDTH_ABSENT_CODE ? (CODE) :                     \\
\t KPROG_X86_WIDTH_EFFECTIVE_DEFAULT)
#endif
'''
def main():
 p=argparse.ArgumentParser(); p.add_argument("--check",action="store_true"); a=p.parse_args(); ws,eff=load()
 for path,want in ((LEAN,render_lean(ws,eff)),(CHEADER,render_c(ws,eff))):
  if a.check:
   if not path.is_file() or path.read_text()!=want: raise SystemExit(f"generated x86 width contract is stale: {path}")
  else: path.parent.mkdir(parents=True,exist_ok=True); path.write_text(want)
if __name__=="__main__": main()
