// Per-pass × per-app apply/match/skip totals across the 542-program testbin
// corpus. Writes a checked-in YAML snapshot at
// `bpfopt/testbin/applied_counts.yaml`. The test fails if the freshly computed
// totals diverge from the checked-in snapshot; refresh after intentional pass
// changes with:
//
//   BPFOPT_TESTBIN_UPDATE=1 cargo test -p bpfopt --test testbin_pass_counts
//
// Verifier-state-consuming passes (`map_inline`, `const_prop`) run with empty
// verifier states here, so their apply counts are 0 even if real daemon-side
// verifier logs would let them fire. `branch_flip` is skipped (per-site PMU
// profile required). `prog_type` is unknown for testbin entries, so passes
// gated on packet ctx layout (`skb_load_bytes_spec`, `bounds_check_merge`)
// short-circuit. The snapshot is still load-bearing because most passes
// (`dce`, `wide_mem`, `noop`, all kinsn-class passes) operate on bytecode +
// arch alone, and a regression in those will surface as a YAML diff.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use bpfopt::analysis::{lift_with_pass_context, print_and_reset_timing, ProgramCFG};
use bpfopt::insn::BpfInsn;
use bpfopt::pass::{run_pass_once, KinsnRegistry, PassContext};
use bpfopt::passes::{PassRegistryEntry, PASS_REGISTRY};

const APPS: &[&str] = &[
    "bcc_set",
    "bpftrace_set",
    "cilium_agent",
    "katran",
    "otelcol-ebpf-profiler_profiling",
    "tetragon_observer",
    "tracee_monitor",
];

// Passes that require external side-input we can't synthesize from bytecode
// alone, so they're excluded from the YAML.
const EXCLUDED_PASSES: &[&str] = &[
    "map_inline",  // needs --map-values + map_ids
    "branch_flip", // needs per-site PMU profile (PassContext::annotations)
];

const SNAPSHOT_HEADER: &str = "\
# Per-pass × per-app apply/match/skip totals across the 542-program testbin
# corpus. Generated by `cargo test -p bpfopt --test testbin_pass_counts`.
# Refresh after intentional pass behavior changes:
#   BPFOPT_TESTBIN_UPDATE=1 cargo test -p bpfopt --test testbin_pass_counts
#
# Coverage caveats:
# - `map_inline` and `branch_flip` are excluded (need external side-input).
# - `const_prop` runs with empty verifier states; expect zero applied.
# - prog_type=0 here, so `skb_load_bytes_spec` and `bounds_check_merge` bail.
# - `arch` defaults to X86_64.
#
# Schema: pass_name -> app_name -> {progs, applied, matched, skipped,
# progs_with_apply, progs_failed}. The `_total` row aggregates across apps.
";

// Gated test: spans 542 programs × ~14 passes and takes several minutes on a
// release build (cilium ≈100s, otel ≈10min). Opt-in via either
// BPFOPT_TESTBIN_VERIFY=1 (assert against checked-in YAML) or
// BPFOPT_TESTBIN_UPDATE=1 (regenerate the YAML). Without either, the test
// returns immediately so the default `cargo test` stays fast.
#[test]
fn testbin_pass_counts_snapshot() -> Result<()> {
    let verify = std::env::var_os("BPFOPT_TESTBIN_VERIFY").is_some();
    let update = std::env::var_os("BPFOPT_TESTBIN_UPDATE").is_some();
    if !verify && !update {
        eprintln!(
            "skipped: set BPFOPT_TESTBIN_VERIFY=1 to assert or BPFOPT_TESTBIN_UPDATE=1 to refresh \
             bpfopt/testbin/applied_counts.yaml"
        );
        return Ok(());
    }

    let snapshot = compute_snapshot()?;
    let yaml = render_yaml(&snapshot)?;
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../testbin/applied_counts.yaml");

    if update {
        fs::write(&path, &yaml).with_context(|| format!("write {}", path.display()))?;
        eprintln!("wrote {}", path.display());
        return Ok(());
    }

    let expected = fs::read_to_string(&path).with_context(|| {
        format!(
            "read {} (run with BPFOPT_TESTBIN_UPDATE=1 to create)",
            path.display()
        )
    })?;
    if expected != yaml {
        let actual_path = path.with_extension("yaml.actual");
        fs::write(&actual_path, &yaml).ok();
        panic!(
            "testbin pass-count snapshot drift.\n\
             Checked-in:  {}\n\
             Just-computed: {}\n\
             If the change is intentional, refresh with:\n  \
             BPFOPT_TESTBIN_UPDATE=1 cargo test --release -p bpfopt --test testbin_pass_counts",
            path.display(),
            actual_path.display(),
        );
    }
    Ok(())
}

#[derive(Default, Clone, Copy)]
struct PassCounts {
    progs: usize,
    applied: usize,
    matched: usize,
    skipped: usize,
    progs_with_apply: usize,
    progs_failed: usize,
}

type AppCounts = BTreeMap<&'static str, PassCounts>;
type Snapshot = BTreeMap<&'static str, AppCounts>;

fn compute_snapshot() -> Result<Snapshot> {
    let registry_template = build_registry()?;
    let mut snapshot: Snapshot = BTreeMap::new();
    let testbin_root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../testbin");

    for app in APPS {
        let app_dir = testbin_root.join(app);
        let mut prog_dirs = Vec::new();
        collect_program_dirs(&app_dir, &mut prog_dirs)
            .with_context(|| format!("walk {}", app_dir.display()))?;
        prog_dirs.sort();
        let t_app = std::time::Instant::now();
        eprintln!("[{}] {} programs", app, prog_dirs.len());

        for prog_dir in &prog_dirs {
            let bytes = fs::read(prog_dir.join("canonicalize_output.bin"))
                .with_context(|| format!("read {}/canonicalize_output.bin", prog_dir.display()))?;
            let insns =
                decode_insns(&bytes).with_context(|| format!("decode {}", prog_dir.display()))?;
            let t_prog = std::time::Instant::now();

            for entry in PASS_REGISTRY {
                if EXCLUDED_PASSES.contains(&entry.name) {
                    continue;
                }
                let counts = snapshot
                    .entry(entry.name)
                    .or_default()
                    .entry(app)
                    .or_default();
                counts.progs += 1;
                let t_pass = std::time::Instant::now();
                match run_pass_on_program(entry, &registry_template, &insns) {
                    Ok(result) => {
                        counts.applied += result.applied;
                        counts.matched += result.matched;
                        counts.skipped += result.skipped;
                        if result.applied > 0 {
                            counts.progs_with_apply += 1;
                        }
                    }
                    Err(_) => counts.progs_failed += 1,
                }
                let dur = t_pass.elapsed();
                if dur.as_secs_f64() >= 0.5 {
                    eprintln!(
                        "  slow: {} {} insns={} dur={:.2}s",
                        entry.name,
                        prog_dir.file_name().unwrap().to_string_lossy(),
                        insns.len(),
                        dur.as_secs_f64()
                    );
                    print_and_reset_timing(&format!(
                        "{} {}",
                        entry.name,
                        prog_dir.file_name().unwrap().to_string_lossy()
                    ));
                } else {
                    // discard counters from this fast pass
                    print_and_reset_timing("");
                }
            }
            let pd = t_prog.elapsed();
            if pd.as_secs() >= 5 {
                eprintln!(
                    "  prog {} total {:.1}s ({} insns)",
                    prog_dir.file_name().unwrap().to_string_lossy(),
                    pd.as_secs_f64(),
                    insns.len()
                );
            }
        }
        eprintln!("  {} done in {:.1}s", app, t_app.elapsed().as_secs_f64());
        // Incremental write after every app so a partial run still produces a
        // useful YAML (full all-7-app pass takes ~2 hours; observers want to
        // see progress without waiting for the very last app).
        if std::env::var_os("BPFOPT_TESTBIN_UPDATE").is_some() {
            let path =
                Path::new(env!("CARGO_MANIFEST_DIR")).join("../../testbin/applied_counts.yaml");
            if let Ok(yaml) = render_yaml(&snapshot) {
                let _ = fs::write(&path, yaml);
            }
        }
    }
    Ok(snapshot)
}

struct PerProgResult {
    applied: usize,
    matched: usize,
    skipped: usize,
}

fn run_pass_on_program(
    entry: &PassRegistryEntry,
    registry_template: &KinsnRegistry,
    insns: &[BpfInsn],
) -> Result<PerProgResult> {
    let mut ctx = PassContext::default();
    ctx.kinsn_registry = registry_template.clone();
    let mut program: ProgramCFG = lift_with_pass_context(insns, &ctx)?;
    let pass = (entry.make)(&[])?;
    let result = run_pass_once(pass.as_ref(), &mut program, &ctx)?;
    let skipped = result.site_skipped.len();
    Ok(PerProgResult {
        applied: result.sites_applied,
        matched: result.sites_applied + skipped,
        skipped,
    })
}

/// Builds a KinsnRegistry with synthetic but unique (btf_id, call_off) per
/// registered target so kinsn-class passes can emit calls without a daemon-
/// supplied target.json. Same registry can be cloned per program/pass.
fn build_registry() -> Result<KinsnRegistry> {
    let mut registry = KinsnRegistry::new()?;
    // Iterate every kinsn name the registry is aware of via PASS_REGISTRY +
    // COMMON_KINSN_TARGETS (the latter is registered inside KinsnRegistry::new()).
    let mut names: Vec<&'static str> = PASS_REGISTRY
        .iter()
        .flat_map(|p| p.kinsn_targets.iter().map(|d| d.name))
        .collect();
    // Common targets registered by KinsnRegistry::new() but not listed in any
    // pass's kinsn_targets — keep this in sync with passes/mod.rs:COMMON_KINSN_TARGETS.
    names.extend(["bpf_x86_movq", "bpf_arm64_mov_x_rr"]);
    names.sort();
    names.dedup();
    for (idx, name) in names.iter().enumerate() {
        let btf_id = (1000 + idx) as i32;
        registry.set_kinsn_call_for_target_name(name, btf_id, 0)?;
    }
    Ok(registry)
}

fn collect_program_dirs(dir: &Path, out: &mut Vec<PathBuf>) -> Result<()> {
    if !dir.exists() {
        return Ok(());
    }
    for entry in fs::read_dir(dir).with_context(|| format!("read_dir {}", dir.display()))? {
        let entry = entry?;
        let path = entry.path();
        if path.is_dir() && path.join("canonicalize_output.bin").exists() {
            out.push(path);
        }
    }
    Ok(())
}

fn decode_insns(bytes: &[u8]) -> Result<Vec<BpfInsn>> {
    if !bytes.len().is_multiple_of(8) {
        anyhow::bail!("bytecode length {} is not a multiple of 8", bytes.len());
    }
    Ok(bytes
        .chunks_exact(8)
        .map(|chunk| BpfInsn::from_raw_bytes(chunk.try_into().expect("chunk is 8 bytes")))
        .collect())
}

fn render_yaml(snapshot: &Snapshot) -> Result<String> {
    use std::fmt::Write;
    let mut out = String::from(SNAPSHOT_HEADER);
    out.push('\n');
    for (&pass_name, apps) in snapshot {
        writeln!(&mut out, "{pass_name}:").unwrap();
        let mut total = PassCounts::default();
        for (&app_name, counts) in apps {
            writeln!(
                &mut out,
                "  {app_name}: {{progs: {}, applied: {}, matched: {}, skipped: {}, progs_with_apply: {}, progs_failed: {}}}",
                counts.progs,
                counts.applied,
                counts.matched,
                counts.skipped,
                counts.progs_with_apply,
                counts.progs_failed,
            ).unwrap();
            total.progs += counts.progs;
            total.applied += counts.applied;
            total.matched += counts.matched;
            total.skipped += counts.skipped;
            total.progs_with_apply += counts.progs_with_apply;
            total.progs_failed += counts.progs_failed;
        }
        writeln!(
            &mut out,
            "  _total: {{progs: {}, applied: {}, matched: {}, skipped: {}, progs_with_apply: {}, progs_failed: {}}}",
            total.progs,
            total.applied,
            total.matched,
            total.skipped,
            total.progs_with_apply,
            total.progs_failed,
        ).unwrap();
    }
    Ok(out)
}
